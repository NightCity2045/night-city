using Content.Client._NC.Bank;
using Content.Client.UserInterface.Controls;
using Content.Shared._NC.Corporations;
using Content.Shared._NC.Medical.Pharmacology.Batch;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._NC.Corporations;

[GenerateTypedNameReferences]
public sealed partial class NCCorpSalesWindow : FancyWindow
{
    [Dependency] private IPrototypeManager _prototypes = default!;

    public event Action<int>? OnFulfill;
    public event Action? OnRefresh;

    public NCCorpSalesWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        RefreshButton.OnPressed += _ => OnRefresh?.Invoke();
    }

    public void UpdateState(NCCorpSalesUiState state)
    {
        _prototypes.TryIndex(state.Corporation, out var corporation);
        CorporationLabel.Text = corporation != null ? Loc.GetString(corporation.Name) : string.Empty;

        WarningLabel.Visible = !state.PalletFound || !state.Employee;
        WarningLabel.Text = !state.PalletFound
            ? Loc.GetString("nc-corp-sales-no-pallet")
            : Loc.GetString("nc-corp-sales-not-employee");

        ContractsContainer.RemoveAllChildren();
        if (state.Contracts.Count == 0)
            ContractsContainer.AddChild(new Label { Text = Loc.GetString("nc-corp-sales-no-contracts") });

        foreach (var entry in state.Contracts)
        {
            if (_prototypes.TryIndex(entry.Contract, out var contract))
                ContractsContainer.AddChild(CreateContract(entry, contract, corporation, state.Employee));
        }
    }

    private Control CreateContract(NCCorpContractEntry entry, NCCorpContractPrototype contract, NCCorpSalesPrototype? corporation, bool employee)
    {
        var panel = new PanelContainer { StyleClasses = { "AngleRect" } };
        var box = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, SeparationOverride = 3, Margin = new Thickness(6) };
        panel.AddChild(box);

        box.AddChild(new Label { Text = Loc.GetString(contract.Name), StyleClasses = { "LabelHeading" } });
        if (contract.Description is { } description)
            box.AddChild(new Label { Text = Loc.GetString(description), FontColorOverride = Color.FromHex("#AAAAAA") });

        foreach (var progress in entry.Progress)
        {
            if (progress.Index >= contract.Requirements.Count)
                continue;

            var done = progress.Have >= progress.Need;
            box.AddChild(new Label
            {
                Text = Loc.GetString("nc-corp-sales-requirement",
                    ("what", Describe(contract.Requirements[progress.Index])),
                    ("have", progress.Have),
                    ("need", progress.Need)),
                FontColorOverride = done ? Color.FromHex("#9FE3A5") : Color.FromHex("#E3C59F"),
            });
        }

        var share = corporation?.DepartmentShare ?? 0.5f;
        var departmentAmount = (long) Math.Round(contract.Reward * share);
        var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 6 };
        row.AddChild(new Label
        {
            Text = Loc.GetString("nc-corp-sales-reward",
                ("reward", contract.Reward),
                ("department", departmentAmount),
                ("corporation", contract.Reward - departmentAmount)),
            HorizontalExpand = true,
        });
        var fulfill = new Button { Text = Loc.GetString("nc-corp-sales-fulfill"), Disabled = !employee || !entry.Ready };
        var slot = entry.Slot;
        fulfill.OnPressed += _ => OnFulfill?.Invoke(slot);
        row.AddChild(fulfill);
        box.AddChild(row);
        return panel;
    }

    private string Describe(NCCorpContractRequirement requirement)
    {
        switch (requirement)
        {
            case NCCorpItemRequirement item:
                return _prototypes.TryIndex(item.Item, out var entity) ? entity.Name : item.Item.Id;
            case NCCorpImplantRequirement implant:
            {
                var name = _prototypes.TryIndex(implant.Item, out var implantPrototype) ? implantPrototype.Name : implant.Item.Id;
                return Loc.GetString(implant.Tested ? "nc-corp-sales-implant-tested" : "nc-corp-sales-implant", ("implant", name));
            }
            case NCCorpDrugRequirement drug:
            {
                var name = _prototypes.TryIndex(drug.Formula, out var formula) ? Loc.GetString(formula.Name) : drug.Formula.Id;
                return Loc.GetString(drug.Certified ? "nc-corp-sales-drug-certified" : "nc-corp-sales-drug",
                    ("formula", name),
                    ("grade", Loc.GetString(GradeName(drug.MinimumGrade))));
            }
            default:
                return string.Empty;
        }
    }

    private static string GradeName(NCPharmaGrade grade)
    {
        return grade switch
        {
            NCPharmaGrade.Street => "nc-corp-sales-grade-street",
            NCPharmaGrade.Corporate => "nc-corp-sales-grade-corporate",
            _ => "nc-corp-sales-grade-medical",
        };
    }
}
