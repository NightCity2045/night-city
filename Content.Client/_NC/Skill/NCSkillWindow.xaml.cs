using System.Linq;
using System.Numerics;
using Content.Client.UserInterface.Controls;
using Content.Shared._NC.Skill;
using Content.Shared.CCVar;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Configuration;
using Robust.Shared.Prototypes;

namespace Content.Client._NC.Skill;

[GenerateTypedNameReferences]
public sealed partial class NCSkillWindow : FancyWindow
{
    private readonly IPrototypeManager _prototypes = IoCManager.Resolve<IPrototypeManager>();
    private readonly IConfigurationManager _config = IoCManager.Resolve<IConfigurationManager>();
    private readonly bool _editing;
    private readonly NCSkillTreePrototype[] _trees;
    private readonly Dictionary<string, List<NCSkillNode>> _drafts = new();
    private NCSkillPrototype[] _choices = [];
    private NCSkillsState _progress = new(-1, []);
    private HashSet<string> _learned = [];
    private string? _tree;
    private string? _connection;
    private string? _pendingPurchase;
    private bool _connectingAny;
    private LocId? _status;

    public event Action<string>? Purchase;
    public event Action<string, NCSkillNode[]?>? EditRequested;

    public NCSkillWindow(bool editing)
    {
        RobustXamlLoader.Load(this);
        _editing = editing;
        Graph.Editing = editing;
        EditorTools.Visible = RemoveButton.Visible = LoadButton.Visible = SaveButton.Visible = editing;
        LearnButton.Visible = ProgressLabel.Visible = !editing;
        _trees = _prototypes.EnumeratePrototypes<NCSkillTreePrototype>()
            .OrderBy(tree => Loc.GetString(tree.Name)).ToArray();
        for (var i = 0; i < _trees.Length; i++)
            TreeSelector.AddItem(Loc.GetString(_trees[i].Name), i);

        TreeSelector.OnItemSelected += args => SelectTree(args.Id);
        CenterButton.OnPressed += _ => Graph.Center();
        Graph.Picked += SelectSkill;
        LearnButton.OnPressed += _ =>
        {
            if (Graph.Selected is not { } selected || LearnButton.Disabled)
                return;

            _pendingPurchase = selected;
            SetStatus();
            UpdateDetails();
            Purchase?.Invoke(selected);
        };
        Search.OnTextChanged += _ => RefreshChoices();
        AddSelector.OnItemSelected += args => AddSkill(_choices[args.Id].ID);
        RemoveButton.OnPressed += _ => RemoveSkill();
        RequiredButton.OnPressed += _ => Connect(false);
        AnyButton.OnPressed += _ => Connect(true);
        LoadButton.OnPressed += _ =>
        {
            if (_tree != null)
                EditRequested?.Invoke(_tree, null);
        };
        SaveButton.OnPressed += _ =>
        {
            if (_tree != null)
                EditRequested?.Invoke(_tree, Graph.Nodes.ToArray());
        };

        if (_trees.Length > 0)
            SelectTree(0);
        else
            UpdateDetails();
    }

    protected override void EnteredTree()
    {
        base.EnteredTree();
        _config.OnValueChanged(CCVars.NCClientCulture, Relocalize, invokeImmediately: true);
    }

    protected override void ExitedTree()
    {
        _config.UnsubValueChanged(CCVars.NCClientCulture, Relocalize);
        base.ExitedTree();
    }

    private void Relocalize(string culture)
    {
        Title = Loc.GetString(_editing ? "nc-skill-editor-title" : "nc-skill-title");
        CenterButton.Text = Loc.GetString("nc-skill-editor-center");
        Search.PlaceHolder = Loc.GetString("nc-skill-editor-search");
        RequiredButton.Text = Loc.GetString("nc-skill-editor-connect");
        AnyButton.Text = Loc.GetString("nc-skill-editor-connect-any");
        AnyGroup.ToolTip = Loc.GetString("nc-skill-editor-group");
        RemoveButton.Text = Loc.GetString("nc-skill-editor-remove");
        LoadButton.Text = Loc.GetString("nc-skill-editor-load");
        SaveButton.Text = Loc.GetString("nc-skill-editor-save");
        SetStatus(_status);

        for (var i = 0; i < _trees.Length; i++)
            TreeSelector.SetItemText(i, Loc.GetString(_trees[i].Name));

        RefreshChoices();
        UpdateDetails();
    }

    private void SetStatus(LocId? status = null)
    {
        _status = status;
        Status.Text = status is { } id ? Loc.GetString(id) : "";
    }

    private void SelectTree(int index)
    {
        TreeSelector.SelectId(index);
        _tree = _trees[index].ID;
        if (!_drafts.TryGetValue(_tree, out var nodes))
        {
            nodes = _prototypes.EnumeratePrototypes<NCSkillPrototype>()
                .Where(skill => skill.Tree.Id == _tree)
                .OrderBy(skill => skill.ID)
                .Select(FromPrototype).ToList();
            _drafts.Add(_tree, nodes);
        }

        Graph.Nodes = nodes;
        Graph.Center();
        Graph.Selected = nodes.FirstOrDefault()?.Id;
        Graph.Connecting = false;
        _connection = null;
        SetStatus();
        RefreshChoices();
        UpdateDetails();
    }

    private static NCSkillNode FromPrototype(NCSkillPrototype skill) => new(
        skill.ID, skill.Position, skill.Prerequisites.Select(id => id.Id).ToArray(),
        skill.AnyPrerequisites.Select(group => group.Select(id => id.Id).ToArray()).ToArray());

    public void SetProgress(NCSkillsState state)
    {
        _progress = state;
        _learned = new HashSet<string>(state.Learned);
        Graph.Learned = _learned;
        UpdateDetails();
    }

    public void FinishPurchase(bool success)
    {
        _pendingPurchase = null;
        SetStatus(success ? null : "nc-skill-purchase-failed");
        UpdateDetails();
    }

    public void FinishEdit(NCSkillEditorResult result)
    {
        if (result.Nodes is { } nodes)
        {
            var list = nodes.ToList();
            _drafts[result.Tree] = list;
            if (_tree == result.Tree)
            {
                Graph.Nodes = list;
                Graph.Selected = list.FirstOrDefault()?.Id;
                Graph.Center();
                RefreshChoices();
                UpdateDetails();
            }
        }

        if (_tree == result.Tree)
            SetStatus(result.Status);
    }

    private void RefreshChoices()
    {
        if (!_editing)
            return;

        var query = Search.Text.Trim();
        _choices = _prototypes.EnumeratePrototypes<NCSkillPrototype>()
            .Where(skill => skill.Tree.Id == _tree && !Graph.Nodes.Any(node => node.Id == skill.ID))
            .Where(skill => skill.ID.Contains(query, StringComparison.OrdinalIgnoreCase) ||
                Loc.GetString(skill.Name).Contains(query, StringComparison.CurrentCultureIgnoreCase))
            .OrderBy(skill => Loc.GetString(skill.Name)).ToArray();
        AddSelector.Clear();
        AddSelector.AddItem(Loc.GetString("nc-skill-editor-add"), -1);
        AddSelector.SelectId(-1);
        AddSelector.SetItemDisabled(0, true);
        AddSelector.Disabled = _choices.Length == 0;
        for (var i = 0; i < _choices.Length; i++)
            AddSelector.AddItem($"{Loc.GetString(_choices[i].Name)} ({_choices[i].ID})", i);
    }

    private void AddSkill(string id)
    {
        if (!_prototypes.TryIndex<NCSkillPrototype>(id, out var skill) ||
            Graph.Nodes.Any(node => node.Id == id))
        {
            return;
        }

        var node = FromPrototype(skill);
        while (Graph.Nodes.Any(other => other.Position == node.Position))
            node = node with { Position = node.Position + Vector2.UnitX };

        Graph.Nodes.Add(node);
        Graph.Selected = id;
        Graph.Center();
        RefreshChoices();
        UpdateDetails();
    }

    private void RemoveSkill()
    {
        if (Graph.Selected is not { } id)
            return;

        for (var i = Graph.Nodes.Count - 1; i >= 0; i--)
        {
            var node = Graph.Nodes[i];
            if (node.Id == id)
            {
                Graph.Nodes.RemoveAt(i);
                continue;
            }

            Graph.Nodes[i] = node with
            {
                Prerequisites = node.Prerequisites.Where(other => other != id).ToArray(),
                AnyPrerequisites = node.AnyPrerequisites
                    .Select(group => group.Where(other => other != id).ToArray())
                    .Where(group => group.Length > 0).ToArray(),
            };
        }

        Graph.Selected = null;
        _connection = null;
        RefreshChoices();
        UpdateDetails();
    }

    private void Connect(bool any)
    {
        var sameMode = Graph.Connecting && _connectingAny == any;
        Graph.Connecting = !sameMode;
        _connectingAny = any;
        _connection = null;
        SetStatus(sameMode ? null : "nc-skill-editor-select-source");
    }

    private void SelectSkill(string id)
    {
        Graph.Selected = id;
        if (Graph.Connecting && _connection is { } source && source != id)
        {
            for (var i = 0; i < Graph.Nodes.Count; i++)
            {
                var node = Graph.Nodes[i];
                if (node.Id != id)
                    continue;

                if (_connectingAny)
                {
                    var groups = node.AnyPrerequisites.ToList();
                    var group = int.TryParse(AnyGroup.Text, out var number)
                        ? Math.Clamp(number, 1, groups.Count + 1) - 1
                        : 0;
                    if (group == groups.Count)
                        groups.Add([source]);
                    else
                        groups[group] = Toggle(groups[group], source);
                    Graph.Nodes[i] = node with { AnyPrerequisites = groups.Where(ids => ids.Length > 0).ToArray() };
                }
                else
                {
                    Graph.Nodes[i] = node with { Prerequisites = Toggle(node.Prerequisites, source) };
                }

                break;
            }

            _connection = null;
            Graph.Connecting = false;
            SetStatus();
        }
        else if (Graph.Connecting)
        {
            _connection = id;
        }

        UpdateDetails();
    }

    private static string[] Toggle(string[] ids, string id) =>
        ids.Contains(id) ? ids.Where(other => other != id).ToArray() : [.. ids, id];

    private void UpdateDetails()
    {
        var level = NCSkillProgression.Level(_progress.Experience);
        var points = NCSkillProgression.Points(_progress.Experience, _learned.Count);
        ProgressLabel.Text = _progress.Experience < 0
            ? Loc.GetString("nc-skill-loading")
            : NCSkillProgression.NextThreshold(level) is { } next
                ? Loc.GetString("nc-skill-level", ("level", level), ("xp", _progress.Experience),
                    ("next", next), ("points", points))
                : Loc.GetString("nc-skill-max-level", ("level", level), ("xp", _progress.Experience),
                    ("points", points));

        LearnButton.Disabled = true;
        RemoveButton.Disabled = Graph.Selected == null;
        var node = Graph.Nodes.FirstOrDefault(node => node.Id == Graph.Selected);
        if (node == null || !_prototypes.TryIndex<NCSkillPrototype>(node.Id, out var skill))
        {
            SkillTitle.Text = "";
            Description.SetMessage("");
            Requirements.SetMessage("");
            return;
        }

        SkillTitle.Text = Loc.GetString(skill.Name);
        Description.SetMessage(Loc.GetString(skill.Description));
        var requirements = new List<string>();
        if (node.Prerequisites.Length > 0)
            requirements.Add(Loc.GetString("nc-skill-prerequisites", ("skills", Names(node.Prerequisites))));

        foreach (var group in node.AnyPrerequisites)
            requirements.Add(Loc.GetString("nc-skill-prerequisites-any", ("skills", Names(group))));

        Requirements.SetMessage(string.Join("\n", requirements));
        var learned = _learned.Contains(skill.ID);
        LearnButton.Text = Loc.GetString(learned ? "nc-skill-learned" : "nc-skill-learn");
        LearnButton.Disabled = _progress.Experience < 0 || learned || points == 0 || _pendingPurchase != null ||
            !skill.MeetsPrerequisites(_learned);
    }

    private string Names(IEnumerable<string> ids) =>
        string.Join(", ", ids.Select(id => _prototypes.TryIndex<NCSkillPrototype>(id, out var skill)
            ? Loc.GetString(skill.Name)
            : id));
}
