using Content.Client.UserInterface.Controls;
using Content.Shared._NC.Meta.UI;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._NC.Meta.UI;

[GenerateTypedNameReferences]
public sealed partial class NCMetaInvoiceWindow : FancyWindow
{
    private NCMetaInvoicePromptMessage? _prompt;
    private bool _completed;
    private bool _sent;
    public Guid SessionId => _prompt?.SessionId ?? Guid.Empty;
    public event Action<NCMetaInvoiceDecisionMessage>? Decided;

    public NCMetaInvoiceWindow()
    {
        RobustXamlLoader.Load(this);
        Pay.OnPressed += _ => Decide(true);
        Decline.OnPressed += _ => { Decide(false); Close(); };
        OnClose += () => { if (!_completed && !_sent) Decide(false); };
    }

    public void ApplyPrompt(NCMetaInvoicePromptMessage prompt)
    {
        if (_prompt is not null) return;
        _prompt = prompt;
        Payee.Text = Loc.GetString("nc-meta-invoice-payee", ("payee", prompt.Payee));
        Amount.Text = Loc.GetString("nc-meta-invoice-amount", ("amount", prompt.Amount));
        Invoice.Text = Loc.GetString("nc-meta-invoice-id", ("id", prompt.InvoiceId.ToString("D")));
        Digest.Text = Loc.GetString("nc-meta-invoice-hash", ("hash", prompt.InvoiceHash));
        Digest.ToolTip = prompt.InvoiceHash;
        Expiry.Text = Loc.GetString("nc-meta-invoice-expiry", ("seconds", prompt.ExpiresInSeconds));
    }

    public void ApplyStatus(NCMetaInvoiceStatusMessage status)
    {
        if (_prompt?.ConfirmationId != status.ConfirmationId) return;
        _completed = !status.Pending;
        Pay.Disabled = true;
        Decline.Disabled = status.Pending;
        Notice.Text = status.Notice;
    }
    private void Decide(bool accept)
    {
        if (_prompt is not { } prompt || _completed || _sent) return;
        _sent = true;
        Pay.Disabled = Decline.Disabled = true;
        Notice.Text = Loc.GetString(accept ? "nc-meta-invoice-pending" : "nc-meta-invoice-cancelled");
        Decided?.Invoke(new(prompt.SessionId, prompt.ConfirmationId, prompt.InvoiceId, prompt.InvoiceHash, prompt.Amount, prompt.Payee, accept));
    }
    protected override void Dispose(bool disposing)
    {
        if (disposing) NCMetaUiLifecycle.BeforeRemove(this);
        _prompt = null;
        Decided = null;
        base.Dispose(disposing);
    }
    public override void Close()
    {
        NCMetaUiLifecycle.BeforeRemove(this);
        base.Close();
    }
}
