using Content.Client.UserInterface.Controls;
using Content.Shared._NC.Meta.UI;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._NC.Meta.UI;

[GenerateTypedNameReferences]
public sealed partial class NCMetaDevelopmentConfirmationWindow : FancyWindow
{
    public event Action<bool>? Decided;
    private bool _decided;
    public NCMetaDevelopmentConfirmationWindow(NCMetaDevelopmentPrompt prompt)
    {
        RobustXamlLoader.Load(this);
        Kind.Text = Loc.GetString(prompt.Funding ? "nc-meta-development-confirm-funding" : "nc-meta-development-confirm-acceptance");
        Details.AddItem(Loc.GetString("nc-meta-development-parties", ("customer", prompt.Customer), ("developer", prompt.Developer)), selectable: false);
        Details.AddItem(Loc.GetString("nc-meta-development-price", ("amount", prompt.Amount)), selectable: false);
        Details.AddItem(Loc.GetString("nc-meta-development-escrow-name"), selectable: false);
        Details.AddItem(Loc.GetString(prompt.SourceCopy ? "nc-meta-development-source-copy" : "nc-meta-development-binary"), selectable: false);
        Details.AddItem(Loc.GetString(prompt.AutomaticAcceptance ? "nc-meta-development-auto-policy" : "nc-meta-development-manual-policy"), selectable: false);
        Details.AddItem(Loc.GetString("nc-meta-development-prompt-expiry", ("seconds", prompt.Seconds)), selectable: false);
        Consent.OnToggled += _ => Confirm.Disabled = !Consent.Pressed;
        Confirm.OnPressed += _ => { if (Consent.Pressed && !Confirm.Disabled) Decide(true); };
        Cancel.OnPressed += _ => Decide(false);
        OnClose += () => { if (!_decided) { _decided = true; Decided?.Invoke(false); } };
    }
    private void Decide(bool accept)
    {
        if (_decided) return;
        _decided = true; Confirm.Disabled = true;
        Decided?.Invoke(accept);
        Close();
    }
    protected override void Dispose(bool disposing)
    {
        if (disposing) NCMetaUiLifecycle.BeforeRemove(this);
        Decided = null;
        base.Dispose(disposing);
    }
    public override void Close() { NCMetaUiLifecycle.BeforeRemove(this); base.Close(); }
}
