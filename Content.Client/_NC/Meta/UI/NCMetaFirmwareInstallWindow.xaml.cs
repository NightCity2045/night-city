using System.Linq;
using Content.Client.UserInterface.Controls;
using Content.Shared._NC.Meta.UI;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._NC.Meta.UI;

/// <summary>Native consent UI. Guest documents cannot restyle, populate or confirm this window.</summary>
[GenerateTypedNameReferences]
public sealed partial class NCMetaFirmwareInstallWindow : FancyWindow
{
    public event Action? Confirmed;

    public NCMetaFirmwareInstallWindow(string device, NCMetaFirmwarePreview preview, List<string> links)
    {
        RobustXamlLoader.Load(this);
        Target.Text = Loc.GetString("nc-meta-firmware-target", ("device", device));
        Target.ToolTip = Target.Text;
        Package.Text = Loc.GetString("nc-meta-firmware-package", ("package", preview.PackageName), ("version", preview.Version));
        Package.ToolTip = Package.Text;
        Artifact.Text = Loc.GetString("nc-meta-firmware-artifact", ("bytes", preview.ArtifactResidentBytes));
        Memory.Text = Loc.GetString("nc-meta-firmware-memory", ("bytes", preview.ProcessMemoryBytes));
        Storage.Text = Loc.GetString("nc-meta-firmware-storage", ("bytes", preview.PackageBytes));
        foreach (var scope in preview.RequiredScopes.Take(64))
            Permissions.AddItem(Loc.GetString("nc-meta-market-scope", ("scope", scope)), selectable: false);
        foreach (var link in links.Take(64)) Permissions.AddItem(link, selectable: false);
        ScopeConsent.OnToggled += _ => UpdateConsent();
        ResourceConsent.OnToggled += _ => UpdateConsent();
        Cancel.OnPressed += _ => Close();
        Confirm.OnPressed += _ =>
        {
            if (!ScopeConsent.Pressed || !ResourceConsent.Pressed || Confirm.Disabled) return;
            Confirm.Disabled = true;
            Confirmed?.Invoke();
            Close();
        };
    }

    private void UpdateConsent() => Confirm.Disabled = !ScopeConsent.Pressed || !ResourceConsent.Pressed;

    protected override void Dispose(bool disposing)
    {
        if (disposing) NCMetaUiLifecycle.BeforeRemove(this);
        Confirmed = null;
        base.Dispose(disposing);
    }
    public override void Close()
    {
        NCMetaUiLifecycle.BeforeRemove(this);
        base.Close();
    }
}
