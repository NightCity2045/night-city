    public void ApplyState(NCMetaWorkspaceState state)
    {
        ApplyLanguageSymbols(state);
        if (state.Partial)
        {
            Status.Text = state.Notice;
            RejectServiceGrantRequest(state.AcknowledgedRequestId);
            RejectDevelopment(state.AcknowledgedRequestId);
            if (_saveRequest != Guid.Empty && state.AcknowledgedRequestId == _saveRequest)
            {
                if (state.SaveStatus == NCMetaSaveStatus.Rejected) RejectPendingSave();
                else RetainUnconfirmedSave();
            }
            return;
        }
        if (SemanticStateChanged(state)) InvalidateLanguageQuery();
        _applying = true;
        if (_state.ProjectId != Guid.Empty && _state.ProjectId != state.ProjectId)
        {
            _selectedFile = Guid.Empty;
            Editor.TrySetSource("");
        }
        _state = state;
        ProjectName.Text = state.ProjectName;
        Files.Clear();
        foreach (var file in state.Files.Take(256))
            Files.AddItem(file.Path);
        Projects.Clear();
        foreach (var project in state.Projects.Take(64))
            Projects.AddItem(project.Name, state.Projects.IndexOf(project));
        var activeProject = state.Projects.FindIndex(x => x.ProjectId == state.ProjectId);
        if (activeProject >= 0)
            Projects.SelectId(activeProject);
        if (_selectedDeviceId.Length == 0 && state.Devices.Count > 0)
            _selectedDeviceId = state.Devices[0].DeviceId;
        var selectedDevice = state.Devices.Take(64).ToList().FindIndex(device => device.DeviceId == _selectedDeviceId);
        Devices.Clear();
        for (var i = 0; i < Math.Min(64, state.Devices.Count); i++)
            Devices.AddItem(Loc.GetString("nc-meta-device-entry", ("name", state.Devices[i].Name), ("status", state.Devices[i].Status)), i);
        if (selectedDevice >= 0)
            Devices.SelectId(selectedDevice);
        else if (_selectedDeviceId.Length > 0)
        {
            Devices.AddItem(Loc.GetString("nc-meta-device-unavailable"), 64);
            Devices.SelectId(64);
        }
        if (state.SaveStatus == NCMetaSaveStatus.Committed && _saveRequest != Guid.Empty && state.AcknowledgedRequestId == _saveRequest &&
            _pendingSave is { Complete: true } pendingCommit && _uploads.Count == 0 && !state.RevisionConflict &&
            _buffers.TryGetValue(_savedFile, out var savedBuffer) && state.Files.FirstOrDefault(file => file.FileId == _savedFile) is { } savedFile &&
            savedFile.Revision > pendingCommit.BaseRevision && savedFile.Revision >= savedBuffer.Revision &&
            string.Equals(savedFile.Sha256, _savedHash, StringComparison.OrdinalIgnoreCase))
        {
            savedBuffer.Revision = savedFile.Revision;
            savedBuffer.SavedSource = _savedSource;
            savedBuffer.Dirty = savedBuffer.Source != _savedSource;
            savedBuffer.Remote = null;
            if (_downloads.TryGetValue(_savedFile, out var pendingSave) && pendingSave.Revision < savedFile.Revision)
                _downloads.Remove(_savedFile);
        }
        foreach (var chunk in state.Contents.Take(16))
        {
            var content = Assemble(chunk);
            if (content is null)
                continue;
            if (!_buffers.TryGetValue(content.FileId, out var buffer))
            {
                if (_buffers.Count >= 16)
                {
                    var discard = _buffers.FirstOrDefault(x => !x.Value.Dirty && x.Key != _selectedFile);
                    if (discard.Key == Guid.Empty)
                    {
                        Status.Text = Loc.GetString("nc-meta-buffer-limit");
                        continue;
                    }
                    _buffers.Remove(discard.Key);
                }
                _buffers[content.FileId] = new(content.Source, content.Revision);
            }
            else if (!buffer.Dirty)
            {
                buffer.Source = content.Source;
                buffer.SavedSource = content.Source;
                buffer.Revision = content.Revision;
            }
            else if (content.FileId == _savedFile && content.Source == _savedSource && !state.RevisionConflict)
            {
                buffer.Revision = content.Revision;
                buffer.SavedSource = content.Source;
                buffer.Dirty = buffer.Source != _savedSource;
            }
            else if (buffer.Revision != content.Revision)
                buffer.Remote = content;
        }
        Diagnostics.Clear();
        foreach (var diagnostic in state.Diagnostics.Take(256))
        {
            var stale = !_buffers.TryGetValue(diagnostic.FileId, out var buffer) || buffer.Revision != diagnostic.Revision || buffer.Dirty;
            Diagnostics.AddItem(Loc.GetString(stale ? "nc-meta-diagnostic-stale" : "nc-meta-diagnostic-entry",
                ("code", diagnostic.Code), ("message", diagnostic.Message), ("offset", diagnostic.StartUtf8Byte)));
        }
        Logs.Clear();
        foreach (var log in state.Logs.TakeLast(256))
            Logs.AddItem(log, selectable: false);
        Variables.Clear();
        foreach (var variable in state.DebugVariables.Take(128))
            Variables.AddItem(variable, selectable: false);
        Status.Text = state.Notice;
        ReleaseInfo.Text = Loc.GetString("nc-meta-release-info", ("digest", state.ActiveReleaseDigest), ("scopes", state.RequestedScopes));
        ApplicationViews.Clear();
        for (var i = 0; i < Math.Min(32, state.ApplicationViews.Count); i++)
            ApplicationViews.AddItem(state.ApplicationViews[i], i);
        OpenApplication.Disabled = ApplicationViews.ItemCount == 0;
        PublishWebsite.Disabled = ApplicationViews.ItemCount == 0;
        var website = state.HostingLeases.Take(64).FirstOrDefault(lease => lease.HostDeviceId == _selectedDeviceId &&
            lease.Status == "nc-meta-hosting-active");
        WebsiteAddress.Text = website is null ? "" : "citi://" + website.Domain;
        WithdrawWebsite.Visible = false;
        Templates.Clear();
        for (var i = 0; i < Math.Min(32, state.Templates.Count); i++)
            Templates.AddItem(_localization.DefaultCulture?.TwoLetterISOLanguageName == "ru" ? state.Templates[i].NameRu : state.Templates[i].Name, i);
        ImportTemplate.Disabled = Templates.ItemCount == 0;
        Templates.Visible = ImportTemplate.Visible = Templates.ItemCount > 0;
        UpdateInstallations();
        UpdateDeviceControls();
        HostingPurchase.Disabled = state.HostingQuote is null;
        HostingPrice.Text = state.HostingQuote is { } quote ? Loc.GetString("nc-meta-hosting-price",
            ("domain", quote.Domain), ("domainFee", quote.DomainFee), ("hostingFee", quote.HostingFee),
            ("seconds", quote.TermSeconds), ("units", quote.Units)) : "";
        HostingLeases.Clear();
        foreach (var lease in state.HostingLeases.Take(64))
            HostingLeases.AddItem(Loc.GetString("nc-meta-hosting-lease", ("domain", lease.Domain), ("units", lease.Units), ("status", Loc.GetString(lease.Status))));
        HostingRefund.Disabled = true;
        LinkContracts.Clear();
        foreach (var link in state.Links.Take(64))
            LinkContracts.AddItem(Loc.GetString("nc-meta-binding-link", ("slot", link.Slot), ("type", link.Capability),
                ("scopes", string.Join(", ", link.RequiredScopes))), selectable: false);
        DeviceInterfaces.Clear();
        foreach (var device in state.Devices.Take(64))
            DeviceInterfaces.AddItem(Loc.GetString("nc-meta-binding-device", ("name", device.Name), ("id", device.DeviceId),
                ("interfaces", string.Join(", ", device.Interfaces ?? []))), selectable: false);
        if (!_bindingsEdited && Rope.CalcTotalLength(BindingsInput.TextRope) == 0 && state.Links.Count > 0)
            BindingsInput.TextRope = new Rope.Leaf(BindingTemplate(state.Links));
        Editor.Editable = state.CanEdit;
        if (_selectedFile == Guid.Empty && state.Files.Count > 0)
            _selectedFile = state.Files[0].FileId;
        if (_buffers.TryGetValue(_selectedFile, out var selected))
        {
            if (Editor.Source != selected.Source)
                Editor.TrySetSource(selected.Source);
            Conflict.Visible = selected.Remote is not null || state.RevisionConflict;
        }
        else if (_selectedFile != Guid.Empty)
        {
            Editor.Editable = false;
            Request(NCMetaWorkspaceOperation.Read);
        }
        ApplyCommerceState(state.Commerce);
        ApplyFirmwareState(state.Firmware);
        ApplyServiceGrantState(state.ServiceGrants);
        ApplyDevelopmentState(state.Development);
        ApplyNativeTools();
        _applying = false;
        RebuildTabs();
        UpdateFileInfo();
        if (_saveRequest != Guid.Empty && state.AcknowledgedRequestId == _saveRequest)
        {
            if (state.SaveStatus == NCMetaSaveStatus.Rejected || state.RevisionConflict)
            {
                RejectPendingSave();
                return;
            }
            if (state.SaveStatus == NCMetaSaveStatus.ChunkAccepted && _pendingSave is
                { Operation: NCMetaWorkspaceOperation.SaveChunk, Complete: false } && _uploads.TryDequeue(out var next))
            {
                _saveRequest = next.RequestId;
                _pendingSave = next;
                SendPendingSave();
                return;
            }
            var committed = state.SaveStatus == NCMetaSaveStatus.Committed && _pendingSave is { Complete: true } pending &&
                _uploads.Count == 0 && state.Files.FirstOrDefault(file => file.FileId == _savedFile) is { } saved &&
                saved.Revision > pending.BaseRevision && string.Equals(saved.Sha256, _savedHash, StringComparison.OrdinalIgnoreCase);
            if (!committed)
            {
                RetainUnconfirmedSave();
                return;
            }
            _saveRequest = Guid.Empty;
            _pendingSave = null;
            _uploads.Clear();
            Save.Disabled = false;
            if (_afterSave is { } operation)
                Request(operation);
            _afterSave = null;
        }
    }

    private NCMetaFileContent? Assemble(NCMetaFileContent chunk)
    {
        if (_buffers.TryGetValue(chunk.FileId, out var current) && (chunk.Revision < current.Revision || current.Remote is { } remote && chunk.Revision < remote.Revision))
            return null;
        var bytes = Encoding.UTF8.GetBytes(chunk.Source);
        var total = chunk.TotalUtf8Bytes == 0 && chunk.Complete ? bytes.Length : chunk.TotalUtf8Bytes;
        if (bytes.Length > 32 * 1024 || total < 0 || total > NCMetaCodeEditor.MaximumBytes || chunk.Utf8Offset < 0 ||
            chunk.Utf8Offset > total - bytes.Length || chunk.Sha256.Length != 64)
            return null;
        if (chunk.Utf8Offset == 0)
        {
            if (_downloads.TryGetValue(chunk.FileId, out var pending))
            {
                if (pending.Revision > chunk.Revision || pending.Revision == chunk.Revision &&
                    (pending.Sha256 != chunk.Sha256 || pending.Received >= bytes.Length))
                    return null;
            }
            if (!_downloads.ContainsKey(chunk.FileId) && _downloads.Count >= 16)
                return null;
            _downloads[chunk.FileId] = new(total, chunk.Revision, chunk.Sha256);
        }
        if (!_downloads.TryGetValue(chunk.FileId, out var download) || download.Received != chunk.Utf8Offset ||
            download.Revision != chunk.Revision || download.Sha256 != chunk.Sha256 || download.Bytes.Length != total)
            return null;
        bytes.CopyTo(download.Bytes.AsSpan(download.Received));
        download.Received += bytes.Length;
        if (!chunk.Complete)
        {
            Requested?.Invoke(new(NCMetaWorkspaceOperation.Read, Guid.NewGuid(), chunk.FileId, chunk.Revision,
                projectId: _state.ProjectId, utf8Offset: download.Received));
            return null;
        }
        _downloads.Remove(chunk.FileId);
        if (download.Received != total || !string.Equals(NCMetaSourceHash.ToHexString(NCMetaSourceHash.HashData(download.Bytes)), download.Sha256, StringComparison.OrdinalIgnoreCase))
            return null;
        return new(chunk.FileId, chunk.Revision, Encoding.UTF8.GetString(download.Bytes), chunk.Sha256);
    }

    private void SelectFile(Guid file)
    {
        if (_selectedFile != file) InvalidateLanguageQuery();
        _selectedFile = file;
        if (_buffers.TryGetValue(file, out var buffer))
        {
            Editor.Editable = _state.CanEdit;
            Editor.TrySetSource(buffer.Source);
            Conflict.Visible = buffer.Remote is not null;
        }
        else
        {
            Editor.Editable = false;
            Request(NCMetaWorkspaceOperation.Read);
        }
        RebuildTabs();
        UpdateFileInfo();
    }

    private void OnSourceChanged()
    {
        if (_applying || _selectedFile == Guid.Empty || !_buffers.TryGetValue(_selectedFile, out var buffer))
            return;
        buffer.Source = Editor.Source;
        buffer.Dirty = buffer.Source != buffer.SavedSource;
        InvalidateLanguageQuery();
        UpdateFileInfo();
    }

    private void RebuildTabs()
    {
        var files = _state.Files.Where(file => _buffers.ContainsKey(file.FileId)).Take(12).ToArray();
        foreach (var removed in _fileTabButtons.Keys.Where(id => !files.Any(file => file.FileId == id)).ToArray())
        {
            var button = _fileTabButtons[removed];
            NCMetaUiLifecycle.BeforeRemove(button);
            button.Dispose();
            _fileTabButtons.Remove(removed);
        }
        foreach (var file in files)
        {
            if (!_fileTabButtons.TryGetValue(file.FileId, out var button))
            {
                button = new Button();
                var id = file.FileId;
                button.OnPressed += _ => SelectFile(id);
                _fileTabButtons.Add(id, button);
                FileTabs.AddChild(button);
            }
            button.Text = file.Path;
            button.Disabled = file.FileId == _selectedFile;
        }
    }

    private void UpdateFileInfo()
    {
        if (!_buffers.TryGetValue(_selectedFile, out var buffer))
            return;
        FileInfo.Text = Loc.GetString(buffer.Dirty ? "nc-meta-file-unsaved" : "nc-meta-file-saved",
            ("revision", buffer.Revision), ("line", Editor.CaretLine + 1), ("offset", Editor.CaretUtf8));
    }

    private void SaveThen(NCMetaWorkspaceOperation operation)
    {
        if (_buffers.TryGetValue(_selectedFile, out var buffer) && buffer.Dirty)
        {
            _afterSave = operation;
            SaveFile();
        }
        else
            Request(operation);
    }

    private void SaveFile()
    {
        if (_saveRequest != Guid.Empty)
        {
            SendPendingSave();
            return;
        }
        if (!_buffers.TryGetValue(_selectedFile, out var buffer) || buffer.Remote is not null)
            return;
        _savedSource = buffer.Source;
        _savedFile = _selectedFile;
        var bytes = Encoding.UTF8.GetBytes(buffer.Source);
        var hash = NCMetaSourceHash.ToHexString(NCMetaSourceHash.HashData(bytes));
        _savedHash = hash;
        if (bytes.Length <= 32 * 1024)
            _uploads.Enqueue(new(NCMetaWorkspaceOperation.Save, Guid.NewGuid(), _selectedFile, buffer.Revision, buffer.Source,
                projectId: _state.ProjectId, totalUtf8Bytes: bytes.Length, contentSha256: hash));
        else
        {
            var transfer = Guid.NewGuid();
            for (var offset = 0; offset < bytes.Length;)
            {
                var length = Math.Min(32 * 1024, bytes.Length - offset);
                while (offset + length < bytes.Length && (bytes[offset + length] & 0xC0) == 0x80)
                    length--;
                _uploads.Enqueue(new(NCMetaWorkspaceOperation.SaveChunk, Guid.NewGuid(), _selectedFile, buffer.Revision,
                    Encoding.UTF8.GetString(bytes, offset, length), projectId: _state.ProjectId, utf8Offset: offset,
                    transferId: transfer, totalUtf8Bytes: bytes.Length, contentSha256: hash, complete: offset + length == bytes.Length));
                offset += length;
            }
        }
        var first = _uploads.Dequeue();
        _saveRequest = first.RequestId;
        _pendingSave = first;
        Status.Text = Loc.GetString("nc-meta-saving");
        SendPendingSave();
    }

    private void SendPendingSave()
    {
        if (_pendingSave is not { } request || request.RequestId != _saveRequest) return;
        _saveRetryElapsed = 0;
        _saveRetryAttempts = 1;
        Save.Disabled = true;
        Requested?.Invoke(request);
    }

    private void RejectPendingSave()
    {
        _pendingSave = null;
        _saveRequest = Guid.Empty;
        _uploads.Clear();
        _afterSave = null;
        Save.Disabled = false;
    }

    private void RetainUnconfirmedSave()
    {
        _saveRetryAttempts = 3;
        _saveRetryElapsed = 0;
        Save.Disabled = false;
        if (string.IsNullOrEmpty(Status.Text)) Status.Text = Loc.GetString("nc-meta-save-unconfirmed");
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        TickSemanticProof();
        TickServiceGrantRequest(args.DeltaSeconds);
        TickDevelopment(args.DeltaSeconds);
        if (_saveRequest == Guid.Empty || _pendingSave is not { } request || _saveRetryAttempts >= 3) return;
        _saveRetryElapsed += args.DeltaSeconds;
        if (_saveRetryElapsed < 5) return;
        _saveRetryElapsed = 0;
        _saveRetryAttempts++;
        Requested?.Invoke(request);
        if (_saveRetryAttempts == 3)
        {
            Save.Disabled = false;
            Status.Text = Loc.GetString("nc-meta-save-unconfirmed");
        }
    }

    private void Request(NCMetaWorkspaceOperation operation, string source = "", string path = "", NCMetaWorkspacePayload? payload = null)
    {
        var device = _selectedDeviceId;
        if (operation == NCMetaWorkspaceOperation.QuoteHosting && HostingHost.Text.Length > 0)
            device = HostingHost.Text;
        var revision = operation is NCMetaWorkspaceOperation.RenameProject or NCMetaWorkspaceOperation.DeleteProject
            ? _state.ProjectRevision : _buffers.TryGetValue(_selectedFile, out var buffer) ? buffer.Revision : 0;
        Requested?.Invoke(new(operation, Guid.NewGuid(), _selectedFile, revision, source, device,
            IsInstallationOperation(operation) && SelectedInstallation is { } installation ? installation.ReleaseId : _state.ActiveReleaseId,
            Editor.CaretUtf8, _state.ProjectId, path, installationId: _selectedInstallationId, payload: payload));
    }

    private NCMetaInstallationSummary? SelectedInstallation => _visibleInstallations.FirstOrDefault(installation => installation.Id == _selectedInstallationId);

    private static bool IsInstallationOperation(NCMetaWorkspaceOperation operation) => operation is
        NCMetaWorkspaceOperation.Start or NCMetaWorkspaceOperation.Stop or NCMetaWorkspaceOperation.Rollback or NCMetaWorkspaceOperation.Logs or
        NCMetaWorkspaceOperation.DebugAttach or NCMetaWorkspaceOperation.DebugDetach or NCMetaWorkspaceOperation.DebugPause or
        NCMetaWorkspaceOperation.DebugContinue or NCMetaWorkspaceOperation.DebugStepInto or NCMetaWorkspaceOperation.DebugStepOver or
        NCMetaWorkspaceOperation.DebugStepOut or NCMetaWorkspaceOperation.DebugSetBreakpoint or NCMetaWorkspaceOperation.DebugEvaluate or
        NCMetaWorkspaceOperation.OpenApplication or NCMetaWorkspaceOperation.PublishWebsite or NCMetaWorkspaceOperation.EnableHostingOffer or
        NCMetaWorkspaceOperation.QuoteHosting;

    private void UpdateInstallations()
    {
        if (_installationDeviceId != _selectedDeviceId)
        {
            _installationDeviceId = _selectedDeviceId;
            _selectedInstallationId = Guid.Empty;
            _installationExplicitNew = false;
        }
        _visibleInstallations.Clear();
        _visibleInstallations.AddRange(_state.Installations.Where(installation => installation.DeviceId == _selectedDeviceId).Take(64));
        if (_selectedInstallationId == Guid.Empty && !_installationExplicitNew)
        {
            var releaseMatches = _visibleInstallations.Where(installation => installation.ReleaseId == _state.ActiveReleaseId).Take(2).ToArray();
            if (releaseMatches.Length == 1) _selectedInstallationId = releaseMatches[0].Id;
            else if (_visibleInstallations.Count == 1) _selectedInstallationId = _visibleInstallations[0].Id;
        }
        Installations.Clear();
        Installations.AddItem(Loc.GetString("nc-meta-installation-new"), 0);
        var selected = 0;
        for (var index = 0; index < _visibleInstallations.Count; index++)
        {
            var installation = _visibleInstallations[index];
            var slot = installation.Slot switch
            {
                "Firmware" => "nc-meta-installation-firmware",
                "Resident" => "nc-meta-installation-resident",
                _ => "nc-meta-installation-user",
            };
            Installations.AddItem(Loc.GetString("nc-meta-installation-entry", ("name", installation.Name), ("slot", Loc.GetString(slot)),
                ("startup", Loc.GetString(installation.AutoStart ? "nc-meta-installation-startup" : "nc-meta-installation-manual"))), index + 1);
            if (installation.Id == _selectedInstallationId) selected = index + 1;
        }
        if (_selectedInstallationId != Guid.Empty && selected == 0)
        {
            selected = 65;
            Installations.AddItem(Loc.GetString("nc-meta-installation-unavailable"), selected);
        }
        Installations.SelectId(selected);
    }

