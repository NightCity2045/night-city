    private string IdentifierAtCaret(bool prefix)
    {
        var source = Editor.Source;
        var start = Editor.CaretUtf16;
        var end = start;
        while (start > 0 && (char.IsAsciiLetterOrDigit(source[start - 1]) || source[start - 1] == '_'))
            start--;
        if (!prefix)
            while (end < source.Length && (char.IsAsciiLetterOrDigit(source[end]) || source[end] == '_'))
                end++;
        return source[start..end];
    }

