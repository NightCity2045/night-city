    private static string BindingTemplate(IEnumerable<NCMetaLinkSummary> links)
    {
        var array = new NCMetaUiArray();
        foreach (var link in links.Take(64))
        {
            var scopes = new NCMetaUiArray();
            foreach (var scope in link.RequiredScopes) scopes.Items.Add(NCMetaMuiValues.Scalar(scope));
            var value = new NCMetaUiObject();
            value["Slot"] = NCMetaMuiValues.Scalar(link.Slot);
            value["DeviceId"] = NCMetaMuiValues.Scalar("");
            value["ContractHash"] = NCMetaMuiValues.Scalar(link.ContractHash);
            value["Scopes"] = scopes; array.Items.Add(value);
        }
        return NCMetaMuiValues.TryWrite(array, 32768, out var json) ? json : "[]";
    }

