using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._NC.Meta.UI;

[GenerateTypedNameReferences]
public sealed partial class NCMetaCitiNetBrowser : BoxContainer
{
    private readonly List<string> _history = [];
    private int _historyIndex = -1;
    public event Action<string>? SiteRequested;

    public NCMetaCitiNetBrowser()
    {
        RobustXamlLoader.Load(this);
        TabContainer.SetTabTitle(WebsiteTab, Loc.GetString("nc-meta-browser-sites"));
        TabContainer.SetTabTitle(FeedHost, Loc.GetString("nc-meta-browser-feed"));
        BrowserGo.OnPressed += _ => Navigate(true);
        BrowserAddress.OnTextEntered += _ => Navigate(true);
        BrowserReload.OnPressed += _ => Navigate(false);
        BrowserBack.OnPressed += _ => NavigateHistory(-1);
        BrowserForward.OnPressed += _ => NavigateHistory(1);
    }

    private void NavigateHistory(int direction)
    {
        var next = _historyIndex + direction;
        if (next < 0 || next >= _history.Count) return;
        _historyIndex = next;
        BrowserAddress.Text = _history[next];
        Navigate(false);
    }

    private void Navigate(bool remember)
    {
        if (Disposed || BrowserAddress.Text.Length is 0 or > 192) return;
        var address = BrowserAddress.Text;
        if (remember && (_historyIndex < 0 || _history[_historyIndex] != address))
        {
            if (_historyIndex + 1 < _history.Count)
                _history.RemoveRange(_historyIndex + 1, _history.Count - _historyIndex - 1);
            if (_history.Count >= 32) _history.RemoveAt(0);
            _history.Add(address);
            _historyIndex = _history.Count - 1;
        }
        BrowserBack.Disabled = _historyIndex <= 0;
        BrowserForward.Disabled = _historyIndex < 0 || _historyIndex >= _history.Count - 1;
        BrowserReload.Disabled = false;
        BrowserEmpty.Visible = false;
        BrowserTitle.Text = Loc.GetString("nc-meta-browser-title");
        BrowserStatus.Text = Loc.GetString("nc-meta-browser-loading");
        SiteRequested?.Invoke(address);
    }

    public bool TryShowWebsite(NCMetaApplicationView view)
    {
        if (Disposed || view.Disposed || BrowserPageHost.ChildCount != 0) return false;
        BrowserStatus.Text = "";
        BrowserEmpty.Visible = false;
        BrowserSections.CurrentTab = 0;
        BrowserPageHost.AddChild(view);
        view.TitleChanged += title =>
        {
            if (!Disposed && view.Parent == BrowserPageHost) BrowserTitle.Text = title;
        };
        return true;
    }

    public void ShowNotice(string notice)
    {
        if (Disposed) return;
        BrowserStatus.Text = notice;
        BrowserTitle.Text = Loc.GetString("nc-meta-browser-title");
        BrowserEmpty.Visible = false;
    }

    protected override void Dispose(bool disposing)
    {
        SiteRequested = null;
        base.Dispose(disposing);
    }
}
