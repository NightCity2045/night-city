using System.Linq;
using Content.Client.UserInterface.Controls;
using Content.Shared._NC.Meta.Network;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._NC.Meta.UI;

[GenerateTypedNameReferences]
public sealed partial class NCMetaNetWindow : FancyWindow
{
    private NCMetaNetState? _state;
    public event Action<NCMetaNetRequest>? Requested;

    public NCMetaNetWindow()
    {
        RobustXamlLoader.Load(this);
        Refresh.OnPressed += _ => Request(NCMetaNetOperation.Refresh);
        Disconnect.OnPressed += _ => Request(NCMetaNetOperation.Disconnect);
        Scan.OnPressed += _ => Request(NCMetaNetOperation.Scan);
        Probe.OnPressed += _ => Request(NCMetaNetOperation.Probe, true);
        Read.OnPressed += _ => Request(NCMetaNetOperation.Read, true);
        CopySoftware.OnPressed += _ => Request(NCMetaNetOperation.CopySoftware, true);
        Control.OnPressed += _ => Request(NCMetaNetOperation.AcquireControl, true);
        Activate.OnPressed += _ => Request(NCMetaNetOperation.Activate, true);
        Deactivate.OnPressed += _ => Request(NCMetaNetOperation.Deactivate, true);
        Defend.OnPressed += _ => Request(NCMetaNetOperation.Defend, true);
    }

    public void ApplyState(NCMetaNetState state)
    {
        var selected = _state is not null && Nodes.GetSelected().Select(Nodes.IndexOf).FirstOrDefault(-1) is var prior && prior >= 0 && prior < _state.Nodes.Length
            ? _state.Nodes[prior].Id : "";
        _state = state;
        Trace.Text = Loc.GetString("nc-meta-net-trace", ("value", state.Trace));
        Budget.Text = Loc.GetString("nc-meta-net-budget", ("value", state.Budget));
        Status.Text = Loc.GetString(state.StatusKey.Length > 0 ? state.StatusKey : state.StateKey);
        Nodes.Clear();
        for (var i = 0; i < Math.Min(256, state.Nodes.Length); i++)
        {
            Nodes.AddItem(state.Nodes[i].Label);
            if (state.Nodes[i].Id == selected) Nodes[i].Selected = true;
        }
        Preview.Text = state.Preview;
        Scan.Disabled = Probe.Disabled = Read.Disabled = CopySoftware.Disabled = Control.Disabled = Activate.Disabled = Deactivate.Disabled = Defend.Disabled = state.ActionPending;
    }

    private void Request(NCMetaNetOperation operation, bool requiresNode = false)
    {
        if (_state is null) return;
        var selected = Nodes.GetSelected().Select(Nodes.IndexOf).FirstOrDefault(-1);
        if (requiresNode && (selected < 0 || selected >= _state.Nodes.Length))
        { Status.Text = Loc.GetString("nc-meta-net-no-selection"); return; }
        Requested?.Invoke(new(operation, _state.SessionId, _state.Revision, selected >= 0 && selected < _state.Nodes.Length ? _state.Nodes[selected].Id : ""));
    }

    protected override void Dispose(bool disposing)
    {
        if (disposing) NCMetaUiLifecycle.BeforeRemove(this);
        Requested = null;
        _state = null;
        base.Dispose(disposing);
    }
    public override void Close()
    {
        NCMetaUiLifecycle.BeforeRemove(this);
        base.Close();
    }
}
