using Content.Client._NC.Meta.Mui;
using System.Linq;
using System.Text;
using Content.Client.UserInterface.Controls;
using Content.Meta.Mui;
using Content.Shared._NC.Meta.UI;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._NC.Meta.UI;

[GenerateTypedNameReferences]
public sealed partial class NCMetaApplicationWindow : FancyWindow
{
    private NCMetaMuiRenderer? _renderer;
    public Guid SessionId => _renderer?.SessionId ?? Guid.Empty;
    public event Action<BoundUserInterfaceMessage>? Requested;

    public NCMetaApplicationWindow() => RobustXamlLoader.Load(this);

    public void ApplyResult(NCMetaAppActionResultMessage result)
    {
#if TOOLS && NC_DIAGNOSTICS
        RecordDiagnosticResult(result);
#endif
        if (result.SessionId == SessionId)
            Notice.Text = result.Notice;
    }

    public void ApplyState(NCMetaAppState state)
    {
        if (state.Closed)
        {
            NCMetaUiLifecycle.RemoveChildren(ViewHost);
            _renderer = null;
            Notice.Text = state.Notice;
            return;
        }
        if (_renderer is null || state.SessionId != _renderer.SessionId)
        {
            if (state.Resources.Count > 32 || state.Resources.Sum(x => (long) Encoding.UTF8.GetByteCount(x.Source)) > 64 * 1024 ||
                state.Resources.Select(x => x.Path).Distinct(StringComparer.Ordinal).Count() != state.Resources.Count)
            { Notice.Text = Loc.GetString("nc-meta-view-invalid"); return; }
            var resources = state.Resources.ToDictionary(x => x.Path, x => x.Source, StringComparer.Ordinal);
            if (!state.FullSnapshot || !MuiContractParser.TryParse(state.ContractJson, out var contract, out _) ||
                !contract!.Views.TryGetValue(state.ViewId, out var view) ||
                resources.Keys.Any(x => !contract.Resources.Contains(x)) ||
                !MuiParser.TryParse(state.Document, view, contract, resources, out var document, out _) ||
                !MuiStyleSheet.TryParse(state.Styles, contract, out var styles, out _) || !styles!.FitsBudget(document!))
            {
                Notice.Text = Loc.GetString("nc-meta-view-invalid");
                return;
            }
            NCMetaUiLifecycle.RemoveChildren(ViewHost);
            _renderer = new(document!, view, contract, styles!, state.SessionId);
            _renderer.ActionRequested += RequestAction;
            _renderer.ResyncRequested += () => Requested?.Invoke(new NCMetaAppResyncMessage(_renderer.SessionId, _renderer.Revision));
            ViewHost.AddChild(_renderer);
        }
        var result = _renderer.TryUpdate(state.BaseRevision, state.Revision, state.StateJson, state.FullSnapshot);
        if (result is MuiUpdateResult.Applied or MuiUpdateResult.Duplicate)
            Requested?.Invoke(new NCMetaAppAckMessage(state.SessionId, _renderer.Revision));
#if TOOLS && NC_DIAGNOSTICS
        RecordDiagnosticUpdate(state, result);
#endif
        Notice.Text = result == MuiUpdateResult.Invalid ? Loc.GetString("nc-meta-view-invalid") :
            result == MuiUpdateResult.Gap ? Loc.GetString("nc-meta-view-resync") : state.Notice;
        Title = state.Title;
    }

    private void RequestAction(string action, string json)
    {
        if (_renderer == null) return;
        var id = Guid.NewGuid();
#if TOOLS && NC_DIAGNOSTICS
        RecordDiagnosticAction(id);
#endif
        Requested?.Invoke(new NCMetaAppActionMessage(_renderer.SessionId, action, id, _renderer.Revision, json));
    }

    public override void Close()
    {
        NCMetaUiLifecycle.BeforeRemove(this);
        base.Close();
    }

    protected override void Dispose(bool disposing)
    {
        if (disposing) NCMetaUiLifecycle.BeforeRemove(this);
        Requested = null;
        base.Dispose(disposing);
    }
}
