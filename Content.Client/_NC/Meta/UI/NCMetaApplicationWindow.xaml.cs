using Content.Client.UserInterface.Controls;
using Content.Shared._NC.Meta.UI;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._NC.Meta.UI;

[GenerateTypedNameReferences]
public sealed partial class NCMetaApplicationWindow : FancyWindow
{
    public Guid SessionId => ApplicationView.SessionId;
    public event Action<BoundUserInterfaceMessage>? Requested;

    public NCMetaApplicationWindow()
    {
        RobustXamlLoader.Load(this);
        ApplicationView.Requested += message => Requested?.Invoke(message);
        ApplicationView.TitleChanged += title => Title = title;
    }

    public void ApplyResult(NCMetaAppActionResultMessage result)
    {
        if (!Disposed) ApplicationView.ApplyResult(result);
    }

    public void ApplyState(NCMetaAppState state)
    {
        if (!Disposed) ApplicationView.ApplyState(state);
    }

    public override void Close()
    {
        NCMetaUiLifecycle.BeforeRemove(this);
        base.Close();
    }

    protected override void Dispose(bool disposing)
    {
        if (disposing) NCMetaUiLifecycle.BeforeRemove(this);
        Requested = null;
        base.Dispose(disposing);
    }

#if TOOLS && NC_DIAGNOSTICS
    public bool TryStartDiagnosticCapture() => ApplicationView.TryStartDiagnosticCapture();
    public void StopDiagnosticCapture() => ApplicationView.StopDiagnosticCapture();
    public NCMetaFrontendSnapshot GetDiagnosticSnapshot() => ApplicationView.GetDiagnosticSnapshot();
    public NCMetaFrontendSample[] ReadDiagnosticSamples(int offset, int count) => ApplicationView.ReadDiagnosticSamples(offset, count);
    public bool TryRequestDiagnosticAction(string action, string json, out Guid requestId) =>
        ApplicationView.TryRequestDiagnosticAction(action, json, out requestId);
#endif
}
