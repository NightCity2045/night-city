using Content.Client.UserInterface.Controls;
using Content.Shared._NC.Medical.Cyberware.Optics;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.XAML;
using SixLabors.ImageSharp;
using SixLabors.ImageSharp.PixelFormats;

namespace Content.Client._NC.Medical.Cyberware.Optics;

[GenerateTypedNameReferences]
public sealed partial class NCOpticAlbumWindow : FancyWindow
{
    public Action<int, bool>? Requested;
    private int _index;
    private Texture? _texture;
    public NCOpticAlbumWindow()
    {
        RobustXamlLoader.Load(this);
        Previous.OnPressed += _ => Requested?.Invoke(_index - 1, false);
        Next.OnPressed += _ => Requested?.Invoke(_index + 1, false);
        Delete.OnPressed += _ => Requested?.Invoke(_index, true);
    }

    public void UpdatePhoto(NCOpticAlbumEvent message)
    {
        _index = message.Index;
        (_texture as IDisposable)?.Dispose(); _texture = null;
        if (message.Pixels.Length == NCOpticMemoryComponent.Bytes)
        {
            using var pixels = new Image<Rgba32>(NCOpticMemoryComponent.Width, NCOpticMemoryComponent.Height);
            for (var y = 0; y < NCOpticMemoryComponent.Height; y++)
            for (var x = 0; x < NCOpticMemoryComponent.Width; x++)
            {
                var index = (y * NCOpticMemoryComponent.Width + x) * 3;
                pixels[x, y] = new Rgba32(message.Pixels[index], message.Pixels[index + 1], message.Pixels[index + 2], 255);
            }
            _texture = Texture.LoadFromImage(pixels);
        }
        Photo.Texture = _texture;
        Counter.Text = Loc.GetString("nc-optics-photo-count", ("index", message.Count == 0 ? 0 : message.Index + 1), ("count", message.Count));
        Previous.Disabled = message.Index <= 0;
        Next.Disabled = message.Index + 1 >= message.Count;
        Delete.Disabled = message.Count == 0;
    }

    protected override void Dispose(bool disposing)
    {
        (_texture as IDisposable)?.Dispose();
        base.Dispose(disposing);
    }
}
