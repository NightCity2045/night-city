using System.Linq;
using Content.Client.UserInterface.Controls;
using Content.Shared._NC.Medical.Cyberware.AutoImplanter;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._NC.Medical.Cyberware.AutoImplanter;

[GenerateTypedNameReferences]
public sealed partial class NCAutoImplanterWindow : FancyWindow
{
    [Dependency] private IPrototypeManager _prototypes = default!;

    public event Action<string>? OnInstall;

    private List<NCAutoImplanterEntry> _entries = new();

    public NCAutoImplanterWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        SearchBar.OnTextChanged += _ => Rebuild();
    }

    public void UpdateState(NCAutoImplanterUiState state)
    {
        _entries = state.Entries;
        Rebuild();
    }

    private void Rebuild()
    {
        EntriesContainer.RemoveAllChildren();
        var search = SearchBar.Text.Trim();
        foreach (var group in _entries.GroupBy(entry => entry.Group).OrderBy(group => group.Key))
        {
            var rows = group
                .Select(entry => (entry.Item, Name: NameOf(entry.Item)))
                .Where(row => search.Length == 0 || row.Name.Contains(search, StringComparison.CurrentCultureIgnoreCase))
                .OrderBy(row => row.Name, StringComparer.CurrentCulture)
                .ToList();
            if (rows.Count == 0)
                continue;

            EntriesContainer.AddChild(new Label
            {
                Text = Loc.GetString($"nc-auto-implanter-group-{group.Key.ToString().ToLowerInvariant()}"),
                StyleClasses = { "LabelHeading" },
            });
            foreach (var (item, name) in rows)
                EntriesContainer.AddChild(BuildRow(item, name));
        }
    }

    private string NameOf(string item)
    {
        return _prototypes.TryIndex<EntityPrototype>(item, out var prototype) ? prototype.Name : item;
    }

    private Control BuildRow(string item, string name)
    {
        var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 6 };
        var view = new EntityPrototypeView { SetSize = new System.Numerics.Vector2(32, 32) };
        view.SetPrototype(item);
        row.AddChild(view);
        row.AddChild(new Label { Text = name, ClipText = true, HorizontalExpand = true, VerticalAlignment = VAlignment.Center });

        var install = new Button { Text = Loc.GetString("nc-auto-implanter-install"), VerticalAlignment = VAlignment.Center };
        install.OnPressed += _ => OnInstall?.Invoke(item);
        row.AddChild(install);
        return row;
    }
}
