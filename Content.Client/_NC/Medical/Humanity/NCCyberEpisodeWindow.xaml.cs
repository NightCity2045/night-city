using Content.Client.UserInterface.Controls;
using Content.Shared._NC.Medical.Humanity;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._NC.Medical.Humanity;

[GenerateTypedNameReferences]
public sealed partial class NCCyberEpisodeWindow : FancyWindow
{
    public Action<NCCyberEpisodeActionEvent>? Requested;
    public Action<bool>? ReduceChanged;
    public Action<bool>? QuietChanged;
    public NCCyberEpisodeWindow()
    {
        RobustXamlLoader.Load(this);
        SafeMode.OnPressed += _ => Requested?.Invoke(new() { DisableEnhancements = true });
        Support.OnPressed += _ => Requested?.Invoke(new() { ToggleSupport = true });
        ReducedEffects.OnToggled += args => ReduceChanged?.Invoke(args.Pressed);
        QuietSounds.OnToggled += args => QuietChanged?.Invoke(args.Pressed);
    }
    public void SetPreferences(bool reduced, bool quiet) { ReducedEffects.Pressed = reduced; QuietSounds.Pressed = quiet; }
    public void SetView(NCCyberEpisodeViewEvent view)
    {
        StageLabel.Text = Loc.GetString(NCCyberEpisodeClientSystem.StageKey(view.Status.Stage));
        Details.SetMessage(Loc.GetString("nc-psychosis-details", ("stress", MathF.Round(view.Status.Stress)),
            ("exhaustion", MathF.Round(view.Status.Exhaustion)), ("burden", MathF.Round(view.Status.Burden)),
            ("support", MathF.Round(view.Status.SupportSeconds))));
        Advice.SetMessage(Loc.GetString("nc-psychosis-advice"));
        Support.Text = Loc.GetString(view.DeclinesSupport ? "nc-psychosis-allow-support" : "nc-psychosis-decline-support");
    }
}
