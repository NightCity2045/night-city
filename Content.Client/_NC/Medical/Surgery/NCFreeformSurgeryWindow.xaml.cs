using System.Numerics;
using System.Linq;
using Content.Client.Message;
using Content.Client.UserInterface.Controls;
using Content.Shared._NC.Combat.Targeting;
using Content.Shared._NC.Medical.Surgery;
using Content.Shared._NC.Medical.Wounds;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Maths;

namespace Content.Client._NC.Medical.Surgery;

/// <summary>
/// Polished medical workstation for one private freeform session. It presents server facts and emits only
/// deliberate selections or normalized field input; it does not infer a successful operation locally.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class NCFreeformSurgeryWindow : FancyWindow
{
    public event Action<NCWoundSurface, float>? SelectionChanged;
    public event Action<float>? DepthPredictionChanged;
    public event Action<ProtoId<NCSurgeryToolCapabilityPrototype>>? CapabilityChanged;
    public event Action<ProtoId<NCTargetZonePrototype>, Vector2[]>? StrokeSubmitted;
    public event Action<ProtoId<NCTargetZonePrototype>, Vector2>? AttachRequested;
    public event Action<int>? DetachRequested;

    private readonly IPrototypeManager _prototypes;
    private readonly ButtonGroup _surfaceGroup = new(isNoneSetAllowed: false);
    private NCFreeformSurgeryState? _state;
    private bool _updating;

    public NCFreeformSurgeryWindow(IPrototypeManager prototypes)
    {
        RobustXamlLoader.Load(this);
        _prototypes = prototypes;

        ConfigureSurfaceButton(SurfaceFront, NCWoundSurface.Front);
        ConfigureSurfaceButton(SurfaceRear, NCWoundSurface.Rear);
        ConfigureSurfaceButton(SurfaceLeft, NCWoundSurface.Left);
        ConfigureSurfaceButton(SurfaceRight, NCWoundSurface.Right);

        DepthSlider.OnValueChanged += _ => OnDepthChanged();
        SurgicalField.StrokeSubmitted += (zone, points) => StrokeSubmitted?.Invoke(zone, points);
        SurgicalField.AttachRequested += (zone, point) => AttachRequested?.Invoke(zone, point);
        SurgicalField.DepthAdjusted += delta =>
            DepthSlider.Value = Math.Clamp(DepthSlider.Value + delta * 100f, DepthSlider.MinValue, DepthSlider.MaxValue);
    }

    public void SetState(NCFreeformSurgeryState state, float predictedDepth)
    {
        _state = state;
        _updating = true;

        PatientName.Text = state.PatientName;
        PatientState.Text = $"{state.Condition} · {state.Consciousness}";
        VitalsLabel.Text =
            $"O₂ {state.Oxygenation:P0}   Perfusion {state.Perfusion:P0}   Pain {state.Pain:0.0}   Shock {state.Shock:P0}";
        MovementBar.Value = Math.Clamp(state.Movement, 0f, 1f);
        MovementValue.Text = $"{state.Movement:P0}";
        MovementValue.FontColorOverride = SeverityColor(state.Movement);

        SetSurface(state.Surface);

        var displayedDepth = Math.Clamp(predictedDepth, 0f, 1f);
        DepthSlider.Value = displayedDepth * 100f;
        DepthLabel.Text = DepthText(displayedDepth, state.Layers);
        LayerLabel.Text = $"ACCESS {state.AccessDepth.ToString().ToUpperInvariant()}";

        ToolName.Text = state.ToolName;
        SterilityBar.Value = Math.Clamp(state.ToolSterility, 0f, 1f);
        SterilityLabel.Text = $"Sterility {state.ToolSterility:P0}";
        SterilityLabel.FontColorOverride = SeverityColor(1f - state.ToolSterility);
        PopulateCapabilities(state);
        PopulateSite(state, displayedDepth);
        PopulateAttachments(state);
        SurgicalField.SetState(state, displayedDepth);

        FeedbackPanel.Visible = !state.Accepted || state.Failure != NCFreeformSurgeryFailure.None;
        FeedbackLabel.Text = FeedbackText(state.Failure);
        ConnectionLabel.Text = state.Accepted ? "● LIVE" : "● RESYNC";
        ConnectionLabel.FontColorOverride = state.Accepted ? Color.FromHex("#67E89A") : Color.FromHex("#FFD46B");
        _updating = false;
    }

    public void ShowFailure(NCFreeformSurgeryFailure failure)
    {
        FeedbackPanel.Visible = true;
        FeedbackLabel.Text = FeedbackText(failure);
        ConnectionLabel.Text = "● PAUSED";
        ConnectionLabel.FontColorOverride = Color.FromHex("#FFD46B");
    }

    public void ResolvePendingStroke()
    {
        SurgicalField.ResolvePendingStroke();
    }

    private void PopulateCapabilities(NCFreeformSurgeryState state)
    {
        CapabilityContainer.RemoveAllChildren();
        ToolSprite.SetPrototype(null);
        ToolSprite.Visible = !string.IsNullOrEmpty(state.ToolPrototype);
        if (!string.IsNullOrEmpty(state.ToolPrototype))
            ToolSprite.SetPrototype(new EntProtoId(state.ToolPrototype));

        foreach (var capability in state.Capabilities)
        {
            var button = new Button
            {
                ToggleMode = true,
                Pressed = capability.Selected,
                HorizontalExpand = true,
                ToolTip = $"{capability.Name}: {ActionName(capability.Action)}",
            };
            var row = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                SeparationOverride = 7,
                HorizontalExpand = true,
            };
            if (!string.IsNullOrEmpty(capability.RepresentativeTool))
            {
                var icon = new EntityPrototypeView
                {
                    SetSize = new Vector2(34f, 34f),
                    Scale = new Vector2(1.4f),
                };
                icon.SetPrototype(new EntProtoId(capability.RepresentativeTool));
                row.AddChild(icon);
            }
            row.AddChild(new Label
            {
                Text = $"{ActionName(capability.Action)}\n{capability.Name}",
                HorizontalExpand = true,
                ClipText = true,
            });
            button.AddChild(row);
            var selected = capability.Capability;
            button.OnPressed += _ => CapabilityChanged?.Invoke(selected);
            CapabilityContainer.AddChild(button);
        }

        if (state.Capabilities.Length == 0)
        {
            CapabilityContainer.AddChild(new Label
            {
                Text = "Hold a compatible surgical instrument in the active hand.",
                FontColorOverride = Color.FromHex("#E9B658"),
            });
        }
    }

    private void PopulateSite(NCFreeformSurgeryState state, float displayedDepth)
    {
        var openIncisions = state.Incisions.Count(value => !value.Sutured);
        var activeBleeding = state.Wounds.Count(value => value.ExternalBleedRate > 0f || value.InternalBleedRate > 0f);
        var exposed = state.Structures.Count(value => value.Exposed);
        var text =
            $"Surface: {SurfaceName(state.Surface)} · working depth: {displayedDepth:P0}\n" +
            $"Local contamination under cursor: {state.SiteContamination:P0}\n" +
            $"Visible open incisions: {openIncisions} · bleeding wounds: {activeBleeding}\n" +
            $"Exposed structures: {exposed} · attached tools: {state.Attachments.Length}";
        SiteStatus.SetMessage(text, Color.FromHex("#C4D4D3"));
    }

    private void PopulateAttachments(NCFreeformSurgeryState state)
    {
        AttachmentContainer.RemoveAllChildren();
        if (state.Attachments.Length == 0)
        {
            AttachmentContainer.AddChild(new Label
            {
                Text = "None",
                FontColorOverride = Color.FromHex("#718B8D"),
            });
            return;
        }

        foreach (var attachment in state.Attachments)
        {
            var button = new Button
            {
                Text = $"Detach {attachment.Name}",
                HorizontalExpand = true,
            };
            var handle = attachment.Handle;
            button.OnPressed += _ => DetachRequested?.Invoke(handle);
            AttachmentContainer.AddChild(button);
        }
    }

    private void ConfigureSurfaceButton(Button button, NCWoundSurface surface)
    {
        button.ToggleMode = true;
        button.Group = _surfaceGroup;
        button.OnPressed += _ =>
        {
            if (_updating || _state == null)
                return;
            SelectionChanged?.Invoke(surface, DepthSlider.Value / 100f);
        };
    }

    private void OnDepthChanged()
    {
        if (_state == null)
            return;
        var depth = DepthSlider.Value / 100f;
        DepthLabel.Text = DepthText(depth, _state.Layers);
        SurgicalField.SetPredictedDepth(depth);
        PopulateSite(_state, depth);
        if (!_updating)
            DepthPredictionChanged?.Invoke(depth);
    }

    private void SetSurface(NCWoundSurface surface)
    {
        // NC: ButtonGroup unsets the previous selection itself. Directly clearing a grouped button throws.
        var selected = surface switch
        {
            NCWoundSurface.Rear => SurfaceRear,
            NCWoundSurface.Left => SurfaceLeft,
            NCWoundSurface.Right => SurfaceRight,
            _ => SurfaceFront,
        };

        if (!selected.Pressed)
            selected.Pressed = true;
    }

    private static string DepthText(float depth, IReadOnlyList<NCFreeformSurgeryLayerSummary> layers)
    {
        var layer = layers.FirstOrDefault(value => depth >= value.StartDepth && depth <= value.EndDepth);
        return $"{depth:P0} · {layer.Kind}";
    }

    private static string SurfaceName(NCWoundSurface surface) => surface switch
    {
        NCWoundSurface.Front => "front",
        NCWoundSurface.Rear => "rear",
        NCWoundSurface.Left => "left",
        NCWoundSurface.Right => "right",
        _ => surface.ToString(),
    };

    private static string ActionName(NCFreeformSurgeryAction action) => action switch
    {
        NCFreeformSurgeryAction.Disinfect => "Field disinfection",
        NCFreeformSurgeryAction.Incise => "Incision",
        NCFreeformSurgeryAction.Hemostasis => "Hemostasis",
        NCFreeformSurgeryAction.Retract => "Retraction",
        NCFreeformSurgeryAction.Suture => "Suturing",
        NCFreeformSurgeryAction.Irrigate => "Irrigation",
        NCFreeformSurgeryAction.Debride => "Debridement",
        NCFreeformSurgeryAction.RepairVessel => "Vascular repair",
        NCFreeformSurgeryAction.RepairOrgan => "Organ repair",
        NCFreeformSurgeryAction.ReduceBone => "Bone reduction",
        NCFreeformSurgeryAction.FixBone => "Bone fixation",
        NCFreeformSurgeryAction.RepairTendon => "Tendon repair",
        NCFreeformSurgeryAction.RepairNerve => "Nerve repair",
        NCFreeformSurgeryAction.ExtractForeignBody => "Foreign-body extraction",
        NCFreeformSurgeryAction.OpenBone => "Bone access",
        NCFreeformSurgeryAction.Separate => "Separation",
        NCFreeformSurgeryAction.Amputate => "Amputation",
        NCFreeformSurgeryAction.Transplant => "Transplantation",
        NCFreeformSurgeryAction.Cyberware => "Cyberware installation / removal",
        NCFreeformSurgeryAction.Cauterize => "Cautery",
        NCFreeformSurgeryAction.Autopsy => "Autopsy",
        NCFreeformSurgeryAction.DrainCavity => "Cavity drainage",
        _ => action.ToString(),
    };

    private static string FeedbackText(NCFreeformSurgeryFailure failure) => failure switch
    {
        NCFreeformSurgeryFailure.None => string.Empty,
        NCFreeformSurgeryFailure.OutOfRange => "Intervention paused: move back within reach of the patient.",
        NCFreeformSurgeryFailure.StaleRevision => "The operative field changed. Live data has been synchronized; repeat the action.",
        NCFreeformSurgeryFailure.ToolUnavailable => "The active hand does not contain a surgical instrument.",
        NCFreeformSurgeryFailure.ToolBroken => "The selected instrument is broken.",
        NCFreeformSurgeryFailure.CapabilityUnavailable => "Select a supported mode of the instrument in your active hand.",
        NCFreeformSurgeryFailure.ResourceEmpty => "The instrument has no remaining material or working charge.",
        NCFreeformSurgeryFailure.AttachmentUnavailable => "The instrument cannot be attached or removed at this point.",
        NCFreeformSurgeryFailure.SurgicalAccessClosed =>
            "This point is not physically exposed at the selected depth. Open or deepen a local incision first.",
        NCFreeformSurgeryFailure.NoApplicableTarget => "No applicable wound, incision or exposed structure is under the instrument.",
        NCFreeformSurgeryFailure.RateLimited => "Move the instrument more deliberately.",
        _ => $"Surgical request rejected: {failure}.",
    };

    private static Color SeverityColor(float value)
    {
        return value >= 0.66f
            ? Color.FromHex("#FF6170")
            : value >= 0.33f
                ? Color.FromHex("#FFD05E")
                : Color.FromHex("#67E89A");
    }
}
