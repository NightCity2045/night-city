using System.Linq;
using Content.Client._NC.Combat.Targeting;
using Content.Client.UserInterface.Controls;
using Content.Shared._NC.Combat.Targeting;
using Content.Shared._NC.Medical.Surgery;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Timing;

namespace Content.Client._NC.Medical.Surgery;

[GenerateTypedNameReferences]
public sealed partial class NCSurgeryConsoleWindow : FancyWindow
{
    [Dependency] private IGameTiming _timing = default!;

    private readonly IPrototypeManager _prototypes;
    private readonly NCTargetingDollControl _doll;
    private readonly List<NCSurgeryConsoleProcedureEntry> _renderedProcedures = [];
    private NCSurgeryConsoleProcedureEntry? _selected;
    private bool _updating;
    private bool _stepInProgress;
    private TimeSpan _stepDeadline;
    private TimeSpan _stepDuration;

    public event Action<NCSurgeryConsoleProcedureEntry>? OnSelect;
    public event Action<ProtoId<NCTargetZonePrototype>>? OnZoneSelect;
    public event Action? OnExecuteStep;
    public event Action? OnClear;

    public NCSurgeryConsoleWindow(IPrototypeManager prototypes)
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _prototypes = prototypes;

        _doll = new NCTargetingDollControl
        {
            DisplayScale = 3f,
            ShowAutomaticSelection = false,
        };
        _doll.TargetingChanged += state =>
        {
            if (_updating || state.Mode != NCTargetingMode.SelectedZone || state.SelectedZone is not { } zone)
                return;
            OnZoneSelect?.Invoke(zone);
        };
        DollHost.AddChild(_doll);

        ProcedureList.OnItemSelected += args =>
        {
            if (_updating || ProcedureList[args.ItemIndex].Metadata is not NCSurgeryConsoleProcedureEntry entry)
                return;
            _selected = entry;
            SelectButton.Disabled = false;
        };
        SelectButton.OnPressed += _ =>
        {
            if (_selected is { } selected)
                OnSelect?.Invoke(selected);
        };
        ExecuteButton.OnPressed += _ =>
        {
            ExecuteButton.Disabled = true;
            OnExecuteStep?.Invoke();
        };
        ClearButton.OnPressed += _ =>
        {
            _selected = null;
            ProcedureList.ClearSelected();
            OnClear?.Invoke();
        };
    }

    public void UpdateState(NCSurgeryConsoleUpdateMessage state)
    {
        _updating = true;
        try
        {
            UpdatePatientHeader(state);
            UpdateDoll(state);
            UpdateProcedures(state);
            UpdateSteps(state);

            AccessLabel.Text = Loc.GetString(
                "nc-medical-surgery-console-access-value",
                ("access", LocalizedEnum("access", state.AccessDepth)));
            GraftLabel.Text = Loc.GetString(
                "nc-medical-surgery-console-graft-value",
                ("graft", state.GraftName ?? Loc.GetString("nc-medical-surgery-console-none")));
            ClearButton.Disabled = state.SelectedProcedure == null;

            _stepInProgress = state.StepInProgress;
            _stepDuration = state.StepDuration;
            _stepDeadline = _timing.RealTime + TimeSpan.FromTicks(Math.Max(
                0L,
                (state.StepDuration - state.StepElapsed).Ticks));
            RefreshProgress();

            NoticeLabel.Visible = state.Notice != NCSurgeryConsoleNotice.None;
            NoticeLabel.Text = state.Notice == NCSurgeryConsoleNotice.None
                ? string.Empty
                : Loc.GetString($"nc-medical-surgery-console-notice-{ToKebabCase(state.Notice.ToString())}");
        }
        finally
        {
            _updating = false;
        }
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        if (_stepInProgress)
            RefreshProgress();
    }

    private void UpdatePatientHeader(NCSurgeryConsoleUpdateMessage state)
    {
        PatientLabel.Text = EmptyOr(state.PatientName, "nc-medical-surgery-console-none");
        FacilityLabel.Text = EmptyOr(state.FacilityName, "nc-medical-surgery-console-none");
        var summary = state.PatientSummary;
        ConditionLabel.Text = Loc.GetString(
            "nc-medical-surgery-console-condition-value",
            ("condition", LocalizedEnum("condition", summary.Condition)),
            ("consciousness", LocalizedEnum("consciousness", summary.Consciousness)));
        PerfusionLabel.Text = Percent(summary.Perfusion);
        OxygenLabel.Text = Percent(summary.Oxygenation);
        ShockLabel.Text = Percent(summary.Shock);
        PainLabel.Text = summary.Pain.ToString("0.0");
        AnalgesiaLabel.Text = Percent(summary.Analgesia);
        SedationLabel.Text = Percent(summary.Sedation);
        AnesthesiaLabel.Text = Percent(summary.Anesthesia);
    }

    private void UpdateDoll(NCSurgeryConsoleUpdateMessage state)
    {
        if (state.AnatomyProfile is { } profile)
        {
            _doll.SetProfile(profile);
            _doll.SetStatusLevels(state.ZoneStatuses.ToDictionary(entry => entry.Zone, entry => entry.Severity));
        }
        else
        {
            _doll.ClearProfile();
        }

        if (state.SelectedZone is { } zone)
            _doll.SetState(new NCTargetingState(NCTargetingMode.SelectedZone, zone));

        ZoneLabel.Text = state.SelectedZone is { } selected &&
                         _prototypes.TryIndex(selected, out NCTargetZonePrototype? zonePrototype)
            ? Loc.GetString(zonePrototype.DisplayName)
            : Loc.GetString("nc-medical-surgery-console-zone-unselected");
    }

    private void UpdateProcedures(NCSurgeryConsoleUpdateMessage state)
    {
        var catalogueChanged = !_renderedProcedures.SequenceEqual(state.Procedures);
        if (catalogueChanged)
        {
            ProcedureList.Clear();
            _renderedProcedures.Clear();
            _renderedProcedures.AddRange(state.Procedures);
            foreach (var entry in state.Procedures)
            {
                var text = Loc.GetString(
                    "nc-medical-surgery-console-procedure-line",
                    ("procedure", ProcedureName(entry.Procedure)),
                    ("target", entry.TargetName),
                    ("graft", entry.RequiresGraft
                        ? Loc.GetString("nc-medical-surgery-console-graft-required")
                        : string.Empty));
                ProcedureList.AddItem(text, metadata: entry);
            }
        }

        // A physiology update arrives frequently while the surgeon is reading the catalogue. Preserve the
        // local highlight until the server binds another plan, and never reset ItemList scrolling if the
        // catalogue itself did not change.
        var selected = state.Procedures.FirstOrDefault(entry =>
            state.SelectedProcedure == entry.Procedure && state.SelectedTarget == entry.TargetCategory);
        if (string.IsNullOrWhiteSpace(selected.Procedure.Id) &&
            _selected is { } local && state.Procedures.Contains(local))
        {
            selected = local;
        }

        _selected = string.IsNullOrWhiteSpace(selected.Procedure.Id) ? null : selected;
        for (var index = 0; index < ProcedureList.Count; index++)
        {
            var entry = state.Procedures[index];
            ProcedureList[index].Selected = _selected is { } active &&
                                             active.Procedure == entry.Procedure &&
                                             active.TargetCategory == entry.TargetCategory;
        }

        SelectButton.Disabled = _selected == null || state.ActiveProcedure != null;
    }

    private void UpdateSteps(NCSurgeryConsoleUpdateMessage state)
    {
        StepList.RemoveAllChildren();
        ToolList.RemoveAllChildren();
        NCSurgeryConsoleStepEntry? current = null;
        foreach (var step in state.Steps)
        {
            if (step.State == NCSurgeryConsoleStepState.Current)
                current = step;
            StepList.AddChild(BuildStepCard(step));
        }

        if (current is not { } currentStep)
        {
            RequiredToolView.SetPrototype(null);
            RequiredToolView.Visible = false;
            CurrentStepLabel.Text = Loc.GetString("nc-medical-surgery-console-no-step");
            StepMetaLabel.Text = Loc.GetString("nc-medical-surgery-console-select-procedure-hint");
            HeldToolLabel.Text = string.Empty;
            ExecuteButton.Disabled = true;
            return;
        }

        CurrentStepLabel.Text = Loc.GetString(
            "nc-medical-surgery-console-current-step",
            ("index", currentStep.Index + 1),
            ("name", StepName(currentStep)));
        StepMetaLabel.Text = Loc.GetString(
            "nc-medical-surgery-console-step-meta",
            ("duration", FormatDuration(currentStep.Duration)),
            ("access", LocalizedEnum("access", currentStep.RequiredAccessDepth)));
        var presentedTool = currentStep.Tools.FirstOrDefault(requirement => requirement.HeldToolMatches);
        if (string.IsNullOrWhiteSpace(presentedTool.RepresentativeTool.Id))
            presentedTool = currentStep.Tools.FirstOrDefault();
        if (!string.IsNullOrWhiteSpace(presentedTool.RepresentativeTool.Id))
        {
            RequiredToolView.SetPrototype(presentedTool.RepresentativeTool);
            RequiredToolView.Visible = true;
        }
        else
        {
            RequiredToolView.SetPrototype(null);
            RequiredToolView.Visible = false;
        }
        foreach (var requirement in currentStep.Tools)
        {
            var status = requirement.HeldToolMatches ? "✓" : "!";
            var detail = Loc.GetString(
                "nc-medical-surgery-console-tool-line",
                ("status", status),
                ("tool", requirement.RepresentativeToolName),
                ("capability", requirement.CapabilityName),
                ("quality", Percent(requirement.MinimumQuality)),
                ("sterility", Percent(requirement.MinimumSterility)),
                ("uses", requirement.ConsumedUses));
            ToolList.AddChild(new Label
            {
                Text = detail,
                FontColorOverride = requirement.HeldToolMatches
                    ? Color.FromHex("#73D98B")
                    : Color.FromHex("#E6C15D"),
            });
        }

        HeldToolLabel.Text = Loc.GetString(
            "nc-medical-surgery-console-held-tool",
            ("tool", state.HeldToolName ?? Loc.GetString("nc-medical-surgery-console-empty-hand")));
        ExecuteButton.Disabled = !currentStep.CanExecute || state.StepInProgress;
    }

    private PanelContainer BuildStepCard(NCSurgeryConsoleStepEntry step)
    {
        var marker = step.State switch
        {
            NCSurgeryConsoleStepState.Completed => "✓",
            NCSurgeryConsoleStepState.Current => "●",
            NCSurgeryConsoleStepState.Blocked => "×",
            _ => "○",
        };
        var color = step.State switch
        {
            NCSurgeryConsoleStepState.Completed => Color.FromHex("#73D98B"),
            NCSurgeryConsoleStepState.Current => Color.FromHex("#E6C15D"),
            NCSurgeryConsoleStepState.Blocked => Color.FromHex("#D66A6A"),
            _ => Color.FromHex("#8A969B"),
        };
        var tool = step.Tools.Count == 0
            ? Loc.GetString("nc-medical-surgery-console-no-tool")
            : string.Join(
                $" {Loc.GetString("nc-medical-surgery-console-tool-or")} ",
                step.Tools.Select(requirement => requirement.RepresentativeToolName));
        var row = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            SeparationOverride = 8,
        };
        row.AddChild(new Label
        {
            Text = marker,
            FontColorOverride = color,
            MinWidth = 18,
        });
        var text = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            HorizontalExpand = true,
        };
        text.AddChild(new Label
        {
            Text = $"{step.Index + 1}. {StepName(step)}",
            FontColorOverride = color,
        });
        text.AddChild(new Label
        {
            Text = Loc.GetString(
                "nc-medical-surgery-console-step-card-detail",
                ("tool", tool),
                ("duration", FormatDuration(step.Duration))),
        });
        row.AddChild(text);
        row.Margin = new Thickness(8, 6);
        var panel = new PanelContainer { StyleClasses = { "AngleRect" } };
        panel.AddChild(row);
        return panel;
    }

    private void RefreshProgress()
    {
        if (!_stepInProgress || _stepDuration <= TimeSpan.Zero)
        {
            StepProgress.Value = 0f;
            ProgressLabel.Text = string.Empty;
            return;
        }

        var remaining = _stepDeadline - _timing.RealTime;
        if (remaining < TimeSpan.Zero)
            remaining = TimeSpan.Zero;
        var elapsed = _stepDuration - remaining;
        StepProgress.Value = (float) Math.Clamp(elapsed.TotalSeconds / _stepDuration.TotalSeconds, 0d, 1d);
        ProgressLabel.Text = Loc.GetString(
            "nc-medical-surgery-console-progress",
            ("remaining", Math.Ceiling(remaining.TotalSeconds)));
    }

    private string ProcedureName(ProtoId<NCSurgeryProcedurePrototype> id)
    {
        var key = $"nc-medical-surgery-procedure-{PrototypeKey(id.Id, "NCSurgery")}";
        if (Loc.TryGetString(key, out var localized))
            return localized;

        return _prototypes.TryIndex(id, out NCSurgeryProcedurePrototype? procedure) ? procedure.Name : id.Id;
    }

    private static string StepName(NCSurgeryConsoleStepEntry step)
    {
        var key = $"nc-medical-surgery-step-{PrototypeKey(step.Step.Id, "NCSurgeryStep")}";
        return Loc.TryGetString(key, out var localized) ? localized : step.Name;
    }

    private static string PrototypeKey(string id, string prefix)
    {
        return ToKebabCase(id.StartsWith(prefix, StringComparison.Ordinal) ? id[prefix.Length..] : id);
    }

    private static string LocalizedEnum<T>(string category, T value) where T : struct, Enum
    {
        var key = $"nc-medical-surgery-{category}-{ToKebabCase(value.ToString())}";
        return Loc.TryGetString(key, out var localized) ? localized : Humanize(value.ToString());
    }

    private static string EmptyOr(string value, string fallback)
    {
        return string.IsNullOrWhiteSpace(value) ? Loc.GetString(fallback) : value;
    }

    private static string Percent(float value)
    {
        return $"{Math.Clamp(value, 0f, 1f) * 100f:0}%";
    }

    private static string FormatDuration(TimeSpan duration)
    {
        return Loc.GetString("nc-medical-surgery-console-duration", ("seconds", Math.Ceiling(duration.TotalSeconds)));
    }

    private static string Humanize(string value)
    {
        return string.Concat(value.Select((character, index) =>
            index > 0 && char.IsUpper(character)
                ? $" {char.ToLowerInvariant(character)}"
                : character.ToString()));
    }

    private static string ToKebabCase(string value)
    {
        return string.Concat(value.Select((character, index) =>
            index > 0 && char.IsUpper(character)
                ? $"-{char.ToLowerInvariant(character)}"
                : char.ToLowerInvariant(character).ToString()));
    }
}
