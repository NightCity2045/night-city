using System.Linq;
using Content.Client.UserInterface.Controls;
using Content.Shared._NC.Medical.Surgery;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._NC.Medical.Surgery;

[GenerateTypedNameReferences]
public sealed partial class NCSurgeryConsoleWindow : FancyWindow
{
    private readonly IPrototypeManager _prototypes;
    private NCSurgeryConsoleProcedureEntry? _selected;
    private bool _updating;

    public event Action<NCSurgeryConsoleProcedureEntry>? OnSelect;
    public event Action? OnClear;
    public event Action? OnRefresh;

    public NCSurgeryConsoleWindow(IPrototypeManager prototypes)
    {
        RobustXamlLoader.Load(this);
        _prototypes = prototypes;
        ProcedureList.OnItemSelected += args =>
        {
            if (_updating || ProcedureList[args.ItemIndex].Metadata is not NCSurgeryConsoleProcedureEntry entry)
                return;
            _selected = entry;
            SelectButton.Disabled = false;
        };
        SelectButton.OnPressed += _ =>
        {
            if (_selected is { } selected)
                OnSelect?.Invoke(selected);
        };
        ClearButton.OnPressed += _ => OnClear?.Invoke();
        RefreshButton.OnPressed += _ => OnRefresh?.Invoke();
    }

    public void UpdateState(NCSurgeryConsoleUpdateMessage state)
    {
        _updating = true;
        try
        {
            PatientLabel.Text = EmptyOr(state.PatientName, "nc-medical-surgery-console-none");
            FacilityLabel.Text = EmptyOr(state.FacilityName, "nc-medical-surgery-console-none");
            ZoneLabel.Text = state.SelectedZone is { } zone
                ? $"{zone.Id} / {state.SelectedRegion?.Id}"
                : Loc.GetString("nc-medical-surgery-console-zone-unselected");
            AccessLabel.Text = state.AccessDepth.ToString();
            GraftLabel.Text = state.GraftName ?? Loc.GetString("nc-medical-surgery-console-none");
            ActiveLabel.Text = state.ActiveProcedure is { } active
                ? Loc.GetString(
                    "nc-medical-surgery-console-active-value",
                    ("procedure", ProcedureName(active)),
                    ("step", state.ActiveStepIndex + 1),
                    ("state", state.ActiveState?.ToString() ?? string.Empty))
                : Loc.GetString("nc-medical-surgery-console-none");

            ProcedureList.Clear();
            _selected = null;
            foreach (var entry in state.Procedures)
            {
                var text = Loc.GetString(
                    "nc-medical-surgery-console-procedure-line",
                    ("procedure", ProcedureName(entry.Procedure)),
                    ("target", entry.TargetName),
                    ("graft", entry.RequiresGraft
                        ? Loc.GetString("nc-medical-surgery-console-graft-required")
                        : string.Empty));
                var item = ProcedureList.AddItem(text, metadata: entry);
                if (state.SelectedProcedure == entry.Procedure &&
                    state.SelectedTarget == entry.TargetCategory)
                {
                    item.Selected = true;
                    _selected = entry;
                }
            }

            SelectButton.Disabled = _selected == null;
            ClearButton.Disabled = state.SelectedProcedure == null;
            NoticeLabel.Visible = state.Notice != NCSurgeryConsoleNotice.None;
            NoticeLabel.Text = state.Notice == NCSurgeryConsoleNotice.None
                ? string.Empty
                : Loc.GetString($"nc-medical-surgery-console-notice-{ToKebabCase(state.Notice.ToString())}");
        }
        finally
        {
            _updating = false;
        }
    }

    private string ProcedureName(ProtoId<NCSurgeryProcedurePrototype> id)
    {
        return _prototypes.TryIndex(id, out NCSurgeryProcedurePrototype? procedure)
            ? procedure.Name
            : id.Id;
    }

    private static string EmptyOr(string value, string fallback)
    {
        return string.IsNullOrWhiteSpace(value) ? Loc.GetString(fallback) : value;
    }

    private static string ToKebabCase(string value)
    {
        return string.Concat(value.Select((character, index) =>
            index > 0 && char.IsUpper(character)
                ? $"-{char.ToLowerInvariant(character)}"
                : char.ToLowerInvariant(character).ToString()));
    }
}
