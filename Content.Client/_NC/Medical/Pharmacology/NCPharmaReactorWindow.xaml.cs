using System.Linq;
using System.Text;
using Content.Client.UserInterface.Controls;
using Content.Shared._NC.Medical.Pharmacology.Batch;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Utility;

namespace Content.Client._NC.Medical.Pharmacology;

/// <summary>
/// Reactor control window. It shows trends and windows rather than a number to hit exactly, so a run never
/// depends on network latency: the operator keeps a value inside a band and watches which way it moves.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class NCPharmaReactorWindow : FancyWindow
{
    [Dependency] private IPrototypeManager _prototypes = default!;

    private NCPharmaFormulaSummary[] _formulas = [];
    private int _units = 3;
    private bool _running;
    private bool _sourcePresent;
    private float _sourceUnits;
    private int _heater;
    private int _cooler;
    private bool _updating;

    public event Action<string, int>? StartRequested;
    public event Action<int, int, bool, bool, bool>? ControlsChanged;
    public event Action<NCPharmaReactorAction>? ActionRequested;

    public NCPharmaReactorWindow()
    {
        RobustXamlLoader.Load(this);

        UnitsDown.OnPressed += _ => ChangeUnits(-1);
        UnitsUp.OnPressed += _ => ChangeUnits(1);
        StartButton.OnPressed += _ => TryStart();
        HeaterDown.OnPressed += _ => ChangeLevel(ref _heater, -1);
        HeaterUp.OnPressed += _ => ChangeLevel(ref _heater, 1);
        CoolerDown.OnPressed += _ => ChangeLevel(ref _cooler, -1);
        CoolerUp.OnPressed += _ => ChangeLevel(ref _cooler, 1);
        StirringCheck.OnToggled += _ => SendControls();
        VentingCheck.OnToggled += _ => SendControls();
        VentilationCheck.OnToggled += _ => SendControls();
        CatalystButton.OnPressed += _ => ActionRequested?.Invoke(NCPharmaReactorAction.AddCatalyst);
        QuenchButton.OnPressed += _ => ActionRequested?.Invoke(NCPharmaReactorAction.Quench);
        StopButton.OnPressed += _ => ActionRequested?.Invoke(NCPharmaReactorAction.EmergencyStop);
        Refresh();
    }

    public void UpdateState(NCPharmaReactorState state)
    {
        _updating = true;
        _running = state.Running;
        _sourcePresent = state.SourcePresent;
        _sourceUnits = state.SourceUnits;
        _heater = state.Heater;
        _cooler = state.Cooler;
        StirringCheck.Pressed = state.Stirring;
        VentingCheck.Pressed = state.Venting;
        VentilationCheck.Pressed = state.Ventilation;
        UpdateFormulas(state.Formulas);

        SourceLabel.Text = state.SourcePresent
            ? Loc.GetString("nc-pharma-station-source-present",
                ("units", state.SourceUnits.ToString("0.#")),
                ("purity", state.SourcePurity.ToString("P0")))
            : Loc.GetString("nc-pharma-station-source-missing");

        _prototypes.TryIndex<NCPharmaReactionProfilePrototype>(state.Reaction, out var profile);
        var arrow = state.TemperatureRate > 0.3f ? "↑" : state.TemperatureRate < -0.3f ? "↓" : "→";
        TemperatureLabel.Text = Loc.GetString("nc-pharma-reactor-temperature",
            ("value", state.Temperature.ToString("0")), ("trend", arrow));
        TemperatureBar.Value = Math.Clamp(state.Temperature / 150f, 0f, 1f);
        PressureLabel.Text = Loc.GetString("nc-pharma-reactor-pressure", ("value", state.Pressure.ToString("0")));
        PressureBar.Value = Math.Clamp(state.Pressure / 300f, 0f, 1f);
        MixingLabel.Text = Loc.GetString("nc-pharma-reactor-mixing",
            ("value", state.Mixing.ToString("P0")), ("catalyst", state.Catalyst.ToString("P0")),
            ("left", state.CatalystLeft));
        ProgressLabel.Text = Loc.GetString("nc-pharma-reactor-progress", ("value", state.Progress.ToString("P0")));
        ProgressBar.Value = state.Progress;
        InstabilityLabel.Text = Loc.GetString("nc-pharma-reactor-instability", ("value", state.Instability.ToString("P0")));
        InstabilityBar.Value = state.Instability;
        WindowsLabel.SetMessage(FormattedMessage.FromMarkupPermissive(profile == null
            ? Loc.GetString("nc-pharma-reactor-no-run")
            : Loc.GetString("nc-pharma-reactor-windows",
                ("optimalMin", profile.OptimalMin.ToString("0")), ("optimalMax", profile.OptimalMax.ToString("0")),
                ("safeMin", profile.SafeMin.ToString("0")), ("safeMax", profile.SafeMax.ToString("0")),
                ("soft", profile.PressureSoftLimit.ToString("0")), ("hard", profile.PressureHardLimit.ToString("0")))));
        WarningsLabel.SetMessage(FormattedMessage.FromMarkupPermissive(BuildWarnings(state.Warnings)));
        NoticeLabel.Text = state.Notice == NCPharmaReactorNotice.None
            ? string.Empty
            : Loc.GetString(NoticeKey(state.Notice));
        _updating = false;
        Refresh();
    }

    private void UpdateFormulas(NCPharmaFormulaSummary[] formulas)
    {
        var previous = SelectedFormula()?.Id;
        if (formulas.Select(formula => formula.Id).SequenceEqual(_formulas.Select(formula => formula.Id)))
            return;

        _formulas = formulas;
        FormulaSelector.Clear();
        for (var i = 0; i < _formulas.Length; i++)
        {
            var formula = _formulas[i];
            var name = formula.CustomName ?? (formula.NameKey != null ? Loc.GetString(formula.NameKey) : formula.Id);
            FormulaSelector.AddItem(Loc.GetString("nc-pharma-station-formula-title",
                ("name", name), ("version", formula.Version)), i);
        }

        var index = previous == null ? 0 : Array.FindIndex(_formulas, formula => formula.Id == previous);
        if (_formulas.Length > 0)
            FormulaSelector.SelectId(Math.Max(0, index));
    }

    private NCPharmaFormulaSummary? SelectedFormula() =>
        FormulaSelector.SelectedId >= 0 && FormulaSelector.SelectedId < _formulas.Length
            ? _formulas[FormulaSelector.SelectedId]
            : null;

    private void ChangeUnits(int delta)
    {
        _units = Math.Clamp(_units + delta, 1, 8);
        Refresh();
    }

    private void ChangeLevel(ref int level, int delta)
    {
        if (!_running)
            return;

        level = Math.Clamp(level + delta, 0, NCReactorMath.MaximumLevel);
        SendControls();
        Refresh();
    }

    private void SendControls()
    {
        if (_updating)
            return;

        ControlsChanged?.Invoke(_heater, _cooler, StirringCheck.Pressed, VentingCheck.Pressed, VentilationCheck.Pressed);
    }

    private void TryStart()
    {
        if (SelectedFormula() is { } formula)
            StartRequested?.Invoke(formula.Id, _units);
    }

    private void Refresh()
    {
        UnitsValue.Text = _units.ToString();
        HeaterValue.Text = _heater.ToString();
        CoolerValue.Text = _cooler.ToString();
        StartButton.Disabled = _running || !_sourcePresent || _sourceUnits < _units || SelectedFormula() == null;
        foreach (var control in new Robust.Client.UserInterface.Controls.BaseButton[]
                 {
                     HeaterDown, HeaterUp, CoolerDown, CoolerUp, StirringCheck, VentingCheck, VentilationCheck,
                     CatalystButton, QuenchButton, StopButton,
                 })
        {
            control.Disabled = !_running;
        }
    }

    private static string BuildWarnings(NCReactorWarnings warnings)
    {
        if (warnings == NCReactorWarnings.None)
            return string.Empty;

        var text = new StringBuilder();
        void Add(NCReactorWarnings flag, string key)
        {
            if (warnings.HasFlag(flag))
                text.AppendLine(Loc.GetString(key));
        }

        Add(NCReactorWarnings.HighTemperature, "nc-pharma-reactor-warning-high-temperature");
        Add(NCReactorWarnings.NearSafeLimit, "nc-pharma-reactor-warning-near-limit");
        Add(NCReactorWarnings.HighPressure, "nc-pharma-reactor-warning-high-pressure");
        Add(NCReactorWarnings.PoorMixing, "nc-pharma-reactor-warning-poor-mixing");
        Add(NCReactorWarnings.Runaway, "nc-pharma-reactor-warning-runaway");
        Add(NCReactorWarnings.InstabilityRising, "nc-pharma-reactor-warning-instability");
        return text.ToString();
    }

    private static string NoticeKey(NCPharmaReactorNotice notice) => notice switch
    {
        NCPharmaReactorNotice.NoSource => "nc-pharma-station-notice-no-source",
        NCPharmaReactorNotice.NotEnoughSource => "nc-pharma-station-notice-not-enough",
        NCPharmaReactorNotice.NotExperimental => "nc-pharma-reactor-notice-not-experimental",
        NCPharmaReactorNotice.UnitsLimit => "nc-pharma-reactor-notice-units-limit",
        NCPharmaReactorNotice.Busy => "nc-pharma-station-notice-busy",
        NCPharmaReactorNotice.Started => "nc-pharma-reactor-notice-started",
        NCPharmaReactorNotice.Finished => "nc-pharma-reactor-notice-finished",
        NCPharmaReactorNotice.Stopped => "nc-pharma-reactor-notice-stopped",
        NCPharmaReactorNotice.Quenched => "nc-pharma-reactor-notice-quenched",
        NCPharmaReactorNotice.Degraded => "nc-pharma-reactor-notice-degraded",
        NCPharmaReactorNotice.Released => "nc-pharma-reactor-notice-released",
        NCPharmaReactorNotice.Ruptured => "nc-pharma-reactor-notice-ruptured",
        NCPharmaReactorNotice.CatalystUsed => "nc-pharma-reactor-notice-catalyst",
        NCPharmaReactorNotice.NoCatalystLeft => "nc-pharma-reactor-notice-no-catalyst",
        _ => "nc-pharma-station-notice-invalid",
    };
}
