using System.Linq;
using Content.Client.UserInterface.Controls;
using Content.Shared._NC.Medical.Pharmacology.Batch;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Utility;

namespace Content.Client._NC.Medical.Pharmacology;

/// <summary>
/// Production window. Formulas and production modes are prototypes the client already has, so this window can
/// show a plain forecast of yield, time and price without asking the server for anything.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class NCPharmaStationWindow : FancyWindow
{
    [Dependency] private IPrototypeManager _prototypes = default!;

    private readonly List<NCPharmaFormulaPrototype> _formulas = [];
    private readonly List<NCPharmaProductionProfilePrototype> _profiles = [];
    private int _units = 5;
    private float _sourceUnits;
    private bool _busy;
    private bool _sourcePresent;

    public event Action<string, string, int>? StartRequested;

    public NCPharmaStationWindow()
    {
        RobustXamlLoader.Load(this);

        _formulas.AddRange(_prototypes.EnumeratePrototypes<NCPharmaFormulaPrototype>()
            .Where(formula => formula.RegulatoryStatus is not
                (NCPharmaRegulatoryStatus.Banned or NCPharmaRegulatoryStatus.Recalled))
            .OrderBy(formula => Loc.GetString(formula.Name), StringComparer.CurrentCulture));
        _profiles.AddRange(_prototypes.EnumeratePrototypes<NCPharmaProductionProfilePrototype>()
            .OrderByDescending(profile => profile.YieldMultiplier));

        foreach (var formula in _formulas)
            FormulaSelector.AddItem(Loc.GetString(formula.Name));
        foreach (var profile in _profiles)
            ProfileSelector.AddItem(Loc.GetString(profile.Name));

        if (_formulas.Count > 0)
            FormulaSelector.SelectId(0);
        if (_profiles.Count > 0)
            ProfileSelector.SelectId(Math.Max(0, _profiles.FindIndex(profile => profile.ID == "NCPharmaProductionStandard")));

        FormulaSelector.OnItemSelected += args =>
        {
            FormulaSelector.SelectId(args.Id);
            Refresh();
        };
        ProfileSelector.OnItemSelected += args =>
        {
            ProfileSelector.SelectId(args.Id);
            Refresh();
        };
        UnitsDown.OnPressed += _ => ChangeUnits(-1);
        UnitsUp.OnPressed += _ => ChangeUnits(1);
        StartButton.OnPressed += _ => TryStart();
        Refresh();
    }

    public void UpdateState(NCPharmaStationState state)
    {
        _sourcePresent = state.SourcePresent;
        _sourceUnits = state.SourceUnits;
        _busy = state.Busy;
        Progress.Value = state.Progress;
        SourceLabel.Text = state.SourcePresent
            ? Loc.GetString("nc-pharma-station-source-present",
                ("units", state.SourceUnits.ToString("0.#")),
                ("purity", state.SourcePurity.ToString("P0")))
            : Loc.GetString("nc-pharma-station-source-missing");
        NoticeLabel.Text = NoticeText(state.Notice);
        Refresh();
    }

    private void ChangeUnits(int delta)
    {
        _units = Math.Clamp(_units + delta, 1, 40);
        Refresh();
    }

    private void TryStart()
    {
        if (SelectedFormula() is not { } formula || SelectedProfile() is not { } profile)
            return;

        StartRequested?.Invoke(formula.ID, profile.ID, _units);
    }

    private NCPharmaFormulaPrototype? SelectedFormula() =>
        FormulaSelector.SelectedId >= 0 && FormulaSelector.SelectedId < _formulas.Count
            ? _formulas[FormulaSelector.SelectedId]
            : null;

    private NCPharmaProductionProfilePrototype? SelectedProfile() =>
        ProfileSelector.SelectedId >= 0 && ProfileSelector.SelectedId < _profiles.Count
            ? _profiles[ProfileSelector.SelectedId]
            : null;

    private void Refresh()
    {
        UnitsValue.Text = _units.ToString();
        var formula = SelectedFormula();
        var profile = SelectedProfile();
        StartButton.Disabled = _busy || !_sourcePresent || _sourceUnits < _units || formula == null || profile == null;
        if (formula == null || profile == null)
            return;

        FormulaCard.SetMessage(FormattedMessage.FromMarkupPermissive(FormulaCardText(formula)));
        var doses = (int) MathF.Floor(_units * profile.YieldMultiplier);
        Forecast.SetMessage(FormattedMessage.FromMarkupPermissive(Loc.GetString(
            "nc-pharma-station-forecast",
            ("doses", doses),
            ("seconds", (int) profile.Duration.TotalSeconds),
            ("cost", profile.CostMultiplier.ToString("0.##")))));
    }

    private string FormulaCardText(NCPharmaFormulaPrototype formula)
    {
        var form = _prototypes.TryIndex(formula.DeliveryForm, out var delivery)
            ? Loc.GetString(delivery.Name)
            : formula.DeliveryForm.Id;
        var modifiers = formula.Modifiers.Count == 0
            ? Loc.GetString("nc-pharma-station-no-modifiers")
            : string.Join(", ", formula.Modifiers.Select(id =>
                _prototypes.TryIndex(id, out var modifier) ? Loc.GetString(modifier.Name) : id.Id));
        return Loc.GetString(
            "nc-pharma-station-formula-card",
            ("version", formula.Version),
            ("form", form),
            ("concentration", formula.TargetConcentration.ToString("0.#")),
            ("modifiers", modifiers),
            ("status", Loc.GetString(NCPharmaTextKeys.RegulatoryStatus(formula.RegulatoryStatus))));
    }

    private static string NoticeText(NCPharmaStationNotice notice) => notice switch
    {
        NCPharmaStationNotice.NoSource => Loc.GetString("nc-pharma-station-notice-no-source"),
        NCPharmaStationNotice.NotEnoughSource => Loc.GetString("nc-pharma-station-notice-not-enough"),
        NCPharmaStationNotice.InvalidRequest => Loc.GetString("nc-pharma-station-notice-invalid"),
        NCPharmaStationNotice.Busy => Loc.GetString("nc-pharma-station-notice-busy"),
        NCPharmaStationNotice.Started => Loc.GetString("nc-pharma-station-notice-started"),
        NCPharmaStationNotice.Finished => Loc.GetString("nc-pharma-station-notice-finished"),
        NCPharmaStationNotice.Failed => Loc.GetString("nc-pharma-station-notice-failed"),
        _ => string.Empty,
    };
}
