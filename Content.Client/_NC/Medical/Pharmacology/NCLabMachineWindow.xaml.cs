using Content.Client.UserInterface.Controls;
using Content.Shared._NC.Medical.Pharmacology.Lab;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._NC.Medical.Pharmacology;

/// <summary>
/// The window of a laboratory machine: what it is doing, what stands in its slots with a button to take each out,
/// what it reports, and the button that starts its procedure.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class NCLabMachineWindow : FancyWindow
{
    [Dependency] private IEntityManager _entities = default!;

    public event Action? StartRequested;
    public event Action? CancelRequested;
    public event Action<string>? EjectRequested;

    public NCLabMachineWindow()
    {
        RobustXamlLoader.Load(this);
        StartButton.OnPressed += _ => StartRequested?.Invoke();
        CancelButton.OnPressed += _ => CancelRequested?.Invoke();
    }

    public void UpdateState(NCLabMachineState state)
    {
        StatusLabel.Text = Loc.GetString(!state.Powered
            ? "nc-lab-machine-ui-status-unpowered"
            : $"nc-lab-machine-ui-status-{state.Phase.ToString().ToLowerInvariant()}");
        Progress.Value = state.Phase == NCLabMachinePhase.Idle ? 0f : state.Progress;
        RemainingLabel.Text = state.Phase == NCLabMachinePhase.Working
            ? Loc.GetString("nc-lab-machine-ui-remaining", ("seconds", state.RemainingSeconds))
            : string.Empty;

        StartButton.Text = Loc.GetString(state.StartKey);
        StartButton.Disabled = !state.CanStart;
        CancelButton.Disabled = state.Phase != NCLabMachinePhase.Working;
        CancelButton.Visible = state.Phase == NCLabMachinePhase.Working;

        SlotList.RemoveAllChildren();
        foreach (var slot in state.Slots)
        {
            var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 6 };
            var item = slot.Item is { } net && _entities.TryGetEntity(net, out var uid)
                ? _entities.GetComponent<MetaDataComponent>(uid.Value).EntityName
                : Loc.GetString("nc-lab-machine-ui-slot-empty");
            row.AddChild(new Label
            {
                Text = Loc.GetString("nc-lab-machine-ui-slot-row",
                    ("slot", Loc.TryGetString(slot.NameKey, out var name) ? name : slot.Id), ("item", item)),
                HorizontalExpand = true,
                ClipText = true,
            });
            var eject = new Button
            {
                Text = Loc.GetString("nc-lab-machine-ui-eject"),
                Disabled = slot.Item == null || state.Phase == NCLabMachinePhase.Working,
            };
            var id = slot.Id;
            eject.OnPressed += _ => EjectRequested?.Invoke(id);
            row.AddChild(eject);
            SlotList.AddChild(row);
        }

        ReadoutList.RemoveAllChildren();
        ReadoutHeading.Visible = state.Readouts.Length > 0;
        foreach (var readout in state.Readouts)
        {
            ReadoutList.AddChild(new Label
            {
                Text = Loc.GetString("nc-lab-machine-ui-readout-row",
                    ("label", Loc.GetString(readout.LabelKey)),
                    ("value", readout.ValueKey != null ? Loc.GetString(readout.ValueKey) : readout.Value)),
            });
        }
    }
}
