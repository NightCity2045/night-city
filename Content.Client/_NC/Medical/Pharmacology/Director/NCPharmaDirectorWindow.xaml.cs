using System.Linq;
using Content.Client.UserInterface.Controls;
using Content.Shared._NC.Medical.Pharmacology.Director;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._NC.Medical.Pharmacology.Director;

[GenerateTypedNameReferences]
public sealed partial class NCPharmaDirectorWindow : FancyWindow
{
    private NCPharmaDirectorRow[][] _tabs = [];
    private NCPharmaDirectorTab _tab;

    public event Action? OnRefresh;
    public event Action<Guid>? OnRecall;
    public event Action<Guid>? OnContaminate;
    public event Action<string, byte>? OnGrant;

    public NCPharmaDirectorWindow()
    {
        RobustXamlLoader.Load(this);

        foreach (var tab in Enum.GetValues<NCPharmaDirectorTab>())
            TabSelector.AddItem(Loc.GetString("nc-pharma-director-tab-" + tab.ToString().ToLowerInvariant()), (int) tab);

        TabSelector.OnItemSelected += args =>
        {
            TabSelector.SelectId(args.Id);
            _tab = (NCPharmaDirectorTab) args.Id;
            Fill();
        };
        RowList.OnItemSelected += _ => ShowDetail();
        RowList.OnItemDeselected += _ => ShowDetail();
        RefreshButton.OnPressed += _ => OnRefresh?.Invoke();
        RecallButton.OnPressed += _ =>
        {
            if (SelectedBatch() is { } id)
                OnRecall?.Invoke(id);
        };
        ContaminateButton.OnPressed += _ =>
        {
            if (SelectedBatch() is { } id)
                OnContaminate?.Invoke(id);
        };
        ChemicalButton.OnPressed += _ => Grant(1);
        InVitroButton.OnPressed += _ => Grant(2);
        InVivoButton.OnPressed += _ => Grant(3);
        TabSelector.SelectId(0);
        UpdateButtons();
    }

    public void SetState(NCPharmaDirectorEuiState state)
    {
        _tabs = state.Tabs;
        Fill();
    }

    private NCPharmaDirectorRow? Selected()
    {
        var selected = RowList.GetSelected().FirstOrDefault();
        if (selected == null || (int) _tab >= _tabs.Length)
            return null;

        var index = RowList.IndexOf(selected);
        var rows = _tabs[(int) _tab];
        return index >= 0 && index < rows.Length ? rows[index] : null;
    }

    private Guid? SelectedBatch() =>
        _tab == NCPharmaDirectorTab.Batches && Selected() is { } row && Guid.TryParse(row.Id, out var id) ? id : null;

    private void Grant(byte level)
    {
        if (_tab == NCPharmaDirectorTab.Compounds && Selected() is { } row)
            OnGrant?.Invoke(row.Id, level);
    }

    private void Fill()
    {
        RowList.Clear();
        if ((int) _tab < _tabs.Length)
        {
            foreach (var row in _tabs[(int) _tab])
                RowList.AddItem(row.Text);
        }

        ShowDetail();
    }

    private void ShowDetail()
    {
        DetailLabel.SetMessage(FormattedMessage.FromUnformatted(Selected()?.Detail ?? string.Empty));
        UpdateButtons();
    }

    private void UpdateButtons()
    {
        var batch = _tab == NCPharmaDirectorTab.Batches && Selected() != null;
        var compound = _tab == NCPharmaDirectorTab.Compounds && Selected() != null;
        RecallButton.Disabled = !batch;
        ContaminateButton.Disabled = !batch;
        ChemicalButton.Disabled = !compound;
        InVitroButton.Disabled = !compound;
        InVivoButton.Disabled = !compound;
    }
}
