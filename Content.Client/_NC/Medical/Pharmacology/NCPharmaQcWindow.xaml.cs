using System.Text;
using Content.Client.UserInterface.Controls;
using Content.Shared._NC.Medical.Pharmacology.Batch;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._NC.Medical.Pharmacology;

/// <summary>
/// Laboratory analyzer window. It compares what the label claims with what the analyzer actually measured,
/// and shows a value only for tests that were performed.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class NCPharmaQcWindow : FancyWindow
{
    private bool _canRun;

    public event Action<NCPharmaQcTests>? RunRequested;

    public NCPharmaQcWindow()
    {
        RobustXamlLoader.Load(this);
        RunButton.OnPressed += _ => RunRequested?.Invoke(SelectedTests());
    }

    public void UpdateState(NCPharmaQcMachineState state)
    {
        _canRun = state.SamplePresent && state.DosesLeft > 0 && !state.Busy;
        RunButton.Disabled = !_canRun;
        Progress.Value = state.Progress;
        NoticeLabel.Text = NoticeText(state.Notice);

        SampleLabel.SetMessage(FormattedMessage.FromMarkupPermissive(state.Label is { } label
            ? Loc.GetString(
                "nc-pharma-qc-sample-info",
                ("code", label.BatchCode),
                ("doses", state.DosesLeft),
                ("state", Loc.GetString(NCPharmaTextKeys.QcState(state.BatchState))))
            : Loc.GetString("nc-pharma-qc-sample-missing")));

        ResultLabel.SetMessage(FormattedMessage.FromMarkupPermissive(
            state.Report is { } report && state.Label is { } claimed
                ? BuildResult(report, claimed)
                : Loc.GetString("nc-pharma-qc-no-result")));
    }

    private NCPharmaQcTests SelectedTests()
    {
        var tests = NCPharmaQcTests.None;
        if (ConcentrationCheck.Pressed)
            tests |= NCPharmaQcTests.Concentration;
        if (PurityCheck.Pressed)
            tests |= NCPharmaQcTests.Purity;
        if (SterilityCheck.Pressed)
            tests |= NCPharmaQcTests.Sterility;
        if (HomogeneityCheck.Pressed)
            tests |= NCPharmaQcTests.Homogeneity;
        if (StabilityCheck.Pressed)
            tests |= NCPharmaQcTests.Stability;
        return tests;
    }

    private static string BuildResult(NCPharmaQcReport report, NCPharmaLabel label)
    {
        var text = new StringBuilder();
        AppendRow(text, report, NCPharmaQcTests.Concentration, "nc-pharma-qc-test-concentration",
            report.Concentration, label.Concentration.ToString("0.##"), "0.##");
        AppendRow(text, report, NCPharmaQcTests.Purity, "nc-pharma-qc-test-purity",
            report.Purity, label.Purity.ToString("P0"), "P1");
        AppendRow(text, report, NCPharmaQcTests.Sterility, "nc-pharma-qc-test-sterility",
            report.Sterility, Loc.GetString(label.Sterile ? "nc-pharma-label-sterile" : "nc-pharma-label-not-sterile"), "P1");
        AppendRow(text, report, NCPharmaQcTests.Homogeneity, "nc-pharma-qc-test-homogeneity",
            report.Homogeneity, "-", "P1");
        AppendRow(text, report, NCPharmaQcTests.Stability, "nc-pharma-qc-test-stability",
            report.Stability, "-", "P1");
        return text.ToString();
    }

    private static void AppendRow(
        StringBuilder text,
        NCPharmaQcReport report,
        NCPharmaQcTests test,
        string nameKey,
        float? value,
        string claimed,
        string format)
    {
        var name = Loc.GetString(nameKey);
        if (!report.Performed.HasFlag(test) || value == null)
        {
            text.AppendLine(Loc.GetString("nc-pharma-qc-row-not-tested", ("name", name)));
            return;
        }

        text.AppendLine(Loc.GetString(
            report.Failed.HasFlag(test) ? "nc-pharma-qc-row-failed" : "nc-pharma-qc-row-passed",
            ("name", name),
            ("label", claimed),
            ("value", value.Value.ToString(format))));
    }

    private static string NoticeText(NCPharmaQcNotice notice) => notice switch
    {
        NCPharmaQcNotice.NoSample => Loc.GetString("nc-pharma-qc-notice-no-sample"),
        NCPharmaQcNotice.NoDoseLeft => Loc.GetString("nc-pharma-qc-notice-no-dose"),
        NCPharmaQcNotice.UnknownBatch => Loc.GetString("nc-pharma-qc-notice-unknown-batch"),
        NCPharmaQcNotice.NoTestsSelected => Loc.GetString("nc-pharma-qc-notice-no-tests"),
        NCPharmaQcNotice.Busy => Loc.GetString("nc-pharma-qc-notice-busy"),
        NCPharmaQcNotice.Started => Loc.GetString("nc-pharma-qc-notice-started"),
        NCPharmaQcNotice.Finished => Loc.GetString("nc-pharma-qc-notice-finished"),
        _ => string.Empty,
    };
}
