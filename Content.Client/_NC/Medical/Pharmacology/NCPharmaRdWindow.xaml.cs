    private void ShowNodeInfo(string? node)
    {
        NodeInfo.SetMessage(FormattedMessage.FromMarkupPermissive(node == null
            ? Loc.GetString("nc-pharma-rd-node-hint")
            : NodeText(node)));
    }

    private string NodeText(string node)
    {
        if (node.StartsWith("core:", StringComparison.Ordinal) && !_availableCores.Contains(node[5..]))
        {
            var known = _formulas.FirstOrDefault(formula => formula.Compound == node[5..] || formula.SecondCompound == node[5..]);
            return Loc.GetString("nc-pharma-rd-core-locked",
                ("formula", known.Id == null ? CoreName(node[5..]) : FormulaName(known)));
        }

        var state = StateOf(node);
        var title = node switch
        {
            _ when node.StartsWith("core:", StringComparison.Ordinal) => CoreName(node[5..]),
            _ when node.StartsWith("form:", StringComparison.Ordinal) =>
                _prototypes.TryIndex<NCPharmaDeliveryFormPrototype>(node[5..], out var form) ? Loc.GetString(form.Name) : node,
            _ when node.StartsWith("mod:", StringComparison.Ordinal) =>
                _prototypes.TryIndex<NCPharmaModifierPrototype>(node[4..], out var modifier) ? Loc.GetString(modifier.Name) : node,
            _ when node.StartsWith("profile:", StringComparison.Ordinal) =>
                _prototypes.TryIndex<NCPharmaProductionProfilePrototype>(node[8..], out var profile) ? Loc.GetString(profile.Name) : node,
            _ => node,
        };

        var header = Loc.GetString("nc-pharma-rd-node-header",
            ("name", title),
            ("state", Loc.GetString($"nc-pharma-rd-node-state-{state.ToString().ToLowerInvariant()}")));
        if (state == NCPharmaNodeState.Unknown)
            return header + "\n" + Loc.GetString("nc-pharma-rd-node-unknown");

        var effects = NodeEffects(node, state == NCPharmaNodeState.Confirmed);
        return effects.Count == 0 ? header : header + "\n" + string.Join("\n", effects);
    }

    private List<string> NodeEffects(string node, bool exact)
    {
        var lines = new List<string>();

        void Add(string what, float value, bool higherIsDifferent = true)
        {
            if (MathF.Abs(value - 1f) < 0.005f)
                return;
            lines.Add(exact
                ? Loc.GetString("nc-pharma-rd-effect-exact", ("what", Loc.GetString($"nc-pharma-rd-effect-{what}")), ("value", value.ToString("0.##")))
                : Loc.GetString(value > 1f ? "nc-pharma-rd-effect-up" : "nc-pharma-rd-effect-down", ("what", Loc.GetString($"nc-pharma-rd-effect-{what}"))));
        }

        void AddDelta(string what, float value)
        {
            if (MathF.Abs(value) < 0.0005f)
                return;
            lines.Add(exact
                ? Loc.GetString("nc-pharma-rd-effect-delta", ("what", Loc.GetString($"nc-pharma-rd-effect-{what}")), ("value", value.ToString("+0.##;-0.##")))
                : Loc.GetString(value > 0f ? "nc-pharma-rd-effect-up" : "nc-pharma-rd-effect-down", ("what", Loc.GetString($"nc-pharma-rd-effect-{what}"))));
        }

        if (node.StartsWith("mod:", StringComparison.Ordinal) && _prototypes.TryIndex<NCPharmaModifierPrototype>(node[4..], out var modifier))
        {
            Add("peak", modifier.ConcentrationMultiplier);
            Add("toxicity", modifier.ToxicityMultiplier);
            Add("absorption", modifier.AbsorptionMultiplier);
            Add("clearance", modifier.ClearanceMultiplier);
            Add("cost", modifier.CostMultiplier);
            AddDelta("stability", modifier.StabilityDelta);
            AddDelta("purity", modifier.PurityDelta);
            if (modifier.LocalTissueFraction > 0f)
                lines.Add(Loc.GetString("nc-pharma-rd-effect-local"));
            if (modifier.MaskingStrength > 0f)
                lines.Add(Loc.GetString("nc-pharma-rd-effect-masking"));
            if (modifier.RequiredReagent is { } required)
            {
                var reagentName = _prototypes.TryIndex<ReagentPrototype>(required.Id, out var reagent)
                    ? reagent.LocalizedName
                    : required.Id;
                lines.Add(Loc.GetString("nc-pharma-rd-effect-requires",
                    ("amount", modifier.RequiredAmount.ToString("0.#")), ("item", reagentName)));
            }
        }
        else if (node.StartsWith("form:", StringComparison.Ordinal) && _prototypes.TryIndex<NCPharmaDeliveryFormPrototype>(node[5..], out var form))
        {
            Add("peak", form.ConcentrationMultiplier);
            Add("sterility-risk", form.SterilityRiskMultiplier);
            Add("contamination", form.AdulterantMultiplier);
            lines.Add(Loc.GetString("nc-pharma-rd-effect-onset", ("seconds", form.AdministrationDelay.TotalSeconds.ToString("0.#"))));
            lines.Add(Loc.GetString("nc-pharma-rd-effect-absorbed", ("seconds", form.AbsorptionDuration.TotalSeconds.ToString("0"))));
        }
        else if (node.StartsWith("profile:", StringComparison.Ordinal) && _prototypes.TryIndex<NCPharmaProductionProfilePrototype>(node[8..], out var profile))
        {
            Add("yield", profile.YieldMultiplier);
            Add("purity", profile.PurityMultiplier);
            Add("sterility", profile.SterilityMultiplier);
            Add("homogeneity", profile.HomogeneityMultiplier);
            Add("stability", profile.StabilityMultiplier);
            Add("cost", profile.CostMultiplier);
            lines.Add(Loc.GetString("nc-pharma-rd-effect-time", ("seconds", ((int) profile.Duration.TotalSeconds).ToString())));
        }
        else if (node.StartsWith("core:", StringComparison.Ordinal) && exact &&
                 _prototypes.TryIndex<NCDrugProfilePrototype>(node[5..], out var compound))
        {
            lines.Add(Loc.GetString("nc-pharma-rd-effect-window",
                ("therapeutic", compound.TherapeuticConcentration.ToString("0.#")),
                ("toxic", compound.ToxicConcentration.ToString("0.#"))));
        }

        return lines;
    }

    private void RefreshForecast()
    {
        ForecastLabel.SetMessage(FormattedMessage.FromMarkupPermissive(string.Empty));
        if (_chosenCores.Count == 0 || _chosenForm == null || _chosenProfile == null ||
            !_prototypes.TryIndex<NCDrugProfilePrototype>(_chosenCores[0], out var first) ||
            !_prototypes.TryIndex<NCPharmaDeliveryFormPrototype>(_chosenForm, out var form) ||
            !_prototypes.TryIndex<NCPharmaProductionProfilePrototype>(_chosenProfile, out var profile))
        {
            return;
        }

        // The forecast knows only what the laboratory has confirmed. An untested node is left out of it, and the
        // line says so: the real batch will include it.
        if (StateOf(NCPharmaNodeIds.Form(_chosenForm)) != NCPharmaNodeState.Confirmed ||
            StateOf(NCPharmaNodeIds.Profile(_chosenProfile)) != NCPharmaNodeState.Confirmed)
        {
            ForecastLabel.SetMessage(FormattedMessage.FromMarkupPermissive(Loc.GetString("nc-pharma-rd-forecast-unknown")));
            return;
        }

        var known = new List<NCPharmaModifierPrototype>();
        var excluded = new List<string>();
        foreach (var id in _chosenModifiers)
        {
            if (!_prototypes.TryIndex<NCPharmaModifierPrototype>(id, out var modifier))
                continue;
            if (StateOf(NCPharmaNodeIds.Modifier(id)) == NCPharmaNodeState.Confirmed)
                known.Add(modifier);
            else
                excluded.Add(Loc.GetString(modifier.Name));
        }

        var candidate = NCPharmaFormulaPrototype.Create(
            "candidate", Loc.GetString("nc-pharma-rd-candidate"), 1, first.ID,
            form.ID, _concentration,
            [.. known.Select(modifier => new ProtoId<NCPharmaModifierPrototype>(modifier.ID))],
            profile.ID, 0.85f, NCPharmaRegulatoryStatus.Experimental, null, null, null,
            null, _chosenCores.Count > 1 ? _chosenCores[1] : null);
        var forecast = NCPharmaBatchMath.Forecast(candidate, known, form, profile, first.ToxicConcentration);
        var margin = float.IsInfinity(forecast.ToxicMargin) ? "∞" : forecast.ToxicMargin.ToString("0.##");
        var text = Loc.GetString(
            "nc-pharma-rd-forecast",
            ("peak", forecast.PeakConcentration.ToString("0.##")),
            ("margin", margin),
            ("seconds", ((int) forecast.Absorption.TotalSeconds).ToString()),
            ("toxicity", forecast.ToxicityMultiplier.ToString("0.##")),
            ("cost", forecast.CostMultiplier.ToString("0.##")));
        if (excluded.Count > 0)
            text += "\n" + Loc.GetString("nc-pharma-rd-forecast-excluded", ("nodes", string.Join(", ", excluded)));
        ForecastLabel.SetMessage(FormattedMessage.FromMarkupPermissive(text));
    }

