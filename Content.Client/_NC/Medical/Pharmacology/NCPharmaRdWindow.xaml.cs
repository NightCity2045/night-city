using System.Linq;
using System.Text;
using Content.Client.UserInterface.Controls;
using Content.Shared._NC.Medical.Pharmacology;
using Content.Shared._NC.Medical.Pharmacology.Batch;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Utility;

namespace Content.Client._NC.Medical.Pharmacology;

/// <summary>
/// Formula development window. The forecast is computed here from the same prototypes and the same rules the
/// server uses, so the designer sees the price of a change before asking for it.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class NCPharmaRdWindow : FancyWindow
{
    [Dependency] private IPrototypeManager _prototypes = default!;

    private readonly List<NCPharmaDeliveryFormPrototype> _forms = [];
    private readonly List<NCPharmaModifierPrototype> _modifiers = [];
    private NCPharmaFormulaSummary[] _formulas = [];
    private int _selected = -1;
    private float _concentration;
    private bool _updating;

    public event Action<string>? SelectRequested;
    public event Action<string, string, string, float, string[]>? DeriveRequested;
    public event Action<string>? ApproveRequested;
    public event Action<string, string>? NoteRequested;

    public NCPharmaRdWindow()
    {
        RobustXamlLoader.Load(this);

        _forms.AddRange(_prototypes.EnumeratePrototypes<NCPharmaDeliveryFormPrototype>().OrderBy(form => form.ID, StringComparer.Ordinal));
        _modifiers.AddRange(_prototypes.EnumeratePrototypes<NCPharmaModifierPrototype>().OrderBy(modifier => modifier.ID, StringComparer.Ordinal));
        foreach (var form in _forms)
            DeliverySelector.AddItem(Loc.GetString(form.Name));
        foreach (var selector in new[] { FirstModifier, SecondModifier })
        {
            selector.AddItem(Loc.GetString("nc-pharma-rd-no-modifier"), 0);
            for (var i = 0; i < _modifiers.Count; i++)
                selector.AddItem(Loc.GetString(_modifiers[i].Name), i + 1);
            selector.SelectId(0);
            selector.OnItemSelected += args =>
            {
                selector.SelectId(args.Id);
                RefreshForecast();
            };
        }

        DeliverySelector.OnItemSelected += args =>
        {
            DeliverySelector.SelectId(args.Id);
            RefreshForecast();
        };
        FormulaList.OnItemSelected += args => SelectFormula(args.ItemIndex);
        ConcentrationDown.OnPressed += _ => ChangeConcentration(-0.5f);
        ConcentrationUp.OnPressed += _ => ChangeConcentration(0.5f);
        CreateButton.OnPressed += _ => TryCreate();
        NoteButton.OnPressed += _ =>
        {
            if (Selected() is { } noted && NoteEdit.Text.Trim().Length > 0)
            {
                NoteRequested?.Invoke(noted.Id, NoteEdit.Text);
                NoteEdit.Text = string.Empty;
            }
        };
        ApproveButton.OnPressed += _ =>
        {
            if (Selected() is { } formula)
                ApproveRequested?.Invoke(formula.Id);
        };
        Refresh();
    }

    public void UpdateState(NCPharmaRdState state)
    {
        var previous = Selected()?.Id;
        _formulas = state.Formulas;
        _updating = true;
        FormulaList.Clear();
        foreach (var formula in _formulas)
            FormulaList.AddItem(FormulaTitle(formula));
        _selected = previous == null ? -1 : Array.FindIndex(_formulas, formula => formula.Id == previous);
        if (_selected >= 0)
            FormulaList[_selected].Selected = true;
        _updating = false;

        NoticeLabel.Text = state.Notice == NCPharmaRdNotice.None
            ? string.Empty
            : Loc.GetString(NCPharmaTextKeys.RdNotice(state.Notice));
        JournalLabel.SetMessage(FormattedMessage.FromMarkupPermissive(BuildJournal(state.Journal)));
        Refresh();
    }

    private NCPharmaFormulaSummary? Selected() =>
        _selected >= 0 && _selected < _formulas.Length ? _formulas[_selected] : null;

    private void SelectFormula(int index)
    {
        if (_updating || index < 0 || index >= _formulas.Length)
            return;

        _selected = index;
        var formula = _formulas[index];
        _concentration = formula.TargetConcentration;
        var formIndex = _forms.FindIndex(form => form.ID == formula.DeliveryForm);
        DeliverySelector.SelectId(Math.Max(0, formIndex));
        SetModifier(FirstModifier, formula.Modifiers.ElementAtOrDefault(0));
        SetModifier(SecondModifier, formula.Modifiers.ElementAtOrDefault(1));
        NameEdit.Text = string.Empty;
        SelectRequested?.Invoke(formula.Id);
        Refresh();
    }

    private void SetModifier(Robust.Client.UserInterface.Controls.OptionButton selector, string? modifierId)
    {
        var index = modifierId == null ? -1 : _modifiers.FindIndex(modifier => modifier.ID == modifierId);
        selector.SelectId(index + 1);
    }

    private void ChangeConcentration(float delta)
    {
        if (Selected() == null)
            return;

        _concentration = MathF.Max(0.5f, _concentration + delta);
        Refresh();
    }

    private string[] ChosenModifiers() =>
        new[] { FirstModifier.SelectedId, SecondModifier.SelectedId }
            .Where(id => id > 0 && id <= _modifiers.Count)
            .Select(id => _modifiers[id - 1].ID)
            .Distinct()
            .ToArray();

    private void TryCreate()
    {
        if (Selected() is not { } parent || DeliverySelector.SelectedId < 0 || DeliverySelector.SelectedId >= _forms.Count)
            return;

        DeriveRequested?.Invoke(
            parent.Id,
            NameEdit.Text.Trim(),
            _forms[DeliverySelector.SelectedId].ID,
            _concentration,
            ChosenModifiers());
    }

    private void Refresh()
    {
        var formula = Selected();
        ConcentrationValue.Text = formula == null ? "-" : _concentration.ToString("0.#");
        CreateButton.Disabled = formula == null;
        ApproveButton.Disabled = formula is not { CanApprove: true };
        NoteButton.Disabled = formula == null;
        SelectedCard.SetMessage(FormattedMessage.FromMarkupPermissive(formula is { } selected
            ? BuildCard(selected)
            : Loc.GetString("nc-pharma-rd-select-hint")));
        RefreshForecast();
    }

    private void RefreshForecast()
    {
        if (Selected() is not { } formula ||
            DeliverySelector.SelectedId < 0 || DeliverySelector.SelectedId >= _forms.Count ||
            formula.ToxicConcentration <= 0f ||
            !_prototypes.TryIndex<NCPharmaProductionProfilePrototype>(formula.DefaultProfile, out var profile))
        {
            ForecastLabel.SetMessage(FormattedMessage.FromMarkupPermissive(string.Empty));
            return;
        }

        var modifiers = ChosenModifiers()
            .Select(id => _prototypes.Index<NCPharmaModifierPrototype>(id))
            .ToList();
        var candidate = NCPharmaFormulaPrototype.Create(
            formula.Id, Loc.GetString("nc-pharma-rd-candidate"), formula.Version, formula.Compound,
            _forms[DeliverySelector.SelectedId].ID, _concentration,
            [.. modifiers.Select(modifier => new ProtoId<NCPharmaModifierPrototype>(modifier.ID))],
            formula.DefaultProfile, 0.85f, NCPharmaRegulatoryStatus.Experimental, null, null, null);
        var forecast = NCPharmaBatchMath.Forecast(
            candidate, modifiers, _forms[DeliverySelector.SelectedId], profile, formula.ToxicConcentration);
        var margin = float.IsInfinity(forecast.ToxicMargin) ? "∞" : forecast.ToxicMargin.ToString("0.##");
        ForecastLabel.SetMessage(FormattedMessage.FromMarkupPermissive(Loc.GetString(
            "nc-pharma-rd-forecast",
            ("peak", forecast.PeakConcentration.ToString("0.##")),
            ("margin", margin),
            ("seconds", ((int) forecast.Absorption.TotalSeconds).ToString()),
            ("toxicity", forecast.ToxicityMultiplier.ToString("0.##")),
            ("cost", forecast.CostMultiplier.ToString("0.##")))));
    }

    private string FormulaTitle(NCPharmaFormulaSummary formula) =>
        Loc.GetString("nc-pharma-rd-formula-title",
            ("name", FormulaName(formula)),
            ("version", formula.Version),
            ("status", Loc.GetString(NCPharmaTextKeys.RegulatoryStatus(formula.Status))));

    private static string FormulaName(NCPharmaFormulaSummary formula) =>
        formula.CustomName ?? (formula.NameKey != null ? Loc.GetString(formula.NameKey) : formula.Id);

    private string BuildCard(NCPharmaFormulaSummary formula)
    {
        var form = _prototypes.TryIndex<NCPharmaDeliveryFormPrototype>(formula.DeliveryForm, out var delivery)
            ? Loc.GetString(delivery.Name)
            : formula.DeliveryForm;
        var modifiers = formula.Modifiers.Length == 0
            ? Loc.GetString("nc-pharma-station-no-modifiers")
            : string.Join(", ", formula.Modifiers.Select(id =>
                _prototypes.TryIndex<NCPharmaModifierPrototype>(id, out var modifier) ? Loc.GetString(modifier.Name) : id));
        return Loc.GetString("nc-pharma-rd-card",
            ("name", FormulaName(formula)),
            ("version", formula.Version),
            ("form", form),
            ("concentration", formula.TargetConcentration.ToString("0.#")),
            ("modifiers", modifiers),
            ("status", Loc.GetString(NCPharmaTextKeys.RegulatoryStatus(formula.Status))));
    }

    private string BuildJournal(NCPharmaJournalSummary[] journal)
    {
        if (journal.Length == 0)
            return Loc.GetString("nc-pharma-rd-journal-empty");

        var text = new StringBuilder();
        foreach (var entry in journal)
        {
            text.AppendLine(Loc.GetString("nc-pharma-rd-journal-row",
                ("kind", Loc.GetString(NCPharmaTextKeys.JournalKind(entry.Kind))),
                ("formula", entry.FormulaId),
                ("batch", entry.BatchCode.Length == 0 ? "-" : entry.BatchCode),
                ("actor", entry.Actor),
                ("detail", entry.Detail)));
        }

        return text.ToString();
    }
}
