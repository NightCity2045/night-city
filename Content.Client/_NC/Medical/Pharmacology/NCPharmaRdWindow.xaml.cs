/// <summary>
/// Formula development window. A formula is built on a tree of five branches: the core, the delivery, the
/// kinetics, the safety and the production. A node the laboratory has not tested stays hidden, and the forecast
/// leaves its effect out, so the only way to learn what a node does is to make a batch with it.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class NCPharmaRdWindow : FancyWindow
{
    private static readonly Color SuspectedColor = Color.FromHex("#FFC95C");
    private static readonly Color UnknownColor = Color.FromHex("#7A8A8C");

    [Dependency] private IPrototypeManager _prototypes = default!;

    private readonly List<NCPharmaDeliveryFormPrototype> _forms = [];
    private readonly List<NCPharmaModifierPrototype> _modifiers = [];
    private readonly List<NCPharmaProductionProfilePrototype> _profiles = [];
    private readonly Dictionary<string, NCPharmaNodeState> _knowledge = new();
    private readonly List<(string Node, Button Button)> _nodes = [];
    private readonly List<string> _chosenCores = [];
    private readonly List<string> _chosenModifiers = [];
    private string? _chosenForm;
    private string? _chosenProfile;
    private BoxContainer _coreColumn = default!;
    private Label _concentrationValue = default!;
    private NCPharmaFormulaSummary[] _formulas = [];
    private string[] _availableCores = [];
    private int _selected = -1;
    private float _concentration;
    private bool _updating;

    public event Action<string>? SelectRequested;
    public event Action<string?, string, string?, string, float, string[], string>? ComposeRequested;
    public event Action<string>? ApproveRequested;
    public event Action<string, string>? NoteRequested;

    public NCPharmaRdWindow()
    {
        RobustXamlLoader.Load(this);

        _forms.AddRange(_prototypes.EnumeratePrototypes<NCPharmaDeliveryFormPrototype>().OrderBy(form => form.ID, StringComparer.Ordinal));
        _modifiers.AddRange(_prototypes.EnumeratePrototypes<NCPharmaModifierPrototype>().OrderBy(modifier => modifier.ID, StringComparer.Ordinal));
        _profiles.AddRange(_prototypes.EnumeratePrototypes<NCPharmaProductionProfilePrototype>()
            .Where(profile => profile.ID != "NCPharmaProductionManual")
            .OrderByDescending(profile => profile.YieldMultiplier));
        BuildTree();

        FormulaList.OnItemSelected += args => SelectFormula(args.ItemIndex);
        CreateButton.OnPressed += _ => TryCreate();
        NoteButton.OnPressed += _ =>
        {
            if (Selected() is { } noted && NoteEdit.Text.Trim().Length > 0)
            {
                NoteRequested?.Invoke(noted.Id, NoteEdit.Text);
                NoteEdit.Text = string.Empty;
            }
        };
        ApproveButton.OnPressed += _ =>
        {
            if (Selected() is { } formula)
                ApproveRequested?.Invoke(formula.Id);
        };
        Refresh();
    }

    public void UpdateState(NCPharmaRdState state)
    {
        var previous = Selected()?.Id;
        _formulas = state.Formulas;
        _availableCores = state.Cores;
        _knowledge.Clear();
        foreach (var entry in state.Knowledge)
            _knowledge[entry.Id] = entry.State;

        _updating = true;
        FormulaList.Clear();
        foreach (var formula in _formulas)
            FormulaList.AddItem(FormulaTitle(formula));
        _selected = previous == null ? -1 : Array.FindIndex(_formulas, formula => formula.Id == previous);
        if (_selected >= 0)
            FormulaList[_selected].Selected = true;
        _updating = false;

        RebuildCoreColumn();
        NoticeLabel.Text = state.Notice == NCPharmaRdNotice.None
            ? string.Empty
            : Loc.GetString(NCPharmaTextKeys.RdNotice(state.Notice));
        JournalLabel.SetMessage(FormattedMessage.FromMarkupPermissive(BuildJournal(state.Journal)));
        RestyleNodes();
        Refresh();
    }

    // ---- the tree ----------------------------------------------------------------------------------------

    private void BuildTree()
    {
        var core = Column(NCPharmaNodeBranch.Core);
        _coreColumn = core;

        var delivery = Column(NCPharmaNodeBranch.Delivery);
        foreach (var form in _forms)
            AddNode(delivery, NCPharmaNodeIds.Form(form.ID), Loc.GetString(form.Name), () => ChooseForm(form.ID));

        var kinetics = Column(NCPharmaNodeBranch.Kinetics);
        var concentration = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 4 };
        var down = new Button { Text = "−", MinWidth = 34 };
        var up = new Button { Text = "+", MinWidth = 34 };
        _concentrationValue = new Label { MinWidth = 60, Align = Label.AlignMode.Center };
        down.OnPressed += _ => ChangeConcentration(-0.5f);
        up.OnPressed += _ => ChangeConcentration(0.5f);
        concentration.AddChild(new Label { Text = Loc.GetString("nc-pharma-rd-concentration") });
        concentration.AddChild(down);
        concentration.AddChild(_concentrationValue);
        concentration.AddChild(up);
        kinetics.AddChild(concentration);
        AddModifierNodes(kinetics, NCPharmaNodeBranch.Kinetics);

        var safety = Column(NCPharmaNodeBranch.Safety);
        AddModifierNodes(safety, NCPharmaNodeBranch.Safety);

        var production = Column(NCPharmaNodeBranch.Production);
        foreach (var profile in _profiles)
            AddNode(production, NCPharmaNodeIds.Profile(profile.ID), Loc.GetString(profile.Name), () => ChooseProfile(profile.ID));
        AddModifierNodes(production, NCPharmaNodeBranch.Production);
    }

    private BoxContainer Column(NCPharmaNodeBranch branch)
    {
        var content = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, SeparationOverride = 3 };
        var scroll = new ScrollContainer { HScrollEnabled = false, VerticalExpand = true };
        scroll.AddChild(content);
        var column = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            HorizontalExpand = true,
            SizeFlagsStretchRatio = 1f,
            SeparationOverride = 4,
        };
        column.AddChild(new Label
        {
            Text = Loc.GetString($"nc-pharma-rd-branch-{branch.ToString().ToLowerInvariant()}"),
            StyleClasses = { "LabelHeading" },
        });
        column.AddChild(scroll);
        TreeColumns.AddChild(column);
        return content;
    }

    private void AddModifierNodes(BoxContainer column, NCPharmaNodeBranch branch)
    {
        foreach (var modifier in _modifiers.Where(modifier => modifier.Branch == branch))
            AddNode(column, NCPharmaNodeIds.Modifier(modifier.ID), Loc.GetString(modifier.Name), () => ToggleModifier(modifier.ID));
    }

    private void AddNode(BoxContainer column, string node, string title, Action pressed)
    {
        var button = new Button { Text = title, ToggleMode = true, HorizontalExpand = true, ClipText = true };
        button.OnPressed += _ =>
        {
            pressed();
            ShowNodeInfo(node);
            SyncSelection();
            Refresh();
        };
        column.AddChild(button);
        _nodes.Add((node, button));
    }

    private void RebuildCoreColumn()
    {
        _nodes.RemoveAll(entry =>
        {
            var isCore = entry.Node.StartsWith("core:", StringComparison.Ordinal);
            if (isCore)
                entry.Button.Dispose();
            return isCore;
        });
        _coreColumn.RemoveAllChildren();
        foreach (var core in _availableCores)
        {
            var id = core;
            AddNode(_coreColumn, NCPharmaNodeIds.Core(id), CoreName(id), () => ToggleCore(id));
        }

        _chosenCores.RemoveAll(core => !_availableCores.Contains(core));
        SyncSelection();
    }

    private string CoreName(string id) =>
        Loc.TryGetString(NCLabText.DrugKey(id), out var name) ? name : id;

    private NCPharmaNodeState StateOf(string node) =>
        _knowledge.TryGetValue(node, out var state) ? state : NCPharmaNodeState.Unknown;

    /// <summary>Colors the nodes by what the laboratory knows: dim when untested, amber when suspected.</summary>
    private void RestyleNodes()
    {
        foreach (var (node, button) in _nodes)
        {
            var state = StateOf(node);
            button.Label.FontColorOverride = state switch
            {
                NCPharmaNodeState.Unknown => UnknownColor,
                NCPharmaNodeState.Suspected => SuspectedColor,
                _ => null,
            };
            button.ToolTip = NodeText(node);
        }
    }

    private void SyncSelection()
    {
        foreach (var (node, button) in _nodes)
        {
            button.Pressed = node switch
            {
                _ when node.StartsWith("core:", StringComparison.Ordinal) => _chosenCores.Contains(node[5..]),
                _ when node.StartsWith("form:", StringComparison.Ordinal) => _chosenForm == node[5..],
                _ when node.StartsWith("mod:", StringComparison.Ordinal) => _chosenModifiers.Contains(node[4..]),
                _ when node.StartsWith("profile:", StringComparison.Ordinal) => _chosenProfile == node[8..],
                _ => false,
            };
        }

        _concentrationValue.Text = _chosenCores.Count == 0 ? "-" : _concentration.ToString("0.#");
    }

    private void ToggleCore(string id)
    {
        if (!_chosenCores.Remove(id))
        {
            _chosenCores.Add(id);
            if (_chosenCores.Count > 2)
                _chosenCores.RemoveAt(0);
        }

        if (_chosenCores.Count > 0 && _concentration <= 0f)
            ResetConcentration();
    }

    private void ChooseForm(string id) => _chosenForm = id;

    private void ChooseProfile(string id) => _chosenProfile = id;

    private void ToggleModifier(string id)
    {
        if (!_chosenModifiers.Remove(id))
        {
            _chosenModifiers.Add(id);
            if (_chosenModifiers.Count > NCPharmaBatchMath.MaximumModifiers)
                _chosenModifiers.RemoveAt(0);
        }
    }

    private void ResetConcentration()
    {
        _concentration = _chosenCores.Count > 0 && _prototypes.TryIndex<NCDrugProfilePrototype>(_chosenCores[0], out var core)
            ? core.TherapeuticConcentration
            : 5f;
    }

    private void ChangeConcentration(float delta)
    {
        if (_chosenCores.Count == 0)
            return;

        _concentration = MathF.Max(0.5f, _concentration + delta);
        SyncSelection();
        Refresh();
    }

    // ---- selection and creation --------------------------------------------------------------------------

    private NCPharmaFormulaSummary? Selected() =>
        _selected >= 0 && _selected < _formulas.Length ? _formulas[_selected] : null;

    private void SelectFormula(int index)
    {
        if (_updating || index < 0 || index >= _formulas.Length)
            return;

        _selected = index;
        var formula = _formulas[index];
        _chosenCores.Clear();
        _chosenCores.Add(formula.Compound);
        if (formula.SecondCompound != null)
            _chosenCores.Add(formula.SecondCompound);
        _chosenForm = formula.DeliveryForm;
        _chosenProfile = formula.DefaultProfile;
        _chosenModifiers.Clear();
        _chosenModifiers.AddRange(formula.Modifiers);
        _concentration = formula.TargetConcentration;
        SelectRequested?.Invoke(formula.Id);
        SyncSelection();
        Refresh();
    }

    private void TryCreate()
    {
        if (_chosenCores.Count == 0 || _chosenForm == null || _chosenProfile == null)
            return;

        ComposeRequested?.Invoke(
            Selected()?.Id,
            _chosenCores[0],
            _chosenCores.Count > 1 ? _chosenCores[1] : null,
            _chosenForm,
            _concentration,
            _chosenModifiers.ToArray(),
            _chosenProfile);
    }

    private void Refresh()
    {
        var formula = Selected();
        CreateButton.Disabled = _chosenCores.Count == 0 || _chosenForm == null || _chosenProfile == null;
        ApproveButton.Disabled = formula is not { CanApprove: true };
        NoteButton.Disabled = formula == null;
        SelectedCard.SetMessage(FormattedMessage.FromMarkupPermissive(formula is { } selected
            ? BuildCard(selected)
            : Loc.GetString("nc-pharma-rd-select-hint")));
        _concentrationValue.Text = _chosenCores.Count == 0 ? "-" : _concentration.ToString("0.#");
        RefreshForecast();
    }

    // ---- what the laboratory knows about a node ----------------------------------------------------------

    private void ShowNodeInfo(string node)
    {
        NodeInfo.SetMessage(FormattedMessage.FromMarkupPermissive(NodeText(node)));
    }

    private string NodeText(string node)
    {
        var state = StateOf(node);
        var title = node switch
        {
            _ when node.StartsWith("core:", StringComparison.Ordinal) => CoreName(node[5..]),
            _ when node.StartsWith("form:", StringComparison.Ordinal) =>
                _prototypes.TryIndex<NCPharmaDeliveryFormPrototype>(node[5..], out var form) ? Loc.GetString(form.Name) : node,
            _ when node.StartsWith("mod:", StringComparison.Ordinal) =>
                _prototypes.TryIndex<NCPharmaModifierPrototype>(node[4..], out var modifier) ? Loc.GetString(modifier.Name) : node,
            _ when node.StartsWith("profile:", StringComparison.Ordinal) =>
                _prototypes.TryIndex<NCPharmaProductionProfilePrototype>(node[8..], out var profile) ? Loc.GetString(profile.Name) : node,
            _ => node,
        };

        var header = Loc.GetString("nc-pharma-rd-node-header",
            ("name", title),
            ("state", Loc.GetString($"nc-pharma-rd-node-state-{state.ToString().ToLowerInvariant()}")));
        if (state == NCPharmaNodeState.Unknown)
            return header + "\n" + Loc.GetString("nc-pharma-rd-node-unknown");

        var effects = NodeEffects(node, state == NCPharmaNodeState.Confirmed);
        return effects.Count == 0 ? header : header + "\n" + string.Join("\n", effects);
    }

    private List<string> NodeEffects(string node, bool exact)
    {
        var lines = new List<string>();

        void Add(string what, float value, bool higherIsDifferent = true)
        {
            if (MathF.Abs(value - 1f) < 0.005f)
                return;
            lines.Add(exact
                ? Loc.GetString("nc-pharma-rd-effect-exact", ("what", Loc.GetString($"nc-pharma-rd-effect-{what}")), ("value", value.ToString("0.##")))
                : Loc.GetString(value > 1f ? "nc-pharma-rd-effect-up" : "nc-pharma-rd-effect-down", ("what", Loc.GetString($"nc-pharma-rd-effect-{what}"))));
        }

        void AddDelta(string what, float value)
        {
            if (MathF.Abs(value) < 0.0005f)
                return;
            lines.Add(exact
                ? Loc.GetString("nc-pharma-rd-effect-delta", ("what", Loc.GetString($"nc-pharma-rd-effect-{what}")), ("value", value.ToString("+0.##;-0.##")))
                : Loc.GetString(value > 0f ? "nc-pharma-rd-effect-up" : "nc-pharma-rd-effect-down", ("what", Loc.GetString($"nc-pharma-rd-effect-{what}"))));
        }

        if (node.StartsWith("mod:", StringComparison.Ordinal) && _prototypes.TryIndex<NCPharmaModifierPrototype>(node[4..], out var modifier))
        {
            Add("peak", modifier.ConcentrationMultiplier);
            Add("toxicity", modifier.ToxicityMultiplier);
            Add("absorption", modifier.AbsorptionMultiplier);
            Add("clearance", modifier.ClearanceMultiplier);
            Add("cost", modifier.CostMultiplier);
            AddDelta("stability", modifier.StabilityDelta);
            AddDelta("purity", modifier.PurityDelta);
            if (modifier.LocalTissueFraction > 0f)
                lines.Add(Loc.GetString("nc-pharma-rd-effect-local"));
            if (modifier.MaskingStrength > 0f)
                lines.Add(Loc.GetString("nc-pharma-rd-effect-masking"));
            if (modifier.RequiredItem is { } required)
            {
                var itemName = _prototypes.TryIndex<EntityPrototype>(required.Id, out var entity) ? entity.Name : required.Id;
                lines.Add(Loc.GetString("nc-pharma-rd-effect-requires", ("item", itemName)));
            }
        }
        else if (node.StartsWith("form:", StringComparison.Ordinal) && _prototypes.TryIndex<NCPharmaDeliveryFormPrototype>(node[5..], out var form))
        {
            Add("peak", form.ConcentrationMultiplier);
            Add("sterility-risk", form.SterilityRiskMultiplier);
            Add("contamination", form.AdulterantMultiplier);
            lines.Add(Loc.GetString("nc-pharma-rd-effect-onset", ("seconds", form.AdministrationDelay.TotalSeconds.ToString("0.#"))));
            lines.Add(Loc.GetString("nc-pharma-rd-effect-absorbed", ("seconds", form.AbsorptionDuration.TotalSeconds.ToString("0"))));
        }
        else if (node.StartsWith("profile:", StringComparison.Ordinal) && _prototypes.TryIndex<NCPharmaProductionProfilePrototype>(node[8..], out var profile))
        {
            Add("yield", profile.YieldMultiplier);
            Add("purity", profile.PurityMultiplier);
            Add("sterility", profile.SterilityMultiplier);
            Add("homogeneity", profile.HomogeneityMultiplier);
            Add("stability", profile.StabilityMultiplier);
            Add("cost", profile.CostMultiplier);
            lines.Add(Loc.GetString("nc-pharma-rd-effect-time", ("seconds", ((int) profile.Duration.TotalSeconds).ToString())));
        }
        else if (node.StartsWith("core:", StringComparison.Ordinal) && exact &&
                 _prototypes.TryIndex<NCDrugProfilePrototype>(node[5..], out var compound))
        {
            lines.Add(Loc.GetString("nc-pharma-rd-effect-window",
                ("therapeutic", compound.TherapeuticConcentration.ToString("0.#")),
                ("toxic", compound.ToxicConcentration.ToString("0.#"))));
        }

        return lines;
    }

    private void RefreshForecast()
    {
        ForecastLabel.SetMessage(FormattedMessage.FromMarkupPermissive(string.Empty));
        if (_chosenCores.Count == 0 || _chosenForm == null || _chosenProfile == null ||
            !_prototypes.TryIndex<NCDrugProfilePrototype>(_chosenCores[0], out var first) ||
            !_prototypes.TryIndex<NCPharmaDeliveryFormPrototype>(_chosenForm, out var form) ||
            !_prototypes.TryIndex<NCPharmaProductionProfilePrototype>(_chosenProfile, out var profile))
        {
            return;
        }

        // The forecast knows only what the laboratory has confirmed. An untested node is left out of it, and the
        // line says so: the real batch will include it.
        if (StateOf(NCPharmaNodeIds.Form(_chosenForm)) != NCPharmaNodeState.Confirmed ||
            StateOf(NCPharmaNodeIds.Profile(_chosenProfile)) != NCPharmaNodeState.Confirmed)
        {
            ForecastLabel.SetMessage(FormattedMessage.FromMarkupPermissive(Loc.GetString("nc-pharma-rd-forecast-unknown")));
            return;
        }

        var known = new List<NCPharmaModifierPrototype>();
        var excluded = new List<string>();
        foreach (var id in _chosenModifiers)
        {
            if (!_prototypes.TryIndex<NCPharmaModifierPrototype>(id, out var modifier))
                continue;
            if (StateOf(NCPharmaNodeIds.Modifier(id)) == NCPharmaNodeState.Confirmed)
                known.Add(modifier);
            else
                excluded.Add(Loc.GetString(modifier.Name));
        }

        var candidate = NCPharmaFormulaPrototype.Create(
            "candidate", Loc.GetString("nc-pharma-rd-candidate"), 1, first.ID,
            form.ID, _concentration,
            [.. known.Select(modifier => new ProtoId<NCPharmaModifierPrototype>(modifier.ID))],
            profile.ID, 0.85f, NCPharmaRegulatoryStatus.Experimental, null, null, null,
            null, _chosenCores.Count > 1 ? _chosenCores[1] : null);
        var forecast = NCPharmaBatchMath.Forecast(candidate, known, form, profile, first.ToxicConcentration);
        var margin = float.IsInfinity(forecast.ToxicMargin) ? "∞" : forecast.ToxicMargin.ToString("0.##");
        var text = Loc.GetString(
            "nc-pharma-rd-forecast",
            ("peak", forecast.PeakConcentration.ToString("0.##")),
            ("margin", margin),
            ("seconds", ((int) forecast.Absorption.TotalSeconds).ToString()),
            ("toxicity", forecast.ToxicityMultiplier.ToString("0.##")),
            ("cost", forecast.CostMultiplier.ToString("0.##")));
        if (excluded.Count > 0)
            text += "\n" + Loc.GetString("nc-pharma-rd-forecast-excluded", ("nodes", string.Join(", ", excluded)));
        ForecastLabel.SetMessage(FormattedMessage.FromMarkupPermissive(text));
    }

    // ---- text --------------------------------------------------------------------------------------------

    private string FormulaTitle(NCPharmaFormulaSummary formula) =>
        Loc.GetString("nc-pharma-rd-formula-title",
            ("name", FormulaName(formula)),
            ("version", formula.Version),
            ("status", Loc.GetString(NCPharmaTextKeys.RegulatoryStatus(formula.Status))));

    private string FormulaName(NCPharmaFormulaSummary formula)
    {
        var name = formula.CustomName ?? (formula.NameKey != null ? Loc.GetString(formula.NameKey) : formula.Id);
        return formula.SecondCompound == null ? name : name + " + " + CoreName(formula.SecondCompound);
    }

    private string BuildCard(NCPharmaFormulaSummary formula)
    {
        var form = _prototypes.TryIndex<NCPharmaDeliveryFormPrototype>(formula.DeliveryForm, out var delivery)
            ? Loc.GetString(delivery.Name)
            : formula.DeliveryForm;
        var modifiers = formula.Modifiers.Length == 0
            ? Loc.GetString("nc-pharma-station-no-modifiers")
            : string.Join(", ", formula.Modifiers.Select(id =>
                _prototypes.TryIndex<NCPharmaModifierPrototype>(id, out var modifier) ? Loc.GetString(modifier.Name) : id));
        return Loc.GetString("nc-pharma-rd-card",
            ("name", FormulaName(formula)),
            ("version", formula.Version),
            ("form", form),
            ("concentration", formula.TargetConcentration.ToString("0.#")),
            ("modifiers", modifiers),
            ("status", Loc.GetString(NCPharmaTextKeys.RegulatoryStatus(formula.Status))));
    }

    private string BuildJournal(NCPharmaJournalSummary[] journal)
    {
        if (journal.Length == 0)
            return Loc.GetString("nc-pharma-rd-journal-empty");

        var text = new StringBuilder();
        foreach (var entry in journal)
        {
            text.AppendLine(Loc.GetString("nc-pharma-rd-journal-row",
                ("kind", Loc.GetString(NCPharmaTextKeys.JournalKind(entry.Kind))),
                ("formula", entry.FormulaId),
                ("batch", entry.BatchCode.Length == 0 ? "-" : entry.BatchCode),
                ("actor", entry.Actor),
                ("detail", entry.Detail)));
        }

        return text.ToString();
    }
}
