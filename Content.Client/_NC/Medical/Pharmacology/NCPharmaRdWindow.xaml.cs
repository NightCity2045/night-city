/// <summary>
/// Formula development window. The first tab is a map of the formula tree: a core, a delivery form, kinetics, safety
/// and a production mode, built from nothing. The second tab invents a new compound from ingredient reagents in the
/// console's beaker. The third keeps the lines of existing formulas, their notes and their journal. A node the
/// laboratory has not tested stays marked, and the forecast leaves its effect out, so the only way to learn what a
/// node does is to make a batch with it.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class NCPharmaRdWindow : FancyWindow
{
    private const float UnitsPerIngredient = 5f;

    [Dependency] private IPrototypeManager _prototypes = default!;

    private readonly List<NCPharmaDeliveryFormPrototype> _forms = [];
    private readonly List<NCPharmaModifierPrototype> _modifiers = [];
    private readonly List<NCPharmaProductionProfilePrototype> _profiles = [];
    private readonly List<NCPharmaIngredientPrototype> _ingredients = [];
    private readonly Dictionary<string, NCPharmaNodeState> _knowledge = new();
    private readonly List<NCPharmaTreeNode> _treeNodes = [];
    private readonly List<string> _chosenCores = [];
    private readonly List<string> _chosenModifiers = [];
    private readonly List<string> _chosenIngredients = [];
    private readonly List<(string Reagent, Button Button, string Name)> _ingredientButtons = [];
    private string? _chosenForm;
    private string? _chosenProfile;
    private string? _infoNode;
    private NCPharmaFormulaSummary[] _formulas = [];
    private string[] _availableCores = [];
    private NCPharmaReagentAmount[] _beaker = [];
    private bool _hasBeaker;
    private bool _hasChip;
    private int _researched;
    private int _selected = -1;
    private float _concentration;
    private bool _updating;

    public event Action<string>? SelectRequested;
    public event Action<string?, string, string?, string, float, string[], string>? ComposeRequested;
    public event Action<string>? ApproveRequested;
    public event Action<string, string>? NoteRequested;
    public event Action<string[]>? InventRequested;

    public NCPharmaRdWindow()
    {
        RobustXamlLoader.Load(this);

        _forms.AddRange(_prototypes.EnumeratePrototypes<NCPharmaDeliveryFormPrototype>().OrderBy(form => form.ID, StringComparer.Ordinal));
        _modifiers.AddRange(_prototypes.EnumeratePrototypes<NCPharmaModifierPrototype>().OrderBy(modifier => modifier.ID, StringComparer.Ordinal));
        _profiles.AddRange(_prototypes.EnumeratePrototypes<NCPharmaProductionProfilePrototype>()
            .Where(profile => profile.ID != "NCPharmaProductionManual")
            .OrderByDescending(profile => profile.YieldMultiplier));
        _ingredients.AddRange(_prototypes.EnumeratePrototypes<NCPharmaIngredientPrototype>()
            .OrderBy(ingredient => IngredientName(ingredient), StringComparer.CurrentCulture));

        TabContainer.SetTabTitle(TreeTab, Loc.GetString("nc-pharma-rd-tab-tree"));
        TabContainer.SetTabTitle(InventTab, Loc.GetString("nc-pharma-rd-tab-invent"));
        TabContainer.SetTabTitle(LinesTab, Loc.GetString("nc-pharma-rd-tab-lines"));

        Canvas.HubTitle = Loc.GetString("nc-pharma-rd-hub");
        Canvas.NodePressed += OnNodePressed;
        Canvas.NodeHovered += node => ShowNodeInfo(node ?? _infoNode);
        Canvas.HubPressed += ClearFormula;
        BuildIngredientList();
        RebuildNodes();

        FormulaList.OnItemSelected += args => SelectFormula(args.ItemIndex);
        NewButton.OnPressed += _ => ClearFormula();
        CreateButton.OnPressed += _ => TryCreate();
        ConcentrationDown.OnPressed += _ => ChangeConcentration(-0.5f);
        ConcentrationUp.OnPressed += _ => ChangeConcentration(0.5f);
        ContinueButton.OnPressed += _ =>
        {
            Tabs.CurrentTab = 0;
            Refresh();
        };
        InventButton.OnPressed += _ => InventRequested?.Invoke(_chosenIngredients.ToArray());
        NoteButton.OnPressed += _ =>
        {
            if (Selected() is { } noted && NoteEdit.Text.Trim().Length > 0)
            {
                NoteRequested?.Invoke(noted.Id, NoteEdit.Text);
                NoteEdit.Text = string.Empty;
            }
        };
        ApproveButton.OnPressed += _ =>
        {
            if (Selected() is { } formula)
                ApproveRequested?.Invoke(formula.Id);
        };
        Refresh();
    }

    public void UpdateState(NCPharmaRdState state)
    {
        var previous = Selected()?.Id;
        _formulas = state.Formulas;
        _availableCores = state.Cores;
        _beaker = state.Beaker;
        _hasBeaker = state.HasBeaker;
        _hasChip = state.HasChip;
        _researched = state.Researched;
        _knowledge.Clear();
        foreach (var entry in state.Knowledge)
            _knowledge[entry.Id] = entry.State;

        _updating = true;
        FormulaList.Clear();
        foreach (var formula in _formulas)
            FormulaList.AddItem(FormulaTitle(formula));
        _selected = previous == null ? -1 : Array.FindIndex(_formulas, formula => formula.Id == previous);
        if (_selected >= 0)
            FormulaList[_selected].Selected = true;
        _updating = false;

        _chosenCores.RemoveAll(core => !_availableCores.Contains(core));
        RebuildNodes();
        NoticeLabel.Text = state.Notice == NCPharmaRdNotice.None
            ? string.Empty
            : Loc.GetString(NCPharmaTextKeys.RdNotice(state.Notice));
        JournalLabel.SetMessage(FormattedMessage.FromMarkupPermissive(BuildJournal(state.Journal)));
        Refresh();
    }

    // ---- the tree ----------------------------------------------------------------------------------------

    /// <summary>Lays the nodes out again: the compounds the laboratory can use, the ones it cannot yet, and the fixed ones.</summary>
    private void RebuildNodes()
    {
        _treeNodes.Clear();
        foreach (var core in _availableCores)
            _treeNodes.Add(new NCPharmaTreeNode(NCPharmaNodeIds.Core(core), NCPharmaNodeBranch.Core, CoreName(core)));

        // A compound that exists in a formula but has not been identified yet. It shows on the map, locked, so a
        // researcher can see that an invented or isolated compound is waiting to be studied.
        foreach (var formula in _formulas)
        {
            foreach (var compound in new[] { formula.Compound, formula.SecondCompound })
            {
                if (compound == null || _availableCores.Contains(compound) ||
                    _treeNodes.Any(node => node.Id == NCPharmaNodeIds.Core(compound)))
                {
                    continue;
                }

                _treeNodes.Add(new NCPharmaTreeNode(NCPharmaNodeIds.Core(compound), NCPharmaNodeBranch.Core,
                    UnidentifiedName(formula, compound))
                {
                    Locked = true,
                    Knowledge = NCPharmaNodeState.Unknown,
                });
            }
        }

        foreach (var form in _forms)
            _treeNodes.Add(new NCPharmaTreeNode(NCPharmaNodeIds.Form(form.ID), NCPharmaNodeBranch.Delivery, Loc.GetString(form.Name)));
        foreach (var branch in new[] { NCPharmaNodeBranch.Kinetics, NCPharmaNodeBranch.Safety })
        {
            foreach (var modifier in _modifiers.Where(modifier => modifier.Branch == branch))
                _treeNodes.Add(new NCPharmaTreeNode(NCPharmaNodeIds.Modifier(modifier.ID), branch, Loc.GetString(modifier.Name)));
        }

        foreach (var profile in _profiles)
            _treeNodes.Add(new NCPharmaTreeNode(NCPharmaNodeIds.Profile(profile.ID), NCPharmaNodeBranch.Production, Loc.GetString(profile.Name)));
        foreach (var modifier in _modifiers.Where(modifier => modifier.Branch == NCPharmaNodeBranch.Production))
            _treeNodes.Add(new NCPharmaTreeNode(NCPharmaNodeIds.Modifier(modifier.ID), NCPharmaNodeBranch.Production, Loc.GetString(modifier.Name)));

        foreach (var node in _treeNodes)
        {
            if (!node.Locked)
                node.Knowledge = StateOf(node.Id);
        }

        Canvas.SetNodes(_treeNodes);
        SyncChosen();
    }

    private string UnidentifiedName(NCPharmaFormulaSummary formula, string compound)
    {
        var name = formula.CustomName ?? (formula.NameKey != null ? Loc.GetString(formula.NameKey) : compound);
        return Loc.GetString("nc-pharma-rd-unidentified", ("name", name));
    }

    private string CoreName(string id) =>
        Loc.TryGetString(NCLabText.DrugKey(id), out var name) ? name : id;

    private NCPharmaNodeState StateOf(string node) =>
        _knowledge.TryGetValue(node, out var state) ? state : NCPharmaNodeState.Unknown;

    private void SyncChosen()
    {
        foreach (var node in _treeNodes)
        {
            node.Chosen = node.Id switch
            {
                _ when node.Id.StartsWith("core:", StringComparison.Ordinal) => _chosenCores.Contains(node.Id[5..]),
                _ when node.Id.StartsWith("form:", StringComparison.Ordinal) => _chosenForm == node.Id[5..],
                _ when node.Id.StartsWith("mod:", StringComparison.Ordinal) => _chosenModifiers.Contains(node.Id[4..]),
                _ when node.Id.StartsWith("profile:", StringComparison.Ordinal) => _chosenProfile == node.Id[8..],
                _ => false,
            };
        }
    }

    private void OnNodePressed(string node)
    {
        switch (node)
        {
            case var core when core.StartsWith("core:", StringComparison.Ordinal):
                // A core the chip has not studied cannot be taken; pressing it explains how to study it.
                if (_availableCores.Contains(core[5..]))
                    ToggleCore(core[5..]);
                break;
            case var form when form.StartsWith("form:", StringComparison.Ordinal):
                _chosenForm = form[5..];
                break;
            case var modifier when modifier.StartsWith("mod:", StringComparison.Ordinal):
                ToggleModifier(modifier[4..]);
                break;
            case var profile when profile.StartsWith("profile:", StringComparison.Ordinal):
                _chosenProfile = profile[8..];
                break;
        }

        _infoNode = node;
        ShowNodeInfo(node);
        Refresh();
    }

    private void ToggleCore(string id)
    {
        if (!_chosenCores.Remove(id))
        {
            _chosenCores.Add(id);
            if (_chosenCores.Count > 2)
                _chosenCores.RemoveAt(0);
        }

        if (_chosenCores.Count > 0 && _concentration <= 0f)
            ResetConcentration();
    }

    private void ToggleModifier(string id)
    {
        if (!_chosenModifiers.Remove(id))
        {
            _chosenModifiers.Add(id);
            if (_chosenModifiers.Count > NCPharmaBatchMath.MaximumModifiers)
                _chosenModifiers.RemoveAt(0);
        }
    }

    private void ResetConcentration()
    {
        _concentration = _chosenCores.Count > 0 && _prototypes.TryIndex<NCDrugProfilePrototype>(_chosenCores[0], out var core)
            ? core.TherapeuticConcentration
            : _formulas.FirstOrDefault(formula => formula.Compound == _chosenCores.FirstOrDefault()).TargetConcentration is var known and > 0f
                ? known
                : 5f;
    }

    private void ChangeConcentration(float delta)
    {
        if (_chosenCores.Count == 0)
            return;

        _concentration = MathF.Max(0.5f, _concentration + delta);
        Refresh();
    }

    /// <summary>Starts a formula from nothing: no line, no nodes taken yet.</summary>
    private void ClearFormula()
    {
        _selected = -1;
        _updating = true;
        FormulaList.ClearSelected();
        _updating = false;
        _chosenCores.Clear();
        _chosenModifiers.Clear();
        _chosenForm = null;
        _chosenProfile = null;
        _concentration = 0f;
        _infoNode = null;
        NodeInfo.SetMessage(FormattedMessage.FromMarkupPermissive(Loc.GetString("nc-pharma-rd-node-hint")));
        Refresh();
    }

    // ---- selection and creation --------------------------------------------------------------------------

    private NCPharmaFormulaSummary? Selected() =>
        _selected >= 0 && _selected < _formulas.Length ? _formulas[_selected] : null;

    /// <summary>Picking a line takes its nodes onto the map, so a new version continues it.</summary>
    private void SelectFormula(int index)
    {
        if (_updating || index < 0 || index >= _formulas.Length)
            return;

        _selected = index;
        var formula = _formulas[index];
        _chosenCores.Clear();
        _chosenCores.Add(formula.Compound);
        if (formula.SecondCompound != null)
            _chosenCores.Add(formula.SecondCompound);
        _chosenForm = formula.DeliveryForm;
        _chosenProfile = formula.DefaultProfile;
        _chosenModifiers.Clear();
        _chosenModifiers.AddRange(formula.Modifiers);
        _concentration = formula.TargetConcentration;
        SelectRequested?.Invoke(formula.Id);
        Refresh();
    }

    private void TryCreate()
    {
        if (_chosenCores.Count == 0 || _chosenForm == null || _chosenProfile == null)
            return;

        ComposeRequested?.Invoke(
            Selected()?.Id,
            _chosenCores[0],
            _chosenCores.Count > 1 ? _chosenCores[1] : null,
            _chosenForm,
            _concentration,
            _chosenModifiers.ToArray(),
            _chosenProfile);
    }

    private void Refresh()
    {
        var formula = Selected();
        var complete = _chosenCores.Count > 0 && _chosenForm != null && _chosenProfile != null;
        CreateButton.Disabled = !complete || !_hasChip;
        ApproveButton.Disabled = formula is not { CanApprove: true };
        ContinueButton.Disabled = formula == null;
        NoteButton.Disabled = formula == null;
        SelectedCard.SetMessage(FormattedMessage.FromMarkupPermissive(formula is { } selected
            ? BuildCard(selected)
            : Loc.GetString("nc-pharma-rd-select-hint")));
        ConcentrationValue.Text = _chosenCores.Count == 0 ? "-" : _concentration.ToString("0.#");
        TreeHint.SetMessage(FormattedMessage.FromMarkupPermissive(Loc.GetString(!_hasChip
            ? "nc-pharma-rd-no-chip"
            : _researched == 0 ? "nc-pharma-rd-chip-blank" : "nc-pharma-rd-tree-hint")));
        CompositionLabel.SetMessage(FormattedMessage.FromMarkupPermissive(BuildComposition()));
        MaterialsLabel.SetMessage(FormattedMessage.FromMarkupPermissive(BuildMaterials()));
        SyncChosen();
        RefreshForecast();
        RefreshInvention();
    }

    /// <summary>What is taken into the formula so far and what is still missing, branch by branch.</summary>
    private string BuildComposition()
    {
        string Line(NCPharmaNodeBranch branch, string value, bool missing) =>
            Loc.GetString(missing ? "nc-pharma-rd-composition-missing" : "nc-pharma-rd-composition-line",
                ("branch", Loc.GetString($"nc-pharma-rd-branch-{branch.ToString().ToLowerInvariant()}")),
                ("value", value));

        var text = new StringBuilder();
        text.AppendLine(Line(NCPharmaNodeBranch.Core,
            string.Join(" + ", _chosenCores.Select(CoreName)), _chosenCores.Count == 0));
        text.AppendLine(Line(NCPharmaNodeBranch.Delivery,
            _chosenForm != null && _prototypes.TryIndex<NCPharmaDeliveryFormPrototype>(_chosenForm, out var form)
                ? Loc.GetString(form.Name)
                : string.Empty, _chosenForm == null));
        text.AppendLine(Line(NCPharmaNodeBranch.Kinetics,
            _chosenModifiers.Count == 0
                ? Loc.GetString("nc-pharma-station-no-modifiers")
                : string.Join(", ", _chosenModifiers.Select(id =>
                    _prototypes.TryIndex<NCPharmaModifierPrototype>(id, out var modifier) ? Loc.GetString(modifier.Name) : id)),
            false));
        text.Append(Line(NCPharmaNodeBranch.Production,
            _chosenProfile != null && _prototypes.TryIndex<NCPharmaProductionProfilePrototype>(_chosenProfile, out var profile)
                ? Loc.GetString(profile.Name)
                : string.Empty, _chosenProfile == null));
        if (Selected() is { } parent)
            text.AppendLine().Append(Loc.GetString("nc-pharma-rd-continues", ("name", FormulaName(parent))));
        else
            text.AppendLine().Append(Loc.GetString("nc-pharma-rd-starts-new"));
        return text.ToString();
    }

    // ---- materials: what the core is made from and how to get it ----------------------------------------------

    private string BuildMaterials()
    {
        if (_chosenCores.Count == 0)
            return Loc.GetString("nc-pharma-rd-materials-hint");

        var text = new StringBuilder();
        foreach (var core in _chosenCores)
        {
            text.AppendLine(Loc.GetString("nc-pharma-rd-materials-core", ("name", CoreName(core))));
            var options = FeedstockOptionsOf(core);
            if (options.Length == 0)
            {
                text.AppendLine(Loc.GetString("nc-pharma-rd-materials-none"));
                continue;
            }

            foreach (var option in options.OrderByDescending(option => option.Yield))
            {
                if (!_prototypes.TryIndex<NCPharmaFeedstockPrototype>(option.Id, out var feedstock))
                    continue;
                text.AppendLine(Loc.GetString("nc-pharma-rd-materials-kind",
                    ("kind", Loc.GetString(feedstock.Name)),
                    ("yield", (option.Yield * 100f).ToString("0"))));
            }

            if (_prototypes.TryIndex<NCPharmaFeedstockPrototype>(options.OrderByDescending(option => option.Yield).First().Id, out var main))
                AppendRecipe(text, main);
        }

        return text.ToString();
    }

    private NCPharmaFeedstockOption[] FeedstockOptionsOf(string core)
    {
        foreach (var formula in _formulas)
        {
            if (formula.Compound == core && formula.Feedstocks is { Length: > 0 } options)
                return options;
        }

        if (!_prototypes.TryIndex<NCDrugProfilePrototype>(core, out var profile) || profile.Feedstock is not { } main)
            return [];

        var result = new List<NCPharmaFeedstockOption> { new(main.Id, 1f) };
        result.AddRange(profile.AlternateFeedstocks.Select(pair => new NCPharmaFeedstockOption(pair.Key.Id, pair.Value)));
        return result.ToArray();
    }

    /// <summary>The way to the raw material: the substrate from ordinary reagents, the broth from the substrate, then extraction.</summary>
    private void AppendRecipe(StringBuilder text, NCPharmaFeedstockPrototype feedstock)
    {
        var substrate = RecipeFor(feedstock.Substrate.Id);
        text.AppendLine(Loc.GetString("nc-pharma-rd-materials-substrate",
            ("name", ReagentName(feedstock.Substrate.Id)),
            ("recipe", substrate ?? Loc.GetString("nc-pharma-rd-materials-supplied"))));
        var broth = RecipeFor(feedstock.Broth.Id);
        text.AppendLine(Loc.GetString("nc-pharma-rd-materials-broth",
            ("name", ReagentName(feedstock.Broth.Id)),
            ("recipe", broth ?? Loc.GetString("nc-pharma-rd-materials-supplied"))));
        text.Append(Loc.GetString("nc-pharma-rd-materials-extract"));
    }

    private string ReagentName(string id) =>
        _prototypes.TryIndex<ReagentPrototype>(id, out var reagent) ? reagent.LocalizedName : id;

    /// <summary>"2 protein + 1 lithium, 310-340 K": the reaction that makes a reagent, if players can make it.</summary>
    private string? RecipeFor(string product)
    {
        foreach (var reaction in _prototypes.EnumeratePrototypes<ReactionPrototype>())
        {
            if (!reaction.Products.ContainsKey(product) || reaction.Reactants.Count == 0)
                continue;

            var parts = string.Join(" + ", reaction.Reactants.Select(pair =>
                $"{pair.Value.Amount.Float():0.#} {ReagentName(pair.Key.Id)}"));
            var temperature = reaction.MinimumTemperature > 0f
                ? float.IsInfinity(reaction.MaximumTemperature)
                    ? Loc.GetString("nc-pharma-rd-materials-above", ("min", reaction.MinimumTemperature.ToString("0")))
                    : Loc.GetString("nc-pharma-rd-materials-between",
                        ("min", reaction.MinimumTemperature.ToString("0")), ("max", reaction.MaximumTemperature.ToString("0")))
                : string.Empty;
            return parts + temperature;
        }

        return null;
    }

    // ---- inventing a compound ----------------------------------------------------------------------------

    private string IngredientName(NCPharmaIngredientPrototype ingredient) => ReagentName(ingredient.Reagent.Id);

    private void BuildIngredientList()
    {
        foreach (var ingredient in _ingredients)
        {
            var reagent = ingredient.Reagent.Id;
            var button = new Button { ToggleMode = true, HorizontalExpand = true, ClipText = true };
            button.OnPressed += _ =>
            {
                if (!_chosenIngredients.Remove(reagent))
                {
                    _chosenIngredients.Add(reagent);
                    if (_chosenIngredients.Count > NCPharmaInvention.MaximumIngredients)
                        _chosenIngredients.RemoveAt(0);
                }

                RefreshInvention();
            };
            IngredientList.AddChild(button);
            _ingredientButtons.Add((reagent, button, IngredientName(ingredient)));
        }
    }

    private float InBeaker(string reagent) =>
        _beaker.Where(entry => entry.Id == reagent).Sum(entry => entry.Amount);

    private string Band(float value, float low, float high, string key) =>
        Loc.GetString($"nc-pharma-rd-band-{key}-{(value < low ? "low" : value < high ? "medium" : "high")}");

    private void RefreshInvention()
    {
        IngredientHint.SetMessage(FormattedMessage.FromMarkupPermissive(Loc.GetString("nc-pharma-rd-ingredients-hint",
            ("units", UnitsPerIngredient.ToString("0")))));
        foreach (var (reagent, button, name) in _ingredientButtons)
        {
            var ingredient = _ingredients.First(candidate => candidate.Reagent.Id == reagent);
            var held = InBeaker(reagent);
            var leaning = ingredient.Category.Length == 0
                ? Loc.GetString("nc-pharma-rd-leaning-neutral")
                : Loc.GetString($"nc-pharma-rd-leaning-{ingredient.Category.ToLowerInvariant()}");
            button.Text = Loc.GetString("nc-pharma-rd-ingredient-row",
                ("name", name), ("leaning", leaning), ("held", held.ToString("0.#")));
            button.Pressed = _chosenIngredients.Contains(reagent);
            button.Label.FontColorOverride = held < UnitsPerIngredient ? Color.FromHex("#7A8A8C") : null;
            button.ToolTip = IngredientTooltip(ingredient);
        }

        BeakerLabel.SetMessage(FormattedMessage.FromMarkupPermissive(_hasBeaker
            ? string.Join("\n", _beaker.Select(entry =>
                Loc.GetString("nc-pharma-rd-beaker-row", ("name", ReagentName(entry.Id)), ("amount", entry.Amount.ToString("0.#")))))
              + (_beaker.Length == 0 ? Loc.GetString("nc-pharma-rd-beaker-empty") : string.Empty)
            : Loc.GetString("nc-pharma-rd-beaker-missing")));

        var traits = _chosenIngredients
            .Select(reagent => _ingredients.First(candidate => candidate.Reagent.Id == reagent))
            .Select(ingredient => new NCIngredientTraits(
                ingredient.Reagent.Id, ingredient.Category, ingredient.Potency, ingredient.Toxicity, ingredient.Side, ingredient.Dependence))
            .ToList();
        var enough = _chosenIngredients.All(reagent => InBeaker(reagent) >= UnitsPerIngredient);
        if (traits.Count < NCPharmaInvention.MinimumIngredients)
        {
            InventionPreview.SetMessage(FormattedMessage.FromMarkupPermissive(Loc.GetString("nc-pharma-rd-expected-pick")));
        }
        else if (!NCPharmaInvention.TryCombine(traits, out var profile))
        {
            InventionPreview.SetMessage(FormattedMessage.FromMarkupPermissive(Loc.GetString("nc-pharma-rd-expected-nothing")));
        }
        else
        {
            var text = new StringBuilder();
            text.AppendLine(Loc.GetString("nc-pharma-rd-expected-action",
                ("action", Loc.GetString($"nc-pharma-rd-leaning-{profile.Category.ToLowerInvariant()}"))));
            text.AppendLine(Loc.GetString("nc-pharma-rd-expected-strength",
                ("strength", Band(profile.Strength, 0.4f, 0.75f, "strength"))));
            text.AppendLine(Loc.GetString("nc-pharma-rd-expected-risk",
                ("risk", Band(-(profile.Toxic / profile.Therapeutic), -2.4f, -1.9f, "risk"))));
            if (profile.SideField != null)
                text.AppendLine(Loc.GetString("nc-pharma-rd-expected-side"));
            if (profile.Dependence != null)
                text.AppendLine(Loc.GetString("nc-pharma-rd-expected-dependence"));
            text.Append(Loc.GetString("nc-pharma-rd-expected-note"));
            InventionPreview.SetMessage(FormattedMessage.FromMarkupPermissive(text.ToString()));
        }

        InventButton.Disabled = !_hasChip || traits.Count < NCPharmaInvention.MinimumIngredients || !_hasBeaker || !enough ||
                                !NCPharmaInvention.TryCombine(traits, out _);
    }

    private string IngredientTooltip(NCPharmaIngredientPrototype ingredient)
    {
        var lines = new List<string>
        {
            ingredient.Category.Length == 0
                ? Loc.GetString("nc-pharma-rd-leaning-neutral")
                : Loc.GetString("nc-pharma-rd-ingredient-leans",
                    ("action", Loc.GetString($"nc-pharma-rd-leaning-{ingredient.Category.ToLowerInvariant()}")),
                    ("power", Band(ingredient.Potency, 0.45f, 0.65f, "strength"))),
            Loc.GetString("nc-pharma-rd-ingredient-harm", ("harm", ingredient.Toxicity < 0f
                ? Loc.GetString("nc-pharma-rd-band-harm-negative")
                : Band(ingredient.Toxicity, 0.2f, 0.35f, "harm"))),
        };
        if (ingredient.Side.Length > 0)
            lines.Add(Loc.GetString("nc-pharma-rd-expected-side"));
        if (ingredient.Dependence != null)
            lines.Add(Loc.GetString("nc-pharma-rd-expected-dependence"));
        return string.Join("\n", lines);
    }

