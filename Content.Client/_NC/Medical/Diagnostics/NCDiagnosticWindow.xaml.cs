using System.Linq;
using System.Text;
using Content.Client.UserInterface.Controls;
using Content.Shared._NC.Combat.Targeting;
using Content.Shared._NC.Medical.Diagnostics.Detail;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._NC.Medical.Diagnostics;

/// <summary>
/// Presents only the capability-filtered DTO supplied by the server. It never reads medical ECS components.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class NCDiagnosticWindow : FancyWindow
{
    private const int MaximumRowsPerSection = 64;

    private readonly IPrototypeManager _prototypes;

    public NCDiagnosticWindow(IPrototypeManager prototypes)
    {
        RobustXamlLoader.Load(this);
        _prototypes = prototypes;

        Tabs.SetTabTitle(0, Loc.GetString("nc-medical-diagnostics-tab-overview"));
        Tabs.SetTabTitle(1, Loc.GetString("nc-medical-diagnostics-tab-regions"));
        Tabs.SetTabTitle(2, Loc.GetString("nc-medical-diagnostics-tab-wounds"));
        Tabs.SetTabTitle(3, Loc.GetString("nc-medical-diagnostics-tab-organs"));
        Tabs.SetTabTitle(4, Loc.GetString("nc-medical-diagnostics-tab-cyberware"));
        Tabs.SetTabTitle(5, Loc.GetString("nc-medical-diagnostics-tab-drugs"));
    }

    public void ShowFailure(NCDiagnosticAccessFailure failure)
    {
        TierLabel.Text = Loc.GetString("nc-medical-diagnostics-unavailable");
        RevisionLabel.Text = string.Empty;
        ObservationLabel.Text = string.Empty;
        FailureLabel.Text = Loc.GetString(
            "nc-medical-diagnostics-failure",
            ("reason", Readable(failure)));
        FailureLabel.Visible = true;
        ClearSections();
    }

    public void SetSnapshot(NCMedicalSnapshot snapshot)
    {
        FailureLabel.Visible = false;
        TierLabel.Text = Loc.GetString(
            "nc-medical-diagnostics-tier",
            ("tier", Readable(snapshot.Tier)));
        RevisionLabel.Text = Loc.GetString(
            "nc-medical-diagnostics-revision",
            ("revision", snapshot.MedicalRevision));
        ObservationLabel.Text = Loc.GetString(
            "nc-medical-diagnostics-observed",
            ("time", snapshot.ObservedAt.ToString(@"hh\:mm\:ss")));

        ClearSections();
        PopulateOverview(snapshot);
        PopulateRegions(snapshot);
        PopulateWounds(snapshot);
        PopulateOrgans(snapshot);
        PopulateCyberware(snapshot);
        PopulateDrugs(snapshot);
    }

    private void PopulateOverview(NCMedicalSnapshot snapshot)
    {
        AddHeading(OverviewContainer, Loc.GetString("nc-medical-diagnostics-vitals"));
        AddRow(OverviewContainer, Loc.GetString(
            "nc-medical-diagnostics-condition",
            ("condition", Readable(snapshot.Vitals.Condition)),
            ("consciousness", Readable(snapshot.Vitals.Consciousness))));
        AddRow(OverviewContainer, Loc.GetString(
            "nc-medical-diagnostics-pain-shock",
            ("pain", Readable(snapshot.Vitals.Pain)),
            ("shock", Readable(snapshot.Vitals.Shock))));

        if (snapshot.Vitals.BloodPressure is { } pressure)
            AddRow(OverviewContainer, Loc.GetString("nc-medical-diagnostics-pressure", ("value", Readable(pressure))));
        if (snapshot.Vitals.HeartRhythm is { } rhythm)
            AddRow(OverviewContainer, Loc.GetString("nc-medical-diagnostics-rhythm", ("value", Readable(rhythm))));
        AddRange(OverviewContainer, "nc-medical-diagnostics-oxygen", snapshot.Vitals.OxygenationPermille, "‰");
        AddRange(OverviewContainer, "nc-medical-diagnostics-volume", snapshot.Vitals.BloodVolumeMl, " ml");
        AddRange(OverviewContainer, "nc-medical-diagnostics-perfusion", snapshot.Vitals.PerfusionPermille, "‰");
        AddRange(OverviewContainer, "nc-medical-diagnostics-external-bleed", snapshot.Vitals.ExternalBleedMilliunits, " mU/s");
        AddRange(OverviewContainer, "nc-medical-diagnostics-internal-bleed", snapshot.Vitals.InternalBleedMilliunits, " mU/s");

        AddHeading(OverviewContainer, Loc.GetString("nc-medical-diagnostics-warnings"));
        if (snapshot.Warnings.Count == 0)
        {
            AddRow(OverviewContainer, Loc.GetString("nc-medical-diagnostics-none"));
        }
        else
        {
            foreach (var warning in snapshot.Warnings.Take(MaximumRowsPerSection))
                AddRow(OverviewContainer, $"• {Readable(warning)}");
        }

        if (snapshot.Surgery is { } surgery)
        {
            AddHeading(OverviewContainer, Loc.GetString("nc-medical-diagnostics-surgery"));
            AddRow(OverviewContainer, Loc.GetString(
                "nc-medical-diagnostics-surgery-row",
                ("region", ReadableId(surgery.Region.Id)),
                ("procedure", ReadableId(surgery.Procedure.Id)),
                ("step", surgery.StepIndex + 1),
                ("state", Readable(surgery.State)),
                ("access", Readable(surgery.AccessDepth))));
        }
    }

    private void PopulateRegions(NCMedicalSnapshot snapshot)
    {
        if (snapshot.Regions.Count == 0)
        {
            AddRow(RegionsContainer, Loc.GetString("nc-medical-diagnostics-none"));
            return;
        }

        foreach (var region in snapshot.Regions.Take(MaximumRowsPerSection))
        {
            var details = new StringBuilder();
            details.Append(Loc.GetString(
                "nc-medical-diagnostics-region-row",
                ("zone", ZoneName(region.Zone)),
                ("burden", Readable(region.Burden)),
                ("function", Readable(region.Function))));
            if (region.WoundCount is { } wounds)
                details.Append($" | {Loc.GetString("nc-medical-diagnostics-wound-count", ("count", wounds))}");
            if (region.BoneState is { } bone)
                details.Append($" | {Loc.GetString("nc-medical-diagnostics-bone", ("state", Readable(bone)))}");
            if (region.Findings != NCDiagnosticFindingFlags.None)
                details.Append($" | {ReadableFlags(region.Findings)}");
            AddRow(RegionsContainer, details.ToString());
        }
    }

    private void PopulateWounds(NCMedicalSnapshot snapshot)
    {
        if (snapshot.Wounds.Count == 0)
        {
            AddRow(WoundsContainer, Loc.GetString("nc-medical-diagnostics-none"));
            return;
        }

        foreach (var wound in snapshot.Wounds.Take(MaximumRowsPerSection))
        {
            var details = new StringBuilder(Loc.GetString(
                "nc-medical-diagnostics-wound-row",
                ("zone", ZoneName(wound.Zone)),
                ("severity", Readable(wound.Severity)),
                ("type", Readable(wound.Type))));
            if (wound.Stage is { } stage)
                details.Append($" | {Readable(stage)}");
            if (wound.Depth is { } depth)
                details.Append($" | {Readable(depth)}");
            if (wound.ExternalBleeding != NCDiagnosticBand.None)
                details.Append($" | EXT {Readable(wound.ExternalBleeding)}");
            if (wound.InternalBleeding != NCDiagnosticBand.None)
                details.Append($" | INT {Readable(wound.InternalBleeding)}");
            if (wound.Infection != NCDiagnosticBand.None)
                details.Append($" | INF {Readable(wound.Infection)}");
            if (wound.ForeignBody)
                details.Append($" | {Loc.GetString("nc-medical-diagnostics-foreign-body")}");
            AddRow(WoundsContainer, details.ToString());
        }

        AddOmitted(WoundsContainer, snapshot.WoundsOmitted);
    }

    private void PopulateOrgans(NCMedicalSnapshot snapshot)
    {
        if (snapshot.Organs.Count == 0)
        {
            AddRow(OrgansContainer, Loc.GetString("nc-medical-diagnostics-none"));
            return;
        }

        foreach (var organ in snapshot.Organs.Take(MaximumRowsPerSection))
        {
            AddRow(OrgansContainer, Loc.GetString(
                "nc-medical-diagnostics-organ-row",
                ("organ", ReadableId(organ.Category.Id)),
                ("type", Readable(organ.FunctionType)),
                ("integrity", Readable(organ.Integrity)),
                ("function", Readable(organ.Function)),
                ("rejection", organ.Rejection == NCDiagnosticBand.None
                    ? string.Empty
                    : Loc.GetString(
                        "nc-medical-diagnostics-rejection",
                        ("value", Readable(organ.Rejection)))),
                ("vital", organ.Vital ? Loc.GetString("nc-medical-diagnostics-vital") : string.Empty),
                ("failing", organ.Failing ? Loc.GetString("nc-medical-diagnostics-failing") : string.Empty)));
        }

        AddOmitted(OrgansContainer, snapshot.OrgansOmitted);
    }

    private void PopulateCyberware(NCMedicalSnapshot snapshot)
    {
        if (snapshot.Cyberware.Count == 0)
        {
            AddRow(CyberwareContainer, Loc.GetString("nc-medical-diagnostics-none"));
            return;
        }

        foreach (var module in snapshot.Cyberware.Take(MaximumRowsPerSection))
        {
            var placement = module.Slot is { } slot
                ? ReadableId(slot.Id)
                : module.HostCategory is { } host
                    ? ReadableId(host.Id)
                    : Readable(module.Form);
            AddRow(CyberwareContainer, Loc.GetString(
                "nc-medical-diagnostics-cyberware-row",
                ("module", ReadableId(module.Profile.Id)),
                ("placement", placement),
                ("integrity", Readable(module.Integrity)),
                ("function", Readable(module.Function)),
                ("power", Readable(module.Power)),
                ("heat", Readable(module.Heat)),
                ("neural", Readable(module.NeuralState)),
                ("state", module.Operational
                    ? Loc.GetString("nc-medical-diagnostics-cyberware-online")
                    : Loc.GetString("nc-medical-diagnostics-cyberware-offline")),
                ("emp", module.EmpDisabled
                    ? Loc.GetString("nc-medical-diagnostics-cyberware-emp")
                    : string.Empty)));
        }

        AddOmitted(CyberwareContainer, snapshot.CyberwareOmitted);
    }

    private void PopulateDrugs(NCMedicalSnapshot snapshot)
    {
        if (snapshot.Drugs.Count == 0)
        {
            AddRow(DrugsContainer, Loc.GetString("nc-medical-diagnostics-none"));
            return;
        }

        foreach (var drug in snapshot.Drugs.Take(MaximumRowsPerSection))
        {
            var range = drug.ConcentrationMilliunits.Minimum == drug.ConcentrationMilliunits.Maximum
                ? $"{drug.ConcentrationMilliunits.Minimum} mU"
                : $"{drug.ConcentrationMilliunits.Minimum}–{drug.ConcentrationMilliunits.Maximum} mU";
            AddRow(DrugsContainer, Loc.GetString(
                "nc-medical-diagnostics-drug-row",
                ("drug", ReadableId(drug.Profile.Id)),
                ("category", Readable(drug.Category)),
                ("concentration", range),
                ("state", drug.Toxic
                    ? Loc.GetString("nc-medical-diagnostics-drug-toxic")
                    : drug.Therapeutic
                        ? Loc.GetString("nc-medical-diagnostics-drug-therapeutic")
                        : Loc.GetString("nc-medical-diagnostics-drug-subtherapeutic"))));
        }

        AddOmitted(DrugsContainer, snapshot.DrugsOmitted);
    }

    private void AddRange(
        BoxContainer container,
        string locId,
        NCDiagnosticNumericRange? range,
        string suffix)
    {
        if (range is not { } value)
            return;

        var formatted = value.Minimum == value.Maximum
            ? $"{value.Minimum}{suffix}"
            : $"{value.Minimum}–{value.Maximum}{suffix}";
        AddRow(container, Loc.GetString(locId, ("value", formatted)));
    }

    private void AddOmitted(BoxContainer container, ushort omitted)
    {
        if (omitted > 0)
            AddRow(container, Loc.GetString("nc-medical-diagnostics-omitted", ("count", omitted)));
    }

    private static void AddHeading(BoxContainer container, string text)
    {
        var label = new Label { Text = text };
        label.StyleClasses.Add("LabelSubHeading");
        container.AddChild(label);
    }

    private static void AddRow(BoxContainer container, string text)
    {
        container.AddChild(new Label
        {
            Text = text,
            HorizontalExpand = true,
        });
    }

    private string ZoneName(ProtoId<NCTargetZonePrototype> id)
    {
        return _prototypes.TryIndex(id, out var zone)
            ? Loc.GetString(zone.DisplayName)
            : ReadableId(id.Id);
    }

    private static string ReadableFlags(NCDiagnosticFindingFlags flags)
    {
        return string.Join(", ", Enum.GetValues<NCDiagnosticFindingFlags>()
            .Where(value => value != NCDiagnosticFindingFlags.None && flags.HasFlag(value))
            .Select(value => Readable(value)));
    }

    private static string Readable(Enum value)
    {
        return ReadableId(value.ToString());
    }

    private static string ReadableId(string value)
    {
        var start = value.StartsWith("NC", StringComparison.Ordinal) ? 2 : 0;
        var builder = new StringBuilder(value.Length + 8);
        for (var i = start; i < value.Length; i++)
        {
            var current = value[i];
            if (i > start && char.IsUpper(current) && !char.IsUpper(value[i - 1]))
                builder.Append(' ');
            builder.Append(current);
        }

        return builder.ToString();
    }

    private void ClearSections()
    {
        OverviewContainer.RemoveAllChildren();
        RegionsContainer.RemoveAllChildren();
        WoundsContainer.RemoveAllChildren();
        OrgansContainer.RemoveAllChildren();
        CyberwareContainer.RemoveAllChildren();
        DrugsContainer.RemoveAllChildren();
    }
}
