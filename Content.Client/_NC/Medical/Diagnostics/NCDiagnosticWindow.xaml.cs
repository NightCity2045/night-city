    private static void AddCard(
        BoxContainer container,
        string title,
        string details,
        Color color,
        string marker = "●",
        Texture? icon = null,
        IReadOnlyList<DiagnosticMetric>? metrics = null)
    {
        var panel = new PanelContainer
        {
            HorizontalExpand = true,
            RectClipContent = true,
            PanelOverride = new StyleBoxFlat
            {
                BackgroundColor = Color.FromHex("#081419"),
                BorderColor = color.WithAlpha(0.72f),
                BorderThickness = new Thickness(0, 0, 0, 2),
            },
        };
        var row = new BoxContainer
        {
            Margin = new Thickness(9, 6),
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            SeparationOverride = 8,
            HorizontalExpand = true,
            RectClipContent = true,
        };
        row.AddChild(new Label
        {
            Text = marker,
            FontColorOverride = color,
            VerticalAlignment = VAlignment.Top,
        });

        if (icon != null)
        {
            var iconFrame = new PanelContainer
            {
                SetSize = new System.Numerics.Vector2(44f, 44f),
                VerticalAlignment = VAlignment.Top,
                PanelOverride = new StyleBoxFlat
                {
                    BackgroundColor = Color.FromHex("#03090C"),
                    BorderColor = color.WithAlpha(0.55f),
                    BorderThickness = new Thickness(1),
                },
            };
            iconFrame.AddChild(new TextureRect
            {
                Texture = icon,
                SetSize = new System.Numerics.Vector2(40f, 40f),
                Stretch = TextureRect.StretchMode.KeepAspectCentered,
                MouseFilter = MouseFilterMode.Ignore,
            });
            row.AddChild(iconFrame);
        }

        var text = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            SeparationOverride = 2,
            HorizontalExpand = true,
            RectClipContent = true,
        };
        var titleLabel = new RichTextLabel
        {
            HorizontalExpand = true,
            VerticalAlignment = VAlignment.Top,
            RectClipContent = true,
        };
        titleLabel.SetMessage(title, color);
        text.AddChild(titleLabel);
        if (!string.IsNullOrWhiteSpace(details))
        {
            var detailLabel = new RichTextLabel
            {
                HorizontalExpand = true,
                VerticalAlignment = VAlignment.Top,
                RectClipContent = true,
                LineHeightScale = 1.08f,
            };
            detailLabel.SetMessage(details, Color.FromHex("#C4CCD2"));
            text.AddChild(detailLabel);
        }

        if (metrics is { Count: > 0 })
        {
            var metricGrid = new GridContainer
            {
                Columns = Math.Min(3, metrics.Count),
                HSeparationOverride = 6,
                VSeparationOverride = 5,
                HorizontalExpand = true,
                Margin = new Thickness(0, 5, 0, 0),
                RectClipContent = true,
            };
            foreach (var metric in metrics)
            {
                var metricPanel = new PanelContainer
                {
                    HorizontalExpand = true,
                    RectClipContent = true,
                    PanelOverride = new StyleBoxFlat
                    {
                        BackgroundColor = Color.FromHex("#0A2024"),
                        BorderColor = metric.Color.WithAlpha(0.35f),
                        BorderThickness = new Thickness(1),
                    },
                };
                var metricBody = new BoxContainer
                {
                    Margin = new Thickness(6, 4),
                    Orientation = BoxContainer.LayoutOrientation.Vertical,
                    SeparationOverride = 2,
                    HorizontalExpand = true,
                    RectClipContent = true,
                };
                metricBody.AddChild(new Label
                {
                    Text = metric.Label,
                    FontColorOverride = Color.FromHex("#62BDB6"),
                    ClipText = true,
                    ToolTip = metric.Label,
                });
                var metricValue = new RichTextLabel
                {
                    HorizontalExpand = true,
                    VerticalAlignment = VAlignment.Top,
                    RectClipContent = true,
                };
                metricValue.SetMessage(metric.Value, metric.Color);
                metricBody.AddChild(metricValue);
                metricBody.AddChild(new ProgressBar
                {
                    MinValue = 0f,
                    MaxValue = 1f,
                    Value = Math.Clamp(metric.Progress, 0f, 1f),
                    SetHeight = 6f,
                    BackgroundStyleBoxOverride = new StyleBoxFlat
                    {
                        BackgroundColor = Color.FromHex("#1A282C"),
                    },
                    ForegroundStyleBoxOverride = new StyleBoxFlat
                    {
                        BackgroundColor = metric.Color,
                    },
                });
                metricPanel.AddChild(metricBody);
                metricGrid.AddChild(metricPanel);
            }
            text.AddChild(metricGrid);
        }

        row.AddChild(text);
        panel.AddChild(row);
        container.AddChild(panel);
    }

