/// <summary>
/// Triage-first presentation of one server-filtered diagnostic snapshot. The window never reads medical
/// components: every visible finding has already passed the server's capability and privacy policy.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class NCDiagnosticWindow : FancyWindow
{
    private const int MaximumRowsPerSection = 64;
    private const float StaleAfterSeconds = 3f;
    private const float LostAfterSeconds = 8f;

    private static readonly ProtoId<NCAnatomyProfilePrototype> HumanAnatomy = "Human";
    private static readonly Color HealthyColor = Color.FromHex("#74C69D");
    private static readonly Color LowColor = Color.FromHex("#B7D66D");
    private static readonly Color ModerateColor = Color.FromHex("#E6C15D");
    private static readonly Color HighColor = Color.FromHex("#F29E4C");
    private static readonly Color CriticalColor = Color.FromHex("#FF6B6B");
    private static readonly Color MutedColor = Color.FromHex("#8A9BA8");

    private readonly IPrototypeManager _prototypes;
    private readonly IEntityManager _entities;

    private NCMedicalSnapshot? _snapshot;
    private EntityUid? _patient;
    private ProtoId<NCTargetZonePrototype>? _selectedZone;
    private float _secondsSinceUpdate;
    private NCDiagnosticAccessFailure? _staleFailure;

    public NCDiagnosticWindow(IPrototypeManager prototypes)
    {
        RobustXamlLoader.Load(this);
        _prototypes = prototypes;
        _entities = IoCManager.Resolve<IEntityManager>();

        BodyDoll.DisplayScale = 4f;
        BodyDoll.InteractionEnabled = true;
        BodyDoll.ShowAutomaticSelection = false;
        BodyDoll.SetProfile(HumanAnatomy);
        BodyDoll.TargetingChanged += OnBodyZoneSelected;
        AllBodyButton.OnPressed += _ => ClearBodyFilter();

        SetTabTitles(0, 0, 0, 0, 0);
        ShowEmptyHeader();
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        if (_snapshot == null)
            return;

        _secondsSinceUpdate += args.DeltaSeconds;
        RefreshFreshness();
    }

    public void ShowFailure(NCDiagnosticAccessFailure failure)
    {
        if (_snapshot != null)
        {
            // Keep the last valid reading on screen. Transient range, power or held-state failures must not
            // erase information while the medic is reacting to it; the age and stale banner remain explicit.
            _staleFailure = failure;
            FailureLabel.Text = Loc.GetString(
                "nc-medical-diagnostics-refresh-failure",
                ("reason", Value(failure)));
            FailurePanel.Visible = true;
            RefreshFreshness();
            return;
        }

        TierLabel.Text = Loc.GetString("nc-medical-diagnostics-unavailable");
        ConfidenceLabel.Text = string.Empty;
        FreshnessLabel.Text = string.Empty;
        ConnectionLabel.Text = Loc.GetString("nc-medical-diagnostics-connection-lost");
        ConnectionLabel.FontColorOverride = CriticalColor;
        FailureLabel.Text = Loc.GetString(
            "nc-medical-diagnostics-failure",
            ("reason", Value(failure)));
        FailurePanel.Visible = true;
        ClearSections();
    }

    public void SetSnapshot(NCMedicalSnapshot snapshot, EntityUid? patient)
    {
        var sameSnapshot = _snapshot?.MedicalRevision == snapshot.MedicalRevision && _patient == patient;
        _snapshot = snapshot;
        _patient = patient;
        _secondsSinceUpdate = 0f;
        _staleFailure = null;
        FailurePanel.Visible = false;

        PopulateHeader(snapshot, patient);
        RefreshFreshness();
        if (sameSnapshot)
            return;

        RefreshAllSections();
    }

    private void PopulateHeader(NCMedicalSnapshot snapshot, EntityUid? patient)
    {
        if (patient is { Valid: true } uid && _entities.EntityExists(uid))
        {
            PatientSprite.SetEntity(uid);
            PatientSprite.Visible = true;
            PatientNameLabel.Text = Identity.Name(uid, _entities);
        }
        else
        {
            PatientSprite.Visible = false;
            PatientNameLabel.Text = Loc.GetString("nc-medical-diagnostics-patient-unknown");
        }

        PatientStateLabel.Text = Loc.GetString(
            "nc-medical-diagnostics-patient-state",
            ("condition", Value(snapshot.Vitals.Condition)),
            ("consciousness", Value(snapshot.Vitals.Consciousness)));
        PatientStateLabel.FontColorOverride = ConditionColor(snapshot.Vitals.Condition);
        TierLabel.Text = TierName(snapshot.Tier);
        ConfidenceLabel.Text = TierConfidence(snapshot.Tier);
    }

    private void ShowEmptyHeader()
    {
        PatientSprite.Visible = false;
        PatientNameLabel.Text = Loc.GetString("nc-medical-diagnostics-patient-unknown");
        PatientStateLabel.Text = string.Empty;
        TierLabel.Text = string.Empty;
        ConfidenceLabel.Text = string.Empty;
        FreshnessLabel.Text = string.Empty;
        ConnectionLabel.Text = string.Empty;
    }

    private void RefreshFreshness()
    {
        if (_snapshot == null)
            return;

        if (_staleFailure is { } failure)
        {
            FreshnessLabel.Text = Loc.GetString(
                "nc-medical-diagnostics-last-update",
                ("seconds", Math.Max(1, (int) MathF.Ceiling(_secondsSinceUpdate))));
            FreshnessLabel.FontColorOverride = HighColor;
            ConnectionLabel.Text = Loc.GetString(
                "nc-medical-diagnostics-connection-stale",
                ("reason", Value(failure)));
            ConnectionLabel.FontColorOverride = CriticalColor;
            return;
        }

        if (_secondsSinceUpdate >= LostAfterSeconds)
        {
            FreshnessLabel.Text = Loc.GetString(
                "nc-medical-diagnostics-last-update",
                ("seconds", (int) _secondsSinceUpdate));
            FreshnessLabel.FontColorOverride = CriticalColor;
            ConnectionLabel.Text = Loc.GetString("nc-medical-diagnostics-connection-lost");
            ConnectionLabel.FontColorOverride = CriticalColor;
        }
        else if (_secondsSinceUpdate >= StaleAfterSeconds)
        {
            FreshnessLabel.Text = Loc.GetString(
                "nc-medical-diagnostics-last-update",
                ("seconds", (int) _secondsSinceUpdate));
            FreshnessLabel.FontColorOverride = ModerateColor;
            ConnectionLabel.Text = Loc.GetString("nc-medical-diagnostics-connection-updating");
            ConnectionLabel.FontColorOverride = ModerateColor;
        }
        else
        {
            FreshnessLabel.Text = Loc.GetString("nc-medical-diagnostics-updated-now");
            FreshnessLabel.FontColorOverride = MutedColor;
            ConnectionLabel.Text = Loc.GetString("nc-medical-diagnostics-connection-live");
            ConnectionLabel.FontColorOverride = HealthyColor;
        }
    }

    private void RefreshAllSections()
    {
        if (_snapshot is not { } snapshot)
            return;

        ClearSections();
        PopulateDoll(snapshot);
        PopulateVitals(snapshot);
        PopulateThreats(snapshot);
        PopulateOverview(snapshot);
        PopulateRegions(snapshot);
        PopulateWounds(snapshot);
        PopulateOrgans(snapshot);
        PopulateCyberware(snapshot);
        PopulateDrugs(snapshot);
        SetTabTitles(
            snapshot.Regions.Count,
            snapshot.Wounds.Count + snapshot.WoundsOmitted,
            snapshot.Organs.Count + snapshot.OrgansOmitted,
            snapshot.Cyberware.Count + snapshot.CyberwareOmitted,
            snapshot.Drugs.Count + snapshot.DrugsOmitted);
    }

    private void PopulateDoll(NCMedicalSnapshot snapshot)
    {
        var levels = new Dictionary<ProtoId<NCTargetZonePrototype>, byte>();
        foreach (var region in snapshot.Regions)
        {
            // Diagnostic bands already describe impairment severity: None is healthy and Critical is nonfunctional.
            // Inverting this value makes healthy anatomy appear destroyed on the composited Status doll.
            var level = Math.Max(DiagnosticStatusLevel(region.Burden), DiagnosticStatusLevel(region.Function));
            if ((region.Findings & (NCDiagnosticFindingFlags.OrganFailure |
                                    NCDiagnosticFindingFlags.InternalBleeding)) != 0)
            {
                level = NCTargetingDollControl.MaximumStatusLevel;
            }
            else if ((region.Findings & (NCDiagnosticFindingFlags.FractureConfirmed |
                                         NCDiagnosticFindingFlags.NeurologicalDeficit)) != 0)
            {
                level = Math.Max(level, (byte) 6);
            }
            levels[region.Zone] = level;
        }
        BodyDoll.SetStatusLevels(levels);
        BodyDoll.SetWoundMarkers(snapshot.Wounds);
        RefreshBodyFilterLabel();
    }

    private void PopulateVitals(NCMedicalSnapshot snapshot)
    {
        SetRatioVital(OxygenValue, OxygenBar, snapshot.Vitals.OxygenationPermille);
        SetBloodVital(
            BloodValue,
            BloodBar,
            snapshot.Vitals.BloodVolumeUnits,
            snapshot.Vitals.NominalBloodVolumeUnits);
        SetRatioVital(PerfusionValue, PerfusionBar, snapshot.Vitals.PerfusionPermille);

        SetValue(PressureValue, snapshot.Vitals.BloodPressure is { } pressure ? Value(pressure) : Unknown(),
            snapshot.Vitals.BloodPressure is { } pressureState ? PressureColor(pressureState) : MutedColor);
        SetValue(RhythmValue, snapshot.Vitals.HeartRhythm is { } rhythm ? Value(rhythm) : Unknown(),
            snapshot.Vitals.HeartRhythm is { } rhythmState ? RhythmColor(rhythmState) : MutedColor);
        SetValue(PainValue, BandName(snapshot.Vitals.Pain), BandColor(snapshot.Vitals.Pain));
        SetValue(ShockValue, BandName(snapshot.Vitals.Shock), BandColor(snapshot.Vitals.Shock));
        SetValue(ExternalBleedValue, BandName(snapshot.Vitals.ExternalBleeding), BandColor(snapshot.Vitals.ExternalBleeding));
        SetValue(InternalBleedValue,
            snapshot.Vitals.InternalBleedMilliunits == null
                ? Loc.GetString("nc-medical-diagnostics-not-measured")
                : BandName(snapshot.Vitals.InternalBleeding),
            snapshot.Vitals.InternalBleedMilliunits == null ? MutedColor : BandColor(snapshot.Vitals.InternalBleeding));

        ExternalBleedValue.ToolTip = ExactBleedTooltip(snapshot.Tier, snapshot.Vitals.ExternalBleedMilliunits);
        InternalBleedValue.ToolTip = ExactBleedTooltip(snapshot.Tier, snapshot.Vitals.InternalBleedMilliunits);
    }

    private void PopulateThreats(NCMedicalSnapshot snapshot)
    {
        var threats = new Dictionary<string, ThreatPresentation>();
        void Add(string id, int priority, NCDiagnosticBand severity, string title, string action)
        {
            if (!threats.TryGetValue(id, out var current) || priority > current.Priority)
                threats[id] = new ThreatPresentation(priority, severity, title, action);
        }

        if (snapshot.Vitals.Consciousness == NCConsciousnessState.BrainDead)
        {
            Add("brain-dead", 1000, NCDiagnosticBand.Critical,
                Loc.GetString("nc-medical-diagnostics-threat-brain-dead"),
                Loc.GetString("nc-medical-diagnostics-action-brain-dead"));
        }
        else if (snapshot.Vitals.Condition == NCPhysiologicalCondition.ClinicalArrest)
        {
            var shockable = snapshot.Vitals.HeartRhythm == NCHeartRhythm.ShockableArrest;
            Add("arrest", 950, NCDiagnosticBand.Critical,
                Loc.GetString(shockable
                    ? "nc-medical-diagnostics-threat-shockable-arrest"
                    : "nc-medical-diagnostics-threat-clinical-arrest"),
                Loc.GetString(shockable
                    ? "nc-medical-diagnostics-action-shockable-arrest"
                    : "nc-medical-diagnostics-action-clinical-arrest"));
        }

        foreach (var warning in snapshot.Warnings)
        {
            var priority = WarningPriority(warning);
            Add(warning.ToString(), priority, WarningBand(warning), WarningName(warning), WarningAction(warning));
        }

        if (threats.Count == 0)
        {
            AddCard(
                ThreatsContainer,
                Loc.GetString("nc-medical-diagnostics-no-immediate-threats"),
                Loc.GetString("nc-medical-diagnostics-continue-observation"),
                HealthyColor,
                "✓");
            return;
        }

        foreach (var threat in threats.Values.OrderByDescending(entry => entry.Priority).Take(5))
            AddCard(ThreatsContainer, threat.Title, threat.Action, BandColor(threat.Severity), "●");
    }

    private void PopulateOverview(NCMedicalSnapshot snapshot)
    {
        if (snapshot.Surgery is { } surgery)
        {
            // Patient condition and scanner capability already live in the fixed record header. The overview
            // keeps only actionable transient context so the primary triage and telemetry remain dominant.
            AddSectionHeading(OverviewContainer, Loc.GetString("nc-medical-diagnostics-surgery"));
            AddCard(
                OverviewContainer,
                Loc.GetString("nc-medical-diagnostics-surgery"),
                Loc.GetString(
                    "nc-medical-diagnostics-surgery-row",
                    ("region", OrganName(surgery.Region.Id)),
                    ("procedure", SurgeryProcedureName(surgery.Procedure)),
                    ("step", surgery.StepIndex + 1),
                    ("state", Value(surgery.State)),
                    ("access", Value(surgery.AccessDepth))),
                ModerateColor);
        }
    }

    private void PopulateRegions(NCMedicalSnapshot snapshot)
    {
        if (!Has(snapshot.Disclosures, NCDiagnosticDisclosure.ProbableRegions))
        {
            AddUnavailable(RegionsContainer, NCDiagnosticTier.Manual);
            return;
        }

        var regions = snapshot.Regions.Where(region => _selectedZone == null || region.Zone == _selectedZone).ToList();
        if (regions.Count == 0)
        {
            AddEmpty(RegionsContainer);
            return;
        }

        foreach (var region in regions.Take(MaximumRowsPerSection))
        {
            var details = new List<string>
            {
                Loc.GetString("nc-medical-diagnostics-burden", ("value", BandName(region.Burden))),
                Loc.GetString("nc-medical-diagnostics-function", ("value", FunctionBandName(region.Function))),
            };
            if (region.WoundCount is { } wounds)
                details.Add(Loc.GetString("nc-medical-diagnostics-wound-count", ("count", wounds)));
            if (region.BoneState is { } bone)
                details.Add(Loc.GetString("nc-medical-diagnostics-bone", ("state", Value(bone))));
            if (region.Findings != NCDiagnosticFindingFlags.None)
                details.Add(ReadableFlags(region.Findings));

            AddCard(
                RegionsContainer,
                ZoneName(region.Zone),
                string.Join(" · ", details),
                BandColor(region.Burden));
        }
    }

    private void PopulateWounds(NCMedicalSnapshot snapshot)
    {
        var canSeeWounds = Has(snapshot.Disclosures, NCDiagnosticDisclosure.VisibleTrauma) ||
                           Has(snapshot.Disclosures, NCDiagnosticDisclosure.DetailedWounds);
        if (!canSeeWounds)
        {
            AddUnavailable(WoundsContainer, NCDiagnosticTier.Visual);
            return;
        }

        var wounds = snapshot.Wounds.Where(wound => _selectedZone == null || wound.Zone == _selectedZone).ToList();
        if (wounds.Count == 0)
        {
            AddEmpty(WoundsContainer);
            return;
        }

        foreach (var wound in wounds.Take(MaximumRowsPerSection))
        {
            var details = new List<string> { Value(wound.Type) };
            if (wound.Stage is { } stage)
                details.Add(Value(stage));
            if (wound.Depth is { } depth)
                details.Add(Value(depth));
            if (wound.ExternalBleeding != NCDiagnosticBand.None)
                details.Add(Loc.GetString("nc-medical-diagnostics-wound-external-bleed", ("value", BandName(wound.ExternalBleeding))));
            if (wound.InternalBleeding != NCDiagnosticBand.None)
                details.Add(Loc.GetString("nc-medical-diagnostics-wound-internal-bleed", ("value", BandName(wound.InternalBleeding))));
            if (wound.Infection != NCDiagnosticBand.None)
                details.Add(Loc.GetString("nc-medical-diagnostics-wound-infection", ("value", BandName(wound.Infection))));
            if (wound.ForeignBody)
                details.Add(Loc.GetString("nc-medical-diagnostics-foreign-body"));

            AddCard(
                WoundsContainer,
                Loc.GetString(
                    "nc-medical-diagnostics-wound-title",
                    ("zone", ZoneName(wound.Zone)),
                    ("severity", Value(wound.Severity))),
                string.Join(" · ", details),
                WoundColor(wound.Severity));
        }
        AddOmitted(WoundsContainer, snapshot.WoundsOmitted);
    }

    private void PopulateOrgans(NCMedicalSnapshot snapshot)
    {
        if (!Has(snapshot.Disclosures, NCDiagnosticDisclosure.Organs))
        {
            AddUnavailable(OrgansContainer, NCDiagnosticTier.ScannerInternal);
            return;
        }
        if (snapshot.Organs.Count == 0)
        {
            AddEmpty(OrgansContainer);
            return;
        }

        foreach (var organ in snapshot.Organs.Take(MaximumRowsPerSection))
        {
            var flags = new List<string>
            {
                Loc.GetString("nc-medical-diagnostics-integrity", ("value", BandName(organ.Integrity))),
                Loc.GetString("nc-medical-diagnostics-function", ("value", FunctionBandName(organ.Function))),
            };
            if (organ.Vital)
                flags.Add(Loc.GetString("nc-medical-diagnostics-vital"));
            if (organ.Failing)
                flags.Add(Loc.GetString("nc-medical-diagnostics-failing"));
            if (organ.Rejection != NCDiagnosticBand.None)
                flags.Add(Loc.GetString("nc-medical-diagnostics-rejection", ("value", BandName(organ.Rejection))));

            var state = organ.Failing
                ? NCDiagnosticBand.Critical
                : MaxBand(organ.Integrity, organ.Function);
            AddCard(
                OrgansContainer,
                OrganName(organ.Category.Id),
                $"{Value(organ.FunctionType)} · {string.Join(" · ", flags)}",
                BandColor(state));
        }
        AddOmitted(OrgansContainer, snapshot.OrgansOmitted);
    }

    private void PopulateCyberware(NCMedicalSnapshot snapshot)
    {
        if (!Has(snapshot.Disclosures, NCDiagnosticDisclosure.Cyberware))
        {
            AddUnavailable(CyberwareContainer, NCDiagnosticTier.ScannerInternal);
            return;
        }
        if (snapshot.Cyberware.Count == 0)
        {
            AddEmpty(CyberwareContainer);
            return;
        }

        foreach (var module in snapshot.Cyberware.Take(MaximumRowsPerSection))
        {
            var placement = module.Slot is { } slot
                ? CyberwareSlotName(slot)
                : module.HostCategory is { } host
                    ? OrganName(host.Id)
                    : Value(module.Form);
            var state = module.Operational
                ? Loc.GetString("nc-medical-diagnostics-cyberware-online")
                : Loc.GetString("nc-medical-diagnostics-cyberware-offline");
            var details = Loc.GetString(
                "nc-medical-diagnostics-cyberware-details",
                ("placement", placement),
                ("integrity", BandName(module.Integrity)),
                ("function", FunctionBandName(module.Function)),
                ("power", BandName(module.Power)),
                ("heat", BandName(module.Heat)),
                ("neural", Value(module.NeuralState)),
                ("state", state));
            var severity = !module.Operational || module.EmpDisabled
                ? NCDiagnosticBand.Critical
                : MaxBand(
                    MaxBand(module.Integrity, module.Function),
                    module.Heat);
            AddCard(CyberwareContainer, CyberwareName(module.Profile), details, BandColor(severity));
        }
        AddOmitted(CyberwareContainer, snapshot.CyberwareOmitted);
    }

    private void PopulateDrugs(NCMedicalSnapshot snapshot)
    {
        if (!Has(snapshot.Disclosures, NCDiagnosticDisclosure.Drugs))
        {
            AddUnavailable(DrugsContainer, NCDiagnosticTier.ScannerInternal);
            return;
        }
        if (snapshot.Drugs.Count == 0)
        {
            AddEmpty(DrugsContainer);
            return;
        }

        foreach (var drug in snapshot.Drugs.Take(MaximumRowsPerSection))
        {
            var concentration = FormatRange(drug.ConcentrationMilliunits, " mU");
            var state = drug.Toxic
                ? Loc.GetString("nc-medical-diagnostics-drug-toxic")
                : drug.Therapeutic
                    ? Loc.GetString("nc-medical-diagnostics-drug-therapeutic")
                    : Loc.GetString("nc-medical-diagnostics-drug-subtherapeutic");
            AddCard(
                DrugsContainer,
                DrugName(drug.Profile),
                Loc.GetString(
                    "nc-medical-diagnostics-drug-details",
                    ("category", Value(drug.Category)),
                    ("concentration", concentration),
                    ("state", state)),
                drug.Toxic ? CriticalColor : drug.Therapeutic ? HealthyColor : ModerateColor);
        }
        AddOmitted(DrugsContainer, snapshot.DrugsOmitted);
    }

    private void OnBodyZoneSelected(NCTargetingState state)
    {
        _selectedZone = state.Mode == NCTargetingMode.SelectedZone ? state.SelectedZone : null;
        RefreshBodyFilterLabel();
        RefreshFilteredSections();
    }

    private void ClearBodyFilter()
    {
        _selectedZone = null;
        BodyDoll.SetState(new NCTargetingState(NCTargetingMode.Automatic, null));
        BodyDoll.SetWoundMarkers([]);
        RefreshBodyFilterLabel();
        RefreshFilteredSections();
    }

    private void RefreshFilteredSections()
    {
        if (_snapshot is not { } snapshot)
            return;
        RegionsContainer.RemoveAllChildren();
        WoundsContainer.RemoveAllChildren();
        PopulateRegions(snapshot);
        PopulateWounds(snapshot);
    }

    private void RefreshBodyFilterLabel()
    {
        BodyFilterLabel.Text = _selectedZone is { } zone
            ? Loc.GetString("nc-medical-diagnostics-body-filter", ("zone", ZoneName(zone)))
            : Loc.GetString("nc-medical-diagnostics-body-all-regions");
    }

    private void SetRatioVital(Label label, ProgressBar bar, NCDiagnosticNumericRange? range)
    {
        if (range is not { } value)
        {
            label.Text = Unknown();
            label.FontColorOverride = MutedColor;
            bar.Value = 0f;
            return;
        }
        label.Text = FormatPercent(value);
        var midpoint = (value.Minimum + value.Maximum) / 2000f;
        bar.Value = Math.Clamp(midpoint, 0f, 1f);
        label.FontColorOverride = RatioColor(midpoint);
    }

    private void SetBloodVital(
        Label label,
        ProgressBar bar,
        NCDiagnosticNumericRange? range,
        int? nominalBloodVolumeUnits)
    {
        if (range is not { } value || nominalBloodVolumeUnits is not > 0)
        {
            label.Text = range is { } raw ? FormatRange(raw, "u") : Unknown();
            label.FontColorOverride = MutedColor;
            bar.Value = 0f;
            return;
        }

        var midpoint = (value.Minimum + value.Maximum) / 2f;
        var ratio = Math.Clamp(midpoint / nominalBloodVolumeUnits.Value, 0f, 1f);
        label.Text = Loc.GetString(
            "nc-medical-diagnostics-blood-value",
            ("volume", FormatRange(value, "u")),
            ("percent", MathF.Round(ratio * 100f)));
        label.FontColorOverride = RatioColor(ratio);
        bar.Value = ratio;
    }

    private string ExactBleedTooltip(NCDiagnosticTier tier, NCDiagnosticNumericRange? range)
    {
        if (tier < NCDiagnosticTier.ScannerInternal || range == null)
            return string.Empty;
        return Loc.GetString(
            "nc-medical-diagnostics-exact-bleed-tooltip",
            ("value", FormatRange(range.Value, " mU/s")));
    }

    private void SetTabTitles(int regions, int wounds, int organs, int cyberware, int drugs)
    {
        Tabs.SetTabTitle(0, Loc.GetString("nc-medical-diagnostics-tab-overview"));
        Tabs.SetTabTitle(1, CountedTab("nc-medical-diagnostics-tab-regions", regions));
        Tabs.SetTabTitle(2, CountedTab("nc-medical-diagnostics-tab-wounds", wounds));
        Tabs.SetTabTitle(3, CountedTab("nc-medical-diagnostics-tab-organs", organs));
        Tabs.SetTabTitle(4, CountedTab("nc-medical-diagnostics-tab-cyberware", cyberware));
        Tabs.SetTabTitle(5, CountedTab("nc-medical-diagnostics-tab-drugs", drugs));
    }

    private static string CountedTab(string locId, int count)
    {
        var title = Loc.GetString(locId);
        return count > 0 ? $"{title} · {count}" : title;
    }

    private static void AddSectionHeading(BoxContainer container, string text)
    {
        var label = new Label
        {
            Text = text,
            FontColorOverride = Color.FromHex("#75FFF2"),
            Margin = new Thickness(2, 4, 0, 1),
        };
        container.AddChild(label);
    }

    private static void AddCard(BoxContainer container, string title, string details, Color color, string marker = "●")
    {
        var panel = new PanelContainer
        {
            HorizontalExpand = true,
            PanelOverride = new StyleBoxFlat
            {
                BackgroundColor = Color.FromHex("#081419"),
                BorderColor = color.WithAlpha(0.72f),
                BorderThickness = new Thickness(0, 0, 0, 2),
            },
        };
        var row = new BoxContainer
        {
            Margin = new Thickness(9, 6),
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            SeparationOverride = 8,
            HorizontalExpand = true,
        };
        row.AddChild(new Label
        {
            Text = marker,
            FontColorOverride = color,
            VerticalAlignment = VAlignment.Top,
        });
        var text = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            SeparationOverride = 2,
            HorizontalExpand = true,
        };
        var titleLabel = new Label { Text = title, FontColorOverride = color, HorizontalExpand = true };
        text.AddChild(titleLabel);
        if (!string.IsNullOrWhiteSpace(details))
            text.AddChild(new Label { Text = details, FontColorOverride = Color.FromHex("#C4CCD2"), HorizontalExpand = true });
