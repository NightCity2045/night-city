    private static string FormatPercent(NCDiagnosticNumericRange value)
    {
        var minimum = value.Minimum / 10f;
        var maximum = value.Maximum / 10f;
        return value.Minimum == value.Maximum
            ? $"{minimum:0.#}%"
            : $"{minimum:0.#}–{maximum:0.#}%";
    }

    private static string FormatRange(NCDiagnosticNumericRange value, string suffix)
    {
        return value.Minimum == value.Maximum
            ? $"{value.Minimum}{suffix}"
            : $"{value.Minimum}–{value.Maximum}{suffix}";
    }

