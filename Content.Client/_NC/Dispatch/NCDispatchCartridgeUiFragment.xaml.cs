using Content.Shared._NC.Dispatch;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._NC.Dispatch;

/// <summary>PDA dispatcher program of NCPD and Trauma Team: the service's incidents, take and close.</summary>
[GenerateTypedNameReferences]
public sealed partial class NCDispatchCartridgeUiFragment : BoxContainer
{
    private static readonly Color OpenColor = Color.FromHex("#FF5A72");
    private static readonly Color AcceptedColor = Color.FromHex("#FFCF66");
    private static readonly Color OnSceneColor = Color.FromHex("#62FFF1");

    public event Action<int>? OnAccept;
    public event Action<int>? OnClose;

    public NCDispatchCartridgeUiFragment()
    {
        RobustXamlLoader.Load(this);
    }

    public void UpdateState(NCDispatchCartridgeUiState state)
    {
        UnavailableLabel.Visible = !state.Available;
        ServiceLabel.Visible = state.Available;
        ServiceLabel.Text = Loc.GetString("nc-dispatch-title", ("service", state.Service));
        EmptyLabel.Visible = state.Available && state.Incidents.Count == 0;

        IncidentsContainer.RemoveAllChildren();
        foreach (var incident in state.Incidents)
            IncidentsContainer.AddChild(BuildRow(incident));
    }

    private Control BuildRow(NCDispatchIncidentView incident)
    {
        var row = new BoxContainer { Orientation = LayoutOrientation.Vertical, SeparationOverride = 2 };
        var (statusId, color) = incident.Status switch
        {
            NCDispatchStatus.Accepted => ("nc-dispatch-status-accepted", AcceptedColor),
            NCDispatchStatus.OnScene => ("nc-dispatch-status-on-scene", OnSceneColor),
            _ => ("nc-dispatch-status-open", OpenColor),
        };

        var kind = Loc.GetString(incident.Kind switch
        {
            NCDispatchIncidentKind.Biomonitor => "nc-dispatch-kind-biomonitor",
            NCDispatchIncidentKind.Shooting => "nc-dispatch-kind-shooting",
            _ => "nc-dispatch-kind-call",
        });

        var header = new BoxContainer { Orientation = LayoutOrientation.Horizontal, SeparationOverride = 6 };
        header.AddChild(new Label
        {
            Text = Loc.GetString("nc-dispatch-row-title", ("id", incident.Id), ("kind", kind)),
            StyleClasses = { "LabelKeyText" },
        });
        header.AddChild(new Label { Text = Loc.GetString(statusId, ("responder", incident.Responder)), FontColorOverride = color });
        header.AddChild(new Control { HorizontalExpand = true });
        header.AddChild(new Label
        {
            Text = Loc.GetString("nc-dispatch-row-age", ("minutes", (int) incident.Age.TotalMinutes)),
            FontColorOverride = Color.FromHex("#888888"),
        });
        row.AddChild(header);

        row.AddChild(new Label
        {
            Text = Loc.GetString("nc-dispatch-row-location", ("location", incident.Location), ("z", incident.Z)),
        });

        var caller = incident.Kind == NCDispatchIncidentKind.Shooting
            ? Loc.GetString("nc-dispatch-row-shots", ("shots", incident.Shots))
            : Loc.GetString("nc-dispatch-row-caller", ("caller", incident.Caller), ("message", incident.Message));
        row.AddChild(new Label { Text = caller, FontColorOverride = Color.FromHex("#CCCCCC") });

        if (incident.Plan.Length > 0)
            row.AddChild(new Label { Text = Loc.GetString("nc-dispatch-row-plan", ("plan", incident.Plan)), FontColorOverride = AcceptedColor });
        if (incident.Uncovered)
            row.AddChild(new Label { Text = Loc.GetString("nc-dispatch-row-uncovered"), FontColorOverride = OpenColor });

        var buttons = new BoxContainer { Orientation = LayoutOrientation.Horizontal, SeparationOverride = 5 };
        if (incident.Status == NCDispatchStatus.Open)
        {
            var accept = new Button { Text = Loc.GetString("nc-dispatch-accept") };
            accept.OnPressed += _ => OnAccept?.Invoke(incident.Id);
            buttons.AddChild(accept);
        }

        var close = new Button { Text = Loc.GetString("nc-dispatch-close") };
        close.OnPressed += _ => OnClose?.Invoke(incident.Id);
        buttons.AddChild(close);
        row.AddChild(buttons);
        row.AddChild(new PanelContainer { StyleClasses = { "LowDivider" } });
        return row;
    }
}
