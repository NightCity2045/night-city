using Content.Client._NC.Bank;
using Content.Shared._NC.Dispatch;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._NC.Dispatch;

/// <summary>PDA emergency program: call NCPD or Trauma Team and manage the Trauma subscription.</summary>
[GenerateTypedNameReferences]
public sealed partial class NCEmergencyCartridgeUiFragment : BoxContainer
{
    private readonly Dictionary<string, ServiceRow> _rows = new();

    public event Action<string, string>? OnCall;
    public event Action<string>? OnCancel;
    public event Action<string>? OnSubscribe;
    public event Action? OnUnsubscribe;

    private sealed class ServiceRow
    {
        public readonly BoxContainer Root = new() { Orientation = LayoutOrientation.Vertical, SeparationOverride = 4 };
        public readonly Label Title = new() { StyleClasses = { "LabelHeading" } };
        public readonly Label Price = new() { FontColorOverride = Color.FromHex("#AAAAAA") };
        public readonly Label Status = new();
        public readonly LineEdit Message = new() { HorizontalExpand = true };
        public readonly Button Call = new();
        public readonly Button Cancel = new();
    }

    public NCEmergencyCartridgeUiFragment()
    {
        RobustXamlLoader.Load(this);
        UnsubscribeButton.OnPressed += _ => OnUnsubscribe?.Invoke();
    }

    public void UpdateState(NCEmergencyCartridgeUiState state)
    {
        BalanceLabel.Text = state.HasAccount
            ? Loc.GetString("nc-emergency-balance", ("balance", NCBankFormat.Money(state.Balance)))
            : Loc.GetString("nc-bank-no-account");

        foreach (var service in state.Services)
            UpdateService(service);

        NCTraumaPlanView? current = null;
        foreach (var plan in state.Plans)
        {
            if (plan.Id == state.Plan)
                current = plan;
        }

        PlanLabel.Text = current is { } active
            ? Loc.GetString("nc-trauma-current-plan", ("plan", active.Name), ("price", NCBankFormat.Money(active.Price)))
            : Loc.GetString("nc-trauma-no-plan");
        UnsubscribeButton.Visible = current != null;

        PlansContainer.RemoveAllChildren();
        foreach (var plan in state.Plans)
        {
            var row = new BoxContainer { Orientation = LayoutOrientation.Vertical };
            var header = new BoxContainer { Orientation = LayoutOrientation.Horizontal, SeparationOverride = 6 };
            header.AddChild(new Label
            {
                Text = Loc.GetString("nc-trauma-plan-line",
                    ("plan", plan.Name),
                    ("price", NCBankFormat.Money(plan.Price)),
                    ("minutes", plan.ResponseMinutes)),
                HorizontalExpand = true,
            });

            var subscribe = new Button
            {
                Text = Loc.GetString(plan.Id == state.Plan ? "nc-trauma-plan-active" : "nc-trauma-subscribe"),
                Disabled = plan.Id == state.Plan || !state.HasAccount,
            };
            var id = plan.Id;
            subscribe.OnPressed += _ => OnSubscribe?.Invoke(id);
            header.AddChild(subscribe);
            row.AddChild(header);
            row.AddChild(new Label { Text = plan.Description, FontColorOverride = Color.FromHex("#888888") });
            PlansContainer.AddChild(row);
        }
    }

    private void UpdateService(NCEmergencyServiceView service)
    {
        if (!_rows.TryGetValue(service.Id, out var row))
        {
            row = new ServiceRow();
            row.Message.PlaceHolder = Loc.GetString("nc-emergency-message-placeholder");
            row.Call.Text = Loc.GetString("nc-emergency-call");
            row.Cancel.Text = Loc.GetString("nc-emergency-cancel");
            var id = service.Id;
            row.Call.OnPressed += _ =>
            {
                OnCall?.Invoke(id, row.Message.Text);
                row.Message.Text = string.Empty;
            };
            row.Cancel.OnPressed += _ => OnCancel?.Invoke(id);

            var input = new BoxContainer { Orientation = LayoutOrientation.Horizontal, SeparationOverride = 5 };
            input.AddChild(row.Message);
            input.AddChild(row.Call);
            input.AddChild(row.Cancel);
            row.Root.AddChild(row.Title);
            row.Root.AddChild(row.Price);
            row.Root.AddChild(row.Status);
            row.Root.AddChild(input);
            ServicesContainer.AddChild(row.Root);
            _rows[service.Id] = row;
        }

        row.Title.Text = service.Name;
        row.Price.Text = service.Price > 0
            ? Loc.GetString("nc-emergency-price", ("price", NCBankFormat.Money(service.Price)))
            : Loc.GetString("nc-emergency-free");

        var active = service.CallId != null;
        row.Status.Visible = active || service.Cooldown > TimeSpan.Zero;
        row.Status.Text = active
            ? Loc.GetString(service.CallStatus switch
            {
                NCDispatchStatus.Accepted => "nc-emergency-status-accepted",
                NCDispatchStatus.OnScene => "nc-emergency-status-on-scene",
                _ => "nc-emergency-status-open",
            }, ("id", service.CallId ?? 0), ("responder", service.Responder))
            : Loc.GetString("nc-emergency-cooldown", ("seconds", (int) Math.Ceiling(service.Cooldown.TotalSeconds)));
        row.Call.Disabled = active || service.Cooldown > TimeSpan.Zero;
        row.Cancel.Visible = active;
    }
}
