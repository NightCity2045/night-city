using Content.Client.UserInterface.Controls;
using Content.Shared._NC.Shops;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._NC.Shops;

[GenerateTypedNameReferences]
public sealed partial class NCShopWindow : FancyWindow
{
    [Dependency] private IPrototypeManager _prototypes = default!;

    public event Action<int>? OnBuy;

    public NCShopWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
    }

    public void UpdateState(NCShopUiState state)
    {
        if (_prototypes.TryIndex<NCShopCatalogPrototype>(state.Catalog, out var catalog))
            Title = Loc.GetString(catalog.Name);

        AccountLabel.Text = state.HasAccount
            ? Loc.GetString("nc-shop-balance", ("amount", state.Balance))
            : Loc.GetString("nc-shop-error-no-account");

        LinesContainer.RemoveAllChildren();
        foreach (var line in state.Lines)
            LinesContainer.AddChild(BuildLine(line, state));
    }

    private Control BuildLine(NCShopLine line, NCShopUiState state)
    {
        var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 6 };
        var view = new EntityPrototypeView { SetSize = new System.Numerics.Vector2(32, 32) };
        view.SetPrototype(line.Item);
        row.AddChild(view);

        var name = _prototypes.TryIndex<EntityPrototype>(line.Item, out var prototype) ? prototype.Name : line.Item;
        var text = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, HorizontalExpand = true };
        text.AddChild(new Label { Text = name, ClipText = true });
        text.AddChild(new Label
        {
            Text = line.Stock > 0
                ? Loc.GetString("nc-shop-stock", ("count", line.Stock))
                : Loc.GetString("nc-shop-sold-out"),
            FontColorOverride = line.Stock > 0 ? Color.FromHex("#AAAAAA") : Color.FromHex("#E3A59F"),
        });
        row.AddChild(text);

        var buy = new Button
        {
            Text = Loc.GetString("nc-shop-buy", ("price", line.Price)),
            Disabled = !state.HasAccount || line.Stock <= 0 || line.Price > state.Balance,
            VerticalAlignment = VAlignment.Center,
        };
        buy.OnPressed += _ => OnBuy?.Invoke(line.Index);
        row.AddChild(buy);
        return row;
    }
}
