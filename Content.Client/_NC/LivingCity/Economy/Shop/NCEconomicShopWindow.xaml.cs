using System.Linq;
using Content.Client.UserInterface.Controls;
using Content.Shared._NC.LivingCity.Economy;
using Content.Shared._NC.LivingCity.Economy.Shop;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._NC.LivingCity.Economy.Shop;

[GenerateTypedNameReferences]
public sealed partial class NCEconomicShopWindow : FancyWindow
{
    private const string AllCategories = "nc-economic-shop-category-all";

    private readonly List<NCEconomicShopListingSummary> _listings = [];
    private readonly List<string> _categories = [];
    private NCEconomicShopListingCard? _selectedCard;
    private NCEconomicShopListingSummary? _selected;
    private string _selectedCategory = AllCategories;
    private bool _ready;
    private bool _hasAccount;

    public event Action<NCEconomicOfferKind, string, long>? OnPurchase;

    public NCEconomicShopWindow()
    {
        RobustXamlLoader.Load(this);
        CategorySelector.OnItemSelected += args =>
        {
            CategorySelector.SelectId(args.Id);
            _selectedCategory = _categories[args.Id];
            PopulateListings();
        };
        SearchEdit.OnTextChanged += _ => PopulateListings();
        PurchaseButton.OnPressed += _ =>
        {
            if (_selected is not { } selected || !long.TryParse(QuantityEdit.Text, out var quantity) ||
                quantity <= 0 || quantity > selected.AvailableQuantity)
                return;

            OnPurchase?.Invoke(selected.Kind, selected.AssetId, quantity);
        };
        QuantityEdit.OnTextChanged += _ => UpdateOrderControls();
        ClearSelection();
    }

    public void UpdateState(NCEconomicShopState state)
    {
        _ready = state.Ready;
        _hasAccount = state.HasAccount;
        ShopNameLabel.Text = state.ShopName.StartsWith("nc-", StringComparison.Ordinal)
            ? Loc.GetString(state.ShopName)
            : state.ShopName;
        BalanceLabel.Text = state.HasAccount
            ? Loc.GetString("nc-economic-shop-credits", ("amount", state.Balance))
            : Loc.GetString("nc-economic-shop-no-account");
        BalanceLabel.FontColorOverride = state.HasAccount ? Color.FromHex("#72F4FF") : Color.Orange;
        LoadingPanel.Visible = !state.Ready;
        CatalogPanel.Visible = state.Ready;
        NoticeLabel.Text = string.IsNullOrEmpty(state.Notice) ? string.Empty : Loc.GetString(state.Notice);
        NoticePanel.Visible = !string.IsNullOrEmpty(state.Notice);

        _listings.Clear();
        _listings.AddRange(state.Listings);
        RefreshCategories();
        PopulateListings();
    }

    private void RefreshCategories()
    {
        var categories = _listings
            .Select(listing => listing.Category)
            .Where(category => !string.IsNullOrWhiteSpace(category))
            .Distinct()
            .OrderBy(category => Loc.GetString(category))
            .ToList();
        categories.Insert(0, AllCategories);

        if (!_categories.SequenceEqual(categories))
        {
            _categories.Clear();
            _categories.AddRange(categories);
            CategorySelector.Clear();
            for (var index = 0; index < _categories.Count; index++)
                CategorySelector.AddItem(Loc.GetString(_categories[index]), index);
        }

        var selectedIndex = _categories.IndexOf(_selectedCategory);
        if (selectedIndex < 0)
        {
            selectedIndex = 0;
            _selectedCategory = AllCategories;
        }

        CategorySelector.SelectId(selectedIndex);
    }

    private void PopulateListings()
    {
        var selectedId = _selected?.AssetId;
        _selected = null;
        _selectedCard = null;
        ListingGrid.RemoveAllChildren();
        var search = SearchEdit.Text.Trim();
        var count = 0;

        foreach (var listing in _listings)
        {
            var displayName = LocalizeDisplayName(listing.DisplayName);
            var description = Loc.GetString(listing.Description);
            if (_selectedCategory != AllCategories && listing.Category != _selectedCategory ||
                search.Length > 0 && !displayName.Contains(search, StringComparison.CurrentCultureIgnoreCase) &&
                !description.Contains(search, StringComparison.CurrentCultureIgnoreCase))
                continue;

            var card = new NCEconomicShopListingCard(listing);
            card.OnPressed += _ => SelectListing(card);
            ListingGrid.AddChild(card);
            count++;
            if (listing.AssetId == selectedId)
                SelectListing(card);
        }

        ListingCountLabel.Text = Loc.GetString("nc-economic-shop-listing-count", ("count", count));
        EmptyLabel.Visible = count == 0;
        if (_selected == null)
            ClearSelection();
    }

    private void SelectListing(NCEconomicShopListingCard card)
    {
        _selectedCard?.SetSelected(false);
        _selectedCard = card;
        _selected = card.Listing;
        card.SetSelected(true);

        var listing = card.Listing;
        ProductNameLabel.Text = LocalizeDisplayName(listing.DisplayName);
        ProductCategoryLabel.Text = Loc.GetString(listing.Category);
        DescriptionLabel.SetMessage(Loc.GetString(listing.Description), Color.FromHex("#91A9AF"));
        StockValueLabel.Text = listing.AvailableQuantity.ToString();
        PriceValueLabel.Text = Loc.GetString("nc-economic-shop-credits", ("amount", listing.BaseUnitPrice));
        if (!string.IsNullOrWhiteSpace(listing.PreviewPrototype))
        {
            SelectedPreview.SetPrototype(new EntProtoId(listing.PreviewPrototype));
            SelectedPreview.Visible = true;
        }
        else
        {
            SelectedPreview.Visible = false;
        }

        var supportsQuantity = listing.Kind == NCEconomicOfferKind.CommodityBatch;
        QuantityLabel.Visible = supportsQuantity;
        QuantityEdit.Visible = supportsQuantity;
        if (!supportsQuantity)
            QuantityEdit.Text = "1";
        UpdateOrderControls();
    }

    private void ClearSelection()
    {
        _selectedCard?.SetSelected(false);
        _selectedCard = null;
        _selected = null;
        SelectedPreview.Visible = false;
        ProductNameLabel.Text = Loc.GetString("nc-economic-shop-select-item");
        ProductCategoryLabel.Text = string.Empty;
        DescriptionLabel.SetMessage(
            Loc.GetString("nc-economic-shop-select-item-description"),
            Color.FromHex("#91A9AF"));
        StockValueLabel.Text = "--";
        PriceValueLabel.Text = "--";
        QuantityLabel.Visible = false;
        QuantityEdit.Visible = false;
        OrderTotalLabel.Text = "--";
        UpdateOrderControls();
    }

    private void UpdateOrderControls()
    {
        var validQuantity = long.TryParse(QuantityEdit.Text, out var quantity) && quantity > 0 &&
                            _selected != null && quantity <= _selected.AvailableQuantity &&
                            (_selected.Kind != NCEconomicOfferKind.ItemInstance || quantity == 1) &&
                            (_selected.BaseUnitPrice == 0 || quantity <= long.MaxValue / _selected.BaseUnitPrice);
        PurchaseButton.Disabled = !_ready || !_hasAccount || !validQuantity;
        QuantityEdit.Editable = _selected?.Kind != NCEconomicOfferKind.ItemInstance;
        OrderTotalLabel.Text = validQuantity
            ? Loc.GetString("nc-economic-shop-credits", ("amount", quantity * _selected!.BaseUnitPrice))
            : "--";
    }

    private static string LocalizeDisplayName(string displayName)
    {
        return Loc.TryGetString(displayName, out var localizedName) ? localizedName : displayName;
    }
}
