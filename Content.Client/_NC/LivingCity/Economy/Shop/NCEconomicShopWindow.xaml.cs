using Content.Client.UserInterface.Controls;
using Content.Shared._NC.LivingCity.Economy;
using Content.Shared._NC.LivingCity.Economy.Shop;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._NC.LivingCity.Economy.Shop;

[GenerateTypedNameReferences]
public sealed partial class NCEconomicShopWindow : FancyWindow
{
    private NCEconomicShopListingSummary? _selected;
    private bool _ready;
    private bool _hasAccount;

    public event Action<NCEconomicOfferKind, string, long>? OnPurchase;

    public NCEconomicShopWindow()
    {
        RobustXamlLoader.Load(this);
        ListingList.OnItemSelected += args =>
        {
            _selected = ListingList[args.ItemIndex].Metadata as NCEconomicShopListingSummary;
            if (_selected?.Kind == NCEconomicOfferKind.ItemInstance)
                QuantityEdit.Text = "1";
            UpdateButton();
        };
        PurchaseButton.OnPressed += _ =>
        {
            if (_selected is not { } selected || !long.TryParse(QuantityEdit.Text, out var quantity) ||
                quantity <= 0 || quantity > selected.AvailableQuantity)
                return;
            OnPurchase?.Invoke(selected.Kind, selected.AssetId, quantity);
        };
        QuantityEdit.OnTextChanged += _ => UpdateButton();
    }

    public void UpdateState(NCEconomicShopState state)
    {
        _ready = state.Ready;
        _hasAccount = state.HasAccount;
        ShopNameLabel.Text = state.ShopName;
        BalanceLabel.Text = state.HasAccount
            ? Loc.GetString("nc-economic-shop-credits", ("amount", state.Balance))
            : Loc.GetString("nc-economic-shop-no-account");
        BalanceLabel.FontColorOverride = state.HasAccount ? Color.LightGreen : Color.Orange;
        StatusLabel.Text = state.Ready
            ? string.Empty
            : Loc.GetString("nc-economic-shop-not-ready");
        StatusLabel.Visible = !state.Ready;
        NoticeLabel.Text = string.IsNullOrEmpty(state.Notice) ? string.Empty : Loc.GetString(state.Notice);
        NoticeLabel.Visible = !string.IsNullOrEmpty(state.Notice);

        var selectedId = _selected?.AssetId;
        _selected = null;
        ListingList.Clear();
        foreach (var listing in state.Listings)
        {
            var expiry = listing.ShelfLifeRemaining is { } remaining
                ? Loc.GetString("nc-economic-shop-expiry", ("hours", Math.Max(0, (int) remaining.TotalHours)))
                : string.Empty;
            var item = ListingList.AddItem(Loc.GetString("nc-economic-shop-listing",
                ("name", listing.DisplayName),
                ("quantity", listing.AvailableQuantity),
                ("price", listing.BaseUnitPrice),
                ("quality", listing.QualityOrCondition),
                ("expiry", expiry)), metadata: listing);
            if (listing.AssetId == selectedId)
            {
                item.Selected = true;
                _selected = listing;
            }
        }
        EmptyLabel.Visible = state.Listings.Count == 0;
        UpdateButton();
    }

    private void UpdateButton()
    {
        var validQuantity = long.TryParse(QuantityEdit.Text, out var quantity) && quantity > 0 &&
                            _selected != null && quantity <= _selected.AvailableQuantity &&
                            (_selected.Kind != NCEconomicOfferKind.ItemInstance || quantity == 1);
        PurchaseButton.Disabled = !_ready || !_hasAccount || _selected == null || !validQuantity;
        QuantityEdit.Editable = _selected?.Kind != NCEconomicOfferKind.ItemInstance;
    }
}
