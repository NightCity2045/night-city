using Content.Shared._NC.LivingCity.Economy.Shop;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._NC.LivingCity.Economy.Shop;

/// <summary>
/// A compact product card that keeps catalog presentation separate from the authoritative shop state.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class NCEconomicShopListingCard : ContainerButton
{
    public NCEconomicShopListingSummary Listing { get; }

    public NCEconomicShopListingCard(NCEconomicShopListingSummary listing)
    {
        Listing = listing;
        RobustXamlLoader.Load(this);

        ProductName.Text = Loc.TryGetString(listing.DisplayName, out var localizedName)
            ? localizedName
            : listing.DisplayName;
        CategoryLabel.Text = Loc.GetString(listing.Category);
        PriceLabel.Text = Loc.GetString("nc-economic-shop-card-price", ("price", listing.BaseUnitPrice));
        StockLabel.Text = Loc.GetString("nc-economic-shop-card-stock", ("quantity", listing.AvailableQuantity));

        if (!string.IsNullOrWhiteSpace(listing.PreviewPrototype))
            Preview.SetPrototype(new EntProtoId(listing.PreviewPrototype));
        else
            Preview.Visible = false;
    }

    public void SetSelected(bool selected)
    {
        CardPanel.PanelOverride = new StyleBoxFlat
        {
            BackgroundColor = Color.FromHex(selected ? "#14252A" : "#0B171D"),
            BorderColor = Color.FromHex(selected ? "#FFB32C" : "#25505A"),
            BorderThickness = new Thickness(1, 1, 1, selected ? 3 : 2),
        };
    }
}
