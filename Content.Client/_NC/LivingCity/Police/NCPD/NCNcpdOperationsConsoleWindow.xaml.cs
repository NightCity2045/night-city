using Content.Client.UserInterface.Controls;
using System.Linq;
using Content.Shared._NC.Agent.UI;
using Content.Shared._NC.LivingCity.Police.NCPD;
using Content.Shared.Roles;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Maths;
using Robust.Shared.Timing;
using Robust.Shared.Utility;

namespace Content.Client._NC.LivingCity.Police.NCPD;

[GenerateTypedNameReferences]
public sealed partial class NCNcpdOperationsConsoleWindow : FancyWindow
{
    private static readonly TimeSpan RefreshInterval = TimeSpan.FromSeconds(1);

    [Dependency] private IPrototypeManager _prototypes = default!;
    [Dependency] private IGameTiming _timing = default!;

    private readonly Dictionary<int, Guid> _units = [];
    private readonly Dictionary<int, Guid> _zones = [];
    private readonly Dictionary<int, NCNcpdCommandKind> _orders = [];
    private readonly Dictionary<int, Guid> _commands = [];
    private List<NCNcpdOperationsZoneSummary> _allZones = [];
    private List<NCNcpdOperationsCommandSummary> _allCommands = [];
    private Guid? _selectedUnit;
    private Guid? _selectedZone;
    private Guid? _selectedCommand;
    private bool _canIssue;
    private TimeSpan _nextRefresh;

    public event Action<Guid, NCNcpdCommandKind, Guid, int, string>? OnIssue;
    public event Action<Guid, string>? OnCancel;
    public event Action? OnRefresh;

    public NCNcpdOperationsConsoleWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        UnitList.OnItemSelected += args => SelectUnit(args.ItemIndex);
        ZoneList.OnItemSelected += args => SelectZone(args.ItemIndex);
        CommandList.OnItemSelected += args => SelectCommand(args.ItemIndex);
        OrderSelector.OnItemSelected += args =>
        {
            args.Button.SelectId(args.Id);
            UpdateButtons();
        };
        ZoneFilter.OnTextChanged += _ => PopulateZones();
        RefreshButton.OnPressed += _ => RequestRefresh();
        IssueButton.OnPressed += _ => Issue();
        CancelButton.OnPressed += _ => Cancel();
        _nextRefresh = _timing.RealTime + RefreshInterval;
    }

    public void UpdateState(NCNcpdOperationsUpdateMessage state)
    {
        _canIssue = state.CanIssue;
        AuthorityLabel.Text = state.CanIssue
            ? Loc.GetString("nc-ncpd-operations-authority", ("name", state.AuthorityName),
                ("job", JobName(state.AuthorityJob)))
            : Loc.GetString("nc-ncpd-operations-read-only", ("name", state.AuthorityName));
        AuthorityLabel.FontColorOverride = state.CanIssue ? Color.FromHex("#78E69B") : Color.FromHex("#E8A16D");
        NoticeLabel.Text = string.IsNullOrWhiteSpace(state.Notice)
            ? Loc.GetString("nc-ncpd-operations-live")
            : state.Notice;

        PopulateUnits(state.Units);
        if (state.Zones.Count > 0)
        {
            _allZones = state.Zones;
            PopulateZones();
        }
        PopulateOrders(state.AllowedCommands);
        PopulateCommands(state.Commands);

        if (state.MapFeatures.Count > 0)
        {
            CityMap.SetMapData(new NCAgentMapUpdateMessage(
                state.NetworkId,
                state.Z,
                state.ConsolePosition,
                state.MapFeatures,
                string.Empty));
        }

        UpdateButtons();
        _nextRefresh = _timing.RealTime + RefreshInterval;
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        if (_timing.RealTime < _nextRefresh)
            return;
        RequestRefresh();
    }

    private void RequestRefresh()
    {
        _nextRefresh = _timing.RealTime + RefreshInterval;
        OnRefresh?.Invoke();
    }

    private void PopulateUnits(IReadOnlyList<NCNcpdOperationsUnitSummary> units)
    {
        var keep = _selectedUnit;
        _units.Clear();
        UnitList.Clear();
        var selectedIndex = -1;
        for (var index = 0; index < units.Count; index++)
        {
            var unit = units[index];
            _units[index] = unit.UnitId;
            UnitList.AddItem($"{unit.Callsign} // {unit.Leader}\n{unit.Assignment}", metadata: unit);
            if (keep == unit.UnitId)
                selectedIndex = index;
        }
        if (selectedIndex >= 0)
            UnitList[selectedIndex].Selected = true;
        else
            _selectedUnit = null;
    }

    private void PopulateZones()
    {
        var keep = _selectedZone;
        var filter = ZoneFilter.Text.Trim();
        _zones.Clear();
        ZoneList.Clear();
        var item = 0;
        var selectedIndex = -1;
        foreach (var zone in _allZones)
        {
            if (filter.Length > 0 && !zone.Name.Contains(filter, StringComparison.OrdinalIgnoreCase) &&
                !zone.ParentName.Contains(filter, StringComparison.OrdinalIgnoreCase))
                continue;
            _zones[item] = zone.ZoneId;
            ZoneList.AddItem($"[{zone.Scope}] {zone.Name} // {zone.ParentName}", metadata: zone);
            if (keep == zone.ZoneId)
                selectedIndex = item;
            item++;
        }
        if (selectedIndex >= 0)
            ZoneList[selectedIndex].Selected = true;
        else if (keep != null)
            _selectedZone = null;
        UpdateButtons();
    }

    private void PopulateOrders(IReadOnlyList<NCNcpdCommandKind> orders)
    {
        NCNcpdCommandKind? keep = _orders.GetValueOrDefault(OrderSelector.SelectedId);
        _orders.Clear();
        OrderSelector.Clear();
        for (var index = 0; index < orders.Count; index++)
        {
            _orders[index] = orders[index];
            OrderSelector.AddItem(OrderName(orders[index]), index);
            if (keep == orders[index])
                OrderSelector.SelectId(index);
        }
        if (orders.Count > 0 && !_orders.ContainsKey(OrderSelector.SelectedId))
            OrderSelector.SelectId(0);
    }

    private void PopulateCommands(List<NCNcpdOperationsCommandSummary> commands)
    {
        _allCommands = commands;
        var keep = _selectedCommand;
        _commands.Clear();
        CommandList.Clear();
        var selectedIndex = -1;
        for (var index = 0; index < commands.Count; index++)
        {
            var command = commands[index];
            _commands[index] = command.CommandId;
            CommandList.AddItem($"{command.Callsign} // {OrderName(command.Kind)} // {command.Status}", metadata: command);
            if (keep == command.CommandId)
                selectedIndex = index;
        }
        if (selectedIndex >= 0)
            CommandList[selectedIndex].Selected = true;
        else
            _selectedCommand = null;
    }

    private void SelectUnit(int index)
    {
        if (!_units.TryGetValue(index, out var id) || UnitList[index].Metadata is not NCNcpdOperationsUnitSummary unit)
            return;
        _selectedUnit = id;
        SelectedUnitLabel.Text = $"{unit.Callsign} // {unit.Leader}";
        UnitDetails.Text = $"Members: {unit.Members}\nCurrent zone: {unit.CurrentZone}\n{unit.Assignment}";
        UpdateButtons();
    }

    private void SelectZone(int index)
    {
        if (!_zones.TryGetValue(index, out var id) || ZoneList[index].Metadata is not NCNcpdOperationsZoneSummary zone)
            return;
        _selectedZone = id;
        NoticeLabel.Text = $"Selected zone: {zone.Name} // {zone.ParentName}";
        UpdateButtons();
    }

    private void SelectCommand(int index)
    {
        if (!_commands.TryGetValue(index, out var id) ||
            CommandList[index].Metadata is not NCNcpdOperationsCommandSummary command)
            return;
        _selectedCommand = id;
        CommandDetails.Text =
            $"{command.Zone} // priority {command.Priority}\nIssued by {command.Issuer}: {command.Reason}\n{command.Note}";
        UpdateButtons();
    }

    private void Issue()
    {
        if (_selectedUnit is not { } unit || !_orders.TryGetValue(OrderSelector.SelectedId, out var kind) ||
            !int.TryParse(PriorityEdit.Text.Trim(), out var priority))
            return;
        var noZone = kind is NCNcpdCommandKind.ReturnToStation or NCNcpdCommandKind.StandDown;
        if (!noZone && _selectedZone is not { })
            return;
        var reason = Rope.Collapse(ReasonEdit.TextRope).Trim();
        OnIssue?.Invoke(unit, kind, noZone ? Guid.Empty : _selectedZone!.Value, priority, reason);
    }

    private void Cancel()
    {
        if (_selectedCommand is not { } command)
            return;
        OnCancel?.Invoke(command, Rope.Collapse(ReasonEdit.TextRope).Trim());
    }

    private void UpdateButtons()
    {
        var hasOrder = _orders.TryGetValue(OrderSelector.SelectedId, out var order);
        var noZone = hasOrder && order is (NCNcpdCommandKind.ReturnToStation or NCNcpdCommandKind.StandDown);
        IssueButton.Disabled = !_canIssue || _selectedUnit == null || !hasOrder || (!noZone && _selectedZone == null);
        var command = _selectedCommand is { } selected
            ? _allCommands.FirstOrDefault(value => value.CommandId == selected)
            : null;
        CancelButton.Disabled = command is not { Cancellable: true };
        OrderSelector.Disabled = !_canIssue || _orders.Count == 0;
        PriorityEdit.Editable = _canIssue;
        ReasonEdit.Editable = _canIssue;
    }

    private string JobName(string jobId) =>
        _prototypes.TryIndex<JobPrototype>(jobId, out var job) ? job.LocalizedName : jobId;

    private static string OrderName(NCNcpdCommandKind kind) =>
        Loc.GetString($"nc-ncpd-order-{kind.ToString().ToLowerInvariant()}");
}
