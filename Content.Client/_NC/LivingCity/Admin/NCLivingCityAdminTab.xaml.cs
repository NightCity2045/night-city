    private static bool IsProblem(NCLivingCityAdminField field)
    {
        if (field.Value.Equals("critical", StringComparison.OrdinalIgnoreCase))
            return true;
        if ((field.Key.Contains("configuration-error", StringComparison.Ordinal) ||
             field.Key.Contains("last-fetch-error", StringComparison.Ordinal) ||
             field.Key.Equals("error", StringComparison.Ordinal)) &&
            !field.Value.Equals("none", StringComparison.OrdinalIgnoreCase))
            return true;
        return field.Key.Contains("validation-errors", StringComparison.Ordinal) && Positive(field.Value);
    }

    private static bool IsWarning(NCLivingCityAdminField field)
    {
        if (field.Value.Equals("elevated", StringComparison.OrdinalIgnoreCase))
            return true;
        return (field.Key.Contains("failed", StringComparison.Ordinal) ||
                field.Key.Contains("rejected", StringComparison.Ordinal) ||
                field.Key.Contains("exhausted", StringComparison.Ordinal) ||
                field.Key.Contains("conflicts", StringComparison.Ordinal) ||
                field.Key.Contains("warnings", StringComparison.Ordinal)) &&
               Positive(field.Value);
    }

    private static bool Positive(string value) => int.TryParse(value, out var number) && number > 0;

    private enum StatusTone : byte
    {
        Info,
        Loading,
        Success,
        Warning,
        Error,
    }

