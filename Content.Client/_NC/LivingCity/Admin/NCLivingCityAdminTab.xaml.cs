    private void SendPopulationAction(NCLivingCityAdminPopulationAction action, Guid confirmationToken)
    {
        var profileId = SelectedPopulationProfile();
        if (action is NCLivingCityAdminPopulationAction.ValidateProfile or
            NCLivingCityAdminPopulationAction.ImportProfile &&
            !Require(PopulationActionStatus,
                (Loc.GetString("nc-living-city-admin-population-profile"), profileId)))
            return;

        if (action != NCLivingCityAdminPopulationAction.ValidateProfile &&
            !Require(PopulationActionStatus,
                (Loc.GetString("nc-living-city-admin-reason"), PopulationReason.Text)))
            return;

        SetStatus(PopulationActionStatus, Loc.GetString("nc-living-city-admin-loading"), StatusTone.Loading);
        _admin.RequestPopulationAction(
            action,
            profileId,
            PopulationReason.Text,
            confirmationToken);
    }

    /// <summary>
    /// Presents every data-authored population profile without requiring administrators to memorize prototype IDs.
    /// The selected index is resolved back to its stable prototype ID only when an operation is submitted.
    /// </summary>
    private void PopulatePopulationProfiles()
    {
        PopulationProfile.Clear();
        _populationProfileIds.Clear();

        foreach (var profile in _prototypes
                     .EnumeratePrototypes<NCCityPopulationProfilePrototype>()
                     .OrderBy(static profile => profile.ID, StringComparer.Ordinal))
        {
            var actorCount = profile.Actors.Count + profile.Cohorts.Sum(static cohort => cohort.Count);
            var index = _populationProfileIds.Count;
            _populationProfileIds.Add(profile.ID);
            PopulationProfile.AddItem($"{profile.ID} ({actorCount} NPC)", index);
        }

        if (_populationProfileIds.Count != 0)
            PopulationProfile.SelectId(0);
    }

    private string SelectedPopulationProfile()
    {
        var selected = PopulationProfile.SelectedId;
        return selected >= 0 && selected < _populationProfileIds.Count
            ? _populationProfileIds[selected]
            : string.Empty;
    }

