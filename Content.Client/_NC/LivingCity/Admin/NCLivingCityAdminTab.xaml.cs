using System.Linq;
using Content.Shared._NC.LivingCity.Admin;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._NC.LivingCity.Admin;

[GenerateTypedNameReferences]
public sealed partial class NCLivingCityAdminTab : Control
{
    [Dependency] private IEntitySystemManager _systems = default!;

    private readonly NCLivingCityAdminClientSystem _admin;
    private Guid _pendingRequest;

    public NCLivingCityAdminTab()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _admin = _systems.GetEntitySystem<NCLivingCityAdminClientSystem>();
        _admin.ResultReceived += OnResult;
        CreateRandomResident.OnPressed += _ => RequestRandomResident();
    }

    /// <summary>The reduced tab has no polling; the hook remains for the parent F7 window.</summary>
    public void SetMonitoringActive(bool active)
    {
    }

    protected override void Dispose(bool disposing)
    {
        if (disposing)
            _admin.ResultReceived -= OnResult;
        base.Dispose(disposing);
    }

    private void RequestRandomResident()
    {
        if (_pendingRequest != Guid.Empty)
            return;
        CreateRandomResident.Disabled = true;
        Status.Text = Loc.GetString("nc-living-city-admin-loading");
        Result.Text = string.Empty;
        _pendingRequest = _admin.RequestRandomResident();
    }

    private void OnResult(NCLivingCityAdminRandomResidentResult result)
    {
        if (result.RequestId != _pendingRequest)
            return;
        _pendingRequest = Guid.Empty;
        CreateRandomResident.Disabled = false;
        Status.Text = result.Status == NCLivingCityAdminMutationStatus.Applied
            ? Loc.GetString("nc-living-city-admin-action-complete")
            : result.Error ?? result.Status.ToString();
        Result.Text = string.Join('\n', result.Fields.Select(field => $"{field.Key}: {field.Value}"));
    }
}
