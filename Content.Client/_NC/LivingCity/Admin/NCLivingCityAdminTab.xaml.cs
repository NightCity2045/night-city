        RunInspection.OnPressed += _ => RequestInspection();
        BindActorAction(CreateActor, NCLivingCityAdminActorAction.Create);
        BindActorAction(FreezeActor, NCLivingCityAdminActorAction.Freeze);
        BindActorAction(UnfreezeActor, NCLivingCityAdminActorAction.Unfreeze);
        BindActorAction(MoveActor, NCLivingCityAdminActorAction.Move);
        BindActorAction(CaptureActorDomains, NCLivingCityAdminActorAction.CaptureDomains);
        BindActorAction(RestoreActorHealth, NCLivingCityAdminActorAction.RestoreHealth);
        BindActorAction(MaterializeActor, NCLivingCityAdminActorAction.Materialize);
        BindActorAction(DematerializeActor, NCLivingCityAdminActorAction.Dematerialize);

        BindGroupAction(CreateGroup, NCLivingCityAdminGroupAction.Create);
        BindGroupAction(AddGroupMember, NCLivingCityAdminGroupAction.AddMember);
        BindGroupAction(RemoveGroupMember, NCLivingCityAdminGroupAction.RemoveMember);
        BindGroupAction(TransferGroupMember, NCLivingCityAdminGroupAction.TransferMember);
        BindGroupAction(SetGroupLeader, NCLivingCityAdminGroupAction.SetLeader);
        BindGroupAction(SetGroupDirective, NCLivingCityAdminGroupAction.SetDirective);
        BindGroupAction(MaterializeGroup, NCLivingCityAdminGroupAction.Materialize);
        BindGroupAction(DematerializeGroup, NCLivingCityAdminGroupAction.Dematerialize);

        ValidatePopulationProfile.OnPressed += _ =>
            SendPopulationAction(NCLivingCityAdminPopulationAction.ValidateProfile, Guid.Empty);
        BindPopulationAction(ImportPopulationProfile, NCLivingCityAdminPopulationAction.ImportProfile);
        BindPopulationAction(RebuildZoneStates, NCLivingCityAdminPopulationAction.RebuildZoneStates);
        BindInfrastructureAction(
            RequeueOutboxMessage,
            NCLivingCityAdminInfrastructureAction.RequeueOutboxMessage);

        foreach (var mode in Enum.GetValues<NCZoneActivityMode>())
            GeographyActivityMode.AddItem(mode.ToString(), (int) mode);
        GeographyActivityMode.SelectId((int) NCZoneActivityMode.Active);
        ValidateGeography.OnPressed += _ => RequestGeographyInspection(
            NCLivingCityAdminInspectKind.CityConnectivityValidation,
            "all");
        InspectCityZone.OnPressed += _ => RequestGeographyInspection(
            NCLivingCityAdminInspectKind.CityZone,
            GeographyZoneId.Text);
        InspectConnectivityZone.OnPressed += _ => RequestGeographyInspection(
            NCLivingCityAdminInspectKind.CityConnectivityZone,
            GeographyZoneId.Text);
        ToggleConnectivityOverlay.OnPressed += _ =>
        {
            GeographyStatus.Text = Loc.GetString("nc-living-city-admin-loading");
            _connectivityDebug.SetEnabled(!_connectivityDebug.Enabled);
        };
        UpdateConnectivityOverlayButton();
        BindGeographyAction(SetZoneActivity, NCLivingCityAdminGeographyAction.SetZoneActivity);
    }

    public void OnSelected()
    {
        if (_overviewRequest == Guid.Empty)
            RequestOverview();
    }

    protected override void Dispose(bool disposing)
    {
        if (disposing)
        {
            _admin.OverviewReceived -= OnOverview;
            _admin.InspectionReceived -= OnInspection;
            _admin.ActorActionReceived -= OnActorAction;
            _admin.GroupActionReceived -= OnGroupAction;
            _admin.PopulationActionReceived -= OnPopulationAction;
            _admin.InfrastructureActionReceived -= OnInfrastructureAction;
            _admin.GeographyActionReceived -= OnGeographyAction;
            _connectivityDebug.SnapshotReceived -= OnConnectivitySnapshot;
        }
        base.Dispose(disposing);
    }

    private void RequestOverview()
    {
        OverviewStatus.Text = Loc.GetString("nc-living-city-admin-loading");
        RefreshOverview.Disabled = true;
        _overviewRequest = _admin.RequestOverview();
    }

    private void RequestInspection()
    {
        if (InspectKind.SelectedMetadata is not int rawKind ||
            !Enum.IsDefined((NCLivingCityAdminInspectKind) rawKind))
        {
            InspectStatus.Text = Loc.GetString("nc-living-city-admin-invalid-inspection");
            return;
        }

        InspectStatus.Text = Loc.GetString("nc-living-city-admin-loading");
        RunInspection.Disabled = true;
        _inspectRequest = _admin.RequestInspection(
            (NCLivingCityAdminInspectKind) rawKind,
            InspectTarget.Text,
            InspectSecondaryTarget.Text);
    }

    private void OnOverview(NCLivingCityAdminOverviewSnapshot snapshot)
    {
        if (snapshot.RequestId != _overviewRequest)
            return;
        RefreshOverview.Disabled = false;
        OverviewStatus.Text = snapshot.Authorized && snapshot.Error == null
            ? Loc.GetString("nc-living-city-admin-ready")
            : snapshot.Error ?? Loc.GetString("nc-living-city-admin-not-authorized");
        RenderFields(OverviewFields, snapshot.Fields);
    }

    private void OnInspection(NCLivingCityAdminInspectResult result)
    {
        if (result.RequestId == _geographyInspectRequest)
        {
            GeographyStatus.Text = result.Success
                ? Loc.GetString("nc-living-city-admin-inspection-ready")
                : result.Error ?? Loc.GetString("nc-living-city-admin-inspection-failed");
            RenderFields(GeographyFields, result.Fields);
            return;
        }
        if (result.RequestId != _inspectRequest)
            return;
        RunInspection.Disabled = false;
        InspectStatus.Text = result.Success
            ? Loc.GetString("nc-living-city-admin-inspection-ready")
            : result.Error ?? Loc.GetString("nc-living-city-admin-inspection-failed");
        RenderFields(InspectionFields, result.Fields);
    }

    private void BindActorAction(
        Content.Client.UserInterface.Controls.ConfirmButton button,
        NCLivingCityAdminActorAction action)
    {
        _actorButtons[action] = button;
        button.ResetTime = TimeSpan.FromSeconds(15);
        button.OnConfirming += _ => SendActorAction(action, Guid.Empty);
        button.OnPressed += _ =>
        {
            var token = _actorConfirmations.GetValueOrDefault(action);
            if (token == Guid.Empty)
            {
                button.IsConfirming = true;
                ActorActionStatus.Text = Loc.GetString("nc-living-city-admin-waiting-confirmation");
                return;
            }
            SendActorAction(action, token);
        };
    }

    private void SendActorAction(NCLivingCityAdminActorAction action, Guid confirmationToken)
    {
        if (!int.TryParse(ActorPriority.Text, out var priority))
        {
            ActorActionStatus.Text = Loc.GetString("nc-living-city-admin-invalid-priority");
            return;
        }

        ActorActionStatus.Text = Loc.GetString("nc-living-city-admin-loading");
        _admin.RequestActorAction(
            action,
            ActionActorId.Text,
            ActorPopulationScope.Text,
            ActorStableLocalId.Text,
            ActorArchetype.Text,
            ActorHomeZone.Text,
            ActorWorkZone.Text,
            ActorFullName.Text,
            ActorTargetZone.Text,
            priority,
            ActorReason.Text,
            confirmationToken);
    }

    private void OnActorAction(NCLivingCityAdminActorActionResult result)
    {
        if (result.Status == NCLivingCityAdminMutationStatus.ConfirmationRequired)
        {
            _actorConfirmations[result.Action] = result.ConfirmationToken;
            if (_actorButtons.TryGetValue(result.Action, out var button))
                button.IsConfirming = true;
            ActorActionStatus.Text = Loc.GetString("nc-living-city-admin-server-confirmation-ready");
            return;
        }

        _actorConfirmations.Remove(result.Action);
        if (_actorButtons.TryGetValue(result.Action, out var completedButton))
            completedButton.IsConfirming = false;
        ActorActionStatus.Text = result.Status is NCLivingCityAdminMutationStatus.Applied or
            NCLivingCityAdminMutationStatus.Duplicate
            ? Loc.GetString("nc-living-city-admin-action-complete")
            : result.Error ?? Loc.GetString("nc-living-city-admin-action-failed");
        RenderFields(ActorActionFields, result.Fields);
        if (result.Status is NCLivingCityAdminMutationStatus.Applied or NCLivingCityAdminMutationStatus.Duplicate)
            RequestOverview();
    }

