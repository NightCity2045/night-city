    public NCLivingCityAdminTab()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        _admin = _systems.GetEntitySystem<NCLivingCityAdminClientSystem>();
        _connectivityDebug = _systems.GetEntitySystem<NCCityConnectivityDebugClientSystem>();
        _admin.OverviewReceived += OnOverview;
        _admin.InspectionReceived += OnInspection;
        _admin.ActorActionReceived += OnActorAction;
        _admin.GroupActionReceived += OnGroupAction;
        _admin.PopulationActionReceived += OnPopulationAction;
        _admin.InfrastructureActionReceived += OnInfrastructureAction;
        _admin.GeographyActionReceived += OnGeographyAction;
        _connectivityDebug.SnapshotReceived += OnConnectivitySnapshot;

        Tabs.SetTabTitle(0, Loc.GetString("nc-living-city-admin-overview-tab"));
        Tabs.SetTabTitle(1, Loc.GetString("nc-living-city-admin-inspect-tab"));
        Tabs.SetTabTitle(2, Loc.GetString("nc-living-city-admin-actors-tab"));
        Tabs.SetTabTitle(3, Loc.GetString("nc-living-city-admin-groups-tab"));
        Tabs.SetTabTitle(4, Loc.GetString("nc-living-city-admin-population-tab"));
        Tabs.SetTabTitle(5, Loc.GetString("nc-living-city-admin-infrastructure-tab"));
