    }

    private void UpdateConnectivityOverlayButton()
    {
        ToggleConnectivityOverlay.Text = _connectivityDebug.Enabled
            ? Loc.GetString("nc-living-city-admin-disable-connectivity-overlay")
            : Loc.GetString("nc-living-city-admin-enable-connectivity-overlay");
    }

    private static bool Successful(NCLivingCityAdminMutationStatus status) =>
        status is NCLivingCityAdminMutationStatus.Applied or NCLivingCityAdminMutationStatus.Duplicate;

    private static void RenderFields(
        Robust.Client.UserInterface.Controls.ItemList list,
        IReadOnlyList<NCLivingCityAdminField> fields)
    {
        list.Clear();
        string? section = null;
        foreach (var field in fields)
        {
            if (!string.Equals(section, field.Section, StringComparison.Ordinal))
            {
                section = field.Section;
                list.AddItem($"── {section.ToUpperInvariant()} ──", selectable: false);
            }
            list.AddItem($"{field.Key}: {field.Value}", selectable: false);
        }
    }

