    public void OnSelected()
    {
        SetMonitoringActive(true);
    }

    /// <summary>
    /// Enables polling only while the outer F7 Living City page is visible. Hidden admin tabs do no network work.
    /// </summary>
    public void SetMonitoringActive(bool active)
    {
        _monitoringActive = active;
        if (!active)
            return;

        ScheduleAutoRefresh();
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        if (!_monitoringActive || _timing.RealTime < _nextAutoRefresh)
            return;

        _nextAutoRefresh = _timing.RealTime + AutoRefreshInterval;
        RefreshActiveTab();
    }

    protected override void Dispose(bool disposing)
    {
        if (disposing)
        {
            _admin.OverviewReceived -= OnOverview;
            _admin.ObserverReceived -= OnObserver;
            _admin.InspectionReceived -= OnInspection;
            _admin.ActorActionReceived -= OnActorAction;
            _admin.GroupActionReceived -= OnGroupAction;
            _admin.PopulationActionReceived -= OnPopulationAction;
            _admin.InfrastructureActionReceived -= OnInfrastructureAction;
            _admin.GeographyActionReceived -= OnGeographyAction;
            _connectivityDebug.SnapshotReceived -= OnConnectivitySnapshot;
            _renderedFieldLists.Clear();
            _renderedObserverZoneIds = [];
            _renderedObserverZones = [];
        }
        base.Dispose(disposing);
    }

    private void RequestOverview(bool automatic = false)
    {
        if (_overviewRequest != Guid.Empty)
            return;

        if (!automatic)
        {
            SetStatus(OverviewStatus, Loc.GetString("nc-living-city-admin-loading"), StatusTone.Loading);
            RefreshOverview.Disabled = true;
        }
        _overviewRequest = _admin.RequestOverview();
    }

    private void RequestObserver(bool automatic = false)
    {
        if (_observerRequest != Guid.Empty)
            return;

        if (!automatic)
        {
            SetStatus(ObserverStatus, Loc.GetString("nc-living-city-admin-loading"), StatusTone.Loading);
            RefreshObserver.Disabled = true;
        }
        _observerRequest = _admin.RequestObserver(
            ObserverZoneFilter.Text.Trim(),
            ObserverActorId.Text.Trim());
    }

    private void RequestInspection(bool automatic = false)
    {
        if (automatic && _inspectRequest != Guid.Empty)
            return;

        if (InspectKind.SelectedMetadata is not int rawKind ||
            !Enum.IsDefined((NCLivingCityAdminInspectKind) rawKind))
        {
            if (!automatic)
                SetStatus(InspectStatus, Loc.GetString("nc-living-city-admin-invalid-inspection"), StatusTone.Error);
            return;
        }

        var kind = (NCLivingCityAdminInspectKind) rawKind;
        var target = InspectTarget.Text.Trim();
        if (kind == NCLivingCityAdminInspectKind.CityConnectivityValidation && target.Length == 0)
            target = "all";
        if (target.Length == 0)
        {
            if (!automatic)
                SetStatus(InspectStatus, Loc.GetString("nc-living-city-admin-target-required"), StatusTone.Error);
            return;
        }
        if (kind == NCLivingCityAdminInspectKind.Relationship &&
            InspectSecondaryTarget.Text.Trim().Length == 0)
        {
            if (!automatic)
                SetStatus(InspectStatus, Loc.GetString("nc-living-city-admin-secondary-required"), StatusTone.Error);
            return;
        }

        if (!automatic)
        {
            SetStatus(InspectStatus, Loc.GetString("nc-living-city-admin-loading"), StatusTone.Loading);
            RunInspection.Disabled = true;
        }
        _inspectRequest = _admin.RequestInspection(
            kind,
            target,
            InspectSecondaryTarget.Text.Trim());
    }

    private void OnOverview(NCLivingCityAdminOverviewSnapshot snapshot)
    {
        if (snapshot.RequestId != _overviewRequest)
            return;
        _overviewRequest = Guid.Empty;
        RefreshOverview.Disabled = false;
        var success = snapshot.Authorized && snapshot.Error == null;
        SetStatus(
            OverviewStatus,
            success
                ? Loc.GetString("nc-living-city-admin-ready")
                : snapshot.Error ?? Loc.GetString("nc-living-city-admin-not-authorized"),
            success ? StatusTone.Success : StatusTone.Error);
        if (Tabs.CurrentTab == 0)
            RenderFields(OverviewFields, snapshot.Fields);

        // Population operations are mutations, while these two sections are a read-only live projection.
        // Keeping them in the same panel makes long imports and projection rebuilds observable once per second.
        if (Tabs.CurrentTab == 4 && success)
        {
            var populationFields = snapshot.Fields
                .Where(static field => field.Section is "population-import" or "zone-states")
                .ToArray();
            RenderFields(PopulationActionFields, populationFields);
        }

        if (Tabs.CurrentTab == 8)
        {
            SetStatus(
                NcpdStatus,
                success
                    ? Loc.GetString("nc-living-city-admin-ncpd-live")
                    : snapshot.Error ?? Loc.GetString("nc-living-city-admin-not-authorized"),
                success ? StatusTone.Success : StatusTone.Error);
            var ncpdFields = snapshot.Fields
                .Where(static field => field.Section.StartsWith("ncpd-", StringComparison.Ordinal))
                .ToArray();
            RenderFields(NcpdFields, ncpdFields);
        }
    }

    private void OnObserver(NCLivingCityAdminObserverSnapshot snapshot)
    {
        if (snapshot.RequestId != _observerRequest)
            return;
        _observerRequest = Guid.Empty;
        RefreshObserver.Disabled = false;
        var success = snapshot.Authorized && snapshot.Error == null;
        SetStatus(
            ObserverStatus,
            success
                ? Loc.GetString("nc-living-city-admin-observer-live")
                : snapshot.Error ?? Loc.GetString("nc-living-city-admin-not-authorized"),
            success ? StatusTone.Success : StatusTone.Error);
        if (!success)
        {
            ClearRenderedFields(ObserverSummaryFields);
            ClearObserverZones(ObserverZones);
            ClearRenderedFields(ObserverActorFields);
            return;
        }

        RenderFields(ObserverSummaryFields, snapshot.SummaryFields);
        RenderObserverZones(ObserverZones, snapshot.Zones);
        if (ObserverActorId.Text.Trim().Length == 0)
        {
            SetStatus(
                ObserverActorStatus,
                Loc.GetString("nc-living-city-admin-observer-no-actor"),
                StatusTone.Info);
            ClearRenderedFields(ObserverActorFields);
        }
        else if (snapshot.ActorError != null)
        {
            SetStatus(ObserverActorStatus, snapshot.ActorError, StatusTone.Error);
            ClearRenderedFields(ObserverActorFields);
        }
        else
        {
            SetStatus(
                ObserverActorStatus,
                Loc.GetString("nc-living-city-admin-observer-actor-live"),
                StatusTone.Success);
            RenderFields(ObserverActorFields, snapshot.ActorFields);
        }
    }

    private void OnInspection(NCLivingCityAdminInspectResult result)
    {
        if (result.RequestId == _geographyInspectRequest)
        {
            _geographyInspectRequest = Guid.Empty;
            SetStatus(
                GeographyStatus,
                result.Success
                    ? Loc.GetString("nc-living-city-admin-inspection-ready")
                    : result.Error ?? Loc.GetString("nc-living-city-admin-inspection-failed"),
                result.Success ? StatusTone.Success : StatusTone.Error);
            RenderFields(GeographyFields, result.Fields);
            return;
        }
        if (result.RequestId != _inspectRequest)
            return;
        _inspectRequest = Guid.Empty;
        RunInspection.Disabled = false;
        SetStatus(
            InspectStatus,
            result.Success
                ? Loc.GetString("nc-living-city-admin-inspection-ready")
                : result.Error ?? Loc.GetString("nc-living-city-admin-inspection-failed"),
            result.Success ? StatusTone.Success : StatusTone.Error);
        RenderFields(InspectionFields, result.Fields);
    }

    private void BindActorAction(
        Content.Client.UserInterface.Controls.ConfirmButton button,
        NCLivingCityAdminActorAction action)
    {
        _actorButtons[action] = button;
        button.ResetTime = TimeSpan.FromSeconds(15);
        button.OnConfirming += _ => SendActorAction(action, Guid.Empty);
        button.OnPressed += _ =>
        {
            var token = _actorConfirmations.GetValueOrDefault(action);
            if (token == Guid.Empty)
            {
                button.IsConfirming = true;
                SetStatus(
                    ActorActionStatus,
                    Loc.GetString("nc-living-city-admin-waiting-confirmation"),
                    StatusTone.Warning);
                return;
            }
            SendActorAction(action, token);
        };
    }

    private void SendActorAction(NCLivingCityAdminActorAction action, Guid confirmationToken)
    {
        if (!int.TryParse(ActorPriority.Text, out var priority) || priority is < 0 or > 1000)
        {
            SetStatus(
                ActorActionStatus,
                Loc.GetString("nc-living-city-admin-invalid-priority"),
                StatusTone.Error);
            return;
        }

        if (!Require(ActorActionStatus,
                (Loc.GetString("nc-living-city-admin-reason"), ActorReason.Text)))
            return;

        if (action == NCLivingCityAdminActorAction.Create)
        {
            if (!Require(ActorActionStatus,
                    (Loc.GetString("nc-living-city-admin-population-scope"), ActorPopulationScope.Text),
                    (Loc.GetString("nc-living-city-admin-stable-local-id"), ActorStableLocalId.Text),
                    (Loc.GetString("nc-living-city-admin-archetype"), ActorArchetype.Text),
                    (Loc.GetString("nc-living-city-admin-home-zone"), ActorHomeZone.Text),
                    (Loc.GetString("nc-living-city-admin-full-name"), ActorFullName.Text)))
                return;
        }
        else if (!Require(ActorActionStatus,
                     (Loc.GetString("nc-living-city-admin-actor-id"), ActionActorId.Text)))
        {
            return;
        }

        if (action == NCLivingCityAdminActorAction.Move &&
            !Require(ActorActionStatus,
                (Loc.GetString("nc-living-city-admin-target-zone"), ActorTargetZone.Text)))
            return;

        SetStatus(ActorActionStatus, Loc.GetString("nc-living-city-admin-loading"), StatusTone.Loading);
        _admin.RequestActorAction(
            action,
            ActionActorId.Text,
            ActorPopulationScope.Text,
            ActorStableLocalId.Text,
            ActorArchetype.Text,
            ActorHomeZone.Text,
            ActorWorkZone.Text,
            ActorFullName.Text,
            ActorTargetZone.Text,
            priority,
            ActorReason.Text,
            confirmationToken);
    }

    private void OnActorAction(NCLivingCityAdminActorActionResult result)
    {
        if (result.Status == NCLivingCityAdminMutationStatus.ConfirmationRequired)
        {
            _actorConfirmations[result.Action] = result.ConfirmationToken;
            if (_actorButtons.TryGetValue(result.Action, out var button))
                button.IsConfirming = true;
            SetStatus(
                ActorActionStatus,
                Loc.GetString("nc-living-city-admin-server-confirmation-ready"),
                StatusTone.Warning);
            return;
        }

        _actorConfirmations.Remove(result.Action);
        if (_actorButtons.TryGetValue(result.Action, out var completedButton))
            completedButton.IsConfirming = false;
        var success = Successful(result.Status);
        SetStatus(
            ActorActionStatus,
            success
                ? Loc.GetString("nc-living-city-admin-action-complete")
                : result.Error ?? Loc.GetString("nc-living-city-admin-action-failed"),
            success ? StatusTone.Success : StatusTone.Error);
        RenderFields(ActorActionFields, result.Fields);
        if (result.Status is NCLivingCityAdminMutationStatus.Applied or NCLivingCityAdminMutationStatus.Duplicate)
            RequestOverview();
    }

