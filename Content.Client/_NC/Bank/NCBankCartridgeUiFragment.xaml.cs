using Content.Shared._NC.Bank;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._NC.Bank;

[GenerateTypedNameReferences]
public sealed partial class NCBankCartridgeUiFragment : BoxContainer
{
    [Dependency] private IPrototypeManager _prototypes = default!;

    private int _feeBasisPoints;

    public event Action<string, long>? OnTransfer;

    public NCBankCartridgeUiFragment()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        AmountEdit.OnTextChanged += _ => UpdateTotal();
        TransferButton.OnPressed += _ =>
        {
            if (TargetEdit.Text.Trim().Length > 0 && NCBankFormat.TryParseAmount(AmountEdit.Text, out var amount))
                OnTransfer?.Invoke(TargetEdit.Text.Trim(), amount);
        };
    }

    public void UpdateState(NCBankCartridgeUiState state)
    {
        UnavailableLabel.Visible = !state.Available;
        AccountContainer.Visible = state.Available;
        NumberLabel.Text = state.AccountNumber;
        BalanceLabel.Text = NCBankFormat.Money(state.Balance);
        FeeLabel.Text = NCBankFormat.Percent(state.FeeBasisPoints);
        _feeBasisPoints = state.FeeBasisPoints;
        UpdateTotal();
        NCBankFormat.FillHistory(HistoryContainer, state.History, _prototypes);
    }

    private void UpdateTotal()
    {
        if (!NCBankFormat.TryParseAmount(AmountEdit.Text, out var amount))
        {
            TotalLabel.Text = string.Empty;
            return;
        }

        var fee = NCBankFees.Calculate(amount, _feeBasisPoints);
        TotalLabel.Text = Loc.GetString("nc-bank-transfer-total", ("total", amount + fee), ("fee", fee));
    }
}
