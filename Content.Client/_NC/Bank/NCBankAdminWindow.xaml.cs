using System.Globalization;
using Content.Client.UserInterface.Controls;
using Content.Shared._NC.Bank;
using Content.Shared.Roles;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._NC.Bank;

[GenerateTypedNameReferences]
public sealed partial class NCBankAdminWindow : FancyWindow
{
    [Dependency] private IPrototypeManager _prototypes = default!;

    public event Action<string>? OnLookup;
    public event Action<string, long, string>? OnAdjust;
    public event Action<string, int>? OnSetFee;

    public NCBankAdminWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        LookupButton.OnPressed += _ => OnLookup?.Invoke(NumberEdit.Text.Trim());
        GrantButton.OnPressed += _ => Adjust(1);
        TakeButton.OnPressed += _ => Adjust(-1);
    }

    private void Adjust(int sign)
    {
        if (NCBankFormat.TryParseAmount(AmountEdit.Text, out var amount))
            OnAdjust?.Invoke(NumberEdit.Text.Trim(), sign * amount, ReasonEdit.Text);
    }

    public void UpdateState(NCBankAdminEuiState state)
    {
        StatusLabel.Text = state.Status ?? string.Empty;
        StatusLabel.Visible = state.Status != null;

        DepartmentsContainer.RemoveAllChildren();
        foreach (var account in state.Departments)
        {
            var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 8 };
            row.AddChild(new Label { Text = AccountName(account.Name), HorizontalExpand = true });
            row.AddChild(new Label { Text = account.Number, MinWidth = 90 });
            row.AddChild(new Label { Text = NCBankFormat.Money(account.Balance), MinWidth = 120 });
            var select = new Button { Text = Loc.GetString("nc-bank-admin-select") };
            var number = account.Number;
            select.OnPressed += _ =>
            {
                NumberEdit.Text = number;
                OnLookup?.Invoke(number);
            };
            row.AddChild(select);
            DepartmentsContainer.AddChild(row);
        }

        LookupLabel.Text = state.Lookup is { } lookup
            ? Loc.GetString("nc-bank-admin-lookup-result",
                ("number", lookup.Number),
                ("owner", lookup.Name != null ? AccountName(lookup.Name) : Loc.GetString("nc-bank-admin-owner-character")),
                ("balance", lookup.Balance))
            : string.Empty;

        FeesContainer.RemoveAllChildren();
        foreach (var fee in state.Fees)
        {
            var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 6 };
            var name = fee.Name != null ? AccountName(fee.Name) : Loc.GetString("nc-bank-admin-fee-resident");
            row.AddChild(new Label { Text = name, HorizontalExpand = true });
            var edit = new LineEdit { Text = (fee.BasisPoints / 100f).ToString(CultureInfo.InvariantCulture), MinWidth = 70 };
            row.AddChild(edit);
            row.AddChild(new Label { Text = "%" });
            var apply = new Button { Text = Loc.GetString("nc-bank-salary-apply") };
            var category = fee.Category;
            apply.OnPressed += _ =>
            {
                if (float.TryParse(edit.Text.Trim().Replace(',', '.'), NumberStyles.Float, CultureInfo.InvariantCulture, out var percent))
                    OnSetFee?.Invoke(category, (int) MathF.Round(percent * 100));
            };
            row.AddChild(apply);
            FeesContainer.AddChild(row);
        }
    }

    private static string AccountName(string? name)
    {
        return name != null && Loc.TryGetString(name, out var text) ? text : name ?? string.Empty;
    }
}
