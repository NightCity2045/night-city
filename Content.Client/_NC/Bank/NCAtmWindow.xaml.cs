using Content.Client.UserInterface.Controls;
using Content.Shared._NC.Bank;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._NC.Bank;

[GenerateTypedNameReferences]
public sealed partial class NCAtmWindow : FancyWindow
{
    public event Action? OnDeposit;
    public event Action<long>? OnWithdraw;

    public NCAtmWindow()
    {
        RobustXamlLoader.Load(this);
        DepositButton.OnPressed += _ => OnDeposit?.Invoke();
        WithdrawButton.OnPressed += _ =>
        {
            if (NCBankFormat.TryParseAmount(WithdrawEdit.Text, out var amount))
                OnWithdraw?.Invoke(amount);
        };
    }

    public void UpdateState(NCAtmUiState state)
    {
        UnavailableLabel.Visible = !state.Available;
        AccountContainer.Visible = state.Available;
        NumberLabel.Text = state.AccountNumber;
        BalanceLabel.Text = NCBankFormat.Money(state.Balance);
        FeeLabel.Text = NCBankFormat.Percent(state.FeeBasisPoints);
        CashLabel.Text = NCBankFormat.Money(state.CashInSlot);
        DepositButton.Disabled = state.CashInSlot <= 0;
    }
}
