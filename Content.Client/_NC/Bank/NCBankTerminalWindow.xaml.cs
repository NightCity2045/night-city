using Content.Client.UserInterface.Controls;
using Content.Shared._NC.Bank;
using Content.Shared.Roles;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._NC.Bank;

[GenerateTypedNameReferences]
public sealed partial class NCBankTerminalWindow : FancyWindow
{
    [Dependency] private IPrototypeManager _prototypes = default!;

    public event Action? OnDeposit;
    public event Action<long>? OnWithdraw;
    public event Action<ProtoId<JobPrototype>, int>? OnSetSalary;

    public NCBankTerminalWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        DepositButton.OnPressed += _ => OnDeposit?.Invoke();
        WithdrawButton.OnPressed += _ =>
        {
            if (NCBankFormat.TryParseAmount(WithdrawEdit.Text, out var amount))
                OnWithdraw?.Invoke(amount);
        };
    }

    public void UpdateState(NCBankTerminalUiState state)
    {
        var showAccount = state.Available && state.Authorized;
        AccountContainer.Visible = showAccount;
        MessageLabel.Visible = !showAccount;
        MessageLabel.Text = Loc.GetString(state.Available ? "nc-bank-terminal-denied" : "nc-bank-offline");
        if (!showAccount)
            return;

        DepartmentLabel.Text = state.Department is { } department && _prototypes.TryIndex(department, out var prototype)
            ? Loc.GetString(prototype.Name)
            : string.Empty;
        NumberLabel.Text = state.AccountNumber;
        BalanceLabel.Text = NCBankFormat.Money(state.Balance);
        FeeLabel.Text = NCBankFormat.Percent(state.FeeBasisPoints);
        CashLabel.Text = NCBankFormat.Money(state.CashInSlot);
        DepositButton.Disabled = state.CashInSlot <= 0;

        SalariesContainer.RemoveAllChildren();
        foreach (var salary in state.Salaries)
            SalariesContainer.AddChild(CreateSalaryRow(salary));

        NCBankFormat.FillHistory(HistoryContainer, state.History, _prototypes);
    }

    private Control CreateSalaryRow(NCBankSalaryLine salary)
    {
        var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 6 };
        var name = _prototypes.TryIndex(salary.Job, out var job) ? job.LocalizedName : salary.Job.Id;
        row.AddChild(new Label { Text = name, HorizontalExpand = true });
        var edit = new LineEdit { Text = salary.Amount.ToString(), MinWidth = 90 };
        row.AddChild(edit);
        var apply = new Button { Text = Loc.GetString("nc-bank-salary-apply") };
        apply.OnPressed += _ =>
        {
            if (int.TryParse(edit.Text.Trim(), out var amount) && amount >= 0)
                OnSetSalary?.Invoke(salary.Job, amount);
        };
        row.AddChild(apply);
        return row;
    }
}
