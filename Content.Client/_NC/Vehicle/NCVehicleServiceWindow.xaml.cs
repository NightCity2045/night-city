using System.Linq;
using Content.Client.UserInterface.Controls;
using Content.Shared._NC.Vehicle;
using Content.Shared._NC.Vehicle.Prototypes;
using Content.Shared._NC.Vehicle.Workshop;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Timing;

namespace Content.Client._NC.Vehicle;

[GenerateTypedNameReferences]
public sealed partial class NCVehicleServiceWindow : FancyWindow
{
    public event Action<string, NCVehicleServiceAction>? Requested;
    public event Action<ProtoId<NCVehicleTuningPrototype>>? CalibrationRequested;
    public event Action<NCVehicleWorkshopRequest>? WorkshopRequested;
    public event Action<float>? TorqueRequested;
    public event Action? RefreshRequested;
    private NCVehicleWorkshopSnapshot? _state;
    private NCVehicleWorkshopPrototype? _profile;
    private NCVehicleChassisPrototype? _chassis;
    private string[] _views = [];
    private string? _selected;
    private uint _sequence;
    private float _refresh;

    public NCVehicleServiceWindow()
    {
        RobustXamlLoader.Load(this);
        Instructions.SetMessage(Loc.GetString("nc-workshop-controls"));
        foreach (var action in Enum.GetValues<NCVehicleWorkshopAction>())
            Mode.AddItem(Loc.GetString(action switch
            {
                NCVehicleWorkshopAction.Inspect => "nc-workshop-mode-inspect",
                NCVehicleWorkshopAction.Remove => "nc-workshop-mode-remove",
                NCVehicleWorkshopAction.Install => "nc-workshop-mode-install",
                NCVehicleWorkshopAction.Fill => "nc-workshop-mode-fill",
                NCVehicleWorkshopAction.Drain => "nc-workshop-mode-drain",
                _ => "nc-workshop-mode-work",
            }), (int) action);
        Mode.SelectId((int) NCVehicleWorkshopAction.Work);
        Mode.OnItemSelected += args => Mode.SelectId(args.Id);
        Views.OnItemSelected += args => { Views.SelectId(args.Id); _selected = null; ApplyField(); };
        Field.Selection += slot => { _selected = slot; UpdateSelection(); };
        Field.Contact += (node, point, position, revision) =>
        {
            if (_state == null || Field.Pending || _views.Length == 0) return;
            var action = (NCVehicleWorkshopAction) Mode.SelectedId;
            if (action == NCVehicleWorkshopAction.Work && point.Length == 0) return;
            WorkshopRequested?.Invoke(new NCVehicleWorkshopRequest(_views[Views.SelectedId], position, node,
                action == NCVehicleWorkshopAction.Work ? point : string.Empty, revision, ++_sequence, action));
            Field.Pending = true;
            Feedback.SetMessage(Loc.GetString("nc-workshop-working"));
        };
        Hood.OnPressed += _ => Requested?.Invoke(string.Empty, NCVehicleServiceAction.Hood);
        Lift.OnPressed += _ => Requested?.Invoke(string.Empty, NCVehicleServiceAction.Lift);
        Right.OnPressed += _ => Requested?.Invoke(string.Empty, NCVehicleServiceAction.Right);
        Calibration.OnItemSelected += args => Calibration.SelectId(args.Id);
        Tune.OnPressed += _ =>
        {
            if (_state != null && Calibration.SelectedId >= 0 && Calibration.SelectedId < _state.Calibrations.Length)
                CalibrationRequested?.Invoke(_state.Calibrations[Calibration.SelectedId].Prototype);
        };
        TorqueDown.OnPressed += _ => AdjustTorque(-1);
        TorqueUp.OnPressed += _ => AdjustTorque(1);
    }

    public void ApplyWorkshop(NCVehicleWorkshopSnapshot state, NCVehicleWorkshopPrototype profile, NCVehicleChassisPrototype chassis)
    {
        // Older refreshes cannot erase an action still awaiting its authoritative acknowledgment.
        if (state.Sequence != _sequence && !NCVehicleControlSystem.Newer(state.Sequence, _sequence)) return;
        _sequence = state.Sequence;
        _state = state;
        _chassis = chassis;
        if (_profile != profile)
        {
            _profile = profile;
            _views = profile.Views.Keys.ToArray();
            Views.Clear();
            for (var i = 0; i < _views.Length; i++) Views.AddItem(Loc.GetString(profile.Views[_views[i]].Name), i);
            Views.SelectId(0);
        }
        Feedback.SetMessage(Loc.GetString(state.Feedback));
        Status.Text = Loc.GetString("nc-vehicle-service-status", ("hood", state.Hood), ("lift", state.Lifted));
        ToolSprite.SetPrototype(state.Tool);
        var hasTorque = state.ToolTorque != null;
        TorqueControls.Visible = hasTorque;
        TorqueValue.Text = hasTorque
            ? Loc.GetString("nc-workshop-torque-value", ("value", (int) state.ToolTorque!.Value))
            : string.Empty;
        TorqueDown.Disabled = state.Pending || state.ToolTorque <= state.MinimumTorque;
        TorqueUp.Disabled = state.Pending || state.ToolTorque >= state.MaximumTorque;
        var selected = Calibration.SelectedId;
        Calibration.Clear();
        for (var i = 0; i < state.Calibrations.Length; i++)
            Calibration.AddItem(Loc.GetString(state.Calibrations[i].Name), i);
        if (state.Calibrations.Length > 0) Calibration.SelectId(Math.Clamp(selected, 0, state.Calibrations.Length - 1));
        Tune.Disabled = state.Calibrations.Length == 0 || state.Pending;
        ApplyField();
    }

    private void AdjustTorque(int direction)
    {
        if (_state?.ToolTorque is not { } torque || _state.TorqueStep is not { } step)
            return;
        TorqueRequested?.Invoke(torque + step * direction);
    }

    private void ApplyField()
    {
        if (_state == null || _profile == null || _chassis == null || _views.Length == 0) return;
        var view = _profile.Views[_views[Views.SelectedId]];
        if (view.RequiresHood && !_state.Hood) Feedback.SetMessage(Loc.GetString("nc-workshop-hood"));
        else if (view.RequiresLift && !_state.Lifted) Feedback.SetMessage(Loc.GetString("nc-workshop-lift"));
        Field.SetState(_profile, _chassis, _state, _views[Views.SelectedId]);
        UpdateSelection();
    }

    private void UpdateSelection()
    {
        if (_selected == null || _chassis == null || _state == null || !_chassis.Slots.TryGetValue(_selected, out var slot))
        { SelectionInfo.SetMessage(Loc.GetString("nc-workshop-select")); return; }
        var part = _state.Parts.First(p => p.Slot == _selected);
        var status = !part.Installed ? Loc.GetString("nc-vehicle-service-empty") :
            part.Condition is { } value ? Loc.GetString(part.Exact ? "nc-vehicle-service-condition" : "nc-vehicle-service-estimate", ("value", (int) (value * 100))) :
            Loc.GetString("nc-vehicle-service-unknown");
        SelectionInfo.SetMessage(Loc.GetString("nc-workshop-selection", ("part", Loc.GetString(slot.Name)), ("status", status),
            ("attached", part.Points.Values.Count(p => p)), ("total", part.Points.Count)) +
            (part.Stale ? "\n" + Loc.GetString("nc-workshop-measurement-stale") : string.Empty) +
            FluidInfo(_profile?.Nodes.Values.FirstOrDefault(node => node.Slot == _selected)?.Fluid));
    }

    private string FluidInfo(NCVehicleFluidCircuit? circuit)
    {
        if (circuit is not { } kind || _state == null)
            return string.Empty;
        var fluid = _state.Fluids.FirstOrDefault(x => x.Circuit == kind);
        if (fluid.Capacity <= 0)
            return string.Empty;
        return "\n" + Loc.GetString("nc-workshop-fluid-state", ("circuit", Loc.GetString("nc-workshop-fluid-" + kind.ToString().ToLowerInvariant())),
            ("level", (int) (fluid.Fraction * 100)), ("purity", (int) (fluid.Purity * 100)), ("volume", (int) fluid.Volume));
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        _refresh -= args.DeltaSeconds;
        if (_refresh <= 0) { _refresh = _profile?.RefreshSeconds ?? 0.5f; RefreshRequested?.Invoke(); }
    }
}
