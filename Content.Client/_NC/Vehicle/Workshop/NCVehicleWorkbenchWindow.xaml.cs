using System.Linq;
using Content.Client.UserInterface.Controls;
using Content.Shared._NC.Vehicle.Prototypes;
using Content.Shared._NC.Vehicle.Workshop;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._NC.Vehicle.Workshop;

[GenerateTypedNameReferences]
public sealed partial class NCVehicleWorkbenchWindow : FancyWindow
{
    public event Action<NCVehicleWorkbenchRequest>? Requested;
    private NCVehicleWorkbenchState? _state;
    private NCVehicleChassisPrototype? _chassis;
    private NCVehicleWorkshopPrototype? _profile;
    private string? _selected;

    public NCVehicleWorkbenchWindow()
    {
        RobustXamlLoader.Load(this);
        Instructions.SetMessage(Loc.GetString("nc-workbench-controls"));
        foreach (var action in Enum.GetValues<NCVehicleWorkbenchAction>())
            Mode.AddItem(Loc.GetString(action switch
            {
                NCVehicleWorkbenchAction.Remove => "nc-workbench-mode-remove",
                NCVehicleWorkbenchAction.Install => "nc-workbench-mode-install",
                NCVehicleWorkbenchAction.Repair => "nc-workbench-mode-repair",
                _ => "nc-workbench-mode-inspect",
            }), (int) action);
        Mode.SelectId((int) NCVehicleWorkbenchAction.Inspect);
        Mode.OnItemSelected += args => Mode.SelectId(args.Id);
        Field.Selection += slot =>
        {
            _selected = slot;
            UpdateSelection();
        };
        Field.Contact += (node, _, position, revision) =>
        {
            if (_state == null || Field.Pending)
                return;
            Requested?.Invoke(new NCVehicleWorkbenchRequest(node, position, revision,
                (NCVehicleWorkbenchAction) Mode.SelectedId));
            Field.Pending = true;
            Feedback.SetMessage(Loc.GetString("nc-workbench-working"));
        };
    }

    public void Apply(NCVehicleWorkbenchState state, NCVehicleChassisPrototype? chassis,
        NCVehicleWorkshopPrototype? profile)
    {
        _state = state;
        _chassis = chassis;
        _profile = profile;
        Feedback.SetMessage(Loc.GetString(state.Feedback));
        ToolSprite.SetPrototype(state.Tool);
        Field.Pending = state.Pending;
        AssemblyName.Text = chassis == null || string.IsNullOrEmpty(state.RootSlot)
            ? Loc.GetString("nc-workbench-no-assembly")
            : Loc.GetString(chassis.Slots[state.RootSlot].Name);
        Mode.Disabled = chassis == null;
        if (chassis == null || profile == null || state.Parts.Length == 0)
        {
            SelectionInfo.SetMessage(Loc.GetString("nc-workbench-insert-assembly"));
            return;
        }
        var rootNode = profile.Nodes.FirstOrDefault(pair => pair.Value.Slot == state.RootSlot);
        if (rootNode.Value == null)
        {
            SelectionInfo.SetMessage(Loc.GetString("nc-workbench-no-visual"));
            return;
        }
        Field.SetDetachedState(profile, chassis, state.Parts, rootNode.Value.View,
            state.Parts.Select(part => part.Slot).ToHashSet());
        UpdateSelection();
    }

    private void UpdateSelection()
    {
        if (_state == null || _chassis == null || _selected == null ||
            !_chassis.Slots.TryGetValue(_selected, out var slot))
        {
            SelectionInfo.SetMessage(Loc.GetString("nc-workshop-select"));
            return;
        }
        var part = _state.Parts.First(entry => entry.Slot == _selected);
        var status = part.Installed && part.Condition is { } condition
            ? Loc.GetString("nc-vehicle-service-condition", ("value", (int) (condition * 100)))
            : Loc.GetString("nc-vehicle-service-empty");
        SelectionInfo.SetMessage(Loc.GetString("nc-workbench-selection",
            ("part", Loc.GetString(slot.Name)), ("status", status)));
    }
}
