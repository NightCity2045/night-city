using Content.Client.UserInterface.Controls;
using Content.Shared._NC.Vehicle;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;

namespace Content.Client._NC.Vehicle;

[GenerateTypedNameReferences]
public sealed partial class NCVehicleDriverWindow : FancyWindow
{
    public event Action<NCVehicleDriverAction>? DriverAction;
    public event Action? Tick;
    public event Action<bool>? InfrastructureAction;

    public string TelemetryText { set => Telemetry.Text = value; }
    public string EngineStatusText { set => EngineStatus.SetMessage(value); }
    public string IgnitionText { set => Ignition.Text = value; }
    public string PedalsText { set => Pedals.Text = value; }
    public string ShiftStatusText { set => ShiftStatus.SetMessage(value); }
    public string LaunchText { set => LaunchInstructions.SetMessage(value); }
    public string ConditionText { set => Condition.Text = value; }
    public string FluidsText { set => Fluids.Text = value; }
    public string AccessoriesText { set => Accessories.Text = value; }
    public string GearText { set => GearGate.Text = value; }
    public void SetShifter(bool automatic, int column, int row, NCVehicleSelector selector, bool reverseArmed) =>
        Shifter.SetState(automatic, column, row, selector, reverseArmed);
    public float SteeringValue { get => Steering.Value; set => Steering.Value = value; }
    public bool SteeringHeld => Steering.Held;
    public float SteeringMaximumAngle { set => Steering.MaximumAngle = value; }
    public void ReleaseSteeringGrip() => Steering.ReleaseGrip();

    public NCVehicleDriverWindow()
    {
        RobustXamlLoader.Load(this);
        Instructions.SetMessage(Loc.GetString("nc-vehicle-controls"));
        Ignition.OnPressed += _ => DriverAction?.Invoke(NCVehicleDriverAction.Ignition);
        Lights.OnPressed += _ => DriverAction?.Invoke(NCVehicleDriverAction.Lights);
        Horn.OnPressed += _ => DriverAction?.Invoke(NCVehicleDriverAction.Horn);
        Wash.OnPressed += _ => DriverAction?.Invoke(NCVehicleDriverAction.Wash);
        Neutral.OnPressed += _ => DriverAction?.Invoke(NCVehicleDriverAction.Neutral);
        Reverse.OnPressed += _ => DriverAction?.Invoke(NCVehicleDriverAction.Reverse);
        LowerGear.OnPressed += _ => DriverAction?.Invoke(NCVehicleDriverAction.GearDown);
        HigherGear.OnPressed += _ => DriverAction?.Invoke(NCVehicleDriverAction.GearUp);
        LeftGate.OnPressed += _ => DriverAction?.Invoke(NCVehicleDriverAction.GearLeft);
        RightGate.OnPressed += _ => DriverAction?.Invoke(NCVehicleDriverAction.GearRight);
        Exit.OnPressed += _ => DriverAction?.Invoke(NCVehicleDriverAction.Exit);
        Park.OnPressed += _ => InfrastructureAction?.Invoke(false);
        Travel.OnPressed += _ => InfrastructureAction?.Invoke(true);
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        Tick?.Invoke();
    }
}
