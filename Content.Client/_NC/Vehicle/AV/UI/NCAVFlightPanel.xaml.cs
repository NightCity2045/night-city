using Content.Shared._NC.Vehicle.AV.Components;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._NC.Vehicle.AV.UI;

/// <summary>
/// Compact flight instrumentation embedded into the ordinary shuttle console when it controls an AV.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class NCAVFlightPanel : BoxContainer
{
    private static readonly Color NominalColor = Color.FromHex("#72F3E7");
    private static readonly Color CautionColor = Color.FromHex("#F3BA58");
    private static readonly Color CriticalColor = Color.FromHex("#FF657D");

    public NCAVFlightPanel()
    {
        RobustXamlLoader.Load(this);
    }

    /// <summary>Formats replicated flight state without owning or mutating gameplay state.</summary>
    public void UpdateState(NCAVComponent av, float requiredLift)
    {
        AltitudeValue.Text = Loc.GetString("nc-av-console-altitude-value", ("height", $"{av.Height:0.00}"));
        VerticalSpeedValue.Text = Loc.GetString("nc-av-console-vertical-speed-value", ("speed", $"{av.VerticalVelocity:+0.00;-0.00;0.00}"));
        LiftValue.Text = Loc.GetString("nc-av-console-lift-value",
            ("available", $"{av.AvailableLift / 1000f:0.0}"),
            ("required", $"{requiredLift / 1000f:0.0}"));

        var liftRatio = requiredLift > 0f ? av.AvailableLift / requiredLift : 0f;
        LiftBar.Value = Math.Clamp(liftRatio, 0f, 1f);

        var insufficientLift = requiredLift > 0f && av.AvailableLift <= requiredLift;
        var statusKey = GetStatusKey(av, insufficientLift);
        StatusLabel.Text = Loc.GetString(statusKey);
        StatusLabel.FontColorOverride = av.LandingBlocked || insufficientLift
            ? CriticalColor
            : MathF.Abs(av.VerticalVelocity) > 0.05f
                ? CautionColor
                : NominalColor;

        WarningLabel.Visible = av.LandingBlocked || insufficientLift;
        if (av.LandingBlocked)
            WarningLabel.Text = Loc.GetString("nc-av-console-warning-landing-blocked");
        else if (insufficientLift)
            WarningLabel.Text = Loc.GetString("nc-av-console-warning-insufficient-lift");
    }

    private static string GetStatusKey(NCAVComponent av, bool insufficientLift)
    {
        if (av.LandingBlocked)
            return "nc-av-console-status-landing-blocked";
        if (insufficientLift && av.Airborne)
            return "nc-av-console-status-lift-critical";
        if (!av.Airborne)
            return "nc-av-console-status-grounded";
        if (av.VerticalVelocity > 0.05f)
            return "nc-av-console-status-ascending";
        if (av.VerticalVelocity < -0.05f)
            return "nc-av-console-status-descending";

        return "nc-av-console-status-hovering";
    }
}
