using Content.Shared._NC.Vehicle;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;

namespace Content.Client._NC.Vehicle;

/// <summary>Always-visible driver controls mounted over the bottom of the gameplay viewport.</summary>
[GenerateTypedNameReferences]
public sealed partial class NCVehicleDriverHud : LayoutContainer
{
    public event Action<NCVehicleDriverAction>? DriverAction;
    public event Action? Tick;
    public event Action<bool>? InfrastructureAction;
    public event Action? BeltRequested;

    public string TelemetryText { set => Instruments.ToolTip = value; }
    public string EngineStatusText { set => EngineStatus.SetMessage(value); }
    public string IgnitionText { set => Ignition.ToolTip = value; }
    public string PedalsText { set => Pedals.ToolTip = value; }
    public string ShiftStatusText { set => Shifter.ToolTip = value; }
    public string LaunchText { set => Console.ToolTip = value; }
    public string ConditionText { set => Instruments.ToolTip = value; }
    public string FluidsText { set => Instruments.ToolTip = value; }
    public string AccessoriesText { set => More.ToolTip = value; }
    public string SafetyText { set => Seatbelt.ToolTip = value; }
    public string SeatbeltText { set => Seatbelt.ToolTip = value; }
    public string DrivingHintText { set => DrivingHint.SetMessage(value); }
    public string GripStatusText { set => Steering.ToolTip = value; }
    public string GearText { set => Shifter.ToolTip = value; }
    public float SteeringValue { get => Steering.Value; set => Steering.Value = value; }
    public bool SteeringHeld => Steering.Held;
    public float SteeringMaximumAngle { set => Steering.MaximumAngle = value; }

    public NCVehicleDriverHud()
    {
        RobustXamlLoader.Load(this);
        // This overlay must fill the gameplay viewport. Its console is then positioned against that full area;
        // ordinary alignment would otherwise be measured inside the console's own minimum-sized root.
        InheritChildMeasure = false;
        LayoutContainer.SetAnchorAndMarginPreset(Console, LayoutPreset.CenterBottom, margin: 68);
        Ignition.OnPressed += _ => DriverAction?.Invoke(NCVehicleDriverAction.Ignition);
        Lights.OnPressed += _ => DriverAction?.Invoke(NCVehicleDriverAction.Lights);
        Horn.OnPressed += _ => DriverAction?.Invoke(NCVehicleDriverAction.Horn);
        Wash.OnPressed += _ => DriverAction?.Invoke(NCVehicleDriverAction.Wash);
        Seatbelt.OnPressed += _ => BeltRequested?.Invoke();
        Neutral.OnPressed += _ => DriverAction?.Invoke(NCVehicleDriverAction.Neutral);
        Reverse.OnPressed += _ => DriverAction?.Invoke(NCVehicleDriverAction.Reverse);
        Exit.OnPressed += _ => DriverAction?.Invoke(NCVehicleDriverAction.Exit);
        Shifter.DriverAction += action => DriverAction?.Invoke(action);
        Park.OnPressed += _ => InfrastructureAction?.Invoke(false);
        Travel.OnPressed += _ => InfrastructureAction?.Invoke(true);
        More.OnPressed += _ => MoreControls.Visible = !MoreControls.Visible;
    }

    public void SetSafetyVisual(bool fastened)
    {
        Seatbelt.ModulateSelfOverride = fastened ? Color.FromHex("#67d8b4") : Color.FromHex("#ff765f");
        Instruments.BeltWarning = !fastened;
    }

    public void SetShifter(bool automatic, bool sequential, int gear, int forwardGears,
        int column, int row, NCVehicleSelector selector, bool reverseArmed) =>
        Shifter.SetState(automatic, sequential, gear, forwardGears, column, row, selector, reverseArmed);

    public void SetInstruments(float speed, float rpm, float redline, float fuelFraction, float temperature,
        string gear, bool engineWarning, bool oilWarning, bool batteryWarning, bool handbrakeWarning, bool gripWarning)
    {
        Instruments.Speed = speed;
        Instruments.Rpm = rpm;
        Instruments.RedlineRpm = redline;
        Instruments.FuelFraction = fuelFraction;
        Instruments.TemperatureCelsius = temperature;
        Instruments.Gear = gear;
        Instruments.EngineWarning = engineWarning;
        Instruments.OilWarning = oilWarning;
        Instruments.BatteryWarning = batteryWarning;
        Instruments.HandbrakeWarning = handbrakeWarning;
        Instruments.GripWarning = gripWarning;
    }

    public void SetPedals(float throttle, float brake, float clutch, bool automatic)
    {
        Pedals.Throttle = throttle;
        Pedals.Brake = brake;
        Pedals.Clutch = clutch;
        Pedals.Automatic = automatic;
    }

    public void ReleaseSteeringGrip() => Steering.ReleaseGrip();

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        Tick?.Invoke();
    }
}
