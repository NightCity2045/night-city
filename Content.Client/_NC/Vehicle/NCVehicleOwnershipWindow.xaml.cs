using Content.Client.UserInterface.Controls;
using Content.Shared._NC.Vehicle;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._NC.Vehicle;

[GenerateTypedNameReferences]
public sealed partial class NCVehicleOwnershipWindow : FancyWindow
{
    public event Action<NCVehicleOwnershipAction, int, uint>? Requested;
    private int _price = -1;
    private uint _revision;

    public NCVehicleOwnershipWindow()
    {
        RobustXamlLoader.Load(this);
        Instructions.SetMessage(Loc.GetString("nc-vehicle-sale-instructions"));
        Offer.OnPressed += _ =>
        {
            if (int.TryParse(Price.Text, out var price) && price >= 0)
                Requested?.Invoke(NCVehicleOwnershipAction.Offer, price, _revision);
        };
        Withdraw.OnPressed += _ => Requested?.Invoke(NCVehicleOwnershipAction.Withdraw, -1, _revision);
        Accept.OnPressed += _ => Requested?.Invoke(NCVehicleOwnershipAction.Accept, _price, _revision);
        Rekey.OnPressed += _ => Requested?.Invoke(NCVehicleOwnershipAction.Rekey, -1, _revision);
    }

    public void ApplyState(NCVehicleOwnershipState state)
    {
        _price = state.Price;
        _revision = state.Revision;
        OwnerLabel.Text = Loc.GetString("nc-vehicle-sale-owner", ("owner", state.Owner));
        OfferLabel.Text = state.Price < 0 ? Loc.GetString("nc-vehicle-sale-none") : Loc.GetString("nc-vehicle-sale-current", ("price", state.Price));
        Accept.Disabled = state.Price < 0;
    }
}
