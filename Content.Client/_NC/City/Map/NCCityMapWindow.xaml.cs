using System.Numerics;
using Content.Client.UserInterface.Controls;
using Content.Shared._NC.City.Map;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._NC.City.Map;

/// <summary>
/// NC: Standalone city map window. Admins with mapping rights also get the markup tools here: name the
/// detected building under the cursor, and draw, rename, redraw or delete district outlines.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class NCCityMapWindow : FancyWindow
{
    private static readonly Color SuccessColor = Color.FromHex("#A3FFF7");
    private static readonly Color FailureColor = Color.FromHex("#FF8A8A");

    private enum EditMode : byte
    {
        None,
        Building,
        District,
        Draw,
    }

    private EditMode _mode;
    private Vector2 _buildingPoint;
    private string _districtId = string.Empty;
    private List<Vector2> _districtVertices = [];
    private string _redrawId = string.Empty;
    private readonly List<Vector2> _draft = [];

    public event Action<Vector2, string>? OnNameBuilding;
    public event Action<string, string, List<Vector2>>? OnSaveDistrict;
    public event Action<string>? OnDeleteDistrict;

    public NCCityMapWindow()
    {
        RobustXamlLoader.Load(this);
        MapControl.OnMapClicked += OnMapClicked;
        BuildingModeButton.OnPressed += _ => SetMode(EditMode.Building);
        DistrictModeButton.OnPressed += _ => SetMode(EditMode.District);
        DrawModeButton.OnPressed += _ => SetMode(EditMode.Draw);
        ApplyButton.OnPressed += _ => Apply();
        RedrawButton.OnPressed += _ => StartRedraw();
        UndoPointButton.OnPressed += _ => UndoPoint();
        DeleteButton.OnPressed += _ => Delete();
        CancelButton.OnPressed += _ =>
        {
            _redrawId = string.Empty;
            SetMode(_mode);
        };
        SetMode(EditMode.None);
    }

    public void SetSource(EntityUid? gridUid)
    {
        MapControl.SetMapSource(gridUid);
    }

    public void ApplySnapshot(NCCityMapSnapshotEvent snapshot)
    {
        StatusLabel.Text = snapshot.Notice;
        StatusLabel.Visible = !string.IsNullOrEmpty(snapshot.Notice);
        EditPanel.Visible = snapshot.CanEdit;
        if (!snapshot.CanEdit)
            SetMode(EditMode.None);

        MapControl.SetMapData(snapshot);
    }

    public void ApplyTracking(NCCityMapTrackingEvent tracking)
    {
        MapControl.SetTrackingData(tracking);
    }

    public void ShowEditResult(NCCityMapEditResultEvent result)
    {
        if (result.Success)
        {
            // Building ids are per snapshot; districts keep theirs, but a finished outline is no longer a draft.
            _redrawId = string.Empty;
            SetMode(_mode == EditMode.Draw ? EditMode.District : _mode);
        }

        EditStatusLabel.Text = result.Message;
        EditStatusLabel.FontColorOverride = result.Success ? SuccessColor : FailureColor;
    }

    private void SetMode(EditMode mode)
    {
        _mode = mode;
        _districtId = string.Empty;
        _districtVertices = [];
        _redrawId = mode == EditMode.Draw ? _redrawId : string.Empty;
        _draft.Clear();
        NameEdit.Text = string.Empty;

        BuildingModeButton.Pressed = mode == EditMode.Building;
        DistrictModeButton.Pressed = mode == EditMode.District;
        DrawModeButton.Pressed = mode == EditMode.Draw;

        MapControl.SelectedFeatureId = null;
        MapControl.HighlightUnnamed = mode == EditMode.Building;
        MapControl.DraftVertices = mode == EditMode.Draw ? _draft : null;
        RefreshButtons();
        EditStatusLabel.Text = mode switch
        {
            EditMode.Building => Loc.GetString("nc-city-map-edit-hint-building"),
            EditMode.District => Loc.GetString("nc-city-map-edit-hint-district"),
            EditMode.Draw => Loc.GetString("nc-city-map-edit-hint-draw"),
            _ => string.Empty,
        };
        EditStatusLabel.FontColorOverride = SuccessColor;
    }

    private void RefreshButtons()
    {
        var hasDistrict = _mode == EditMode.District && _districtId.Length > 0;
        ApplyButton.Disabled = _mode switch
        {
            EditMode.Building => MapControl.SelectedFeatureId == null,
            EditMode.District => !hasDistrict,
            EditMode.Draw => _draft.Count < 3,
            _ => true,
        };
        RedrawButton.Disabled = !hasDistrict;
        DeleteButton.Disabled = !hasDistrict;
        UndoPointButton.Disabled = _mode != EditMode.Draw || _draft.Count == 0;
    }

    private void OnMapClicked(Vector2 point)
    {
        switch (_mode)
        {
            case EditMode.Building:
                if (!MapControl.TryFindFeature(point, NCCityMapFeatureKind.Building, out var buildingId, out var buildingName, out _))
                {
                    MapControl.SelectedFeatureId = null;
                    EditStatusLabel.Text = Loc.GetString("nc-city-map-edit-no-building");
                    break;
                }

                _buildingPoint = point;
                MapControl.SelectedFeatureId = buildingId;
                NameEdit.Text = buildingName;
                EditStatusLabel.Text = Loc.GetString("nc-city-map-edit-hint-building-selected");
                break;
            case EditMode.District:
                if (!MapControl.TryFindFeature(point, NCCityMapFeatureKind.District, out var districtId, out var districtName, out var vertices))
                {
                    _districtId = string.Empty;
                    MapControl.SelectedFeatureId = null;
                    break;
                }

                _districtId = districtId;
                _districtVertices = vertices;
                MapControl.SelectedFeatureId = districtId;
                NameEdit.Text = districtName;
                break;
            case EditMode.Draw:
                // Outlines snap to tile corners so district borders line up with the streets.
                _draft.Add(new Vector2(MathF.Round(point.X), MathF.Round(point.Y)));
                break;
        }

        RefreshButtons();
    }

    private void Apply()
    {
        switch (_mode)
        {
            case EditMode.Building:
                OnNameBuilding?.Invoke(_buildingPoint, NameEdit.Text);
                break;
            case EditMode.District when _districtId.Length > 0:
                OnSaveDistrict?.Invoke(_districtId, NameEdit.Text, _districtVertices);
                break;
            case EditMode.Draw when _draft.Count >= 3:
                OnSaveDistrict?.Invoke(_redrawId, NameEdit.Text, [.. _draft]);
                break;
        }
    }

    private void StartRedraw()
    {
        if (_districtId.Length == 0)
            return;

        var name = NameEdit.Text;
        _redrawId = _districtId;
        SetMode(EditMode.Draw);
        NameEdit.Text = name;
    }

    private void UndoPoint()
    {
        if (_draft.Count > 0)
            _draft.RemoveAt(_draft.Count - 1);
        RefreshButtons();
    }

    private void Delete()
    {
        if (_districtId.Length > 0)
            OnDeleteDistrict?.Invoke(_districtId);
    }
}
