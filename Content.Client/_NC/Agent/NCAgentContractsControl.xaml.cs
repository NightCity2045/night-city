using System.Linq;
using Content.Shared._NC.Agent.UI;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._NC.Agent;

[GenerateTypedNameReferences]
public sealed partial class NCAgentContractsControl : BoxContainer
{
    public event Action<BoundUserInterfaceMessage>? OnRequest;
    private NCAgentContractsUpdateMessage? _data;
    private NCPlayerContractEntry? _selected;
    private Guid _draftCommand = Guid.NewGuid();

    public NCAgentContractsControl()
    {
        RobustXamlLoader.Load(this);
        NCAgentAppTheme.Apply(this);
        RefreshButton.OnPressed += _ => OnRequest?.Invoke(new NCAgentContractsPageMessage(_data?.History ?? true, null));
        BoardButton.OnPressed += _ => OnRequest?.Invoke(new NCAgentContractsPageMessage(false, null));
        HistoryButton.OnPressed += _ => OnRequest?.Invoke(new NCAgentContractsPageMessage(true, null));
        NextButton.OnPressed += _ => OnRequest?.Invoke(new NCAgentContractsPageMessage(_data?.History ?? false, _data?.NextCursor));
        AcceptButton.OnPressed += _ => Act(NCPlayerContractAction.Accept);
        ReadyButton.OnPressed += _ => Act(NCPlayerContractAction.Ready);
        CompleteButton.OnPressed += _ => Act(NCPlayerContractAction.Complete);
        CancelButton.OnPressed += _ => Act(NCPlayerContractAction.Cancel);
        WithdrawButton.OnPressed += _ => Act(NCPlayerContractAction.Withdraw);
        NewButton.OnPressed += _ => Editor.Visible = !Editor.Visible;
        // Editing a draft is a new command; retrying unchanged text keeps the existing idempotency key.
        TitleEdit.OnTextChanged += _ => _draftCommand = Guid.NewGuid();
        TermsEdit.OnTextChanged += _ => _draftCommand = Guid.NewGuid();
        RewardEdit.OnTextChanged += _ => _draftCommand = Guid.NewGuid();
        DeadlineEdit.OnTextChanged += _ => _draftCommand = Guid.NewGuid();
        PublishButton.OnPressed += _ =>
        {
            if (!int.TryParse(DeadlineEdit.Text, out var minutes) || minutes < 0)
            {
                NoticeLabel.SetMessage(Loc.GetString("nc-contract-invalid-deadline"));
                return;
            }
            PublishButton.Disabled = true;
            OnRequest?.Invoke(new NCAgentContractCreateMessage(_draftCommand, TitleEdit.Text, TermsEdit.Text,
                RewardEdit.Text, minutes));
        };
    }

    public void SetData(NCAgentContractsUpdateMessage? data)
    {
        if (_data != null && ReferenceEquals(_data, data)) return;
        var selectedId = _selected?.Id;
        _data = data;
        PublishButton.Disabled = false;
        if (data?.Notice == "nc-contract-created")
        {
            _draftCommand = Guid.NewGuid();
            TitleEdit.Text = TermsEdit.Text = RewardEdit.Text = string.Empty;
            Editor.Visible = false;
        }
        ContractList.RemoveAllChildren();
        _selected = null;
        if (data != null)
            foreach (var entry in data.Entries)
            {
                var button = NCAgentAppTheme.CreateEntry(entry.Title, Loc.GetString(StatusKey(entry.Status)));
                button.OnPressed += _ => { _selected = entry; RefreshDetails(); };
                ContractList.AddChild(button);
                if (entry.Id == selectedId) _selected = entry;
            }
        // Keep the current job open after an action; the next available job is selected on a new page.
        _selected ??= data?.Entries.FirstOrDefault();
        EmptyLabel.Visible = data?.Entries.Count == 0;
        BoardButton.Disabled = data?.History == false;
        HistoryButton.Disabled = data?.History == true;
        NextButton.Disabled = data?.NextCursor == null;
        NoticeLabel.SetMessage(Loc.GetString(string.IsNullOrEmpty(data?.Notice) ? "nc-contract-manual" : data.Notice));
        RefreshDetails();
    }

    private void Act(NCPlayerContractAction action)
    {
        if (_selected is not { } value)
            return;
        OnRequest?.Invoke(new NCAgentContractActionMessage(value.Id, value.Version, action));
        AcceptButton.Disabled = ReadyButton.Disabled = CompleteButton.Disabled = CancelButton.Disabled = WithdrawButton.Disabled = true;
    }

    private void RefreshDetails()
    {
        AcceptButton.Visible = ReadyButton.Visible = CompleteButton.Visible = CancelButton.Visible = WithdrawButton.Visible = false;
        AcceptButton.Disabled = ReadyButton.Disabled = CompleteButton.Disabled = CancelButton.Disabled = WithdrawButton.Disabled = false;
        DetailsLabel.SetMessage(string.Empty);
        SelectedTitle.SetMessage(string.Empty);
        ActionHint.SetMessage(string.Empty);
        if (_selected is not { } value || _data == null)
            return;
        var message = new FormattedMessage();
        var selectedTitle = new FormattedMessage();
        selectedTitle.PushColor(Color.FromHex("#77FFF2"));
        selectedTitle.AddText(value.Title);
        selectedTitle.Pop();
        SelectedTitle.SetMessage(selectedTitle);
        // Player-authored terms are plain text; they must never be interpreted as rich-text markup.
        message.AddText(Loc.GetString("nc-contract-details", ("title", value.Title), ("customer", value.CustomerName),
            ("contractor", value.ContractorName), ("terms", value.Terms), ("reward", value.Reward),
            ("status", Loc.GetString(StatusKey(value.Status)))));
        message.PushNewline();
        message.AddText(value.RemainingSeconds is { } seconds
            ? Loc.GetString("nc-contract-time", ("minutes", (long) Math.Ceiling(seconds / 60.0)))
            : Loc.GetString("nc-contract-no-deadline"));
        DetailsLabel.SetMessage(message);
        var customer = value.Customer == _data.Viewer;
        var contractor = value.Contractor == _data.Viewer;
        var active = value.Status is NCPlayerContractStatus.Accepted or NCPlayerContractStatus.Ready;
        AcceptButton.Visible = !customer && value.Status == NCPlayerContractStatus.Open;
        ReadyButton.Visible = contractor && value.Status == NCPlayerContractStatus.Accepted;
        CompleteButton.Visible = customer;
        CompleteButton.Disabled = !active;
        ActionHint.SetMessage(Loc.GetString(customer
            ? active ? "nc-contract-customer-hint" : "nc-contract-customer-inactive-hint"
            : contractor ? "nc-contract-contractor-hint" : "nc-contract-manual"));
        CancelButton.Visible = customer && (active || value.Status == NCPlayerContractStatus.Open);
        WithdrawButton.Visible = contractor && active;
    }

    private static string StatusKey(NCPlayerContractStatus status) => status switch
    {
        NCPlayerContractStatus.Open => "nc-contract-status-open",
        NCPlayerContractStatus.Accepted => "nc-contract-status-accepted",
        NCPlayerContractStatus.Ready => "nc-contract-status-ready",
        NCPlayerContractStatus.Completed => "nc-contract-status-completed",
        NCPlayerContractStatus.Cancelled => "nc-contract-status-cancelled",
        NCPlayerContractStatus.Withdrawn => "nc-contract-status-withdrawn",
        _ => "nc-contract-status-expired",
    };
}
