using System.Linq;
using Content.Shared.CriminalRecords.Systems;
using Content.Shared.Security;
using Robust.Client.Animations;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Animations;

namespace Content.Client._NC.Agent.Shards.Watchlist;

[GenerateTypedNameReferences]
public sealed partial class NCAgentWatchlistFragment : BoxContainer
{
    private static readonly Animation QueryAnimation = new()
    {
        Length = TimeSpan.FromSeconds(0.24),
        AnimationTracks =
        {
            new AnimationTrackControlProperty
            {
                Property = nameof(Modulate),
                InterpolationMode = AnimationInterpolationMode.Linear,
                KeyFrames =
                {
                    new AnimationTrackProperty.KeyFrame(Color.FromHex("#FF5C7C44"), 0f),
                    new AnimationTrackProperty.KeyFrame(Color.White, 0.24f),
                },
            },
        },
    };

    private List<WantedRecord> _records = [];

    public NCAgentWatchlistFragment()
    {
        RobustXamlLoader.Load(this);
        SearchInput.OnTextChanged += _ => Rebuild();
        Rebuild();
    }

    public void UpdateState(List<WantedRecord> records)
    {
        _records = records;
        RecordCount.Text = $"{records.Count} RECORDS";
        QueryStatus.Text = records.Count == 0 ? "QUERY COMPLETE // NO ACTIVE RECORDS" : "QUERY COMPLETE // RECORDS RECEIVED";
        QueryStatus.FontColorOverride = records.Count == 0 ? Color.FromHex("#76FF95") : Color.FromHex("#FFD66B");
        Rebuild();
        RecordContainer.StopAnimation("nc-agent-watchlist-query");
        RecordContainer.PlayAnimation(QueryAnimation, "nc-agent-watchlist-query");
    }

    private void Rebuild()
    {
        RecordContainer.RemoveAllChildren();
        var query = SearchInput.Text.Trim();
        var visible = _records.Where(record => string.IsNullOrEmpty(query) ||
            record.TargetInfo.Name.Contains(query, StringComparison.OrdinalIgnoreCase) ||
            record.TargetInfo.JobTitle.Contains(query, StringComparison.OrdinalIgnoreCase) ||
            record.Status.ToString().Contains(query, StringComparison.OrdinalIgnoreCase) ||
            (record.Reason?.Contains(query, StringComparison.OrdinalIgnoreCase) ?? false));

        var any = false;
        foreach (var record in visible.OrderByDescending(record => Severity(record.Status)).ThenBy(record => record.TargetInfo.Name))
        {
            any = true;
            RecordContainer.AddChild(CreateRecord(record));
        }

        if (!any)
        {
            RecordContainer.AddChild(new Label
            {
                Text = _records.Count == 0 ? "NO ACTIVE NCPD RECORDS" : "NO MATCHING RECORDS",
                FontColorOverride = Color.FromHex("#6F454D"),
                HorizontalAlignment = HAlignment.Center,
                Margin = new Thickness(0, 18),
            });
        }
    }

    private static Control CreateRecord(WantedRecord record)
    {
        var color = StatusColor(record.Status);
        var content = new BoxContainer
        {
            Orientation = LayoutOrientation.Vertical,
            HorizontalExpand = true,
            Margin = new Thickness(10, 7),
        };
        var heading = new BoxContainer { Orientation = LayoutOrientation.Horizontal, HorizontalExpand = true };
        heading.AddChild(new Label { Text = record.TargetInfo.Name.ToUpperInvariant(), FontColorOverride = Color.FromHex("#FFE4EA") });
        heading.AddChild(new Control { HorizontalExpand = true });
        heading.AddChild(new Label { Text = record.Status.ToString().ToUpperInvariant(), FontColorOverride = color });
        content.AddChild(heading);
        content.AddChild(new Label
        {
            Text = $"{record.TargetInfo.JobTitle} // AGE {record.TargetInfo.Age} // {record.TargetInfo.Species}",
            FontColorOverride = Color.FromHex("#B58B94"),
        });
        content.AddChild(new Label
        {
            Text = $"REASON // {record.Reason ?? "UNSPECIFIED"}",
            FontColorOverride = Color.FromHex("#FF91A6"),
        });
        content.AddChild(new Label
        {
            Text = $"INITIATOR // {record.Initiator ?? "UNKNOWN"}",
            FontColorOverride = Color.FromHex("#8C6870"),
        });

        foreach (var history in record.History.OrderByDescending(entry => entry.AddTime).Take(3))
        {
            content.AddChild(new Label
            {
                Text = $"{history.AddTime:hh\\:mm\\:ss} // {history.Crime} // {history.InitiatorName ?? "UNKNOWN"}",
                FontColorOverride = Color.FromHex("#C8A8AF"),
            });
        }

        return new PanelContainer
        {
            HorizontalExpand = true,
            Margin = new Thickness(0, 0, 0, 5),
            PanelOverride = new StyleBoxFlat
            {
                BackgroundColor = Color.FromHex("#1A1015"),
                BorderColor = color,
                BorderThickness = new Thickness(1, 1, 1, 2),
            },
            Children = { content },
        };
    }

    private static int Severity(SecurityStatus status)
    {
        return status switch
        {
            SecurityStatus.Hostile => 4,
            SecurityStatus.Wanted => 3,
            SecurityStatus.Suspected => 2,
            SecurityStatus.Detained => 1,
            _ => 0,
        };
    }

    private static Color StatusColor(SecurityStatus status)
    {
        return status switch
        {
            SecurityStatus.Hostile => Color.FromHex("#FF3C56"),
            SecurityStatus.Wanted => Color.FromHex("#FF7897"),
            SecurityStatus.Suspected => Color.FromHex("#FFD66B"),
            SecurityStatus.Detained => Color.FromHex("#8FB8FF"),
            _ => Color.FromHex("#76FF95"),
        };
    }
}
