/// <summary>
/// Cyberpunk-styled program card used by the Agent instead of the vanilla PDA tile.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class NCAgentShardItem : ContainerButton
{
    private static readonly Animation DeniedAnimation = new()
    {
        Length = TimeSpan.FromSeconds(0.34),
        AnimationTracks =
        {
            new AnimationTrackControlProperty
            {
                Property = nameof(Modulate),
                InterpolationMode = AnimationInterpolationMode.Linear,
                KeyFrames =
                {
                    new AnimationTrackProperty.KeyFrame(Color.White, 0f),
                    new AnimationTrackProperty.KeyFrame(Color.FromHex("#FF4568"), 0.10f),
                    new AnimationTrackProperty.KeyFrame(Color.White, 0.34f),
                },
            },
        },
    };

    private readonly NCAgentShardDisplayData _data;

    public event Action<NCAgentShardDisplayData>? OpenPressed;
    public event Action<NCAgentShardDisplayData>? InstallPressed;
    public event Action<NCAgentShardDisplayData>? UninstallPressed;
    public event Action<NCAgentShardDisplayData>? AccessDenied;

    public NCAgentShardItem(NCAgentShardDisplayData data)
    {
        _data = data;
        RobustXamlLoader.Load(this);

        if (data.Icon is { } icon)
            ShardIcon.SetFromSpriteSpecifier(icon);

        ShardName.Text = data.Name.ToUpperInvariant();
        ShardMeta.Text = $"{data.Category.ToString().ToUpperInvariant()} // {data.Size}U";
        ShardDescription.Text = data.Description;
        ShardPermissions.Text = data.Permissions.Count == 0
            ? "PERM // NONE"
            : $"PERM // {string.Join(" + ", data.Permissions.Select(PermissionText))}";

        if (data.ServerAuthorized)
        {
            ShardPermissions.Text += $" // {Loc.GetString("nc-agent-shard-server-authorized",
                ("access", data.AccessLabel.ToUpperInvariant()))}";
        }
        else if (data.RequiredAccess.Count == 0)
        {
            ShardPermissions.Text += " // ACCESS PUBLIC";
        }
        else
        {
            ShardPermissions.Text += data.Authorized
                ? $" // VIN {data.AccessLabel.ToUpperInvariant()} VERIFIED"
                : $" // VIN {data.AccessLabel.ToUpperInvariant()} REQUIRED";
        }

        switch (data.Status)
        {
            case InstallationStatus.Cartridge:
                ShardState.Text = "CHIP";
                ShardState.FontColorOverride = Color.FromHex("#FFD66B");
                ShardAction.Text = "INSTALL";
                break;
            case InstallationStatus.Installed:
                ShardState.Text = data.Authorized ? "LOCAL" : "LOCKED";
                ShardState.FontColorOverride = data.Authorized
                    ? Color.FromHex("#76FF95")
                    : Color.FromHex("#FF7897");
                // Removing a physical shard never requires permission to run its program.
                ShardAction.Text = "REMOVE";
                break;
            default:
                ShardState.Text = data.Authorized ? "SYSTEM" : "LOCKED";
                ShardState.FontColorOverride = data.Authorized
                    ? Color.FromHex("#77FFF2")
                    : Color.FromHex("#FF7897");
                ShardAction.Text = data.Authorized ? "OPEN" : "LOCKED";
                break;
        }

        OnPressed += _ => OnPrimaryPressed();
        ShardAction.OnPressed += _ => OnActionPressed();
    }

    public void PlayDeniedAnimation()
    {
        StopAnimation("nc-agent-shard-denied");
        PlayAnimation(DeniedAnimation, "nc-agent-shard-denied");
    }

    private void OnActionPressed()
    {
        if (_data.Status == InstallationStatus.Readonly && !_data.Authorized)
        {
            AccessDenied?.Invoke(_data);
            PlayDeniedAnimation();
            return;
        }

        switch (_data.Status)
        {
            case InstallationStatus.Cartridge:
                InstallPressed?.Invoke(_data);
                break;
            case InstallationStatus.Installed:
                UninstallPressed?.Invoke(_data);
                break;
            case InstallationStatus.Readonly:
                OpenPressed?.Invoke(_data);
                break;
        }
    }

    private void OnPrimaryPressed()
    {
        // A physical chip must be installed before it can run from Agent memory.
        if (_data.Status == InstallationStatus.Cartridge)
        {
            OnActionPressed();
            return;
        }

        if (!_data.Authorized)
        {
            AccessDenied?.Invoke(_data);
            PlayDeniedAnimation();
            return;
        }

        OpenPressed?.Invoke(_data);
    }

    private static string PermissionText(NCAgentShardPermission permission)
    {
        return permission switch
        {
            NCAgentShardPermission.LocalStorage => "STORAGE",
            NCAgentShardPermission.NetworkRead => "NET",
            NCAgentShardPermission.LocationRead => "LOCATION",
            NCAgentShardPermission.VinRead => "VIN",
            NCAgentShardPermission.DeviceControl => "CONTROL",
            _ => permission.ToString().ToUpperInvariant(),
        };
    }
}

/// <summary>
/// Immutable client-side projection of networked cartridge and SHARDS metadata.
/// </summary>
public sealed record NCAgentShardDisplayData(
    EntityUid Uid,
    string Name,
    string Description,
    int Size,
    NCAgentShardCategory Category,
    IReadOnlyList<NCAgentShardPermission> Permissions,
    IReadOnlyList<ProtoId<AccessLevelPrototype>> RequiredAccess,
    bool ServerAuthorized,
    string AccessLabel,
    bool Authorized,
    InstallationStatus Status,
    SpriteSpecifier? Icon);
