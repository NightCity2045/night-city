using Content.Shared._NC.Agent.Shards.TraumaResponse;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._NC.Agent.Shards.TraumaResponse;

/// <summary>
/// Compact field dispatch board designed for use while the responder is moving.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class NCAgentTraumaResponseFragment : BoxContainer
{
    public event Action<NCTraumaResponseAction, Guid, long>? ActionRequested;

    public NCAgentTraumaResponseFragment()
    {
        RobustXamlLoader.Load(this);
    }

    public void UpdateState(NCAgentTraumaResponseUiState state)
    {
        DutyStatus.Text = Loc.GetString(state.Authorized
            ? "nc-trauma-response-ready-state"
            : "nc-trauma-response-unavailable-state");
        NoticeLabel.Text = Loc.GetString(string.IsNullOrEmpty(state.Notice)
            ? "nc-trauma-response-board-online"
            : state.Notice);

        ActiveContainer.RemoveAllChildren();
        if (state.ActiveCall is { } active)
            ActiveContainer.AddChild(CreateCall(active, true));
        else
            ActiveContainer.AddChild(Empty("nc-trauma-response-no-active"));

        QueueContainer.RemoveAllChildren();
        foreach (var call in state.Queue)
            QueueContainer.AddChild(CreateCall(call, false));
        if (state.Queue.Count == 0)
            QueueContainer.AddChild(Empty("nc-trauma-response-queue-empty"));

        RosterContainer.RemoveAllChildren();
        foreach (var responder in state.Responders)
            RosterContainer.AddChild(CreateResponder(responder));
        if (state.Responders.Count == 0)
            RosterContainer.AddChild(Empty("nc-trauma-response-roster-empty"));

        RecentContainer.RemoveAllChildren();
        foreach (var call in state.RecentCalls)
            RecentContainer.AddChild(CreateCall(call, false, true));
        if (state.RecentCalls.Count == 0)
            RecentContainer.AddChild(Empty("nc-trauma-response-recent-empty"));
    }

    private Control CreateCall(NCTraumaResponseCallSummary call, bool active, bool recent = false)
    {
        var body = new BoxContainer
        {
            Orientation = LayoutOrientation.Vertical,
            HorizontalExpand = true,
            Margin = new Thickness(10, 7),
        };
        body.AddChild(new Label
        {
            Text = Loc.GetString("nc-trauma-response-call-title", ("client", call.ClientName),
                ("urgency", Urgency(call.Urgency))),
            FontColorOverride = call.Urgency == NCTraumaResponseUrgency.UnderFire
                ? Color.FromHex("#FF5A72")
                : Color.FromHex("#B9FBFF"),
        });
        body.AddChild(new Label
        {
            Text = Loc.GetString("nc-trauma-response-call-state", ("status", Status(call.Status)),
                ("plan", Plan(call.PlanId)), ("priority", call.Priority), ("wait", call.WaitingSeconds / 60)),
            FontColorOverride = Color.FromHex("#72F4FF"),
        });
        body.AddChild(new Label { Text = call.Zone, FontColorOverride = Color.FromHex("#83AEB5") });
        if (call.Coordinates is { } coordinates)
        {
            body.AddChild(new Label
            {
                Text = Loc.GetString("nc-trauma-response-call-coordinates", ("x", $"{coordinates.Position.X:0.0}"),
                    ("y", $"{coordinates.Position.Y:0.0}"), ("z", coordinates.Z)),
                FontColorOverride = Color.FromHex("#FFCF66"),
            });
        }
        if (!string.IsNullOrWhiteSpace(call.Description))
            body.AddChild(new Label { Text = call.Description, FontColorOverride = Color.FromHex("#D3E7E9") });
        body.AddChild(new Label
        {
            Text = Loc.GetString("nc-trauma-response-call-team", ("lead", string.IsNullOrEmpty(call.LeadName)
                    ? Loc.GetString("nc-trauma-response-unassigned") : call.LeadName),
                ("members", call.Participants.Count == 0 ? Loc.GetString("nc-trauma-response-no-members")
                    : string.Join(", ", call.Participants))),
            FontColorOverride = Color.FromHex("#83AEB5"),
        });

        if (!recent)
            AddActions(body, call, active);

        return new PanelContainer
        {
            HorizontalExpand = true,
            Margin = new Thickness(0, 0, 0, 5),
            PanelOverride = new StyleBoxFlat
            {
                BackgroundColor = Color.FromHex("#09171A"),
                BorderColor = active ? Color.FromHex("#FFCF66") : Color.FromHex("#24535A"),
                BorderThickness = new Thickness(1, 1, 1, 2),
            },
            Children = { body },
        };
    }

    private void AddActions(BoxContainer body, NCTraumaResponseCallSummary call, bool active)
    {
        var row = new BoxContainer { Orientation = LayoutOrientation.Horizontal, HorizontalExpand = true };
        if (!active)
        {
            AddAction(row, "nc-trauma-response-accept", NCTraumaResponseAction.Accept, call);
            AddAction(row, "nc-trauma-response-reject", NCTraumaResponseAction.Reject, call);
        }
        else if (call.ViewerAssigned)
        {
            AddAction(row, "nc-trauma-response-complete", NCTraumaResponseAction.Complete, call);
        }
        if (row.ChildCount > 0)
            body.AddChild(row);
    }

    private void AddAction(BoxContainer row, string locale, NCTraumaResponseAction action,
        NCTraumaResponseCallSummary call)
    {
        var button = new Button { Text = Loc.GetString(locale), HorizontalExpand = true, Margin = new Thickness(0, 5, 4, 0) };
        button.OnPressed += _ => ActionRequested?.Invoke(action, call.Id, call.Version);
        row.AddChild(button);
    }

    private static Control CreateResponder(NCTraumaResponseResponderSummary responder)
    {
        var status = responder.Busy
            ? Loc.GetString("nc-trauma-response-responder-busy")
            : Loc.GetString("nc-trauma-response-responder-available");
        return new Label
        {
            Text = Loc.GetString("nc-trauma-response-responder-line", ("name", responder.Name),
                ("role", Role(responder.JobId)), ("status", status)),
            FontColorOverride = !responder.Busy ? Color.FromHex("#72F4FF") : Color.FromHex("#7898A0"),
            Margin = new Thickness(8, 3),
        };
    }

    private static Control Empty(string locale) => new Label
    {
        Text = Loc.GetString(locale),
        FontColorOverride = Color.FromHex("#52747A"),
        HorizontalAlignment = HAlignment.Center,
        Margin = new Thickness(0, 8),
    };

    private static string Status(NCTraumaResponseCallStatus status) =>
        Loc.GetString($"nc-trauma-response-status-{status.ToString().ToLowerInvariant()}");

    private static string Urgency(NCTraumaResponseUrgency urgency) => urgency switch
    {
        NCTraumaResponseUrgency.Wounded => Loc.GetString("nc-trauma-team-urgency-wounded"),
        NCTraumaResponseUrgency.Critical => Loc.GetString("nc-trauma-team-urgency-critical"),
        _ => Loc.GetString("nc-trauma-team-urgency-under-fire"),
    };

    private static string Plan(string planId) => planId switch
    {
        "NCTraumaBronze" => Loc.GetString("nc-trauma-team-plan-bronze"),
        "NCTraumaSilver" => Loc.GetString("nc-trauma-team-plan-silver"),
        "NCTraumaGold" => Loc.GetString("nc-trauma-team-plan-gold"),
        "NCTraumaPlatinum" => Loc.GetString("nc-trauma-team-plan-platinum"),
        _ => Loc.GetString("nc-trauma-response-plan-unknown"),
    };

    private static string Role(string jobId) => jobId switch
    {
        "TraumaTeamParamedic" => Loc.GetString("job-name-trauma-team-paramedic"),
        "TraumaTeamOperative" => Loc.GetString("job-name-trauma-team-operative"),
        _ => Loc.GetString("nc-trauma-response-role-unknown"),
    };

}
