using Content.Shared.CartridgeLoader.Cartridges;
using Robust.Client.Animations;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Animations;

namespace Content.Client._NC.Agent.Shards.LogProbe;

[GenerateTypedNameReferences]
public sealed partial class NCAgentLogProbeFragment : BoxContainer
{
    private static readonly Animation ScanAnimation = new()
    {
        Length = TimeSpan.FromSeconds(0.36),
        AnimationTracks =
        {
            new AnimationTrackControlProperty
            {
                Property = nameof(Modulate),
                InterpolationMode = AnimationInterpolationMode.Linear,
                KeyFrames =
                {
                    new AnimationTrackProperty.KeyFrame(Color.FromHex("#F0C75E55"), 0f),
                    new AnimationTrackProperty.KeyFrame(Color.White, 0.36f),
                },
            },
        },
    };

    private string _previousDevice = string.Empty;

    public event Action? PrintRequested;

    public NCAgentLogProbeFragment()
    {
        RobustXamlLoader.Load(this);
        PrintButton.OnPressed += _ => PrintRequested?.Invoke();
        UpdateState(string.Empty, []);
    }

    public void UpdateState(string device, List<PulledAccessLog> logs)
    {
        var newScan = !string.IsNullOrWhiteSpace(device) && device != _previousDevice;
        _previousDevice = device;
        DeviceName.Text = string.IsNullOrWhiteSpace(device) ? "TARGET // NONE" : $"TARGET // {device.ToUpperInvariant()}";
        LogCount.Text = $"{logs.Count} LOGS";
        PrintButton.Disabled = string.IsNullOrWhiteSpace(device);
        ProbeStatus.Text = string.IsNullOrWhiteSpace(device)
            ? "ARMED // USE AGENT ON ACCESS DEVICE"
            : "CAPTURE COMPLETE // LOCAL SNAPSHOT";
        ProbeStatus.FontColorOverride = string.IsNullOrWhiteSpace(device)
            ? Color.FromHex("#76FF95")
            : Color.FromHex("#FFD66B");

        LogContainer.RemoveAllChildren();
        for (var index = 0; index < logs.Count; index++)
            LogContainer.AddChild(CreateLog(logs[index], index + 1));

        if (logs.Count == 0)
        {
            LogContainer.AddChild(new Label
            {
                Text = string.IsNullOrWhiteSpace(device) ? "NO DEVICE CAPTURED" : "DEVICE EXPOSED NO ACCESS LOGS",
                FontColorOverride = Color.FromHex("#655B46"),
                HorizontalAlignment = HAlignment.Center,
                Margin = new Thickness(0, 18),
            });
        }

        if (newScan)
        {
            ScanHeader.StopAnimation("nc-agent-logprobe-scan");
            ScanHeader.PlayAnimation(ScanAnimation, "nc-agent-logprobe-scan");
        }
    }

    private static Control CreateLog(PulledAccessLog log, int index)
    {
        var row = new BoxContainer
        {
            Orientation = LayoutOrientation.Horizontal,
            HorizontalExpand = true,
            Margin = new Thickness(9, 6),
        };
        row.AddChild(new Label { Text = $"#{index:000}", FontColorOverride = Color.FromHex("#8F7540"), MinWidth = 48 });
        row.AddChild(new Label { Text = log.Time.ToString(@"hh\:mm\:ss"), FontColorOverride = Color.FromHex("#FFD66B"), MinWidth = 86 });
        row.AddChild(new Label { Text = log.Accessor, FontColorOverride = Color.FromHex("#D7FFFB"), HorizontalExpand = true });

        return new PanelContainer
        {
            HorizontalExpand = true,
            Margin = new Thickness(0, 0, 0, 4),
            PanelOverride = new StyleBoxFlat
            {
                BackgroundColor = Color.FromHex("#17150F"),
                BorderColor = Color.FromHex("#6B5A32"),
                BorderThickness = new Thickness(1),
            },
            Children = { row },
        };
    }
}
