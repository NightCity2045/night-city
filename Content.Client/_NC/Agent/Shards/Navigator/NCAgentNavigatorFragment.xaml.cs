using System.Linq;
using Content.Shared._NC.Agent.Shards.Navigator;
using Content.Shared._NC.Coordinates;
using Robust.Client.Animations;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Animations;

namespace Content.Client._NC.Agent.Shards.Navigator;

/// <summary>
/// Request-driven city coordinate display with device-local waypoint storage.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class NCAgentNavigatorFragment : BoxContainer
{
    private static readonly Animation PositionAnimation = new()
    {
        Length = TimeSpan.FromSeconds(0.3),
        AnimationTracks =
        {
            new AnimationTrackControlProperty
            {
                Property = nameof(Modulate),
                InterpolationMode = AnimationInterpolationMode.Linear,
                KeyFrames =
                {
                    new AnimationTrackProperty.KeyFrame(Color.FromHex("#FFD66B55"), 0f),
                    new AnimationTrackProperty.KeyFrame(Color.White, 0.3f),
                },
            },
        },
    };

    private NCMapCoordinates? _current;

    public event Action<NCAgentNavigatorAction, Guid, string>? ActionRequested;

    public NCAgentNavigatorFragment()
    {
        RobustXamlLoader.Load(this);
        RefreshButton.OnPressed += _ => Request(NCAgentNavigatorAction.Refresh);
        SaveButton.OnPressed += _ => SaveCurrent();
    }

    public void UpdateState(NCMapCoordinates? current, string currentZone, List<NCAgentWaypoint> waypoints)
    {
        _current = current;
        WaypointCount.Text = $"{waypoints.Count} / 24";
        CurrentZone.Text = currentZone.ToUpperInvariant();
        if (current is { } coordinates)
        {
            CurrentCoordinates.Text = $"X {coordinates.Position.X:0.0} // Y {coordinates.Position.Y:0.0} // Z {coordinates.Z:+0;-0;0}";
            SignalStatus.Text = $"LOCKED // {ShortNetwork(coordinates)}";
            SignalStatus.FontColorOverride = Color.FromHex("#76FF95");
        }
        else
        {
            CurrentCoordinates.Text = "X -- // Y -- // Z --";
            SignalStatus.Text = "CITY GRID // SIGNAL UNAVAILABLE";
            SignalStatus.FontColorOverride = Color.FromHex("#FF7897");
        }

        WaypointContainer.RemoveAllChildren();
        foreach (var waypoint in waypoints.AsEnumerable().Reverse())
            WaypointContainer.AddChild(CreateWaypoint(waypoint));

        if (waypoints.Count == 0)
        {
            WaypointContainer.AddChild(new Label
            {
                Text = "NO SAVED WAYPOINTS",
                FontColorOverride = Color.FromHex("#426D69"),
                HorizontalAlignment = HAlignment.Center,
                Margin = new Thickness(0, 18),
            });
        }

        CurrentCoordinates.StopAnimation("nc-agent-navigator-position");
        CurrentCoordinates.PlayAnimation(PositionAnimation, "nc-agent-navigator-position");
    }

    private Control CreateWaypoint(NCAgentWaypoint waypoint)
    {
        var content = new BoxContainer
        {
            Orientation = LayoutOrientation.Vertical,
            HorizontalExpand = true,
            Margin = new Thickness(10, 7),
        };
        var heading = new BoxContainer { Orientation = LayoutOrientation.Horizontal, HorizontalExpand = true };
        heading.AddChild(new Label { Text = waypoint.Label.ToUpperInvariant(), FontColorOverride = Color.FromHex("#FFD66B") });
        heading.AddChild(new Control { HorizontalExpand = true });
        var delete = new Button { Text = "DELETE", MinWidth = 68 };
        delete.Label.FontColorOverride = Color.FromHex("#FF7897");
        delete.OnPressed += _ => ActionRequested?.Invoke(NCAgentNavigatorAction.Delete, waypoint.Id, string.Empty);
        heading.AddChild(delete);
        content.AddChild(heading);
        content.AddChild(new Label
        {
            Text = $"X {waypoint.Coordinates.Position.X:0.0} // Y {waypoint.Coordinates.Position.Y:0.0} // Z {waypoint.Coordinates.Z:+0;-0;0}",
            FontColorOverride = Color.FromHex("#77FFF2"),
        });
        content.AddChild(new Label { Text = waypoint.ZonePath.ToUpperInvariant(), FontColorOverride = Color.FromHex("#6C918E") });
        content.AddChild(new Label { Text = DirectionText(waypoint), FontColorOverride = Color.FromHex("#8FB8FF") });

        return new PanelContainer
        {
            HorizontalExpand = true,
            Margin = new Thickness(0, 0, 0, 5),
            PanelOverride = new StyleBoxFlat
            {
                BackgroundColor = Color.FromHex("#101B1D"),
                BorderColor = Color.FromHex("#8F7540"),
                BorderThickness = new Thickness(1, 1, 1, 2),
            },
            Children = { content },
        };
    }

    private string DirectionText(NCAgentWaypoint waypoint)
    {
        if (_current is not { } current ||
            current.NetworkId != waypoint.Coordinates.NetworkId ||
            current.Z != waypoint.Coordinates.Z)
        {
            return "ROUTE // DIFFERENT GRID OR LEVEL";
        }

        var delta = waypoint.Coordinates.Position - current.Position;
        var distance = delta.Length();
        if (distance < 0.5f)
            return "ROUTE // CURRENT POSITION";

        var direction = MathF.Abs(delta.X) > MathF.Abs(delta.Y)
            ? delta.X > 0 ? "EAST" : "WEST"
            : delta.Y > 0 ? "NORTH" : "SOUTH";
        return $"ROUTE // {distance:0.0} M // {direction}";
    }

    private void SaveCurrent()
    {
        var label = WaypointLabel.Text.Trim();
        if (_current == null || string.IsNullOrWhiteSpace(label) || label.Length > 30)
        {
            SignalStatus.Text = _current == null ? "ERROR // POSITION UNAVAILABLE" : "ERROR // LABEL REQUIRED // 30 CHAR LIMIT";
            SignalStatus.FontColorOverride = Color.FromHex("#FF7897");
            return;
        }

        ActionRequested?.Invoke(NCAgentNavigatorAction.SaveCurrent, Guid.Empty, label);
        WaypointLabel.Text = string.Empty;
        SignalStatus.Text = "SAVING WAYPOINT // SYNCING";
        SignalStatus.FontColorOverride = Color.FromHex("#FFD66B");
    }

    private void Request(NCAgentNavigatorAction action)
    {
        SignalStatus.Text = "ACQUIRING POSITION // CITY GRID";
        SignalStatus.FontColorOverride = Color.FromHex("#FFD66B");
        ActionRequested?.Invoke(action, Guid.Empty, string.Empty);
    }

    private static string ShortNetwork(NCMapCoordinates coordinates)
    {
        var network = coordinates.NetworkId.ToString().ToUpperInvariant();
        return network.Length > 12 ? network[..12] : network;
    }
}
