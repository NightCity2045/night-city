using System.Linq;
using Content.Shared._NC.Agent.Shards.MedTek;
using Robust.Client.Animations;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Animations;

namespace Content.Client._NC.Agent.Shards.MedTek;

[GenerateTypedNameReferences]
public sealed partial class NCAgentMedTekFragment : BoxContainer
{
    private static readonly Animation ScanAnimation = new()
    {
        Length = TimeSpan.FromSeconds(0.34),
        AnimationTracks =
        {
            new AnimationTrackControlProperty
            {
                Property = nameof(Modulate),
                InterpolationMode = AnimationInterpolationMode.Linear,
                KeyFrames =
                {
                    new AnimationTrackProperty.KeyFrame(Color.FromHex("#58E88755"), 0f),
                    new AnimationTrackProperty.KeyFrame(Color.White, 0.34f),
                },
            },
        },
    };

    private int _previousCount;

    public event Action? ClearRequested;

    public NCAgentMedTekFragment()
    {
        RobustXamlLoader.Load(this);
        ClearButton.OnPressed += _ => ClearRequested?.Invoke();
        UpdateState([]);
    }

    public void UpdateState(List<NCAgentMedicalScan> history)
    {
        var newScan = history.Count > _previousCount;
        _previousCount = history.Count;
        HistoryCount.Text = $"{history.Count} / 12";
        ClearButton.Disabled = history.Count == 0;
        MedicalStatus.Text = newScan ? "SCAN CAPTURED // SNAPSHOT STORED" : "ARMED // USE AGENT ON PATIENT";
        MedicalStatus.FontColorOverride = newScan ? Color.FromHex("#FFD66B") : Color.FromHex("#76FF95");

        HistoryContainer.RemoveAllChildren();
        foreach (var scan in history.AsEnumerable().Reverse())
            HistoryContainer.AddChild(CreateScan(scan));

        if (history.Count == 0)
        {
            HistoryContainer.AddChild(new Label
            {
                Text = "NO STORED PATIENT SCANS",
                FontColorOverride = Color.FromHex("#42634B"),
                HorizontalAlignment = HAlignment.Center,
                Margin = new Thickness(0, 18),
            });
        }

        if (newScan)
        {
            MedicalHeader.StopAnimation("nc-agent-medtek-scan");
            MedicalHeader.PlayAnimation(ScanAnimation, "nc-agent-medtek-scan");
        }
    }

    private static Control CreateScan(NCAgentMedicalScan scan)
    {
        var content = new BoxContainer
        {
            Orientation = LayoutOrientation.Vertical,
            HorizontalExpand = true,
            Margin = new Thickness(10, 7),
        };
        var heading = new BoxContainer { Orientation = LayoutOrientation.Horizontal, HorizontalExpand = true };
        heading.AddChild(new Label { Text = scan.TargetName.ToUpperInvariant(), FontColorOverride = Color.FromHex("#D7FFE2") });
        heading.AddChild(new Control { HorizontalExpand = true });
        heading.AddChild(new Label { Text = scan.ScannedAt.ToLocalTime().ToString("HH:mm:ss"), FontColorOverride = Color.FromHex("#58956B") });
        content.AddChild(heading);

        var temperature = float.IsNaN(scan.Temperature) ? "--" : $"{scan.Temperature - 273.15f:0.0} C";
        var blood = float.IsNaN(scan.BloodLevel) ? "--" : $"{scan.BloodLevel * 100f:0.0}%";
        content.AddChild(new Label
        {
            Text = $"TEMP {temperature} // BLOOD {blood} // DAMAGE {scan.TotalDamage:0.0}",
            FontColorOverride = Color.FromHex("#76FF95"),
        });
        if (scan.Bleeding || scan.Unrevivable)
        {
            var alerts = scan.Bleeding && scan.Unrevivable ? "BLEEDING // UNREVIVABLE" : scan.Bleeding ? "BLEEDING" : "UNREVIVABLE";
            content.AddChild(new Label { Text = $"ALERT // {alerts}", FontColorOverride = Color.FromHex("#FF7897") });
        }

        foreach (var damage in scan.Damage.Take(6))
            content.AddChild(new Label { Text = $"{damage.Type.ToUpperInvariant()} // {damage.Amount:0.0}", FontColorOverride = Color.FromHex("#8FB89A") });

        return new PanelContainer
        {
            HorizontalExpand = true,
            Margin = new Thickness(0, 0, 0, 5),
            PanelOverride = new StyleBoxFlat
            {
                BackgroundColor = Color.FromHex("#0C1B12"),
                BorderColor = scan.Bleeding || scan.Unrevivable ? Color.FromHex("#A94255") : Color.FromHex("#28593A"),
                BorderThickness = new Thickness(1, 1, 1, 2),
            },
            Children = { content },
        };
    }
}
