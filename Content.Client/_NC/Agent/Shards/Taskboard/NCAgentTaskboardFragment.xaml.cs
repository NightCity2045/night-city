using System.Linq;
using Content.Shared.CartridgeLoader.Cartridges;
using Robust.Client.Animations;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Animations;

namespace Content.Client._NC.Agent.Shards.Taskboard;

/// <summary>
/// Compact searchable workflow board designed for the Agent phone viewport.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class NCAgentTaskboardFragment : BoxContainer
{
    private static readonly Animation SyncAnimation = new()
    {
        Length = TimeSpan.FromSeconds(0.22),
        AnimationTracks =
        {
            new AnimationTrackControlProperty
            {
                Property = nameof(Modulate),
                InterpolationMode = AnimationInterpolationMode.Linear,
                KeyFrames =
                {
                    new AnimationTrackProperty.KeyFrame(Color.FromHex("#508DFF55"), 0f),
                    new AnimationTrackProperty.KeyFrame(Color.White, 0.22f),
                },
            },
        },
    };

    private readonly List<NanoTaskItemAndId> _tasks = [];
    private int? _editingId;

    public event Action<NanoTaskItem>? CreateRequested;
    public event Action<int, NanoTaskItem>? UpdateRequested;
    public event Action<int>? DeleteRequested;
    public event Action<NanoTaskItem>? PrintRequested;

    public NCAgentTaskboardFragment()
    {
        RobustXamlLoader.Load(this);

        foreach (var priority in Enum.GetValues<NanoTaskPriority>())
            PrioritySelector.AddItem(priority.ToString().ToUpperInvariant(), (int) priority);
        foreach (var status in Enum.GetValues<NanoTaskStatus>())
            StateSelector.AddItem(status.ToString().ToUpperInvariant(), (int) status);

        PrioritySelector.OnItemSelected += args => args.Button.SelectId(args.Id);
        StateSelector.OnItemSelected += args => args.Button.SelectId(args.Id);
        SearchInput.OnTextChanged += _ => RebuildList();
        NewButton.OnPressed += _ => OpenEditor();
        CancelButton.OnPressed += _ => CloseEditor();
        SaveButton.OnPressed += _ => Save();
        DeleteButton.OnPressed += _ => Delete();
        PrintButton.OnPressed += _ => Print();
        CloseEditor();
        RebuildList();
    }

    public void UpdateState(List<NanoTaskItemAndId> tasks)
    {
        _tasks.Clear();
        _tasks.AddRange(tasks.OrderBy(task => task.Data.Status)
            .ThenBy(task => task.Data.Priority)
            .ThenBy(task => task.Id));
        CountLabel.Text = $"{_tasks.Count} TASKS";
        StatusLabel.Text = "SYNC COMPLETE // DEVICE LOCAL";
        StatusLabel.FontColorOverride = Color.FromHex("#76FF95");
        RebuildList();
        TasksContainer.StopAnimation("nc-agent-taskboard-sync");
        TasksContainer.PlayAnimation(SyncAnimation, "nc-agent-taskboard-sync");
    }

    private void RebuildList()
    {
        TasksContainer.RemoveAllChildren();
        var query = SearchInput.Text.Trim();
        var visible = _tasks.Where(task => string.IsNullOrEmpty(query) ||
            task.Data.Description.Contains(query, StringComparison.OrdinalIgnoreCase) ||
            task.Data.TaskIsFor.Contains(query, StringComparison.OrdinalIgnoreCase) ||
            task.Data.Deadline.Contains(query, StringComparison.OrdinalIgnoreCase));

        var any = false;
        foreach (var task in visible)
        {
            any = true;
            TasksContainer.AddChild(CreateTaskCard(task));
        }

        if (!any)
        {
            TasksContainer.AddChild(new Label
            {
                Text = _tasks.Count == 0 ? "NO TASKS IN LOCAL QUEUE" : "NO MATCHING TASKS",
                FontColorOverride = Color.FromHex("#426D69"),
                HorizontalAlignment = HAlignment.Center,
                Margin = new Thickness(0, 18),
            });
        }
    }

    private Control CreateTaskCard(NanoTaskItemAndId task)
    {
        var statusColor = StatusColor(task.Data.Status);
        var priority = task.Data.Priority switch
        {
            NanoTaskPriority.High => "HIGH",
            NanoTaskPriority.Medium => "MED",
            _ => "LOW",
        };

        var content = new BoxContainer
        {
            Orientation = LayoutOrientation.Vertical,
            HorizontalExpand = true,
            Margin = new Thickness(10, 7),
        };
        var heading = new BoxContainer { Orientation = LayoutOrientation.Horizontal, HorizontalExpand = true };
        heading.AddChild(new Label { Text = $"{task.Data.Status.ToString().ToUpperInvariant()} // {priority}", FontColorOverride = statusColor });
        heading.AddChild(new Control { HorizontalExpand = true });
        heading.AddChild(new Label { Text = $"#{task.Id:000}", FontColorOverride = Color.FromHex("#5B718E") });
        content.AddChild(heading);
        content.AddChild(new Label
        {
            Text = task.Data.Description,
            FontColorOverride = task.Data.Status == NanoTaskStatus.Done ? Color.FromHex("#66817E") : Color.FromHex("#D7FFFB"),
        });

        var details = string.IsNullOrWhiteSpace(task.Data.TaskIsFor) ? "UNASSIGNED" : task.Data.TaskIsFor;
        if (!string.IsNullOrWhiteSpace(task.Data.Deadline))
            details += $" // DUE {task.Data.Deadline}";
        content.AddChild(new Label { Text = details, FontColorOverride = Color.FromHex("#6C918E") });

        var actions = new BoxContainer { Orientation = LayoutOrientation.Horizontal, HorizontalExpand = true, Margin = new Thickness(0, 4, 0, 0) };
        actions.AddChild(new Control { HorizontalExpand = true });
        if (task.Data.Status != NanoTaskStatus.Done)
        {
            var advance = CreateButton(task.Data.Status == NanoTaskStatus.Open ? "START" : "DONE", statusColor);
            advance.OnPressed += _ => Advance(task);
            actions.AddChild(advance);
        }
        var edit = CreateButton("EDIT", Color.FromHex("#8FB8FF"));
        edit.OnPressed += _ => OpenEditor(task);
        actions.AddChild(edit);
        content.AddChild(actions);

        return new PanelContainer
        {
            HorizontalExpand = true,
            Margin = new Thickness(0, 0, 0, 5),
            PanelOverride = new StyleBoxFlat
            {
                BackgroundColor = Color.FromHex("#0C1722"),
                BorderColor = statusColor,
                BorderThickness = new Thickness(1, 1, 1, 2),
            },
            Children = { content },
        };
    }

    private void Advance(NanoTaskItemAndId task)
    {
        var next = task.Data.Status == NanoTaskStatus.Open ? NanoTaskStatus.Active : NanoTaskStatus.Done;
        UpdateRequested?.Invoke(task.Id, Copy(task.Data, next));
        SetPendingStatus($"MOVING #{task.Id:000} // {next.ToString().ToUpperInvariant()}");
    }

    private void OpenEditor(NanoTaskItemAndId? task = null)
    {
        _editingId = task?.Id;
        DescriptionInput.Text = task?.Data.Description ?? string.Empty;
        TargetInput.Text = task?.Data.TaskIsFor ?? string.Empty;
        DeadlineInput.Text = task?.Data.Deadline ?? string.Empty;
        PrioritySelector.SelectId((int) (task?.Data.Priority ?? NanoTaskPriority.Medium));
        StateSelector.SelectId((int) (task?.Data.Status ?? NanoTaskStatus.Open));
        EditorTitle.Text = task == null ? "NEW TASK" : $"EDIT TASK // #{task.Id:000}";
        EditorPanel.Visible = true;
        DeleteButton.Visible = task != null;
        PrintButton.Visible = task != null;
        DescriptionInput.GrabKeyboardFocus();
    }

    private void CloseEditor()
    {
        _editingId = null;
        EditorPanel.Visible = false;
    }

    private void Save()
    {
        var item = ReadEditor();
        if (item == null)
            return;

        if (_editingId is { } id)
            UpdateRequested?.Invoke(id, item);
        else
            CreateRequested?.Invoke(item);

        SetPendingStatus(_editingId.HasValue ? "UPDATING TASK // SYNCING" : "CREATING TASK // SYNCING");
        CloseEditor();
    }

    private void Delete()
    {
        if (_editingId is not { } id)
            return;

        DeleteRequested?.Invoke(id);
        SetPendingStatus($"DELETING #{id:000} // SYNCING");
        CloseEditor();
    }

    private void Print()
    {
        var item = ReadEditor();
        if (item == null)
            return;

        PrintRequested?.Invoke(item);
        SetPendingStatus("PRINT JOB SENT // LOCAL RELAY");
    }

    private NanoTaskItem? ReadEditor()
    {
        var description = DescriptionInput.Text.Trim();
        var target = TargetInput.Text.Trim();
        var deadline = DeadlineInput.Text.Trim();
        if (string.IsNullOrWhiteSpace(description) ||
            description.Length > NanoTaskItem.MaximumStringLength ||
            target.Length > NanoTaskItem.MaximumStringLength ||
            deadline.Length > NanoTaskItem.MaximumStringLength)
        {
            StatusLabel.Text = "ERROR // DESCRIPTION REQUIRED // 30 CHAR LIMIT";
            StatusLabel.FontColorOverride = Color.FromHex("#FF7897");
            return null;
        }

        var status = (NanoTaskStatus) StateSelector.SelectedId;
        return new NanoTaskItem(
            description,
            target,
            status == NanoTaskStatus.Done,
            (NanoTaskPriority) PrioritySelector.SelectedId,
            status,
            deadline);
    }

    private void SetPendingStatus(string text)
    {
        StatusLabel.Text = text;
        StatusLabel.FontColorOverride = Color.FromHex("#FFD66B");
    }

    private static NanoTaskItem Copy(NanoTaskItem item, NanoTaskStatus status)
    {
        return new NanoTaskItem(
            item.Description,
            item.TaskIsFor,
            status == NanoTaskStatus.Done,
            item.Priority,
            status,
            item.Deadline);
    }

    private static Color StatusColor(NanoTaskStatus status)
    {
        return status switch
        {
            NanoTaskStatus.Active => Color.FromHex("#FFD66B"),
            NanoTaskStatus.Done => Color.FromHex("#76FF95"),
            _ => Color.FromHex("#8FB8FF"),
        };
    }

    private static Button CreateButton(string text, Color color)
    {
        var button = new Button { Text = text, MinWidth = 68, Margin = new Thickness(4, 0, 0, 0) };
        button.Label.FontColorOverride = color;
        return button;
    }
}
