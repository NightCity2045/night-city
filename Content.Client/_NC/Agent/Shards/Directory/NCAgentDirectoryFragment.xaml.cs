using System.Linq;
using Content.Shared._NC.Agent.Shards.Directory;
using Robust.Client.Animations;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Animations;

namespace Content.Client._NC.Agent.Shards.Directory;

[GenerateTypedNameReferences]
public sealed partial class NCAgentDirectoryFragment : BoxContainer
{
    private static readonly Animation SyncAnimation = new()
    {
        Length = TimeSpan.FromSeconds(0.2),
        AnimationTracks =
        {
            new AnimationTrackControlProperty
            {
                Property = nameof(Modulate),
                InterpolationMode = AnimationInterpolationMode.Linear,
                KeyFrames =
                {
                    new AnimationTrackProperty.KeyFrame(Color.FromHex("#24E0D044"), 0f),
                    new AnimationTrackProperty.KeyFrame(Color.White, 0.2f),
                },
            },
        },
    };

    private List<NCAgentDirectoryRecord> _entries = [];

    public NCAgentDirectoryFragment()
    {
        RobustXamlLoader.Load(this);
        SearchInput.OnTextChanged += _ => Rebuild();
        Rebuild();
    }

    public void UpdateState(List<NCAgentDirectoryRecord> entries)
    {
        _entries = entries;
        OrganizationName.Text = "NIGHT CITY // PUBLIC PERSONNEL";
        EntryCount.Text = $"{_entries.Count} ENTRIES";
        Rebuild();
        EntryContainer.StopAnimation("nc-agent-directory-sync");
        EntryContainer.PlayAnimation(SyncAnimation, "nc-agent-directory-sync");
    }

    private void Rebuild()
    {
        EntryContainer.RemoveAllChildren();
        var query = SearchInput.Text.Trim();
        var visible = _entries
            .Where(entry => string.IsNullOrEmpty(query) ||
                entry.CharacterName.Contains(query, StringComparison.OrdinalIgnoreCase) ||
                entry.JobTitle.Contains(query, StringComparison.OrdinalIgnoreCase) ||
                entry.Organization.Contains(query, StringComparison.OrdinalIgnoreCase))
            .OrderBy(entry => entry.Organization)
            .ThenBy(entry => entry.JobTitle)
            .ThenBy(entry => entry.CharacterName)
            .ToArray();

        foreach (var entry in visible)
            EntryContainer.AddChild(CreateEntry(entry));

        if (visible.Length == 0)
        {
            EntryContainer.AddChild(new Label
            {
                Text = _entries.Count == 0 ? "DIRECTORY UNAVAILABLE" : "NO MATCHING RECORDS",
                FontColorOverride = Color.FromHex("#426D69"),
                HorizontalAlignment = HAlignment.Center,
                Margin = new Thickness(0, 18),
            });
        }
    }

    private static Control CreateEntry(NCAgentDirectoryRecord entry)
    {
        var content = new BoxContainer
        {
            Orientation = LayoutOrientation.Vertical,
            HorizontalExpand = true,
            Margin = new Thickness(10, 7),
        };
        content.AddChild(new Label { Text = entry.CharacterName.ToUpperInvariant(), FontColorOverride = Color.FromHex("#D7FFFB") });
        content.AddChild(new Label { Text = $"POSITION // {entry.JobTitle}", FontColorOverride = Color.FromHex("#77FFF2") });
        content.AddChild(new Label { Text = $"ORG // {entry.Organization.ToUpperInvariant()}", FontColorOverride = Color.FromHex("#5FA39E") });
        content.AddChild(new Label { Text = $"VIN RECORD // NC-{entry.CharacterId:D6}", FontColorOverride = Color.FromHex("#426D69") });

        return new PanelContainer
        {
            HorizontalExpand = true,
            Margin = new Thickness(0, 0, 0, 5),
            PanelOverride = new StyleBoxFlat
            {
                BackgroundColor = Color.FromHex("#0C1B21"),
                BorderColor = Color.FromHex("#245C59"),
                BorderThickness = new Thickness(1, 1, 1, 2),
            },
            Children = { content },
        };
    }
}
