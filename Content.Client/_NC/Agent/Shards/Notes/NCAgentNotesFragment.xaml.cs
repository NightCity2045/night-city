using System.Linq;
using Content.Shared._NC.Agent.Shards.Notes;
using Robust.Client.Animations;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Animations;
using Robust.Shared.Utility;

namespace Content.Client._NC.Agent.Shards.Notes;

/// <summary>
/// Searchable, editable Agent note vault. It only requests mutations; the server returns the authoritative list.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class NCAgentNotesFragment : BoxContainer
{
    private static readonly Animation SyncAnimation = new()
    {
        Length = TimeSpan.FromSeconds(0.24),
        AnimationTracks =
        {
            new AnimationTrackControlProperty
            {
                Property = nameof(Modulate),
                InterpolationMode = AnimationInterpolationMode.Linear,
                KeyFrames =
                {
                    new AnimationTrackProperty.KeyFrame(Color.FromHex("#77FFF244"), 0f),
                    new AnimationTrackProperty.KeyFrame(Color.White, 0.24f),
                },
            },
        },
    };

    private readonly List<NCAgentNoteEntry> _entries = [];
    private Guid? _editing;

    public event Action<NCAgentNotesAction, Guid, string>? ActionRequested;

    public NCAgentNotesFragment()
    {
        RobustXamlLoader.Load(this);
        SearchInput.OnTextChanged += _ => RebuildList();
        SaveButton.OnPressed += _ => SaveNote();
        CancelEditButton.OnPressed += _ => ResetEditor();
        RebuildList();
    }

    public void UpdateState(List<NCAgentNoteEntry> entries)
    {
        _entries.Clear();
        _entries.AddRange(entries.OrderByDescending(note => note.UpdatedAt));
        CountLabel.Text = $"{_entries.Count} / 64";
        StatusLabel.Text = "SYNC COMPLETE // DEVICE LOCAL";
        StatusLabel.FontColorOverride = Color.FromHex("#76FF95");
        RebuildList();
        NotesContainer.StopAnimation("nc-agent-notes-sync");
        NotesContainer.PlayAnimation(SyncAnimation, "nc-agent-notes-sync");
    }

    private void RebuildList()
    {
        NotesContainer.RemoveAllChildren();
        var query = SearchInput.Text.Trim();
        var visible = _entries.Where(note =>
            string.IsNullOrEmpty(query) || note.Body.Contains(query, StringComparison.OrdinalIgnoreCase));

        var any = false;
        foreach (var note in visible)
        {
            any = true;
            NotesContainer.AddChild(CreateNoteCard(note));
        }

        if (!any)
        {
            NotesContainer.AddChild(new Label
            {
                Text = _entries.Count == 0 ? "NO LOCAL NOTES" : "NO MATCHING NOTES",
                FontColorOverride = Color.FromHex("#426D69"),
                HorizontalAlignment = HAlignment.Center,
                Margin = new Thickness(0, 18),
            });
        }
    }

    private Control CreateNoteCard(NCAgentNoteEntry note)
    {
        var content = new BoxContainer
        {
            Orientation = LayoutOrientation.Vertical,
            HorizontalExpand = true,
            Margin = new Thickness(10, 7),
        };
        var timestamp = note.UpdatedAt == note.CreatedAt
            ? $"CREATED // {note.CreatedAt.ToLocalTime():yyyy-MM-dd HH:mm}"
            : $"UPDATED // {note.UpdatedAt.ToLocalTime():yyyy-MM-dd HH:mm}";
        content.AddChild(new Label { Text = timestamp, FontColorOverride = Color.FromHex("#5FA39E") });

        var body = new RichTextLabel { HorizontalExpand = true, Margin = new Thickness(0, 4) };
        body.SetMessage(FormattedMessage.FromUnformatted(note.Body));
        content.AddChild(body);

        var actions = new BoxContainer { Orientation = LayoutOrientation.Horizontal };
        actions.AddChild(new Control { HorizontalExpand = true });
        var edit = CreateButton("EDIT", "#77FFF2");
        edit.OnPressed += _ => BeginEdit(note);
        var delete = CreateButton("DELETE", "#FF7897");
        delete.OnPressed += _ =>
        {
            StatusLabel.Text = "DELETING NOTE // SYNCING";
            StatusLabel.FontColorOverride = Color.FromHex("#FFD66B");
            ActionRequested?.Invoke(NCAgentNotesAction.Delete, note.Id, string.Empty);
        };
        actions.AddChild(edit);
        actions.AddChild(delete);
        content.AddChild(actions);

        return new PanelContainer
        {
            HorizontalExpand = true,
            Margin = new Thickness(0, 0, 0, 5),
            PanelOverride = new StyleBoxFlat
            {
                BackgroundColor = Color.FromHex("#0C1B21"),
                BorderColor = Color.FromHex("#245C59"),
                BorderThickness = new Thickness(1, 1, 1, 2),
            },
            Children = { content },
        };
    }

    private void BeginEdit(NCAgentNoteEntry note)
    {
        _editing = note.Id;
        NoteInput.TextRope = new Rope.Leaf(note.Body);
        EditorModeLabel.Text = "EDIT NOTE";
        EditorModeLabel.FontColorOverride = Color.FromHex("#FFD66B");
        SaveButton.Text = "APPLY";
        CancelEditButton.Visible = true;
        NoteInput.GrabKeyboardFocus();
    }

    private void SaveNote()
    {
        var body = Rope.Collapse(NoteInput.TextRope).Trim();
        if (string.IsNullOrWhiteSpace(body))
        {
            StatusLabel.Text = "ERROR // EMPTY NOTE";
            StatusLabel.FontColorOverride = Color.FromHex("#FF7897");
            return;
        }

        var action = _editing.HasValue ? NCAgentNotesAction.Edit : NCAgentNotesAction.Add;
        StatusLabel.Text = action == NCAgentNotesAction.Add
            ? "WRITING NOTE // SYNCING"
            : "UPDATING NOTE // SYNCING";
        StatusLabel.FontColorOverride = Color.FromHex("#FFD66B");
        ActionRequested?.Invoke(action, _editing ?? Guid.Empty, body);
        ResetEditor();
    }

    private void ResetEditor()
    {
        _editing = null;
        NoteInput.TextRope = Rope.Leaf.Empty;
        EditorModeLabel.Text = "NEW NOTE";
        EditorModeLabel.FontColorOverride = Color.FromHex("#76FF95");
        SaveButton.Text = "SAVE";
        CancelEditButton.Visible = false;
    }

    private static Button CreateButton(string text, string color)
    {
        var button = new Button { Text = text, MinWidth = 76, Margin = new Thickness(4, 0, 0, 0) };
        button.Label.FontColorOverride = Color.FromHex(color);
        return button;
    }
}
