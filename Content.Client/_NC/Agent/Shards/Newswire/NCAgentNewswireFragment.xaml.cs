namespace Content.Client._NC.Agent.Shards.Newswire;

[GenerateTypedNameReferences]
public sealed partial class NCAgentNewswireFragment : BoxContainer
{
    private static readonly Animation ArticleAnimation = new()
    {
        Length = TimeSpan.FromSeconds(0.24),
        AnimationTracks =
        {
            new AnimationTrackControlProperty
            {
                Property = nameof(Modulate),
                InterpolationMode = AnimationInterpolationMode.Linear,
                KeyFrames =
                {
                    new AnimationTrackProperty.KeyFrame(Color.FromHex("#E05CFF44"), 0f),
                    new AnimationTrackProperty.KeyFrame(Color.White, 0.24f),
                },
            },
        },
    };

    public event Action<NewsReaderUiAction>? ActionRequested;

    public NCAgentNewswireFragment()
    {
        RobustXamlLoader.Load(this);
        PreviousButton.OnPressed += _ => ActionRequested?.Invoke(NewsReaderUiAction.Prev);
        NextButton.OnPressed += _ => ActionRequested?.Invoke(NewsReaderUiAction.Next);
        NotificationsButton.OnPressed += _ => ActionRequested?.Invoke(NewsReaderUiAction.NotificationSwitch);
    }

    public void UpdateArticle(NewsArticle article, int target, int total, bool notifications)
    {
        ArticleIndex.Text = $"{target} / {total}";
        ArticleTitle.Text = article.Title.ToUpperInvariant();
        ArticleAuthor.Text = $"AUTHOR // {(article.Author ?? "UNKNOWN")}";
        ArticleTime.Text = article.ShareTime.ToString(@"hh\:mm\:ss");
        ArticleBody.SetMessage(
            FormattedMessage.FromMarkupPermissive(article.Content),
            UserFormattableTags.BaseAllowedTags);
        FeedStatus.Text = "LIVE FEED // ARTICLE RECEIVED";
        FeedStatus.FontColorOverride = Color.FromHex("#76FF95");
        PreviousButton.Disabled = target <= 1;
        NextButton.Disabled = target >= total;
        UpdateNotifications(notifications);
        ArticleBody.StopAnimation("nc-agent-newswire-article");
        ArticleBody.PlayAnimation(ArticleAnimation, "nc-agent-newswire-article");
    }

    public void UpdateEmpty(bool notifications)
    {
        ArticleIndex.Text = "0 / 0";
        ArticleTitle.Text = "NO PUBLICATIONS";
        ArticleAuthor.Text = "AUTHOR // --";
        ArticleTime.Text = "--:--:--";
        ArticleBody.SetMessage(FormattedMessage.FromUnformatted("The public CityNet feed is currently silent."));
        FeedStatus.Text = "FEED ONLINE // NO ARTICLES";
        FeedStatus.FontColorOverride = Color.FromHex("#FFD66B");
        PreviousButton.Disabled = true;
        NextButton.Disabled = true;
        UpdateNotifications(notifications);
    }

    private void UpdateNotifications(bool enabled)
    {
        NotificationsButton.Text = enabled ? "ALERTS ON" : "ALERTS OFF";
        NotificationsButton.Label.FontColorOverride = enabled
            ? Color.FromHex("#76FF95")
            : Color.FromHex("#6C918E");
    }
}
