using System.Linq;
using Content.Shared.CartridgeLoader.Cartridges;
using Robust.Client.Animations;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Animations;

namespace Content.Client._NC.Agent.Shards.Scanner;

/// <summary>
/// Animated local history for network devices scanned through the Agent interaction relay.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class NCAgentScannerFragment : BoxContainer
{
    private static readonly Animation ScanAnimation = new()
    {
        Length = TimeSpan.FromSeconds(0.48),
        AnimationTracks =
        {
            new AnimationTrackControlProperty
            {
                Property = nameof(Modulate),
                InterpolationMode = AnimationInterpolationMode.Linear,
                KeyFrames =
                {
                    new AnimationTrackProperty.KeyFrame(Color.White, 0f),
                    new AnimationTrackProperty.KeyFrame(Color.FromHex("#508DFF66"), 0.14f),
                    new AnimationTrackProperty.KeyFrame(Color.FromHex("#76FF95AA"), 0.28f),
                    new AnimationTrackProperty.KeyFrame(Color.White, 0.48f),
                },
            },
        },
    };

    private int _previousCount;

    public NCAgentScannerFragment()
    {
        RobustXamlLoader.Load(this);
        UpdateState([]);
    }

    public void UpdateState(List<ProbedNetworkDevice> devices)
    {
        var gainedResult = devices.Count > _previousCount;
        _previousCount = devices.Count;
        ResultCount.Text = $"{devices.Count} / 9";
        ScannerStatus.Text = gainedResult
            ? "TARGET ACQUIRED // ADDRESS STORED"
            : "ARMED // USE AGENT ON A NETWORK DEVICE";
        ScannerStatus.FontColorOverride = gainedResult
            ? Color.FromHex("#76FF95")
            : Color.FromHex("#8FB8FF");

        ResultsContainer.RemoveAllChildren();
        foreach (var device in devices.AsEnumerable().Reverse())
            ResultsContainer.AddChild(CreateResult(device));

        if (devices.Count == 0)
        {
            ResultsContainer.AddChild(new Label
            {
                Text = "NO CAPTURED DEVICES",
                FontColorOverride = Color.FromHex("#426D69"),
                HorizontalAlignment = HAlignment.Center,
                Margin = new Thickness(0, 18),
            });
        }

        if (gainedResult)
        {
            ScanPulse.StopAnimation("nc-agent-scanner-result");
            ScanPulse.PlayAnimation(ScanAnimation, "nc-agent-scanner-result");
        }
    }

    private static Control CreateResult(ProbedNetworkDevice device)
    {
        var content = new BoxContainer
        {
            Orientation = LayoutOrientation.Vertical,
            HorizontalExpand = true,
            Margin = new Thickness(10, 7),
        };
        content.AddChild(new Label { Text = device.Name.ToUpperInvariant(), FontColorOverride = Color.FromHex("#D7FFFB") });
        content.AddChild(new Label { Text = $"ADDRESS // {device.Address}", FontColorOverride = Color.FromHex("#8FB8FF") });
        content.AddChild(new Label { Text = $"NETWORK // {device.NetId}", FontColorOverride = Color.FromHex("#5FA39E") });
        content.AddChild(new Label { Text = $"FREQUENCY // {device.Frequency}", FontColorOverride = Color.FromHex("#5B718E") });

        return new PanelContainer
        {
            HorizontalExpand = true,
            Margin = new Thickness(0, 0, 0, 5),
            PanelOverride = new StyleBoxFlat
            {
                BackgroundColor = Color.FromHex("#0C1722"),
                BorderColor = Color.FromHex("#355D9A"),
                BorderThickness = new Thickness(1, 1, 1, 2),
            },
            Children = { content },
        };
    }
}
