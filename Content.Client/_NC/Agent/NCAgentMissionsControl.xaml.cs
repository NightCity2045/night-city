using Content.Shared._NC.Agent.UI;
using Content.Shared._NC.Missions.Prototypes;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Timing;

namespace Content.Client._NC.Agent;

[GenerateTypedNameReferences]
public sealed partial class NCAgentMissionsControl : BoxContainer
{
    [Dependency] private IPrototypeManager _prototypes = default!;
    [Dependency] private IGameTiming _timing = default!;
    private readonly List<NCAgentMissionEntry> _entries = [];
    private NCAgentMissionEntry? _selected;
    private TimeSpan _receivedAt;
    private double _warningSeconds;
    public event Action? OnRefresh;
    public event Action<string>? OnSelect;
    public event Action<string>? OnStart;
    public event Action<Guid>? OnFinish;

    public NCAgentMissionsControl()
    {
        IoCManager.InjectDependencies(this);
        RobustXamlLoader.Load(this);
        WarningLabel.SetMessage(Loc.GetString("nc-mission-console-evacuation-warning"));
        RefreshButton.OnPressed += _ => OnRefresh?.Invoke();
        MissionList.OnItemSelected += args => SelectMission(args.ItemIndex);
        StartButton.OnPressed += _ =>
        {
            if (_selected is not { CanStart: true } selected)
                return;
            StartButton.Disabled = true;
            OnStart?.Invoke(selected.DefinitionId);
        };
        FinishButton.OnPressed += _ =>
        {
            if (_selected is not { CanFinish: true, RunId: { } run })
                return;
            FinishButton.Disabled = true;
            OnFinish?.Invoke(run);
        };
    }

    public void SetData(NCAgentMissionsUpdateMessage? data, string? selectedId, TimeSpan receivedAt)
    {
        _receivedAt = receivedAt;
        MissionList.Clear();
        _entries.Clear();
        _selected = null;
        StartButton.Disabled = true;
        FinishButton.Visible = false;
        if (data == null)
        {
            NoticeLabel.SetMessage(Loc.GetString("nc-agent-missions-loading"));
            return;
        }
        NoticeLabel.SetMessage(string.IsNullOrEmpty(data.Notice)
            ? Loc.GetString("nc-agent-missions-public") : Loc.GetString(data.Notice));
        foreach (var entry in data.Entries)
        {
            if (!_prototypes.TryIndex<NCMissionDefinitionPrototype>(entry.DefinitionId, out var definition))
                continue;
            _entries.Add(entry);
            MissionList.AddItem($"{DifficultyName(definition)} — {Loc.GetString(definition.Name ?? "nc-agent-missions-unavailable")}");
        }
        if (_entries.Count == 0)
        {
            DetailsLabel.SetMessage(Loc.GetString("nc-agent-missions-empty"));
            return;
        }
        var index = Math.Max(0, _entries.FindIndex(value => value.DefinitionId == selectedId));
        MissionList[index].Selected = true;
        SelectMission(index);
    }

    private void SelectMission(int index)
    {
        if (index < 0 || index >= _entries.Count)
            return;
        var entry = _entries[index];
        var definition = _prototypes.Index<NCMissionDefinitionPrototype>(entry.DefinitionId);
        _selected = entry;
        _warningSeconds = definition.EvacuationTime.TotalSeconds;
        OnSelect?.Invoke(entry.DefinitionId);
        DetailsLabel.SetMessage(Loc.GetString("nc-agent-missions-details",
            ("name", Loc.GetString(definition.Name ?? "nc-agent-missions-unavailable")), ("difficulty", DifficultyName(definition)),
            ("players", definition.RecommendedPlayers), ("minutes", (int) definition.RunDuration.TotalMinutes),
            ("location", string.IsNullOrEmpty(entry.Location) ? Loc.GetString("nc-agent-missions-location-unknown") : entry.Location),
            ("description", Loc.GetString(definition.Description ?? "nc-agent-missions-unavailable")),
            ("reward", Loc.GetString(definition.RewardDescription ?? "nc-agent-missions-unavailable"))));
        AvailabilityLabel.SetMessage(entry.State is { } state
            ? Loc.GetString($"nc-mission-console-state-{state.ToString().ToLowerInvariant()}")
            : string.IsNullOrEmpty(entry.UnavailableReason) ? string.Empty : Loc.GetString(entry.UnavailableReason));
        StartButton.Disabled = !entry.CanStart;
        FinishButton.Visible = entry.CanFinish;
        FinishButton.Disabled = !entry.CanFinish;
        UpdateTimer();
    }

    private string DifficultyName(NCMissionDefinitionPrototype definition) =>
        definition.Difficulty is { } id && _prototypes.TryIndex(id, out var difficulty)
            ? Loc.GetString(difficulty.Name) : Loc.GetString("nc-agent-missions-unavailable");

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        UpdateTimer();
    }

    private void UpdateTimer()
    {
        // Countdown is presentation only. The server owns expiry and never trusts this clock.
        TimerLabel.Visible = _selected?.RemainingSeconds != null;
        WarningLabel.Visible = false;
        if (_selected?.RemainingSeconds is not { } remaining)
            return;
        var seconds = Math.Max(0, remaining - (int) (_timing.RealTime - _receivedAt).TotalSeconds);
        WarningLabel.Visible = seconds <= _warningSeconds;
        TimerLabel.Text = Loc.GetString("nc-mission-console-time-value", ("time", $"{seconds / 60}:{seconds % 60:00}"));
    }
}
