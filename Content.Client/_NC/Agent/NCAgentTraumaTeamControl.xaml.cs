using System.Linq;
using Content.Shared._NC.Agent.TraumaTeam;
using Content.Shared._NC.Agent.Shards.TraumaResponse;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Utility;

namespace Content.Client._NC.Agent;

[GenerateTypedNameReferences]
public sealed partial class NCAgentTraumaTeamControl : BoxContainer
{
    public event Action<BoundUserInterfaceMessage>? OnRequest;
    private NCAgentTraumaTeamUpdateMessage? _data;
    private NCAgentTraumaTeamPlanSummary? _selectedPlan;
    private bool _coverage;
    private Guid _commandId = Guid.NewGuid();
    private NCTraumaResponseUrgency _urgency = NCTraumaResponseUrgency.Wounded;

    public NCAgentTraumaTeamControl()
    {
        RobustXamlLoader.Load(this);
        NCAgentAppTheme.Apply(this);
        CareerButton.OnPressed += _ => { _coverage = false; Render(); };
        CoverageButton.OnPressed += _ => { _coverage = true; Render(); };
        RefreshButton.OnPressed += _ => OnRequest?.Invoke(new NCAgentTraumaTeamRefreshMessage());
        DaysEdit.OnTextChanged += _ => _commandId = Guid.NewGuid();
        PurchaseButton.OnPressed += _ => Purchase();
        WoundedButton.OnPressed += _ => SelectUrgency(NCTraumaResponseUrgency.Wounded);
        CriticalButton.OnPressed += _ => SelectUrgency(NCTraumaResponseUrgency.Critical);
        UnderFireButton.OnPressed += _ => SelectUrgency(NCTraumaResponseUrgency.UnderFire);
        RequestResponseButton.OnPressed += _ =>
            OnRequest?.Invoke(new NCAgentTraumaTeamRequestResponseMessage(_urgency, ResponseDescription.Text));
        CancelResponseButton.OnPressed += _ =>
        {
            if (_data?.ResponseCall is { } call)
                OnRequest?.Invoke(new NCAgentTraumaTeamCancelResponseMessage(call.Id, call.Version));
        };
        SelectUrgency(_urgency);
    }

    public void SetData(NCAgentTraumaTeamUpdateMessage data)
    {
        _data = data;
        _selectedPlan = data.Plans.FirstOrDefault(value => value.PlanId == _selectedPlan?.PlanId)
            ?? data.Plans.FirstOrDefault();
        PurchaseButton.Disabled = false;
        Render();
    }

    private void Render()
    {
        Entries.RemoveAllChildren();
        PurchaseBar.Visible = _coverage;
        ResponseBar.Visible = _coverage;
        CareerButton.Disabled = !_coverage;
        CoverageButton.Disabled = _coverage;
        if (_data == null)
            return;

        StatusLabel.SetMessage(Loc.GetString(string.IsNullOrEmpty(_data.Notice)
            ? "nc-trauma-team-ready" : _data.Notice));
        if (!_coverage)
        {
            foreach (var job in _data.Jobs)
            {
                var status = _data.CurrentJobId == job.JobId
                    ? Loc.GetString("nc-trauma-team-current-job")
                    : Loc.GetString("nc-trauma-team-job-capacity", ("occupied", job.Occupied), ("limit", job.Limit),
                        ("salary", job.Salary));
                var entry = NCAgentAppTheme.CreateEntry(job.Name, $"{job.Description}\n{status}");
                entry.Disabled = _data.CurrentJobId != null || !job.Available;
                entry.OnPressed += _ => OnRequest?.Invoke(new NCAgentTraumaTeamHireMessage(job.JobId));
                Entries.AddChild(entry);
            }
            return;
        }

        Entries.AddChild(NCAgentAppTheme.CreateEntry(Loc.GetString("nc-trauma-team-balance"), _data.Balance.ToString()));
        if (_data.ResponseCall is { } response)
        {
            Entries.AddChild(NCAgentAppTheme.CreateEntry(Loc.GetString("nc-trauma-team-response-active"),
                Loc.GetString("nc-trauma-team-response-active-details", ("status", ResponseStatus(response.Status)),
                    ("zone", response.Zone), ("lead", string.IsNullOrEmpty(response.LeadName)
                        ? Loc.GetString("nc-trauma-team-response-unassigned") : response.LeadName))));
            RequestResponseButton.Visible = false;
            ResponseDescription.Visible = false;
            WoundedButton.Visible = CriticalButton.Visible = UnderFireButton.Visible = false;
            CancelResponseButton.Visible = true;
        }
        else
        {
            RequestResponseButton.Visible = true;
            ResponseDescription.Visible = true;
            WoundedButton.Visible = CriticalButton.Visible = UnderFireButton.Visible = true;
            CancelResponseButton.Visible = false;
        }
        if (_data.ActivePlanId != null)
        {
            Entries.AddChild(NCAgentAppTheme.CreateEntry(Loc.GetString("nc-trauma-team-active-plan"),
                Loc.GetString("nc-trauma-team-active-plan-details", ("plan", _data.ActivePlanId),
                    ("hours", (long) Math.Ceiling(_data.RemainingSeconds / 3600.0)))));
        }
        foreach (var plan in _data.Plans)
        {
            var status = Loc.GetString("nc-trauma-team-plan-details", ("price", plan.PricePerDay),
                ("coverage", plan.TreatmentCoverageBasisPoints / 100), ("threat", plan.MaximumThreatBasisPoints / 100),
                ("priority", plan.DispatchPriority));
            var entry = NCAgentAppTheme.CreateEntry(plan.Name, $"{plan.Description}\n{status}");
            entry.OnPressed += _ => { _selectedPlan = plan; Render(); };
            entry.Modulate = plan.PlanId == _selectedPlan?.PlanId ? Color.White : Color.FromHex("#A0A0A0");
            Entries.AddChild(entry);
        }
    }

    private void SelectUrgency(NCTraumaResponseUrgency urgency)
    {
        _urgency = urgency;
        WoundedButton.Disabled = urgency == NCTraumaResponseUrgency.Wounded;
        CriticalButton.Disabled = urgency == NCTraumaResponseUrgency.Critical;
        UnderFireButton.Disabled = urgency == NCTraumaResponseUrgency.UnderFire;
    }

    private static string ResponseStatus(NCTraumaResponseCallStatus status) =>
        Loc.GetString($"nc-trauma-response-status-{status.ToString().ToLowerInvariant()}");

    private void Purchase()
    {
        if (_data == null || _selectedPlan == null || !int.TryParse(DaysEdit.Text, out var days) ||
            days < _data.MinimumDays || days > _data.MaximumDays)
        {
            StatusLabel.SetMessage(Loc.GetString("nc-trauma-team-days-invalid"));
            return;
        }
        PurchaseButton.Disabled = true;
        OnRequest?.Invoke(new NCAgentTraumaTeamPurchaseMessage(_commandId, _selectedPlan.PlanId, days));
    }
}
