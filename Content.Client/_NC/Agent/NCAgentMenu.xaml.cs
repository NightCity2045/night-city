    private void RenderAgentApp(NCAgentApp app)
    {
        if (_agentData is not { } data)
            return;

        BuiltInContent.RemoveAllChildren();
        BuiltInTitle.Text = AppTitle(app);

        if (!string.IsNullOrWhiteSpace(data.Notice))
            BuiltInContent.AddChild(CreateStatusLabel(data.Notice, "#FFD66B"));

        switch (app)
        {
            case NCAgentApp.Contacts:
                BuildContacts(data);
                break;
            case NCAgentApp.Messages:
                BuildMessages(data);
                break;
            case NCAgentApp.Calls:
                BuildCalls(data);
                break;
            case NCAgentApp.CitiNet:
                BuildCitiNet(data);
                break;
            case NCAgentApp.Map:
                BuildMap();
                break;
            default:
                BuiltInContent.AddChild(CreateStatusLabel("SELECT AN APPLICATION", "#77FFF2"));
                break;
        }
    }

    private void BuildContacts(NCAgentUpdateMessage data)
    {
        BuiltInContent.AddChild(CreateStatusLabel($"YOUR ADDRESS // {data.OwnAddress}", "#77FFF2"));

        var search = new LineEdit
        {
            PlaceHolder = "handle or Agent address",
            HorizontalExpand = true,
        };
        var searchButton = CreateActionButton("SEARCH", "#2DA69C");
        searchButton.OnPressed += _ => OnDirectorySearch?.Invoke(search.Text);
        var searchRow = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal };
        searchRow.AddChild(search);
        searchRow.AddChild(searchButton);
        BuiltInContent.AddChild(searchRow);

        BuiltInContent.AddChild(CreateSectionTitle("DIRECTORY"));
        if (data.Directory.Count == 0)
            BuiltInContent.AddChild(CreateMutedLabel("Search CitiNet to find another registered Agent."));

        foreach (var entry in data.Directory)
        {
            var button = CreateActionButton(entry.IsContact ? "SAVED" : "ADD", "#2DA69C");
            button.Disabled = entry.IsContact;
            button.OnPressed += _ => OnAddContact?.Invoke(entry.CharacterId);
            BuiltInContent.AddChild(CreatePersonRow(entry.Alias, entry.Address, button));
        }

        BuiltInContent.AddChild(CreateSectionTitle("CONTACTS"));
        if (data.Contacts.Count == 0)
            BuiltInContent.AddChild(CreateMutedLabel("No saved contacts."));

        foreach (var contact in data.Contacts)
        {
            var message = CreateActionButton("MESSAGE", "#508DFF");
            message.OnPressed += _ => OnSelectConversation?.Invoke(contact.CharacterId);
            var call = CreateActionButton("CALL", "#F0C75E");
            call.OnPressed += _ => OnStartCall?.Invoke(contact.CharacterId);
            var remove = CreateActionButton("REMOVE", "#A64A61");
            remove.OnPressed += _ => OnRemoveContact?.Invoke(contact.CharacterId);
            BuiltInContent.AddChild(CreatePersonRow(contact.Alias, contact.Address, message, call, remove));
        }
    }

    private void BuildMessages(NCAgentUpdateMessage data)
    {
        var conversationPeers = data.Contacts
            .Concat(data.Conversations)
            .GroupBy(value => value.CharacterId)
            .Select(group => group.First())
            .OrderBy(value => value.Alias)
            .ToList();

        var contactRow = new WrapContainer
        {
            LayoutAxis = Axis.Horizontal,
            HorizontalExpand = true,
            SeparationOverride = 2,
            CrossSeparationOverride = 2,
        };
        foreach (var contact in conversationPeers)
        {
            var button = CreateActionButton(contact.Alias, data.SelectedCharacterId == contact.CharacterId ? "#77FFF2" : "#406E6B");
            button.OnPressed += _ => OnSelectConversation?.Invoke(contact.CharacterId);
            contactRow.AddChild(button);
        }
        BuiltInContent.AddChild(contactRow);

        if (data.SelectedCharacterId is not { } selected)
        {
            BuiltInContent.AddChild(CreateMutedLabel("Select a contact or incoming conversation."));
            return;
        }

        var selectedContact = conversationPeers.FirstOrDefault(value => value.CharacterId == selected);
        BuiltInContent.AddChild(CreateSectionTitle(selectedContact == null
            ? "CONVERSATION"
            : $"{selectedContact.Alias} // {selectedContact.Address}"));

        var messageList = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            HorizontalExpand = true,
        };
        foreach (var message in data.Messages)
            messageList.AddChild(CreateMessageCard(message));

        var scroll = new ScrollContainer
        {
            HorizontalExpand = true,
            VerticalExpand = true,
        };
        scroll.AddChild(messageList);
        BuiltInContent.AddChild(scroll);

        var input = new LineEdit
        {
            PlaceHolder = "encrypted message",
            HorizontalExpand = true,
        };
        var send = CreateActionButton("SEND", "#508DFF");
        send.OnPressed += _ => OnSendDirectMessage?.Invoke(selected, input.Text);
        var compose = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal };
        compose.AddChild(input);
        compose.AddChild(send);
        BuiltInContent.AddChild(compose);
    }

    private void BuildCalls(NCAgentUpdateMessage data)
    {
        var call = data.Call;
        switch (call.State)
        {
            case NCAgentCallState.Incoming:
            {
                BuiltInContent.AddChild(CreateStatusLabel(
                    $"INCOMING // {call.RemoteAlias} // {call.RemoteAddress}", "#FFE28D"));
                var accept = CreateActionButton("ACCEPT", "#69E890");
                accept.OnPressed += _ => OnAnswerCall?.Invoke(true);
                var reject = CreateActionButton("REJECT", "#FF7897");
                reject.OnPressed += _ => OnAnswerCall?.Invoke(false);
                var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal };
                row.AddChild(accept);
                row.AddChild(reject);
                BuiltInContent.AddChild(row);
                return;
            }
            case NCAgentCallState.Outgoing:
                BuiltInContent.AddChild(CreateStatusLabel(
                    $"CALLING // {call.RemoteAlias} // {call.RemoteAddress}", "#FFE28D"));
                AddEndCallButton();
                return;
            case NCAgentCallState.Connected:
                BuiltInContent.AddChild(CreateStatusLabel(
                    $"CONNECTED // {call.RemoteAlias} // {call.RemoteAddress}", "#76FF95"));
                BuiltInContent.AddChild(CreateMutedLabel(
                    "Speak in ordinary IC chat. The remote party hears the message while both Agents remain in hand, ID slot, or belt slot."));
                AddEndCallButton();
                return;
        }

        BuiltInContent.AddChild(CreateMutedLabel("Select a contact to start a voice-text call."));
        foreach (var contact in data.Contacts)
        {
            var button = CreateActionButton("CALL", "#F0C75E");
            button.OnPressed += _ => OnStartCall?.Invoke(contact.CharacterId);
            BuiltInContent.AddChild(CreatePersonRow(contact.Alias, contact.Address, button));
        }
    }

    private void AddEndCallButton()
    {
        var end = CreateActionButton("END CALL", "#FF7897");
        end.OnPressed += _ => OnEndCall?.Invoke();
        BuiltInContent.AddChild(end);
    }

