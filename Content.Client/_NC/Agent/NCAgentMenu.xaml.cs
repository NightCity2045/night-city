    private void RenderAgentApp(NCAgentApp app)
    {
        if (_agentData is not { } data)
            return;

        BuiltInContent.RemoveAllChildren();
        BuiltInTitle.Text = AppTitle(app);

        if (!string.IsNullOrWhiteSpace(data.Notice))
            BuiltInContent.AddChild(CreateStatusLabel(data.Notice, "#FFD66B"));

        switch (app)
        {
            case NCAgentApp.Contacts:
                BuildContacts(data);
                break;
            case NCAgentApp.Messages:
                BuildMessages(data);
                break;
            case NCAgentApp.Calls:
                BuildCalls(data);
                break;
            case NCAgentApp.CitiNet:
                BuildCitiNet(data);
                break;
            case NCAgentApp.Map:
                BuildMap();
                break;
            case NCAgentApp.City:
                BuildCity();
                break;
            case NCAgentApp.Missions:
                BuildMissions();
                break;
            case NCAgentApp.Contracts:
                BuildContracts();
                break;
            default:
                BuiltInContent.AddChild(CreateStatusLabel("SELECT AN APPLICATION", "#77FFF2"));
                break;
        }
    }

    private void BuildCity()
    {
        if (_cityData == null)
        {
            BuiltInContent.AddChild(CreateMutedLabel(Loc.GetString("nc-agent-city-loading")));
            return;
        }
        if (!string.IsNullOrWhiteSpace(_cityData.Notice))
            BuiltInContent.AddChild(CreateStatusLabel(CityText(_cityData.Notice), "#FFD66B"));
        foreach (var area in Enum.GetValues<NCAgentCityArea>())
        {
            var entries = _cityData.Entries.Where(value => value.Area == area).ToArray();
            if (entries.Length == 0) continue;
            BuiltInContent.AddChild(CreateSectionTitle(Loc.GetString($"nc-agent-city-area-{area.ToString().ToLowerInvariant()}")));
            foreach (var entry in entries)
            {
                var content = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical,
                    HorizontalExpand = true, Margin = new Thickness(8, 6) };
                content.AddChild(CreateStatusLabel(CityText(entry.Title, entry.TextArguments), "#D7FFFB"));
                content.AddChild(CreateMutedLabel(CityText(entry.Details, entry.TextArguments)));
                if (entry.Action != NCAgentCityAction.None)
                {
                    var action = CreateActionButton(
                        Loc.GetString($"nc-agent-city-action-{entry.Action.ToString().ToLowerInvariant()}"),
                        "#76FF95");
                    action.OnPressed += _ => OnCityAction?.Invoke(entry.Action, entry.Id, entry.Version);
                    content.AddChild(action);
                }
                BuiltInContent.AddChild(WrapCard(content, "#245C59", "#0C1C22"));
            }
        }
    }

    private static string CityText(string value, IReadOnlyList<string>? arguments = null)
    {
        if (!value.StartsWith("nc-", StringComparison.Ordinal))
            return value;
        if (arguments == null || arguments.Count == 0)
            return Loc.GetString(value);
        var localizationArguments = arguments
            .Select((argument, index) => ($"arg{index}", (object) argument))
            .ToArray();
        return Loc.GetString(value, localizationArguments);
    }

    private void BuildContacts(NCAgentUpdateMessage data)
    {
        BuiltInContent.AddChild(CreateStatusLabel($"YOUR ADDRESS // {data.OwnAddress}", "#77FFF2"));

        var nearbyHeader = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            HorizontalExpand = true,
        };
        nearbyHeader.AddChild(CreateSectionTitle("NEARBY AGENTS"));
        var scan = CreateActionButton("SCAN", "#76FF95");
        scan.OnPressed += _ => OnOpenAgentApp?.Invoke(NCAgentApp.Contacts);
        nearbyHeader.AddChild(scan);
        BuiltInContent.AddChild(nearbyHeader);
        if (data.NearbyUsers.Count == 0)
            BuiltInContent.AddChild(CreateMutedLabel("No Agent users detected nearby."));
        foreach (var nearby in data.NearbyUsers)
        {
            var connected = data.Contacts.Any(value => value.CharacterId == nearby.CharacterId);
            var exchange = CreateActionButton(connected ? "CONNECTED" : "EXCHANGE", "#76FF95");
            exchange.Disabled = connected;
            exchange.OnPressed += _ => OnRequestContactExchange?.Invoke(nearby.CharacterId);
            BuiltInContent.AddChild(CreatePersonRow(nearby.Alias, nearby.Address, exchange));
        }

        var search = new LineEdit
        {
            PlaceHolder = "handle or Agent address",
            HorizontalExpand = true,
        };
        var searchButton = CreateActionButton("SEARCH", "#2DA69C");
        searchButton.OnPressed += _ => OnDirectorySearch?.Invoke(search.Text);
        var searchRow = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal };
        searchRow.AddChild(search);
        searchRow.AddChild(searchButton);
        BuiltInContent.AddChild(searchRow);

        BuiltInContent.AddChild(CreateSectionTitle("DIRECTORY"));
        if (data.Directory.Count == 0)
            BuiltInContent.AddChild(CreateMutedLabel("Search CitiNet to find another registered Agent."));

        foreach (var entry in data.Directory)
        {
            var button = CreateActionButton(entry.IsContact ? "SAVED" : "ADD", "#2DA69C");
            button.Disabled = entry.IsContact;
            button.OnPressed += _ => OnAddContact?.Invoke(entry.CharacterId);
