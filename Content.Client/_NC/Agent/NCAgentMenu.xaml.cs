        ShardsButton.OnPressed += _ => ToProgramList();

        HideAllViews();
        ToHomeScreen();
        AgentScreen.PlayAnimation(ScreenBootAnimation, "nc-agent-screen-boot");
    }

    /// <summary>
    /// Updates the Agent status area without changing the current application.
    /// </summary>
    public void UpdateState(PdaUpdateState state)
    {
        FlashlightButton.IsActive = state.FlashlightEnabled;

        if (state.PdaOwnerInfo.IdOwner != null || state.PdaOwnerInfo.JobTitle != null)
        {
            var idOwner = state.PdaOwnerInfo.IdOwner ?? Loc.GetString("comp-pda-ui-unknown");
            var job = state.PdaOwnerInfo.JobTitle ?? Loc.GetString("comp-pda-ui-unassigned");
            VinCardLabel.Text = $"VIN CARD // {idOwner} // {job}";
        }
        else
        {
            VinCardLabel.Text = "VIN CARD // NOT DETECTED";
        }

        var station = state.StationName ?? Loc.GetString("comp-pda-ui-unknown");
        NetworkLabel.Text = $"NETWORK // {station}";
        EjectVinButton.Disabled = state.PdaOwnerInfo.IdOwner == null && state.PdaOwnerInfo.JobTitle == null;
        EjectPenButton.Disabled = !state.HasPen;
        EjectPaiButton.Disabled = !state.HasPai;
        MusicButton.Visible = state.CanPlayMusic;
        ShowUplinkButton.Visible = state.HasUplink;
        LockUplinkButton.Visible = state.HasUplink;
    }

    /// <summary>
    /// Applies a per-user Agent service update without disturbing an open vanilla cartridge UI.
    /// </summary>
    public void UpdateAgentData(NCAgentUpdateMessage update)
    {
        var incomingCallStarted = update.Call.State == NCAgentCallState.Incoming &&
                                  _agentData?.Call.State != NCAgentCallState.Incoming;
        _agentData = update;
        OwnerLabel.Text = $"USER // @{update.OwnAlias.ToUpperInvariant()}";

        // Surface an incoming call immediately while preserving any active vanilla cartridge program.
        if (incomingCallStarted && _currentView != ProgramContentView)
        {
            OpenAgentApp(NCAgentApp.Calls, "CALLS");
            return;
        }

        if (_currentView == BuiltInAppView)
            RenderAgentApp(update.ActiveApp);
    }

    /// <summary>
    /// Applies the separate semantic city snapshot without rebuilding unrelated Agent applications.
    /// </summary>
    public void UpdateMapData(NCAgentMapUpdateMessage update)
    {
        _mapData = update;
        if (_currentView == BuiltInAppView && _agentData?.ActiveApp == NCAgentApp.Map)
            RenderAgentApp(NCAgentApp.Map);
    }

