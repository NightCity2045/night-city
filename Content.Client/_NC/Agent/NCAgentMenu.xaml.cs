    private void ChangeView(int view)
    {
        if (view < 0 || view >= ViewContainer.ChildCount)
            return;

        ViewContainer.GetChild(_currentView).Visible = false;
        var next = ViewContainer.GetChild(view);
        next.Visible = true;
        _currentView = view;

        RestartAnimation(next, ViewEnterAnimation, "nc-agent-view-enter");
    }

    /// <summary>
    /// RobustToolbox animation keys must be unique while running, so rapid UI updates restart explicitly.
    /// </summary>
    private static void RestartAnimation(Control control, Animation animation, string key)
    {
        control.StopAnimation(key);
        control.PlayAnimation(animation, key);
    }

    private void HideAllViews()
    {
        foreach (var view in ViewContainer.Children)
            view.Visible = false;
    }

    protected override void Draw(DrawingHandleScreen handle)
    {
        base.Draw(handle);

        var stationTime = _gameTiming.CurTime.Subtract(_gameTicker.RoundStartTimeSpan);
        ClockLabel.Text = stationTime.ToString("hh\\:mm\\:ss");

        if (_currentView != LockViewIndex || _lockState?.Locked != true || _pinRetryEnd == TimeSpan.Zero)
            return;

        var remaining = _pinRetryEnd - _gameTiming.CurTime;
        if (remaining > TimeSpan.Zero)
        {
            PinSubtitleLabel.Text = $"SECURITY LOCKOUT // {Math.Ceiling(remaining.TotalSeconds):0}s";
            return;
        }

        _pinRetryEnd = TimeSpan.Zero;
        PinSubtitleLabel.Text = "ENTER PIN TO ACCESS CITYNET";
        SetPinKeypadDisabled(false);
    }

