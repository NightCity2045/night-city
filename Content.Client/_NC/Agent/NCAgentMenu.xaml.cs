    }

    private static Label CreateMutedLabel(string text)
    {
        return CreateStatusLabel(text, "#6C918E");
    }

    /// <summary>
    /// Rebuilds the small cartridge grid only when the loader reports a new program state.
    /// </summary>
    public void UpdateAvailablePrograms(List<(EntityUid, CartridgeComponent)> programs)
    {
        ProgramList.RemoveAllChildren();

        if (programs.Count == 0)
        {
            ProgramList.AddChild(new Label
            {
                Text = Loc.GetString("comp-pda-io-no-programs-available"),
                HorizontalAlignment = HAlignment.Center,
                VerticalAlignment = VAlignment.Center,
                VerticalExpand = true,
            });
            return;
        }

        foreach (var cartridge in programs)
        {
            var item = new PdaProgramItem(cartridge);
            item.OnProgramItemPressed += uid => OnProgramItemPressed?.Invoke(uid);
            item.OnUninstallButtonPressed += uid => OnUninstallButtonPressed?.Invoke(uid);
            item.OnInstallButtonPressed += uid => OnInstallButtonPressed?.Invoke(uid);
            ProgramList.AddChild(item);
        }

        if (programs.Count % 2 != 0)
            ProgramList.AddChild(new Control { HorizontalExpand = true });
    }

    public void ToHomeScreen()
    {
        SetNavigationState(home: true);
        ChangeView(HomeView);
    }

    public void ToProgramView(string title)
    {
        HomeButton.IsCurrent = false;
        ProgramListButton.Visible = false;
        SettingsButton.Visible = false;
        ProgramTitle.LabelText = title.ToUpperInvariant();
        ProgramTitle.Visible = true;
        ProgramTitle.IsCurrent = true;
        ProgramCloseButton.Visible = true;
        ChangeView(ProgramContentView);
    }

    public void HideProgramHeader()
    {
        ProgramTitle.IsCurrent = false;
        ProgramTitle.Visible = false;
        ProgramCloseButton.Visible = false;
        ProgramListButton.Visible = true;
        SettingsButton.Visible = true;
    }

    private void ToProgramList()
    {
        SetNavigationState(programs: true);
        ChangeView(ProgramListView);
    }

    private void ToSettings()
    {
        SetNavigationState(settings: true);
        ChangeView(SettingsView);
    }

    private void OpenAgentApp(NCAgentApp app, string title)
    {
        if (app == NCAgentApp.Map)
            _mapData = null;

        SetNavigationState();
        BuiltInTitle.Text = title;
        BuiltInContent.RemoveAllChildren();
        BuiltInContent.AddChild(CreateStatusLabel("CONNECTING TO CITYNET...", "#77FFF2"));
        ChangeView(BuiltInAppView);
        OnOpenAgentApp?.Invoke(app);
    }

    private static string AppTitle(NCAgentApp app)
    {
        return app switch
        {
            NCAgentApp.Contacts => "CONTACTS",
            NCAgentApp.Messages => "MESSAGES",
            NCAgentApp.Calls => "CALLS",
            NCAgentApp.CitiNet => "CITINET",
            NCAgentApp.Map => "CITY MAP",
            _ => "AGENT",
        };
    }

    private void SetNavigationState(bool home = false, bool programs = false, bool settings = false)
    {
        HideProgramHeader();
        HomeButton.IsCurrent = home;
        ProgramListButton.IsCurrent = programs;
        SettingsButton.IsCurrent = settings;
        ProgramTitle.IsCurrent = false;
    }

    private void ChangeView(int view)
    {
        if (view < 0 || view >= ViewContainer.ChildCount)
            return;

        ViewContainer.GetChild(_currentView).Visible = false;
        var next = ViewContainer.GetChild(view);
        next.Visible = true;
        _currentView = view;

        if (next.HasRunningAnimation("nc-agent-view-enter"))
            next.StopAnimation("nc-agent-view-enter");

        next.PlayAnimation(ViewEnterAnimation, "nc-agent-view-enter");
    }

    private void HideAllViews()
    {
        foreach (var view in ViewContainer.Children)
            view.Visible = false;
    }

    protected override void Draw(DrawingHandleScreen handle)
    {
        base.Draw(handle);

        var stationTime = _gameTiming.CurTime.Subtract(_gameTicker.RoundStartTimeSpan);
        ClockLabel.Text = stationTime.ToString("hh\\:mm\\:ss");
    }
