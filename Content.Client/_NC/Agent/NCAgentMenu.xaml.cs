            OnOpenAgentApp?.Invoke(NCAgentApp.Home);
        };
        ProgramListButton.OnPressed += _ => ToProgramList();
        SettingsButton.OnPressed += _ => ToSettings();
        ProgramTitle.OnPressed += _ => ChangeView(ProgramContentView);
        ProgramCloseButton.OnPressed += _ =>
        {
            HideProgramHeader();
            ToHomeScreen();
        };

        ContactsButton.OnPressed += _ => OpenAgentApp(NCAgentApp.Contacts, "CONTACTS");
        MessagesButton.OnPressed += _ => OpenAgentApp(NCAgentApp.Messages, "MESSAGES");
        CallsButton.OnPressed += _ => OpenAgentApp(NCAgentApp.Calls, "CALLS");
