using Content.Client.UserInterface.Controls;
using Content.Shared._NC.City.ZoneTemplates.Prototypes;
using Content.Shared._NC.Missions;
using Content.Shared._NC.Missions.Prototypes;
using Content.Shared._NC.Missions.UI;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Timing;

namespace Content.Client._NC.Missions;

[GenerateTypedNameReferences]
public sealed partial class NCMissionConsoleWindow : FancyWindow
{
    private readonly IPrototypeManager _prototypes;
    private readonly IGameTiming _timing;
    private bool _hasRun;
    private NCMissionRunState _state;
    private TimeSpan? _expiresAt;
    private TimeSpan? _warningAt;

    public event Action? OnStart;
    public event Action? OnFinish;

    public NCMissionConsoleWindow(IPrototypeManager prototypes, IGameTiming timing)
    {
        RobustXamlLoader.Load(this);
        _prototypes = prototypes;
        _timing = timing;
        StartButton.OnPressed += _ => OnStart?.Invoke();
        FinishButton.OnPressed += _ => OnFinish?.Invoke();
    }

    public void UpdateState(NCMissionConsoleUpdateMessage state)
    {
        _hasRun = state.HasRun;
        _state = state.State;
        _expiresAt = state.RemainingSeconds is { } remaining
            ? _timing.RealTime + TimeSpan.FromSeconds(remaining)
            : null;
        _warningAt = state.WarningInSeconds is { } warning
            ? _timing.RealTime + TimeSpan.FromSeconds(warning)
            : null;

        MissionLabel.Text = MissionName(state.DefinitionId);
        SlotLabel.Text = state.SlotId.ToString();
        StateLabel.Text = Loc.GetString($"nc-mission-console-state-{state.State.ToString().ToLowerInvariant()}");
        StartButton.Visible = !state.HasRun;
        StartButton.Disabled = !state.CanStart;
        FinishButton.Visible = state.HasRun;
        FinishButton.Disabled = !state.CanFinish;
        NoticeLabel.Visible = !string.IsNullOrEmpty(state.Notice);
        NoticeLabel.Text = string.IsNullOrEmpty(state.Notice) ? string.Empty : Loc.GetString(state.Notice);
        UpdateTimer();
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        UpdateTimer();
    }

    private void UpdateTimer()
    {
        if (!_hasRun || _expiresAt == null)
        {
            TimerLabel.Text = Loc.GetString("nc-mission-console-time-inactive");
            EvacuationWarningLabel.Visible = false;
            return;
        }

        if (_state is NCMissionRunState.Closing or NCMissionRunState.Cleaning)
        {
            TimerLabel.Text = Loc.GetString("nc-mission-console-time-closing");
            EvacuationWarningLabel.Visible = true;
            return;
        }

        var now = _timing.RealTime;
        var remaining = Math.Max(0, (long) Math.Ceiling((_expiresAt.Value - now).TotalSeconds));
        TimerLabel.Text = Loc.GetString("nc-mission-console-time-value",
            ("time", $"{remaining / 60}:{remaining % 60:00}"));
        EvacuationWarningLabel.Visible = _warningAt is { } warning && now >= warning;
    }

    private string MissionName(string definitionId)
    {
        if (!_prototypes.TryIndex<NCMissionDefinitionPrototype>(definitionId, out var definition) ||
            !_prototypes.TryIndex(definition.Template, out NCZoneTemplatePrototype? template))
            return definitionId;

        return Loc.GetString(template.Name);
    }
}
