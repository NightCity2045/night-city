using System.Linq;
using Content.Client._NC.Agent;
using Content.Shared._NC.Agent.UI;
using Content.Shared._NC.Missions.Prototypes;
using Content.Shared._NC.Missions.UI;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Utility;
using Robust.Shared.Timing;

namespace Content.Client._NC.Missions;

[GenerateTypedNameReferences]
public sealed partial class NCFixerMissionControl : BoxContainer
{
    [Dependency] private IPrototypeManager _prototypes = default!;
    [Dependency] private IGameTiming _timing = default!;
    private TimeSpan _receivedAt;
    private int _lastTimerSecond = -1;
    public event Action<BoundUserInterfaceMessage>? OnRequest;
    private NCFixerMissionUpdateMessage? _data;
    private NCFixerWorkEntry? _work;
    private NCFixerMissionOffer? _offer;
    private List<NCAgentContactSummary> _contacts = [];

    public NCFixerMissionControl()
    {
        IoCManager.InjectDependencies(this);
        RobustXamlLoader.Load(this);
        NCAgentAppTheme.Apply(this);
        ReputationButton.OnPressed += _ => ReputationPanel.Visible = !ReputationPanel.Visible;
        RefreshButton.OnPressed += _ => OnRequest?.Invoke(new NCFixerMissionRefreshMessage());
        AcceptOfferButton.OnPressed += _ =>
        {
            if (_offer is { } offer) OnRequest?.Invoke(new NCFixerMissionAcceptMessage(offer.Definition));
            AcceptOfferButton.Disabled = true;
        };
        InviteTarget.OnItemSelected += args => InviteTarget.SelectId(args.Id);
        InviteButton.OnPressed += _ => Act(NCFixerWorkAction.Invite, InviteTarget.SelectedId);
        JoinButton.OnPressed += _ => Act(NCFixerWorkAction.Join);
        DeclineButton.OnPressed += _ => Act(NCFixerWorkAction.Decline);
        LaunchButton.OnPressed += _ => Act(NCFixerWorkAction.Launch);
        CancelButton.OnPressed += _ => Act(NCFixerWorkAction.Cancel);
        DeliverButton.OnPressed += _ => Act(NCFixerWorkAction.Deliver);
    }

    public void SetContacts(List<NCAgentContactSummary> contacts) => _contacts = contacts;

    public void SetData(NCFixerMissionUpdateMessage? data, TimeSpan? receivedAt = null)
    {
        var selected = _work?.Id;
        _data = data;
        _receivedAt = receivedAt ?? _timing.RealTime;
        _work = null;
        _offer = null;
        OffersList.RemoveAllChildren(); WorkList.RemoveAllChildren();
        OffersList.Visible = AcceptOfferButton.Visible = data?.AtContact == true;
        AcceptOfferButton.Disabled = true;
        var notice = Loc.GetString(string.IsNullOrEmpty(data?.Notice) ? "nc-fixer-work-help" : data.Notice);
        if (!string.IsNullOrEmpty(data?.ContactStatus)) notice += "\n" + Loc.GetString(data.ContactStatus);
        NoticeLabel.SetMessage(notice);
        var reputationText = new FormattedMessage();
        foreach (var score in data?.Reputation ?? [])
        {
            reputationText.AddText(Loc.GetString("nc-fixer-reputation-details", ("contact", score.ContactName),
                ("executor", score.Executor), ("organizer", score.Organizer), ("trust", score.Trust),
                ("threshold", score.OrganizerThreshold), ("available", score.AvailableTiers), ("total", score.TotalTiers)));
            reputationText.PushNewline();
        }
        ReputationLabel.SetMessage(reputationText);
        EmptyLabel.Visible = data?.Work.Count == 0;
        if (data != null)
        {
            foreach (var offer in data.Offers)
            {
                var button = NCAgentAppTheme.CreateEntry(MissionName(offer.Definition),
                    Loc.GetString(offer.Available ? "nc-fixer-offer-available" : "nc-fixer-offer-locked",
                        ("name", MissionName(offer.Definition)), ("reward", offer.Reward)));
                button.OnPressed += _ =>
                {
                    _offer = offer;
                    _work = null;
                    RefreshWork();
                    AcceptOfferButton.Disabled = !offer.Available;
                    ShowMission(offer.Definition, offer.Reward, location: offer.Location);
                };
                OffersList.AddChild(button);
            }
            foreach (var work in data.Work)
            {
                var button = NCAgentAppTheme.CreateEntry(MissionName(work.Definition), Loc.GetString(StateKey(work.State)));
                button.OnPressed += _ => { _work = work; _offer = null; AcceptOfferButton.Disabled = true; RefreshWork(); };
                WorkList.AddChild(button);
                if (work.Id == selected) _work = work;
            }
        }
        _work ??= data?.Work.FirstOrDefault();
        RefreshWork();
    }

    private void Act(NCFixerWorkAction action, int target = 0)
    {
        if (_work is not { } work) return;
        OnRequest?.Invoke(new NCFixerWorkActionMessage(work.Id, work.Version, action, target));
        InviteButton.Disabled = JoinButton.Disabled = DeclineButton.Disabled = LaunchButton.Disabled = CancelButton.Disabled = DeliverButton.Disabled = true;
    }

    private void RefreshWork()
    {
        _lastTimerSecond = -1;
        InviteRow.Visible = JoinButton.Visible = DeclineButton.Visible = LaunchButton.Visible = CancelButton.Visible = DeliverButton.Visible = false;
        InviteButton.Disabled = JoinButton.Disabled = DeclineButton.Disabled = LaunchButton.Disabled = CancelButton.Disabled = DeliverButton.Disabled = false;
        DetailsLabel.SetMessage(string.Empty);
        TimeLabel.SetMessage(string.Empty);
        if (_work is not { } work || _data == null) return;
        ShowMission(work.Definition, work.Reward, Loc.GetString("nc-fixer-work-details", ("contact", work.ContactName),
            ("crew", work.Crew.Count), ("invites", work.Invited.Count), ("status", Loc.GetString(StateKey(work.State))),
            ("paid", Loc.GetString(work.Paid ? "nc-fixer-paid" : "nc-fixer-unpaid")),
            ("organizer", work.OrganizerName), ("names", string.Join(", ", work.CrewNames))), work.Location);
        var organizer = work.Organizer == _data.Viewer;
        var planning = work.State == NCFixerWorkState.Planning;
        InviteTarget.Clear();
        foreach (var contact in _contacts)
            if (!work.Crew.Contains(contact.CharacterId) && !work.Invited.Contains(contact.CharacterId))
                InviteTarget.AddItem(contact.Alias, contact.CharacterId);
        InviteRow.Visible = organizer && planning && InviteTarget.ItemCount > 0 && !_data.AtContact;
        if (InviteTarget.ItemCount > 0) InviteTarget.Select(0);
        JoinButton.Visible = planning && work.Invited.Contains(_data.Viewer);
        DeclineButton.Visible = planning && !organizer && (work.Invited.Contains(_data.Viewer) || work.Crew.Contains(_data.Viewer));
        LaunchButton.Visible = organizer && work.State is NCFixerWorkState.Planning or NCFixerWorkState.Deploying;
        CancelButton.Visible = organizer && !work.Surrendered && work.State is not (NCFixerWorkState.Completed or NCFixerWorkState.Cancelled);
        DeliverButton.Visible = organizer && _data.AtContact && work.State is NCFixerWorkState.Active or NCFixerWorkState.Completed;
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        if (_work is not { } work || work.State is NCFixerWorkState.Completed or NCFixerWorkState.Cancelled or NCFixerWorkState.Failed) return;
        var elapsed = (int) (_timing.RealTime - _receivedAt).TotalSeconds;
        if (_lastTimerSecond == elapsed) return;
        _lastTimerSecond = elapsed;
        var delivery = Math.Max(0, work.DeliverySecondsRemaining - elapsed);
        var text = Loc.GetString("nc-fixer-delivery-time", ("minutes", (int) Math.Ceiling(delivery / 60.0)));
        if (work.SecondsRemaining is { } remaining)
        {
            var seconds = Math.Max(0, remaining - elapsed);
            text += "\n" + Loc.GetString("nc-fixer-zone-time", ("time", $"{seconds / 60}:{seconds % 60:00}"));
            if (_prototypes.TryIndex<NCMissionDefinitionPrototype>(work.Definition, out var definition) && seconds <= definition.EvacuationTime.TotalSeconds)
                text += "\n" + Loc.GetString("nc-fixer-evacuate");
        }
        TimeLabel.SetMessage(text);
    }

    private void ShowMission(string id, int reward, string details = "", string location = "")
    {
        var text = new FormattedMessage();
        if (_prototypes.TryIndex<NCMissionDefinitionPrototype>(id, out var definition))
        {
            var difficulty = definition.Difficulty is { } tier && _prototypes.TryIndex(tier, out var level)
                ? Loc.GetString(level.Name) : Loc.GetString("nc-agent-missions-unavailable");
            text.AddText(Loc.GetString("nc-agent-missions-details", ("name", MissionName(id)),
                ("difficulty", difficulty), ("players", definition.RecommendedPlayers),
                ("minutes", (int) definition.RunDuration.TotalMinutes),
                ("location", string.IsNullOrEmpty(location) ? Loc.GetString("nc-agent-missions-location-unknown") : location),
                ("description", Loc.GetString(definition.Description ?? "nc-agent-missions-unavailable")),
                ("reward", Loc.GetString("nc-fixer-reward", ("reward", reward)))));
            text.PushNewline();
        }
        text.AddText(details);
        DetailsLabel.SetMessage(text);
    }
    private string MissionName(string id) => _prototypes.TryIndex<NCMissionDefinitionPrototype>(id, out var definition) && definition.Name is { } name
        ? Loc.GetString(name) : Loc.GetString("nc-fixer-unknown-mission");
    private static string StateKey(NCFixerWorkState state) => state switch
    {
        NCFixerWorkState.Planning => "nc-fixer-state-planning",
        NCFixerWorkState.Deploying => "nc-fixer-state-deploying",
        NCFixerWorkState.Active => "nc-fixer-state-active",
        NCFixerWorkState.Completed => "nc-fixer-state-completed",
        NCFixerWorkState.Cancelled => "nc-fixer-state-cancelled",
        _ => "nc-fixer-state-failed",
    };
}
