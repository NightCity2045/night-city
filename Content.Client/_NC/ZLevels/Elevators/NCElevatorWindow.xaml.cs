using Content.Client.UserInterface.Controls;
using Content.Shared._NC.ZLevels.Elevators;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._NC.ZLevels.Elevators;

[GenerateTypedNameReferences]
public sealed partial class NCElevatorWindow : FancyWindow
{
    public event Action<int>? MoveRequested;

    public NCElevatorWindow()
    {
        RobustXamlLoader.Load(this);
        UpButton.OnPressed += _ => RequestMove(1);
        DownButton.OnPressed += _ => RequestMove(-1);
    }

    private void RequestMove(int offset)
    {
        // Prevent duplicate clicks while the authoritative response is in flight.
        UpButton.Disabled = true;
        DownButton.Disabled = true;
        MoveRequested?.Invoke(offset);
    }

    public void ApplyState(NCElevatorUiState state)
    {
        FloorLabel.Text = state.Depth is { } depth
            ? Loc.GetString("nc-elevator-floor", ("floor", depth))
            : Loc.GetString("nc-elevator-disconnected");
        StatusLabel.Text = state.TargetDepth is { } target
            ? Loc.GetString("nc-elevator-moving", ("floor", target))
            : Loc.GetString("nc-elevator-ready");
        DurationLabel.Text = Loc.GetString("nc-elevator-duration", ("seconds", state.TravelSeconds));
        UpButton.Disabled = !state.CanUp;
        DownButton.Disabled = !state.CanDown;
        FeedbackLabel.Text = state.Feedback is { } feedback ? Loc.GetString(feedback) : string.Empty;
        FeedbackLabel.Visible = state.Feedback != null;
    }
}
