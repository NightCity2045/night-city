using System.Linq;
using Content.Client.UserInterface.Controls;
using Content.Shared._NC.Pawn;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._NC.Pawn;

[GenerateTypedNameReferences]
public sealed partial class NCPawnShopWindow : FancyWindow
{
    public event Action<NetEntity>? OnSell;
    public event Action? OnSellAll;

    private List<NCPawnLine> _shown = new();

    public NCPawnShopWindow()
    {
        RobustXamlLoader.Load(this);
        SellAllButton.OnPressed += _ => OnSellAll?.Invoke();
    }

    public void Update(NCPawnUpdateMessage update)
    {
        Title = update.Shop;
        // Rebuilding every refresh would steal button focus mid-click; only redraw when something changed.
        if (_shown.SequenceEqual(update.Lines))
            return;
        _shown = update.Lines;

        LinesContainer.RemoveAllChildren();
        foreach (var line in update.Lines)
            LinesContainer.AddChild(BuildLine(line));

        var total = update.Lines.Where(line => line.Payout > 0).Sum(line => line.Payout);
        EmptyLabel.Visible = update.Lines.Count == 0;
        TotalLabel.Text = Loc.GetString("nc-pawn-total", ("amount", total));
        SellAllButton.Disabled = total <= 0;
    }

    private Control BuildLine(NCPawnLine line)
    {
        var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 6 };
        var view = new EntityPrototypeView { SetSize = new System.Numerics.Vector2(32, 32) };
        if (line.Prototype.Length > 0)
            view.SetPrototype(line.Prototype);
        row.AddChild(view);

        var text = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, HorizontalExpand = true };
        text.AddChild(new Label
        {
            Text = line.Count > 1 ? Loc.GetString("nc-pawn-line-count", ("name", line.Name), ("count", line.Count)) : line.Name,
            ClipText = true,
        });
        text.AddChild(new Label
        {
            Text = line.Payout > 0 ? Loc.GetString("nc-pawn-offer", ("amount", line.Payout)) : Loc.GetString("nc-pawn-not-buying"),
            FontColorOverride = line.Payout > 0 ? Color.FromHex("#9FE35A") : Color.FromHex("#E3A59F"),
        });
        row.AddChild(text);

        var sell = new Button
        {
            Text = Loc.GetString("nc-pawn-sell"),
            Disabled = line.Payout <= 0,
            VerticalAlignment = VAlignment.Center,
        };
        sell.OnPressed += _ => OnSell?.Invoke(line.Item);
        row.AddChild(sell);
        return row;
    }
}
