using Content.Client.UserInterface.Controls;
using Content.Shared._NC.Cargo.Pawn;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._NC.Cargo.Pawn;

[GenerateTypedNameReferences]
public sealed partial class NCPawnShopWindow : FancyWindow
{
    public event Action? AppraiseRequested;
    public event Action<Guid>? SellRequested;
    private Guid _quoteId;

    public NCPawnShopWindow()
    {
        RobustXamlLoader.Load(this);
        SellButton.Disabled = true;
        SellButton.Text = Loc.GetString("nc-pawn-sell", ("amount", 0));
        AppraiseButton.OnPressed += _ => AppraiseRequested?.Invoke();
        SellButton.OnPressed += _ =>
        {
            SellButton.Disabled = true;
            SellRequested?.Invoke(_quoteId);
        };
    }

    public void UpdateState(NCPawnShopState state)
    {
        _quoteId = state.QuoteId;
        RateLabel.Text = Loc.GetString("nc-pawn-rate", ("percent", state.Percentage));
        TotalLabel.Text = Loc.GetString("nc-pawn-total", ("amount", state.Total));
        NoticeLabel.Text = string.IsNullOrEmpty(state.Notice) ? string.Empty : Loc.GetString(state.Notice);
        SellButton.Text = Loc.GetString("nc-pawn-sell", ("amount", state.Total));
        SellButton.Disabled = !state.CanSell;
        Listings.RemoveAllChildren();
        foreach (var listing in state.Listings)
            Listings.AddChild(new Label { Text = Loc.GetString("nc-pawn-item", ("name", listing.Name), ("amount", listing.Price)), ClipText = true });
    }
}
