using Content.Client.UserInterface.Controls;
using Content.Shared._NC.City.ZoneTemplates.Prototypes;
using Content.Shared._NC.Housing;
using Content.Shared._NC.Housing.UI;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._NC.Housing;

[GenerateTypedNameReferences]
public sealed partial class NCPropertyConsoleWindow : FancyWindow
{
    private readonly IPrototypeManager _prototypes;
    private readonly Dictionary<int, NCPropertyConsoleInteriorOfferSummary> _interiorOffers = [];

    private NCPropertyConsoleListingSummary? _selected;
    private int _pageIndex;
    private int _balance;
    private bool _hasBankAccount;
    private bool _updating;

    public event Action<string>? OnSearch;
    public event Action<int>? OnPage;
    public event Action<string>? OnSelect;
    public event Action<string, string>? OnRent;
    public event Action<string>? OnEndLease;
    public event Action<string>? OnInvokeInterior;

    public NCPropertyConsoleWindow(IPrototypeManager prototypes)
    {
        RobustXamlLoader.Load(this);
        _prototypes = prototypes;

        SearchButton.OnPressed += _ => SubmitSearch();
        SearchEdit.OnTextEntered += _ => SubmitSearch();
        PreviousPageButton.OnPressed += _ => OnPage?.Invoke(Math.Max(0, _pageIndex - 1));
        NextPageButton.OnPressed += _ => OnPage?.Invoke(_pageIndex + 1);
        PropertyList.OnItemSelected += args =>
        {
            if (_updating || PropertyList[args.ItemIndex].Metadata is not string listingId)
                return;
            OnSelect?.Invoke(listingId);
        };
        InteriorSelector.OnItemSelected += args =>
        {
            args.Button.SelectId(args.Id);
            UpdateRentDetails();
            UpdateButtons();
        };
        RentButton.OnPressed += _ =>
        {
            if (_selected is { } selected &&
                _interiorOffers.TryGetValue(InteriorSelector.SelectedId, out var offer))
                OnRent?.Invoke(selected.ListingId, offer.TemplateId);
        };
        EndLeaseButton.OnPressed += _ =>
        {
            if (_selected is { CanEndLease: true } selected)
                OnEndLease?.Invoke(selected.ListingId);
        };
        InvokeInteriorButton.OnPressed += _ =>
        {
            if (_selected is { CanInvokeInterior: true } selected)
                OnInvokeInterior?.Invoke(selected.ListingId);
        };
    }

    public void UpdateState(NCPropertyConsoleUpdateMessage state)
    {
        _updating = true;
        try
        {
            _pageIndex = state.PageIndex;
            _balance = state.Balance;
            _hasBankAccount = state.HasBankAccount;
            BalanceLabel.Text = state.HasBankAccount
                ? Loc.GetString("nc-property-console-credits", ("amount", state.Balance))
                : Loc.GetString("nc-property-console-no-account");
            BalanceLabel.FontColorOverride = state.HasBankAccount ? Color.LightGreen : Color.Orange;
            PageLabel.Text = Loc.GetString("nc-property-console-page",
                ("current", state.PageIndex + 1), ("pages", state.PageCount), ("total", state.TotalCount));
            PreviousPageButton.Disabled = state.PageIndex <= 0;
            NextPageButton.Disabled = state.PageIndex + 1 >= state.PageCount;
            NoticeLabel.Visible = !string.IsNullOrEmpty(state.Notice);
            NoticeLabel.Text = string.IsNullOrEmpty(state.Notice) ? string.Empty : Loc.GetString(state.Notice);

            PropertyList.Clear();
            foreach (var listing in state.Listings)
            {
                var item = PropertyList.AddItem(Loc.GetString("nc-property-console-listing-line",
                    ("building", listing.BuildingName),
                    ("apartment", listing.ApartmentName),
                    ("status", StatusName(listing.Status))), metadata: listing.ListingId);
                if (listing.ListingId == state.SelectedListingId)
                    item.Selected = true;
            }

            EmptyListLabel.Visible = state.Listings.Count == 0;
            _selected = state.Listings.Find(listing => listing.ListingId == state.SelectedListingId);
            UpdateDetails();
        }
        finally
        {
            _updating = false;
        }
    }

    private void UpdateDetails()
    {
        var hasSelection = _selected != null;
        DetailsContainer.Visible = hasSelection;
        SelectPrompt.Visible = !hasSelection;
        if (_selected is not { } selected)
        {
            UpdateButtons();
            return;
        }

        ApartmentNameLabel.Text = selected.ApartmentName;
        BuildingLabel.Text = selected.BuildingName;
        PropertyIdLabel.Text = selected.ApartmentId.ToString();
        StatusLabel.Text = StatusName(selected.Status);
        OccupancyLabel.Text = selected.IsTenant
            ? Loc.GetString("nc-property-console-occupancy-tenant")
            : Loc.GetString("nc-property-console-occupancy-none");
        CurrentInteriorLabel.Text = selected.CurrentInterior is { } current
            ? InteriorName(current)
            : Loc.GetString("nc-property-console-interior-none");
        InteriorStateLabel.Text = selected.InteriorActive
            ? Loc.GetString("nc-property-console-interior-active")
            : selected.CurrentInterior != null
                ? Loc.GetString("nc-property-console-interior-ready")
                : string.Empty;
        InteriorStateLabel.Visible = selected.CurrentInterior != null;

        _interiorOffers.Clear();
        InteriorSelector.Clear();
        var selectorId = 0;
        foreach (var offer in selected.Interiors)
        {
            _interiorOffers[selectorId] = offer;
            InteriorSelector.AddItem(Loc.GetString("nc-property-console-interior-offer",
                ("interior", InteriorName(offer.TemplateId)),
                ("rent", offer.RentAmount)), selectorId);
            selectorId++;
        }

        if (_interiorOffers.Count > 0)
            InteriorSelector.SelectId(0);
        InteriorSelector.Visible = selected.Status == NCPropertyStatus.Available;
        RentButton.Visible = selected.Status == NCPropertyStatus.Available;
        EndLeaseButton.Visible = selected.IsTenant;
        InvokeInteriorButton.Visible = selected.IsTenant && selected.CurrentInterior != null;
        NextRentDueLabel.Visible = selected.IsTenant && selected.NextRentDueUnixSeconds != null;
        NextRentDueLabel.Text = selected.NextRentDueUnixSeconds is { } due
            ? Loc.GetString("nc-property-console-next-rent",
                ("date", DateTimeOffset.FromUnixTimeSeconds(due).LocalDateTime.ToString("g")))
            : string.Empty;
        UpdateRentDetails();
        UpdateButtons();
    }

    private void UpdateButtons()
    {
        var affordable = _interiorOffers.TryGetValue(InteriorSelector.SelectedId, out var offer) &&
                         _hasBankAccount && _balance >= offer.RentAmount;
        RentButton.Disabled = _selected is not { CanRent: true } || !affordable;
        EndLeaseButton.Disabled = _selected is not { CanEndLease: true };
        InteriorSelector.Disabled = _selected?.Status != NCPropertyStatus.Available || _interiorOffers.Count == 0;
        InvokeInteriorButton.Disabled = _selected is not { CanInvokeInterior: true };
    }

    private void UpdateRentDetails()
    {
        if (_selected is not { } selected)
        {
            RentPriceLabel.Text = string.Empty;
            return;
        }

        if (selected.Status == NCPropertyStatus.Available &&
            _interiorOffers.TryGetValue(InteriorSelector.SelectedId, out var offer))
        {
            RentPriceLabel.Text = RentLine(offer.RentAmount, offer.BillingIntervalSeconds, offer.GracePeriodSeconds);
            return;
        }

        RentPriceLabel.Text = selected.IsTenant
            ? RentLine(selected.RentAmount, selected.BillingIntervalSeconds, selected.GracePeriodSeconds)
            : string.Empty;
    }

    private static string RentLine(int rent, long intervalSeconds, long graceSeconds)
    {
        return Loc.GetString("nc-property-console-rent-line",
            ("rent", rent),
            ("hours", Math.Max(1, intervalSeconds / 3600)),
            ("graceHours", Math.Max(0, graceSeconds / 3600)));
    }

    private void SubmitSearch() => OnSearch?.Invoke(SearchEdit.Text.Trim());

    private string InteriorName(string templateId)
    {
        return _prototypes.TryIndex<NCZoneTemplatePrototype>(templateId, out var template)
            ? Loc.GetString(template.Name)
            : templateId;
    }

    private static string StatusName(NCPropertyStatus status) =>
        Loc.GetString($"nc-property-console-status-{status.ToString().ToLowerInvariant()}");
}
