using Content.Client.UserInterface.Controls;
using Content.Shared._NC.Housing;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._NC.Housing;

[GenerateTypedNameReferences]
public sealed partial class NCRealEstateWindow : FancyWindow
{
    public event Action<string, int>? OnRent;
    public event Action<string, int>? OnExtend;
    public event Action<string>? OnCancel;

    private NCRealEstateUiState? _state;

    public NCRealEstateWindow()
    {
        RobustXamlLoader.Load(this);
        MineOnly.OnToggled += _ => Rebuild();
    }

    public void UpdateState(NCRealEstateUiState state)
    {
        _state = state;
        Rebuild();
    }

    private void Rebuild()
    {
        ListingsContainer.RemoveAllChildren();
        if (_state is not { } state)
            return;

        StatusLabel.Visible = !state.Open || !state.HasAccount;
        StatusLabel.Text = Loc.GetString(!state.Open ? "nc-real-estate-closed" : "nc-real-estate-no-account");
        BalanceLabel.Text = Loc.GetString("nc-real-estate-money", ("amount", state.Balance));

        var shown = 0;
        foreach (var listing in state.Properties)
        {
            if (MineOnly.Pressed && listing.Status != NCPropertyStatus.Mine)
                continue;

            ListingsContainer.AddChild(BuildListing(listing, state));
            shown++;
        }

        if (shown == 0)
            ListingsContainer.AddChild(new Label { Text = Loc.GetString("nc-real-estate-empty"), FontColorOverride = Color.Gray });
    }

    private Control BuildListing(NCPropertyListing listing, NCRealEstateUiState state)
    {
        var box = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, SeparationOverride = 3 };
        box.AddChild(new Label { Text = listing.Name, StyleClasses = { "LabelHeading" } });
        box.AddChild(new Label
        {
            Text = Loc.GetString("nc-real-estate-place",
                ("district", Place(listing.District)),
                ("building", Place(listing.Building)),
                ("floor", listing.Floor)),
            FontColorOverride = Color.FromHex("#AAAAAA"),
        });
        box.AddChild(new Label
        {
            Text = Loc.GetString("nc-real-estate-details",
                ("area", listing.Area),
                ("doors", listing.Doors),
                ("rent", listing.RentPerHour)),
        });

        var (statusText, statusColor) = listing.Status switch
        {
            NCPropertyStatus.Mine => (Loc.GetString("nc-real-estate-status-mine", ("time", Format(listing.Remaining))), "#9FE3A5"),
            NCPropertyStatus.Rented => (Loc.GetString("nc-real-estate-status-rented"), "#E3A59F"),
            _ => (Loc.GetString("nc-real-estate-status-vacant"), "#FFB21F"),
        };
        box.AddChild(new Label { Text = statusText, FontColorOverride = Color.FromHex(statusColor) });

        var usable = state.Open && state.HasAccount;
        if (usable && listing.Status != NCPropertyStatus.Rented)
        {
            var terms = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 5 };
            terms.AddChild(new Label
            {
                Text = Loc.GetString(listing.Status == NCPropertyStatus.Mine ? "nc-real-estate-extend" : "nc-real-estate-rent"),
                StyleClasses = { "LabelKeyText" },
            });
            foreach (var hours in state.Terms)
            {
                var cost = (long) listing.RentPerHour * hours;
                var button = new Button
                {
                    Text = Loc.GetString("nc-real-estate-term", ("hours", hours), ("cost", cost)),
                    Disabled = cost > state.Balance,
                };
                var term = hours;
                button.OnPressed += _ =>
                {
                    if (listing.Status == NCPropertyStatus.Mine)
                        OnExtend?.Invoke(listing.Id, term);
                    else
                        OnRent?.Invoke(listing.Id, term);
                };
                terms.AddChild(button);
            }

            box.AddChild(terms);
        }

        if (usable && listing.Status == NCPropertyStatus.Mine)
        {
            var cancel = new Button { Text = Loc.GetString("nc-real-estate-cancel"), HorizontalAlignment = HAlignment.Left };
            cancel.OnPressed += _ => OnCancel?.Invoke(listing.Id);
            box.AddChild(cancel);
        }

        box.AddChild(new PanelContainer { StyleClasses = { "LowDivider" } });
        return box;
    }

    private static string Place(string value)
    {
        return string.IsNullOrWhiteSpace(value) ? Loc.GetString("nc-real-estate-unknown") : value;
    }

    private static string Format(TimeSpan time)
    {
        return $"{(int) time.TotalHours}:{time.Minutes:00}";
    }
}
