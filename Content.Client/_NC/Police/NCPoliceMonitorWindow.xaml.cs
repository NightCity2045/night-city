using Content.Client.UserInterface.Controls;
using Content.Shared._NC.Police.UI;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._NC.Police;

/// <summary>NCPD city monitoring: the city map with a dot for every person the police network sees.</summary>
[GenerateTypedNameReferences]
public sealed partial class NCPoliceMonitorWindow : FancyWindow
{
    public NCPoliceMonitorWindow()
    {
        RobustXamlLoader.Load(this);
        CountLabel.Text = Loc.GetString("nc-police-monitor-count", ("count", 0));
    }

    public void SetSource(EntityUid? gridUid)
    {
        MapControl.SetMapSource(gridUid);
    }

    public void ApplyMap(NCPoliceMonitorMapMessage message)
    {
        StatusLabel.Text = message.Snapshot.Notice;
        StatusLabel.Visible = !string.IsNullOrEmpty(message.Snapshot.Notice);
        MapControl.SetMapData(message.Snapshot);
    }

    public void ApplyContacts(NCPoliceMonitorContactsMessage message)
    {
        CountLabel.Text = Loc.GetString("nc-police-monitor-count", ("count", message.Contacts.Count));
        MapControl.SetContacts(message.Contacts);
        MapControl.SetMarkers(message.Incidents);
    }
}
