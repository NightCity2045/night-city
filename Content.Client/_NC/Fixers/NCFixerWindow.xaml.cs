using Content.Client.UserInterface.Controls;
using Content.Shared._NC.Fixers;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Utility;

namespace Content.Client._NC.Fixers;

[GenerateTypedNameReferences]
public sealed partial class NCFixerWindow : FancyWindow
{
    [Dependency] private IPrototypeManager _prototypes = default!;

    public event Action<int>? OnAccept;
    public event Action? OnAbandon;
    public event Action? OnCollect;

    public NCFixerWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        AbandonButton.OnPressed += _ => OnAbandon?.Invoke();
        CollectButton.OnPressed += _ => OnCollect?.Invoke();
    }

    public void UpdateState(NCFixerUiState state)
    {
        if (!_prototypes.TryIndex(state.Fixer, out var fixer))
            return;

        Title = Loc.GetString(fixer.Name);
        DescriptionLabel.Text = fixer.Description is { } description ? Loc.GetString(description) : string.Empty;
        DescriptionLabel.Visible = fixer.Description != null;
        var greeting = fixer.Greetings.Count > 0
            ? Loc.GetString(fixer.Greetings[Math.Clamp(state.Greeting, 0, fixer.Greetings.Count - 1)])
            : string.Empty;
        GreetingLabel.SetMessage(FormattedMessage.FromUnformatted(greeting));

        var levelName = string.Empty;
        if (_prototypes.TryIndex<NCStreetReputationPrototype>(NCStreetReputationPrototype.DefaultId, out var levels) &&
            state.Level < levels.LevelNames.Count)
        {
            levelName = Loc.GetString(levels.LevelNames[state.Level]);
        }

        ReputationLabel.Text = Loc.GetString("nc-fixer-reputation", ("value", state.Reputation), ("level", levelName));

        UpdateActive(state);
        UpdateOffers(state);
    }

    private void UpdateActive(NCFixerUiState state)
    {
        ActivePanel.Visible = state.Active != null;
        if (state.Active is not { } active || !_prototypes.TryIndex(active.Mission, out var mission))
            return;

        var giver = _prototypes.TryIndex(active.Fixer, out var fixer) ? Loc.GetString(fixer.Name) : string.Empty;
        ActiveNameLabel.Text = Loc.GetString("nc-fixer-active-name", ("mission", Loc.GetString(mission.Name)), ("fixer", giver));
        ActiveStatusLabel.Text = active.Status == NCFixerMissionStatus.AwaitingPayment
            ? Loc.GetString("nc-fixer-status-payment")
            : Loc.GetString("nc-fixer-status-time", ("time", $"{(int) active.TimeLeft.TotalMinutes:00}:{active.TimeLeft.Seconds:00}"));

        ActiveObjectiveLabel.Visible = active.Objective != null;
        ActiveObjectiveLabel.Text = active.Objective is { } objective ? Loc.GetString("nc-fixer-objective", ("place", Place(objective))) : string.Empty;
        ActiveDropLabel.Visible = active.Drop != null;
        ActiveDropLabel.Text = active.Drop is { } drop ? Loc.GetString("nc-fixer-drop", ("place", Place(drop))) : string.Empty;
        ActiveTargetLabel.Visible = active.TargetName != null;
        ActiveTargetLabel.Text = active.TargetName is { } target ? Loc.GetString("nc-fixer-target", ("name", target)) : string.Empty;

        AbandonButton.Visible = state.ActiveHere && active.Status == NCFixerMissionStatus.Active;
        CollectButton.Visible = state.ActiveHere && active.Status == NCFixerMissionStatus.AwaitingPayment;
    }

    private void UpdateOffers(NCFixerUiState state)
    {
        OffersContainer.RemoveAllChildren();
        if (state.Offers.Count == 0)
            OffersContainer.AddChild(new Label { Text = Loc.GetString("nc-fixer-no-offers") });

        foreach (var offer in state.Offers)
        {
            if (_prototypes.TryIndex(offer.Mission, out var mission))
                OffersContainer.AddChild(CreateOffer(offer, mission, state.Active == null));
        }
    }

    private Control CreateOffer(NCFixerOffer offer, NCFixerMissionPrototype mission, bool free)
    {
        var panel = new PanelContainer { StyleClasses = { "AngleRect" } };
        var box = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Vertical, SeparationOverride = 3, Margin = new Thickness(6) };
        panel.AddChild(box);
        box.AddChild(new Label { Text = Loc.GetString(mission.Name), StyleClasses = { "LabelHeading" } });
        box.AddChild(new Label { Text = Loc.GetString(KindName(mission.Kind)), FontColorOverride = Color.FromHex("#FF2A8A") });
        if (mission.Description is { } description)
            box.AddChild(new Label { Text = Loc.GetString(description), FontColorOverride = Color.FromHex("#AAAAAA") });
        if (mission.Owner is { } ownerId && _prototypes.TryIndex(ownerId, out var owner))
            box.AddChild(new Label { Text = Loc.GetString("nc-fixer-offer-owner", ("owner", Loc.GetString(owner.Name))) });

        var row = new BoxContainer { Orientation = BoxContainer.LayoutOrientation.Horizontal, SeparationOverride = 6 };
        row.AddChild(new Label
        {
            Text = Loc.GetString("nc-fixer-offer-terms",
                ("reward", mission.Reward),
                ("minutes", (int) mission.TimeLimit.TotalMinutes)),
            HorizontalExpand = true,
        });
        var accept = new Button
        {
            Text = Loc.GetString(offer.Locked ? "nc-fixer-offer-locked" : "nc-fixer-accept"),
            Disabled = offer.Locked || !free,
        };
        var slot = offer.Slot;
        accept.OnPressed += _ => OnAccept?.Invoke(slot);
        row.AddChild(accept);
        box.AddChild(row);
        return panel;
    }

    private string Place(NCMissionPlace place)
    {
        var owner = place.Owner is { } ownerId && _prototypes.TryIndex(ownerId, out var prototype)
            ? Loc.GetString(prototype.Name)
            : Loc.GetString("nc-fixer-place-unknown");
        return Loc.GetString("nc-fixer-place",
            ("district", place.District ?? Loc.GetString("nc-fixer-place-unknown")),
            ("building", place.Building ?? Loc.GetString("nc-fixer-place-unknown")),
            ("floor", place.Floor),
            ("owner", owner));
    }

    private static string KindName(NCFixerMissionKind kind)
    {
        return kind switch
        {
            NCFixerMissionKind.Delivery => "nc-fixer-kind-delivery",
            NCFixerMissionKind.Retrieval => "nc-fixer-kind-retrieval",
            NCFixerMissionKind.Sabotage => "nc-fixer-kind-sabotage",
            NCFixerMissionKind.Elimination => "nc-fixer-kind-elimination",
            NCFixerMissionKind.Beating => "nc-fixer-kind-beating",
            _ => "nc-fixer-kind-collection",
        };
    }
}
