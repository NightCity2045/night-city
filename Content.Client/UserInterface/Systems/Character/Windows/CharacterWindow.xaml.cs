using Robust.Client.AutoGenerated;
using Content.Client.UserInterface.Controls; // NC
using Content.Shared._NC.Skill; // NC
using Content.Shared.CCVar; // NC
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Configuration; // NC
using Robust.Shared.Utility; // NC

namespace Content.Client.UserInterface.Systems.Character.Windows;

[GenerateTypedNameReferences]
public sealed partial class CharacterWindow : FancyWindow // NC
{
    // NC-Edit-Start
    private readonly IConfigurationManager _config = IoCManager.Resolve<IConfigurationManager>();
    private int _experience = -1;
    private int _learned;

    public event Action? SkillsPressed;
    public event Action? Relocalized;
    // NC-Edit-End

    public CharacterWindow()
    {
        RobustXamlLoader.Load(this);
        SkillsButton.OnPressed += _ => SkillsPressed?.Invoke(); // NC
    }

    // NC-Edit-Start
    protected override void EnteredTree()
    {
        base.EnteredTree();
        _config.OnValueChanged(CCVars.NCClientCulture, Relocalize, invokeImmediately: true);
    }

    protected override void ExitedTree()
    {
        _config.UnsubValueChanged(CCVars.NCClientCulture, Relocalize);
        base.ExitedTree();
    }

    public void SetIdentity(EntityUid entity, string name, string job)
    {
        SpriteView.SetEntity(entity);
        var title = new FormattedMessage();
        title.PushTag(new MarkupNode("head", new MarkupParameter(2), null));
        title.AddText(name);
        title.Pop();
        NameLabel.SetMessage(title, Color.FromHex("#EDF3F3"));
        JobLabel.SetMessage(job, Color.FromHex("#AEBCC4"));
    }

    public void ResetCharacter()
    {
        SpriteView.SetEntity(null);
        NameLabel.Clear();
        JobLabel.Clear();
        RoleType.Visible = false;
        ObjectivesSection.Visible = false;
        EmptyObjectives.Visible = false;
        Objectives.RemoveAllChildren();
        BriefingSection.Visible = false;
        BriefingText.Clear();
        AdditionalSection.Visible = false;
        AdditionalInfo.RemoveAllChildren();
        DetailsScroll.VScroll = 0;
        SetProgress(-1, 0);
    }

    public void SetProgress(int experience, int learned)
    {
        _experience = experience;
        _learned = learned;
        UpdateProgress();
    }

    private void UpdateProgress()
    {
        ProgressSummary.Visible = _experience >= 0;
        SkillsButton.Disabled = _experience < 0;
        if (_experience < 0)
        {
            ExperienceBar.Visible = false;
            ExperienceLabel.Text = Loc.GetString("nc-skill-loading");
            return;
        }

        var level = NCSkillProgression.Level(_experience);
        LevelLabel.Text = Loc.GetString("nc-character-card-level", ("level", level));
        PointsLabel.Text = Loc.GetString("nc-character-card-points",
            ("points", NCSkillProgression.Points(_experience, _learned)));

        if (NCSkillProgression.NextThreshold(level) is not { } next)
        {
            ExperienceBar.Visible = false;
            ExperienceLabel.Text = Loc.GetString("nc-character-card-max-level");
            return;
        }

        var start = NCSkillProgression.LevelThreshold(level);
        ExperienceBar.MaxValue = next - start;
        ExperienceBar.Value = _experience - start;
        ExperienceBar.Visible = true;
        ExperienceLabel.Text = Loc.GetString("nc-character-card-experience",
            ("experience", _experience - start), ("next", next - start));
    }

    private void Relocalize(string culture)
    {
        Title = Loc.GetString("character-info-title");
        BriefingTitle.Text = Loc.GetString("nc-character-card-briefing");
        ObjectivesTitle.Text = Loc.GetString("character-info-objectives-label");
        AdditionalTitle.Text = Loc.GetString("nc-character-card-additional");
        EmptyObjectives.Text = Loc.GetString("nc-character-card-empty");
        SkillsButton.Text = Loc.GetString("nc-skill-title");
        UpdateProgress();
        Relocalized?.Invoke();
    }
    // NC-Edit-End
}
