using Robust.Client.AutoGenerated;
using Robust.Client.Console; // NC
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Content.Shared.CCVar; // NC
using Robust.Shared.Configuration; // NC

namespace Content.Client.UserInterface.Systems.MenuBar.Widgets
{
    [GenerateTypedNameReferences]
    public sealed partial class GameTopMenuBar : UIWidget
    {
        private readonly IConfigurationManager _config = IoCManager.Resolve<IConfigurationManager>(); // NC

        public GameTopMenuBar()
        {
            RobustXamlLoader.Load(this);
            SkillsButton.OnPressed += _ => IoCManager.Resolve<IClientConsoleHost>().RemoteExecuteCommand(null, "ncskills"); // NC
        }

        // NC-Edit-Start
        protected override void EnteredTree()
        {
            base.EnteredTree();
            _config.OnValueChanged(CCVars.NCClientCulture, RelocalizeSkillsButton, invokeImmediately: true);
        }

        protected override void ExitedTree()
        {
            _config.UnsubValueChanged(CCVars.NCClientCulture, RelocalizeSkillsButton);
            base.ExitedTree();
        }

        private void RelocalizeSkillsButton(string culture) =>
            SkillsButton.ToolTip = Loc.GetString("nc-skill-title");
        // NC-Edit-End
    }
}
