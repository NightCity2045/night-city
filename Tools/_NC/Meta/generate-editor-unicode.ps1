# Reproduces the installed .NET 10 Unicode property table for the sandboxed editor.
# Reflection is used by this offline source generator only. The game reads a fixed integer table.
[CmdletBinding()]
param()
$ErrorActionPreference = 'Stop'
if ([Environment]::Version.Major -ne 10) { throw 'Generate with PowerShell running on .NET 10.' }
$root = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '../../..'))
$destination = Join-Path $root 'Content.Client/_NC/Meta/Editor/NCMetaGraphemes.Data.cs'
Add-Type -TypeDefinition @'
using System;
using System.Reflection;
using System.Globalization;
using System.Text;
public static class MetaUnicodeGenerator
{
    public static string Generate()
    {
        var method = typeof(CharUnicodeInfo).GetMethod("GetGraphemeClusterBreakType", BindingFlags.Static | BindingFlags.NonPublic)
            ?? throw new InvalidOperationException("The pinned runtime no longer exposes the expected Unicode property table.");
        var names = Enum.GetNames(method.ReturnType);
        if (string.Join(",", names) != "Other,CR,LF,Control,Extend,ZWJ,Regional_Indicator,Prepend,SpacingMark,L,V,T,LV,LVT,Extended_Pictograph")
            throw new InvalidOperationException("The runtime's grapheme property ABI changed.");
        var output = new StringBuilder();
        output.AppendLine("// SPDX-License-Identifier: MIT\n// Copyright (c) .NET Foundation and Contributors\n// Generated by Tools/_NC/Meta/generate-editor-unicode.ps1 from .NET " + Environment.Version + ".\n// See NCMetaGraphemes.license. Do not edit by hand.\nnamespace Content.Client._NC.Meta.Editor;\n\npublic static partial class NCMetaGraphemes\n{\n    private static readonly uint[] PropertyStarts = new uint[]\n    {");
        int previous = -1, column = 0;
        for (int scalar = 0; scalar <= 0x10ffff; scalar++)
        {
            int property = Rune.IsValid(scalar) ? Convert.ToInt32(method.Invoke(null, new object[] { new Rune(scalar) })) : 0;
            if (property == previous) continue;
            if (column++ % 8 == 0) output.Append("        ");
            output.Append("0x").Append(((scalar << 5) | property).ToString("X")).Append(", ");
            if (column % 8 == 0) output.AppendLine();
            previous = property;
        }
        output.AppendLine("\n    };\n}");
        return output.ToString();
    }
}
'@
[IO.File]::WriteAllText($destination, [MetaUnicodeGenerator]::Generate(), [Text.UTF8Encoding]::new($false))
Write-Output $destination
